#!/usr/bin/env python3
"""Dump representative EUR records to inspect what they actually are.

For a given chunk + resultKind, print the underlying method subject ids grouped
by method-name family, so repeated failures of the same pattern collapse into
one row instead of N copies.

USAGE
    python tools/eh/sample_eur.py --chunk System.Xml.ReaderWriter/xml --kind realDefect
    python tools/eh/sample_eur.py --min 5   # all chunk/kind combos with >=5 EUR
"""

from __future__ import annotations

import argparse
import os
import re
import sys
from collections import Counter, defaultdict


def iter_records(root):
    import glob, json
    for path in glob.glob(os.path.join(root, "*", "chunks", "*", "results", "fact-results.json")):
        parts = os.path.normpath(path).split(os.sep)
        try:
            i = parts.index("chunks")
            assembly, chunk = parts[i - 1], parts[i + 1]
        except (ValueError, IndexError):
            continue
        try:
            with open(path, encoding="utf-8") as fh:
                data = json.load(fh)
        except Exception:
            continue
        for mode in ("aot", "jit"):
            for rec in data.get(mode, []) or []:
                if isinstance(rec, dict):
                    yield assembly, chunk, mode, rec


def method_family(subject: str) -> str:
    """Collapse a subject id to its declaring type + method name family."""
    # CombinedSubjects/AutoGenerated.<Asm>.<Type>::<Method>__N:Ret()
    m = re.search(r"::([^(<]+?)(?:\(|__\d|$)", subject or "")
    return m.group(1) if m else (subject or "?")


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", default="artifacts/foundation-dll")
    ap.add_argument("--chunk", default="")
    ap.add_argument("--kind", default="")
    ap.add_argument("--mode", default="aot")
    ap.add_argument("--min", type=int, default=0)
    args = ap.parse_args()

    fam_by_chunk = defaultdict(Counter)   # (chunk,kind) -> family -> count
    subjects = defaultdict(list)

    for assembly, chunk, mode, rec in iter_records(args.root):
        if mode != args.mode:
            continue
        if not (rec.get("caught") and not rec.get("assertFailed")):
            continue
        key = (f"{assembly}/{chunk}", rec.get("resultKind"))
        if args.chunk and key[0] != args.chunk:
            continue
        if args.kind and key[1] != args.kind:
            continue
        fam = method_family(rec.get("methodSubjectId") or "")
        fam_by_chunk[key][fam] += 1
        if len(subjects[key]) < 3:
            subjects[key].append(rec.get("methodSubjectId"))

    for (ck, kind), counter in sorted(fam_by_chunk.items(), key=lambda x: -sum(x[1].values())):
        total = sum(counter.values())
        if total < args.min:
            continue
        print(f"=== {ck}  [{kind}]  total={total}")
        for fam, n in counter.most_common(10):
            print(f"  {n:5d}  {fam}")
        if subjects[(ck, kind)]:
            print("   exemplars:")
            for s in subjects[(ck, kind)]:
                print(f"      {s}")
        print()
    return 0


if __name__ == "__main__":
    sys.exit(main())
