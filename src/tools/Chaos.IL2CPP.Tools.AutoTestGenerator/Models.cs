using System.Collections.Immutable;
using System.Reflection;
using System.Reflection.Metadata;
using System.Reflection.PortableExecutable;

namespace Chaos.IL2CPP.Tools.AutoTestGenerator;

public sealed record MethodParameter(
    string Name,
    string TypeName,
    bool IsOut,
    bool IsRef
);

public sealed record MethodSignature(
    string Name,
    string DeclaringTypeFullName,
    string ReturnTypeName,
    bool IsStatic,
    bool IsVoid,
    bool HasRefParam,
    IReadOnlyList<MethodParameter> Parameters
);

public sealed record ValueSet(
    int SetIndex,
    IReadOnlyList<string> ArgumentExpressions  // C# expressions for each parameter
);

public sealed record ProbeResult(
    int MethodIndex,
    int SetIndex,
    string SubjectId,
    bool IsVoid,
    bool HasException,
    string? ExceptionType,
    long? ReturnValue,    // null for void
    bool IsDeterministic  // false if two probe runs differed
);

public sealed record GeneratedSubject(
    int MethodIndex,
    int SetIndex,
    string SubjectId,
    string MethodName,
    bool IsFact,
    bool IsBenchmark,
    bool IsHotUpdate,
    string CallExpression,         // the method call e.g. "Convert.ToChar(42)"
    string? AssertExpression,      // null if no assert (benchmark-only or non-deterministic)
    bool IsVoid,
    bool SkipReason               // true if this subject couldn't be auto-generated
);

public sealed record CoverageReport(
    string AssemblyName,
    string TypeName,
    int TotalMethods,
    int AutoGeneratedMethods,
    int BenchmarkOnlyMethods,
    int SkippedMethods,
    int TotalSubjects,
    IReadOnlyList<string> SkippedMethodNames
);
