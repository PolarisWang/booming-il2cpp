using System.Text.RegularExpressions;

namespace Chaos.IL2CPP.Tools.AutoTestGenerator;

/// <summary>
/// Aggregates coverage reports from multiple AutoTestGenerator output directories.
/// Scans all README.md files recursively and produces a combined SUMMARY.md.
/// </summary>
public sealed class CoverageAggregator
{
    public sealed record TypeCoverage(
        string TypeName,
        int TotalMethods,
        int AutoGenerated,
        int BenchmarkOnly,
        int Skipped,
        int TotalSubjects);

    public IReadOnlyList<TypeCoverage> Aggregate(string outputRoot)
    {
        var results = new List<TypeCoverage>();
        var readmePattern = new Regex(
            @"^\|\s*Total Methods\s*\|\s*(\d+)\s*\|$" +
            @"|^\|\s*Auto-generated.*\|\s*(\d+)\s*\|$" +
            @"|^\|\s*Benchmark-only.*\|\s*(\d+)\s*\|$" +
            @"|^\|\s*Skipped.*\|\s*(\d+)\s*\|$" +
            @"|^\|\s*Total Subjects\s*\|\s*(\d+)\s*\|$",
            RegexOptions.Multiline);

        var typeNamePattern = new Regex(
            @"^- Type:\s*`(.+)`$",
            RegexOptions.Multiline);

        foreach (var readmePath in Directory.EnumerateFiles(outputRoot, "README.md", SearchOption.AllDirectories))
        {
            try
            {
                var content = File.ReadAllText(readmePath);
                content = content.Replace("\r", ""); // normalize line endings

                var typeMatch = typeNamePattern.Match(content);
                var typeName = typeMatch.Success ? typeMatch.Groups[1].Value : Path.GetFileName(Path.GetDirectoryName(readmePath)) ?? "?";

                var matches = readmePattern.Matches(content);
                int totalM = 0, autoGen = 0, benchOnly = 0, skipped = 0, subjects = 0;

                foreach (Match m in matches)
                {
                    if (m.Groups[1].Success) totalM = int.Parse(m.Groups[1].Value);
                    else if (m.Groups[2].Success) autoGen = int.Parse(m.Groups[2].Value);
                    else if (m.Groups[3].Success) benchOnly = int.Parse(m.Groups[3].Value);
                    else if (m.Groups[4].Success) skipped = int.Parse(m.Groups[4].Value);
                    else if (m.Groups[5].Success) subjects = int.Parse(m.Groups[5].Value);
                }

                if (totalM > 0)
                    results.Add(new TypeCoverage(typeName, totalM, autoGen, benchOnly, skipped, subjects));
            }
            catch (Exception ex)
            {
                Console.Error.WriteLine($"[Warning] Failed to parse {readmePath}: {ex.Message}");
            }
        }

        return results.OrderBy(r => r.TypeName).ToList();
    }

    public string GenerateReport(IReadOnlyList<TypeCoverage> items)
    {
        var totalMethods = items.Sum(i => i.TotalMethods);
        var totalAuto = items.Sum(i => i.AutoGenerated);
        var totalBench = items.Sum(i => i.BenchmarkOnly);
        var totalSkipped = items.Sum(i => i.Skipped);
        var totalSubjects = items.Sum(i => i.TotalSubjects);

        var sb = new System.Text.StringBuilder();
        sb.AppendLine("# AutoTestGenerator Coverage Report");
        sb.AppendLine();
        sb.AppendLine($"Generated: {DateTime.Now:yyyy-MM-dd HH:mm}");
        sb.AppendLine();
        sb.AppendLine("## Grand Totals");
        sb.AppendLine();
        sb.AppendLine("| Metric | Value |");
        sb.AppendLine("|--------|-------|");
        sb.AppendLine($"| Total Types | {items.Count} |");
        sb.AppendLine($"| Total Methods | {totalMethods} |");
        sb.AppendLine($"| Auto-generated | {totalAuto} |");
        sb.AppendLine($"| Benchmark-only | {totalBench} |");
        sb.AppendLine($"| Skipped | {totalSkipped} |");
        sb.AppendLine($"| Total Subjects | {totalSubjects} |");
        sb.AppendLine();
        sb.AppendLine("## Per-Type Breakdown");
        sb.AppendLine();
        sb.AppendLine("| Type | Total Methods | Auto-generated | Benchmark-only | Skipped | Subjects |");
        sb.AppendLine("|------|--------------|---------------|----------------|---------|----------|");

        foreach (var item in items)
        {
            // Sanitize pipe characters in type names for markdown
            var typeName = item.TypeName.Replace("|", "\\|");
            sb.AppendLine($"| {typeName} | {item.TotalMethods} | {item.AutoGenerated} | {item.BenchmarkOnly} | {item.Skipped} | {item.TotalSubjects} |");
        }

        return sb.ToString();
    }
}
