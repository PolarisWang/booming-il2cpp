using System.Text;

namespace Chaos.IL2CPP.Tools.AutoTestGenerator;

public sealed class TestEmitter
{
    private readonly CSharpSerializer _serializer;
    private readonly CSharpExpressionBuilder _expressionBuilder;

    // Types that need explicit casts to disambiguate overloads
    private static readonly HashSet<string> CastNeededTypes = new(StringComparer.Ordinal)
    {
        "System.Boolean", "System.Byte", "System.SByte", "System.Int16", "System.UInt16",
        "System.Int32", "System.UInt32", "System.Int64", "System.UInt64", "System.Single",
        "System.Double", "System.Decimal", "System.Char",
    };

    public TestEmitter(CSharpSerializer serializer, CSharpExpressionBuilder expressionBuilder)
    {
        _serializer = serializer;
        _expressionBuilder = expressionBuilder;
    }

    public string Emit(
        string assemblyName,
        string typeFullName,
        string typeNamespace,
        IReadOnlyList<MethodSignature> methods,
        IReadOnlyList<IReadOnlyList<ValueSet>> allValueSets,
        IReadOnlyList<ProbeResult> probeResults)
    {
        // Use typeFullName directly (not MapToCSharpType) to preserve the parent type
        // prefix for nested types. MapToCSharpType strips the namespace via KeywordMap,
        // causing collisions when MLC flattens nested types from different parents
        // (e.g. AnsiStringMarshaller.ManagedToUnmanagedIn vs
        // BStrStringMarshaller.ManagedToUnmanagedIn both become "ManagedToUnmanagedIn").
        var className = SanitizeIdentifier(typeFullName) + "Tests";
        var resultMap = probeResults.ToDictionary(r => (r.MethodIndex, r.SetIndex));

        var sb = new StringBuilder();
        sb.AppendLine("// Auto-generated by Chaos.IL2CPP.AutoTestGenerator");
        sb.AppendLine("using System;");
        sb.AppendLine("using System.Buffers;");
        sb.AppendLine("using System.Collections;");
        sb.AppendLine("using System.Collections.Concurrent;");
        sb.AppendLine("using System.Collections.Frozen;");
        sb.AppendLine("using System.Collections.Generic;");
        sb.AppendLine("using System.Collections.Immutable;");
        sb.AppendLine("using System.Collections.ObjectModel;");
        sb.AppendLine("using System.ComponentModel;");
        sb.AppendLine("using System.Data;");
        sb.AppendLine("using System.Diagnostics;");
        sb.AppendLine("using System.Formats.Asn1;");
        sb.AppendLine("using System.Globalization;");
        sb.AppendLine("using System.IO;");
        sb.AppendLine("using System.IO.Compression;");
        sb.AppendLine("using System.Linq;");
        sb.AppendLine("using System.Linq.Expressions;");
        sb.AppendLine("using System.Net;");
        sb.AppendLine("using System.Net.Http;");
        sb.AppendLine("using System.Net.Http.Headers;");
        sb.AppendLine("using System.Net.Sockets;");
        sb.AppendLine("using System.Numerics;");
        sb.AppendLine("using System.Reflection;");
        sb.AppendLine("using System.Reflection.Emit;");
        sb.AppendLine("using System.Runtime.CompilerServices;");
        sb.AppendLine("using System.Runtime.InteropServices;");
        sb.AppendLine("using System.Runtime.Serialization;");
        sb.AppendLine("using System.Security.Claims;");
        sb.AppendLine("using System.Security.Cryptography;");
        sb.AppendLine("using System.Security.Cryptography.X509Certificates;");
        sb.AppendLine("using System.Security.Principal;");
        sb.AppendLine("using System.Text;");
        sb.AppendLine("using System.Text.Json;");
        sb.AppendLine("using System.Text.Json.Nodes;");
        sb.AppendLine("using System.Text.Json.Serialization;");
        sb.AppendLine("using System.Text.Json.Serialization.Metadata;");
        sb.AppendLine("using System.Text.RegularExpressions;");
        sb.AppendLine("using System.Threading;");
        sb.AppendLine("using System.Threading.Channels;");
        sb.AppendLine("using System.Threading.Tasks;");
        sb.AppendLine("using System.Xml;");
        sb.AppendLine("using System.Xml.Schema;");
        sb.AppendLine("using Microsoft.Win32.SafeHandles;");
        sb.AppendLine("using Chaos.TestFramework;");

        // Add using for the tested type's namespace so the generated code can reference
        // the type directly (e.g. `using System.Text.RegularExpressions;` for Regex).
        // Use the true namespace from type metadata (not extracted from typeFullName)
        // to correctly handle nested types (e.g. Delegate+InvocationListEnumerator
        // should use `using System;`, not `using System.Delegate;`).
        if (!string.IsNullOrEmpty(typeNamespace) &&
            (typeNamespace.StartsWith("System.") || typeNamespace == "System"))
            sb.AppendLine($"using {typeNamespace};");

        sb.AppendLine();
        sb.AppendLine($"namespace AutoGenerated.{SanitizeIdentifier(assemblyName)}");
        sb.AppendLine("{");
        sb.AppendLine($"    public unsafe partial class {className}");
        sb.AppendLine("    {");

        for (int mi = 0; mi < methods.Count; mi++)
        {
            var method = methods[mi];
            var sets = allValueSets[mi];
            var result = resultMap.GetValueOrDefault((mi, 0));

            var isPureVoid = method.IsVoid && !method.HasRefParam;

            // For pure void methods: only [Benchmark], no [Fact] or [HotUpdate]
            var skipFact = isPureVoid;

            foreach (var set in sets)
            {
                var setResult = resultMap.GetValueOrDefault((mi, set.SetIndex));
                var paramSuffix = string.Join("_", method.Parameters.Select(p =>
                    SanitizeIdentifier(CSharpSerializer.MapToCSharpType(p.TypeName))));
                var methodSuffix = $"{SanitizeIdentifier(method.Name)}_{mi}_{paramSuffix}_{set.SetIndex}";

                // Build arg list with variable declarations for out/ref
                var prelude = new List<string>();
                var finalArgs = new List<string>();
                int refVarCounter = 0;

                for (int pi = 0; pi < method.Parameters.Count; pi++)
                {
                    var param = method.Parameters[pi];
                    var argExpr = set.ArgumentExpressions[pi];

                    if (param.IsOut || param.IsRef)
                    {
                        var baseTypeName = param.TypeName.EndsWith('&')
                            ? param.TypeName[..^1].Trim()
                            : param.TypeName;
                        var csType = CSharpSerializer.MapToCSharpType(baseTypeName);

                        var varName = $"__ref_{mi}_{set.SetIndex}_{refVarCounter++}";
                        prelude.Add($"            {csType} {varName} = default;");
                        finalArgs.Add(param.IsOut ? $"out {varName}" : $"ref {varName}");
                    }
                    else
                    {
                        finalArgs.Add(DisambiguateArg(param.TypeName, argExpr));
                    }
                }

                var preludeStr = prelude.Count > 0
                    ? string.Join("\n", prelude) + "\n"
                    : "";

                var argsStr = string.Join(", ", finalArgs);
                var genericSuffix = method.GenericTypeArgs is { Count: > 0 }
                    ? $"<{string.Join(", ", method.GenericTypeArgs.Select(CSharpSerializer.MapToCSharpType))}>"
                    : "";
                var instanceExpr = _expressionBuilder.GetInstanceExpression(typeFullName, method.IsStatic);
                var callExpr = $"{instanceExpr}.{method.Name}{genericSuffix}({argsStr})";

                // Task-returning methods: unwrap with GetAwaiter().GetResult() so assertions
                // see the actual result value and exceptions propagate synchronously.
                // Covers Task, Task`1, ValueTask, ValueTask`1.
                // DllScanner.GetTypeName outputs generic types in angle-bracket format
                // (e.g. "System.Threading.Tasks.Task<System.Int32>") so we must also
                // match the StartsWith("<") variant alongside the CLR backtick "`1" format.
                var rt = method.ReturnTypeName;
                var isPlainTask = rt == "System.Threading.Tasks.Task" ||
                                  rt == "System.Threading.Tasks.ValueTask";
                var isGenericTask = rt == "System.Threading.Tasks.Task`1" ||
                                    rt == "System.Threading.Tasks.ValueTask`1" ||
                                    rt.StartsWith("System.Threading.Tasks.Task<") ||
                                    rt.StartsWith("System.Threading.Tasks.ValueTask<");
                var isTaskReturn = isPlainTask || isGenericTask;
                if (isTaskReturn)
                    callExpr += ".GetAwaiter().GetResult()";

                // Plain Task (void async): treat as void after unwrapping
                var callStatement = (method.IsVoid || isPlainTask)
                    ? $"{preludeStr}            {callExpr};"
                    : $"{preludeStr}            var result_{mi}_{set.SetIndex} = {callExpr};";

                // When the probe detected an exception, we must NOT evaluate the call
                // directly (it would throw). Instead, only emit prelude (out/ref vars)
                // and let Assert.Throws wrap the call in a lambda.
                var hasException = setResult?.HasException == true;
                var factCallStatement = hasException
                    ? $"{preludeStr}"
                    : callStatement;

                // ── [Fact][HotUpdate] method (merged, return long) ──
                if (!skipFact)
                {
                    sb.AppendLine();
                    sb.AppendLine("        [Fact]");
                    sb.AppendLine("        [HotUpdate]");
                    sb.AppendLine($"        public long {methodSuffix}()");
                    sb.AppendLine("        {");
                    if (!string.IsNullOrEmpty(factCallStatement))
                        sb.AppendLine(factCallStatement);
                    AppendAssert(sb, mi, method, set, setResult, callExpr, method.HasRefParam);
                    // Return long value for hotupdate semantic change detection.
                    // Exception subjects and void methods return sentinel 42L.
                    if (method.IsVoid || isPlainTask || hasException)
                    {
                        sb.AppendLine("            return 42L;");
                    }
                    else
                    {
                        var resultVar = $"result_{mi}_{set.SetIndex}";
                        var returnExpr = ValueGenerator.GetResultToLongExpression(method.ReturnTypeName, resultVar);
                        sb.AppendLine($"            return {returnExpr};");
                    }
                    sb.AppendLine("        }");
                }

                // ── [Benchmark] method ──
                {
                    sb.AppendLine();
                    sb.AppendLine("        [Benchmark]");
                    sb.AppendLine($"        public static void Benchmark_{methodSuffix}()");
                    sb.AppendLine("        {");
                    if (preludeStr.Length > 0)
                        sb.Append(preludeStr);
                    var benchCall = $"{instanceExpr}.{method.Name}{genericSuffix}({argsStr})";
                    if (method.IsVoid)
                        sb.AppendLine($"            {benchCall};");
                    else
                        sb.AppendLine($"            _ = {benchCall};");
                    sb.AppendLine("        }");
                }
            }
        }

        sb.AppendLine("    }");
        sb.AppendLine("}");

        return sb.ToString();
    }

    private void AppendAssert(StringBuilder sb, int mi, MethodSignature method, ValueSet set,
        ProbeResult? result, string callExpr, bool hasRefParam)
    {
        if (result is null) return;

        if (result.HasException && result.ExceptionType is not null)
        {
            // Ref/out locals can't be captured in a lambda — skip Assert.Throws
            if (!hasRefParam)
            {
                // Use the specific exception type from probe (e.g. ArgumentNullException)
                // rather than the generic Exception, so assertion failures are more precise.
                // Fall back to Exception if the type name looks non-public or unavailable.
                var exType = result.ExceptionType;
                if (exType.Contains('+') || exType.StartsWith("System.Reflection"))
                    exType = "Exception";
                // JsonReaderException is internal in .NET 9+; use public base class JsonException
                if (exType == "System.Text.Json.JsonReaderException")
                    exType = "System.Text.Json.JsonException";
                sb.AppendLine($"            Assert.Throws<{exType}>(() => {callExpr});");
            }
            return;
        }

        // Deterministic return value assertion
        if (result.IsDeterministic && !result.IsVoid && result.ReturnValueJson is not null)
        {
            // Null return → assert default(T)!
            if (result.ReturnValueJson == "null" || string.IsNullOrEmpty(result.ReturnValueType))
            {
                var csType = CSharpSerializer.MapToCSharpType(method.ReturnTypeName);
                // For reference types: assert IsNotNull first to catch unexpected non-null
                // results before comparing to default(T)!. This guards against probe
                // serialization gaps where a non-null value was not captured.
                var isRefType = !CSharpSerializer.IsValueType(method.ReturnTypeName);
                if (isRefType)
                    sb.AppendLine($"            Assert.IsNotNull(result_{mi}_{set.SetIndex});");
                sb.AppendLine($"            Assert.AreEqual(default({csType})!, result_{mi}_{set.SetIndex});");
                return;
            }

            // Non-null deterministic return → deserialize JSON to expression.
            // Use the declared return type (always public) rather than the runtime type
            // (which may be an internal implementation type like JsonValueOfElement).
            var returnType = IsInternalRuntimeType(result.ReturnValueType)
                ? method.ReturnTypeName
                : result.ReturnValueType;
            var expectedExpr = _serializer.DeserializeToExpression(
                result.ReturnValueJson, returnType);
            if (!expectedExpr.StartsWith("/* TODO"))
            {
                sb.AppendLine($"            Assert.AreEqual({expectedExpr}, result_{mi}_{set.SetIndex});");
            }
        }

        // Out/ref parameter value assertions
        // Note: ref struct out/ref values can't be serialized by the probe (JsonSerializer
        // can't handle ref structs), so they're skipped here to keep index alignment.
        if (result.OutRefValues is { Count: > 0 })
        {
            int refCounter = 0;
            for (int pi = 0; pi < method.Parameters.Count; pi++)
            {
                var param = method.Parameters[pi];
                if (!param.IsOut && !param.IsRef) continue;
                if (param.IsRefStruct) continue; // probe skips these

                if (refCounter < result.OutRefValues.Count)
                {
                    var json = result.OutRefValues[refCounter];
                    var baseTypeName = param.TypeName.EndsWith('&')
                        ? param.TypeName[..^1].Trim()
                        : param.TypeName;
                    var varName = $"__ref_{mi}_{set.SetIndex}_{refCounter}";

                    // Skip null-valued out/ref or empty types
                    if (json == "null" || string.IsNullOrEmpty(baseTypeName))
                    {
                        refCounter++;
                        continue;
                    }

                    var expectedExpr = _serializer.DeserializeToExpression(json, baseTypeName);
                    if (!expectedExpr.StartsWith("/* TODO"))
                    {
                        sb.AppendLine($"            Assert.AreEqual({expectedExpr}, {varName});");
                    }
                }
                refCounter++;
            }
        }
    }

    /// <summary>
    /// Add explicit type cast for boundary/default values to disambiguate overloads.
    /// E.g., "0" for short param becomes "(short)0".
    /// </summary>
    private static string DisambiguateArg(string paramType, string argExpr)
    {
        // Safety net: untyped null! creates ambiguity for overloaded reference types
        // (e.g. byte[] vs Stream). Cast to the parameter type to disambiguate.
        if (argExpr == "null!")
            return $"({CSharpSerializer.MapToCSharpType(paramType)})null!";

        if (!CastNeededTypes.Contains(paramType))
            return argExpr;

        // Only add cast if the expression is a simple literal (starts with digit, -, or '"')
        if (argExpr.Length == 0) return argExpr;

        var first = argExpr[0];
        if (!char.IsDigit(first) && first != '-' && first != '\"')
            return argExpr;

        // Don't re-cast if already cast
        if (argExpr.StartsWith('('))
            return argExpr;

        var csType = CSharpSerializer.MapToCSharpType(paramType);
        return $"({csType}){argExpr}";
    }

    public CoverageReport GenerateReport(
        string assemblyName,
        string typeFullName,
        IReadOnlyList<MethodSignature> methods,
        IReadOnlyList<IReadOnlyList<ValueSet>> allValueSets,
        IReadOnlyList<ProbeResult> probeResults,
        IReadOnlyList<string> skippedMethods)
    {
        var resultMap = probeResults.ToDictionary(r => (r.MethodIndex, r.SetIndex));
        int autoGen = 0, benchOnly = 0, totalSubjects = 0;
        var skippedNames = new List<string>(skippedMethods);

        for (int mi = 0; mi < methods.Count; mi++)
        {
            var method = methods[mi];
            var sets = allValueSets[mi];
            totalSubjects += sets.Count;

            var isPureVoid = method.IsVoid && !method.HasRefParam;
            if (isPureVoid)
            {
                benchOnly++;
                continue;
            }

            // Check if ANY set produces a valid assertion (return value or Assert.Throws)
            var anyAssertion = sets.Any(s =>
            {
                var r = resultMap.GetValueOrDefault((mi, s.SetIndex));
                if (r is null) return false;
                // Exception subjects generate Assert.Throws<T> — count as assertion
                if (r.HasException && r.ExceptionType is not null) return true;
                // Deterministic return value subjects generate Assert.AreEqual
                return r is { IsDeterministic: true, IsVoid: false, ReturnValueJson: not null };
            });

            if (anyAssertion)
                autoGen++;
            else
                benchOnly++;
        }

        return new CoverageReport(
            assemblyName, typeFullName,
            methods.Count + skippedMethods.Count, autoGen, benchOnly,
            skippedMethods.Count, totalSubjects, skippedNames);
    }

    private static bool IsInternalRuntimeType(string? typeName)
    {
        if (string.IsNullOrEmpty(typeName)) return true;
        // Internal implementation types that can't be used in C# source
        return typeName.StartsWith("System.Text.Json.Nodes.JsonValue", StringComparison.Ordinal)
            // System.Linq.EmptyLookup<TKey,TElement> is internal
            || typeName.Contains("EmptyLookup", StringComparison.Ordinal)
            // System.Collections.Frozen.EmptyFrozenSet is internal
            || typeName.Contains("EmptyFrozenSet", StringComparison.Ordinal);
    }

    private static string SanitizeIdentifier(string name)
    {
        var sb = new StringBuilder();
        foreach (var c in name)
        {
            if (char.IsLetterOrDigit(c) || c == '_')
                sb.Append(c);
            else if (c == '.')
                sb.Append('_');
        }
        if (sb.Length > 0 && char.IsDigit(sb[0]))
            sb.Insert(0, '_');
        return sb.ToString();
    }
}
