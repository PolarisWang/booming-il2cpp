using System.Text;
using System.Text.Json;
using System.Text.RegularExpressions;

namespace Chaos.IL2CPP.Tools.AutoTestGenerator;

/// <summary>
/// Generates CombinedSubjects.cs, CombinedSubjects.csproj, and metadata.json
/// from custom subject .cs files (hand-written .Custom.cs files).
///
/// This replaces the Python f-string generation in build.py's _compile_custom_subjects,
/// moving the responsibility into the C# AutoTestGenerator per the architecture boundary.
/// </summary>
public static class WrapperEmitter
{
    /// <summary>
    /// Parsed method info from a custom .cs file.
    /// </summary>
    public sealed record MethodInfo(
        string Namespace,
        string ClassName,
        string MethodName,
        string ReturnType /// .NET metadata type name (e.g. "System.Int64")
    );

    /// <summary>
    /// Metadata entry for a single wrapper subject method.
    /// </summary>
    public sealed record MetadataEntry(
        int Index,
        string Kind,
        string MethodSubjectId
    );

    /// <summary>
    /// Top-level metadata JSON structure for custom subjects.
    /// </summary>
    public sealed record WrapperMetadata(
        int SchemaVersion,
        string AssemblyName,
        string ChunkSlug,
        int TotalMethods,
        IReadOnlyList<int> CustomEntryIndices,
        IReadOnlyList<int> BenchmarkMethodIndices,
        IReadOnlyList<int> HotupdateMethodIndices,
        IReadOnlyList<MetadataEntry> Methods
    );

    /// <summary>
    /// Generate CombinedSubjects.cs, CombinedSubjects.csproj, and metadata.json
    /// from a list of custom .cs files.
    /// </summary>
    /// <param name="customCsFiles">Paths to .Custom.cs files.</param>
    /// <param name="outputDir">Output directory for generated files.</param>
    /// <param name="slug">Chunk slug for metadata.</param>
    /// <param name="sdkCsproj">Path to Chaos.TestFramework.Sdk.csproj.</param>
    /// <param name="tfm">Target framework moniker (e.g. "net10.0").</param>
    /// <returns>
    /// The list of (asmComponent, typePath, methodName, retType) tuples on success,
    /// or null if no methods were found.
    /// </returns>
    public static IReadOnlyList<(string AsmComponent, string TypePath, string MethodName, string RetType)>? GenerateWrappers(
        List<string> customCsFiles,
        string outputDir,
        string slug,
        string sdkCsproj,
        string tfm)
    {
        // ── Step 1: Parse methods from each .Custom.cs file ──
        var methodInfos = new List<MethodInfo>();
        foreach (var csFile in customCsFiles.OrderBy(f => f))
        {
            var text = File.ReadAllText(csFile);

            // Extract namespace
            var nsMatch = Regex.Match(text, @"namespace\s+(\S+)");
            var ns = nsMatch.Success ? nsMatch.Groups[1].Value : "";

            // Extract class name
            var clsMatch = Regex.Match(text, @"public\s+static\s+(?:partial\s+)?class\s+(\w+)");
            var className = clsMatch.Success ? clsMatch.Groups[1].Value : "CustomSubjects";

            // Extract methods: [Fact] [Benchmark] public static TYPE MethodName()
            foreach (Match match in Regex.Matches(text,
                @"\[(?:Fact|Benchmark)\].*?public\s+static\s+(\S+)\s+(\w+)\s*\(\)",
                RegexOptions.Singleline))
            {
                var retType = match.Groups[1].Value;
                var methodName = match.Groups[2].Value;

                // Map C# return types to .NET metadata types
                var metadataRet = MapCSharpReturnType(retType);
                methodInfos.Add(new MethodInfo(ns, className, methodName, metadataRet));
            }
        }

        if (methodInfos.Count == 0)
            return null;

        // ── Step 2: Generate CombinedSubjects.cs ──
        var combinedCsPath = Path.Combine(outputDir, "CombinedSubjects.cs");
        Directory.CreateDirectory(outputDir);
        using (var writer = new StreamWriter(combinedCsPath, false, Encoding.UTF8))
        {
            writer.WriteLine("// Custom subjects combined file");
            writer.WriteLine("using System;");
            writer.WriteLine("using Chaos.TestFramework;");
            writer.WriteLine();

            // Part 1: Original custom subject class (preserve as-is, verbatim)
            foreach (var csFile in customCsFiles.OrderBy(f => f))
            {
                writer.WriteLine(File.ReadAllText(csFile));
                writer.WriteLine();
            }

            // Part 2: Wrappers in AutoGenerated.* format (matching TPG generate-dll)
            // Use Subject_N naming so codegen includes them in kSubjectSlotMap.
            for (int idx = 0; idx < methodInfos.Count; idx++)
            {
                var mi = methodInfos[idx];
                var wrapperNs = string.IsNullOrEmpty(mi.Namespace)
                    ? "AutoGenerated"
                    : $"AutoGenerated.{mi.Namespace.Replace('.', '_')}";
                var wrapperCls = $"{mi.ClassName.Replace('.', '_')}Tests";
                var qualifiedCls = string.IsNullOrEmpty(mi.Namespace)
                    ? mi.ClassName
                    : $"global::{mi.Namespace}.{mi.ClassName}";
                var isVoid = mi.ReturnType == "System.Void";

                var wrapperBody = isVoid
                    ? $"{{ {qualifiedCls}.{mi.MethodName}(); return 0; }}"
                    : $"{{ return (long){qualifiedCls}.{mi.MethodName}(); }}";

                writer.WriteLine($"namespace {wrapperNs}");
                writer.WriteLine("{");
                writer.WriteLine($"    public unsafe partial class {wrapperCls}");
                writer.WriteLine("    {");
                writer.WriteLine(
                    $"        [Benchmark]\n" +
                    $"        public long Subject_{idx}() {wrapperBody}");
                writer.WriteLine("    }");
                writer.WriteLine("}");
                writer.WriteLine();
            }
        }

        // ── Step 3: Generate CombinedSubjects.csproj ──
        var combinedCsprojPath = Path.Combine(outputDir, "CombinedSubjects.csproj");
        File.WriteAllText(combinedCsprojPath,
            "<Project Sdk=\"Microsoft.NET.Sdk\">\n" +
            "  <PropertyGroup>\n" +
            "    <OutputType>Library</OutputType>\n" +
            $"    <TargetFramework>{tfm}</TargetFramework>\n" +
            "    <ImplicitUsings>enable</ImplicitUsings>\n" +
            "    <Nullable>enable</Nullable>\n" +
            "    <AllowUnsafeBlocks>true</AllowUnsafeBlocks>\n" +
            "    <EnableDefaultCompileItems>false</EnableDefaultCompileItems>\n" +
            "    <NoWarn>$(NoWarn);SYSLIB5006</NoWarn>\n" +
            "  </PropertyGroup>\n" +
            "  <ItemGroup>\n" +
            $"    <Compile Include=\"{Path.GetFileName(combinedCsPath)}\" />\n" +
            $"    <ProjectReference Include=\"{sdkCsproj}\" />\n" +
            "  </ItemGroup>\n" +
            "</Project>\n");

        // ── Step 4: Generate metadata.json ──
        var result = new List<(string AsmComponent, string TypePath, string MethodName, string RetType)>();
        var metadataEntries = new List<MetadataEntry>();
        var benchmarkIndices = new List<int>();

        for (int idx = 0; idx < methodInfos.Count; idx++)
        {
            var mi = methodInfos[idx];
            var asmComponent = mi.Namespace.Replace('.', '_');
            var typePath = mi.ClassName;
            var subjectEntryName = $"Subject_{idx}";

            result.Add((asmComponent, typePath, subjectEntryName, mi.ReturnType));

            var subjectId =
                $"CombinedSubjects/AutoGenerated.{asmComponent}.{typePath}::{subjectEntryName}:{mi.ReturnType}()";
            var kind = "benchmark";
            benchmarkIndices.Add(idx);
            metadataEntries.Add(new MetadataEntry(idx, kind, subjectId));
        }

        var metadata = new WrapperMetadata(
            SchemaVersion: 1,
            AssemblyName: "CombinedSubjects",
            ChunkSlug: slug,
            TotalMethods: metadataEntries.Count,
            CustomEntryIndices: Enumerable.Range(0, metadataEntries.Count).ToList(),
            BenchmarkMethodIndices: benchmarkIndices,
            HotupdateMethodIndices: new List<int>(),
            Methods: metadataEntries
        );

        var metadataPath = Path.Combine(outputDir, "metadata.json");
        var metaJson = JsonSerializer.Serialize(metadata, new JsonSerializerOptions
        {
            WriteIndented = true,
            PropertyNamingPolicy = JsonNamingPolicy.CamelCase,
        });
        File.WriteAllText(metadataPath, metaJson);

        Console.WriteLine($"[Wrapper] CombinedSubjects.cs -> {combinedCsPath}");
        Console.WriteLine($"[Wrapper] CombinedSubjects.csproj -> {combinedCsprojPath}");
        Console.WriteLine($"[Wrapper] metadata.json -> {metadataPath}");
        Console.WriteLine($"[Wrapper] {methodInfos.Count} wrapper methods generated");

        return result;
    }

    /// <summary>
    /// Map C# return type keyword to .NET metadata type name.
    /// </summary>
    private static string MapCSharpReturnType(string csType)
    {
        return csType switch
        {
            "long" => "System.Int64",
            "int" => "System.Int32",
            "void" => "System.Void",
            "bool" => "System.Boolean",
            "string" => "System.String",
            "byte" => "System.Byte",
            "float" => "System.Single",
            "double" => "System.Double",
            _ => csType,
        };
    }
}
