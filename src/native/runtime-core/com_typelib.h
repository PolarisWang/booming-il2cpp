#ifndef CHAOS_IL2CPP_COM_TYPELIB_H_
#define CHAOS_IL2CPP_COM_TYPELIB_H_

#include <cstdint>
#include <chaos/native_types.h>
#include "com_abi.h"

// Forward declaration for ComCcw (defined in com_ccw.h).
namespace chaos::il2cpp::com_ccw { struct ComCcw; }

namespace chaos::il2cpp::runtime_core {

// ── ITypeInfo vtable (COM ABI) ──
// https://learn.microsoft.com/en-us/windows/win32/api/oaidl/nn-oaidl-itypeinfo
struct ITypeInfoVtbl {
    int32_t  (*QueryInterface)(void*, const void*, void**);
    uint32_t (*AddRef)(void*);
    uint32_t (*Release)(void*);
    int32_t  (*GetTypeAttr)(void*, void**);
    int32_t  (*GetTypeComp)(void*, void**);
    int32_t  (*GetFuncDesc)(void*, uint32_t, void**);
    int32_t  (*GetVarDesc)(void*, uint32_t, void**);
    int32_t  (*GetNames)(void*, int32_t, void**, uint32_t, uint32_t*);
    int32_t  (*GetRefTypeOfImplType)(void*, uint32_t, uint32_t*);
    int32_t  (*GetImplTypeFlags)(void*, uint32_t, int32_t*);
    int32_t  (*GetIDsOfNames)(void*, void**, uint32_t, int32_t*);
    int32_t  (*Invoke)(void*, void*, int32_t, uint16_t, void*, void*, void*, uint32_t*);
    int32_t  (*GetDocumentation)(void*, int32_t, void**, void**, uint32_t*, void**);
    int32_t  (*GetDllEntry)(void*, int32_t, void**, void**, void**);
    int32_t  (*GetRefTypeInfo)(void*, uint32_t, void**);
    int32_t  (*AddressOfMember)(void*, int32_t, uint16_t, void**);
    int32_t  (*CreateInstance)(void*, void*, const void*, void**);
    int32_t  (*GetMops)(void*, int32_t, void**);
    int32_t  (*GetContainingTypeLib)(void*, void**, uint32_t*);
    void     (*ReleaseTypeAttr)(void*, void*);
    void     (*ReleaseFuncDesc)(void*, void*);
    void     (*ReleaseVarDesc)(void*, void*);
};

static_assert(sizeof(ITypeInfoVtbl) == 22 * sizeof(void*),
    "ITypeInfoVtbl must be exactly 22 pointers");

// ── ITypeLib vtable (COM ABI) ──
// https://learn.microsoft.com/en-us/windows/win32/api/oaidl/nn-oaidl-itypelib
struct ITypeLibVtbl {
    int32_t  (*QueryInterface)(void*, const void*, void**);
    uint32_t (*AddRef)(void*);
    uint32_t (*Release)(void*);
    int32_t  (*GetTypeInfoCount)(void*, uint32_t*);
    int32_t  (*GetTypeInfo)(void*, uint32_t, void**);
    int32_t  (*GetTypeInfoType)(void*, uint32_t, int32_t*);
    int32_t  (*GetTypeInfoOfGuid)(void*, const void*, void**);
    int32_t  (*GetLibAttr)(void*, void**);
    int32_t  (*GetTypeComp)(void*, void**);
    int32_t  (*GetDocumentation)(void*, int32_t, void**, void**, uint32_t*, void**);
    int32_t  (*IsName)(void*, void*, uint32_t, int32_t*);
    int32_t  (*FindName)(void*, void*, uint32_t, void**, uint32_t*, uint32_t*);
    void     (*ReleaseTLibAttr)(void*, void*);
};

static_assert(sizeof(ITypeLibVtbl) == 13 * sizeof(void*),
    "ITypeLibVtbl must be exactly 13 pointers");

// ── TYPEATTR (type attributes) ──
struct ComTypeAttr {
    CHAOS_IL2CPP_UINT64 guid_lo;         // Interface GUID (low 64 bits)
    CHAOS_IL2CPP_UINT64 guid_hi;         // Interface GUID (high 64 bits)
    CHAOS_IL2CPP_UINT32 lcid;
    CHAOS_IL2CPP_UINT32 dwReserved;
    CHAOS_IL2CPP_INT32  memidConstructor;
    CHAOS_IL2CPP_INT32  memidDestructor;
    void*                lpstrSchema;
    CHAOS_IL2CPP_UINT64 cbSizeInstance;
    CHAOS_IL2CPP_INT32  typekind;
    CHAOS_IL2CPP_INT16  cFuncs;
    CHAOS_IL2CPP_INT16  cVars;
    CHAOS_IL2CPP_INT16  cImplTypes;
    CHAOS_IL2CPP_INT16  cbSizeVft;
    CHAOS_IL2CPP_INT16  cbAlignment;
    CHAOS_IL2CPP_INT16  wMajorVerNum;
    CHAOS_IL2CPP_INT16  wMinorVerNum;
    CHAOS_IL2CPP_INT32  tdescAlias;
    CHAOS_IL2CPP_INT32  idldescType;
};

// ── FUNCDESC (function descriptor) ──
struct ComFuncDesc {
    CHAOS_IL2CPP_INT32  memid;           // DISPID
    CHAOS_IL2CPP_INT32* lprgscode;
    void**               lprgelemdescParam; // Parameter types (ELEMENT_DESC array)
    CHAOS_IL2CPP_INT32  funckind;
    CHAOS_IL2CPP_INT16  invkind;          // INVOKE_PROPERTYGET=2, INVOKE_PROPERTYPUT=4, INVOKE_PROPERTYPUTREF=8
    CHAOS_IL2CPP_INT16  callconv;
    CHAOS_IL2CPP_INT16  cParams;
    CHAOS_IL2CPP_INT16  cParamsOpt;
    CHAOS_IL2CPP_INT16  oVft;            // Vtable offset
    CHAOS_IL2CPP_INT16  cScodes;
    CHAOS_IL2CPP_INT16  elemdescFunc;     // Return type
    CHAOS_IL2CPP_INT16  wFuncFlags;
};

// ── Static TypeLib data (generated by codegen, stored in module) ──

/// Per-parameter type info for method dispatch.
struct ComParamData {
    const char* name;        // Parameter name (UTF-8)
    CHAOS_IL2CPP_UINT16 vt; // Expected VARIANT type (VT_* constant)
    CHAOS_IL2CPP_UINT16 flags; // Parameter flags (PARAMFLAG_FIN/FOUT/FRETVAL/etc.)
};

/// Per-method descriptor for TypeInfo.
struct ComMethodData {
    const char* name;        // Method name (UTF-8)
    CHAOS_IL2CPP_INT32  disp_id;  // DISPID
    CHAOS_IL2CPP_INT16  c_params; // Parameter count
    CHAOS_IL2CPP_INT16  o_vft;    // Vtable offset (3 = first after IUnknown for non-IDispatch)
    CHAOS_IL2CPP_UINT32 method_token; // Metadata token (for runtime method resolution)
    const ComParamData* params;   // Parameter descriptors
};

/// Static TypeLib descriptor for a single CCW interface (generated by codegen).
struct ComTypeLibData {
    const CHAOS_IL2CPP_UINT8* guid;       // Interface GUID (16 bytes)
    CHAOS_IL2CPP_UINT64 stable_id;        // FNV-1a stable ID
    const char* type_name;                 // Type name (UTF-8)
    const char* type_namespace;            // Type namespace (UTF-8)
    CHAOS_IL2CPP_INT16 method_count;       // Number of methods
    CHAOS_IL2CPP_INT16 is_idispatch;       // Whether this is an IDispatch interface
    const ComMethodData* methods;          // Method descriptors
};

// ── Runtime ITypeInfo/ITypeLib implementations ──

/// Runtime ITypeInfo wrapper.  Provides COM-callable ITypeInfo for a single
/// CCW interface.  One ComTypeInfoImpl is shared by all CCWs of the same type.
struct ComTypeInfoImpl {
    ITypeInfoVtbl* vtable;              // Points to s_type_info_vtbl
    CHAOS_IL2CPP_UINT32 refcount;       // Reference count
    const ComTypeLibData* data;         // Static type data
    ComTypeAttr type_attr;              // Cached TYPEATTR
};

/// Runtime ITypeLib wrapper.  One per module/assembly.
struct ComTypeLibImpl {
    ITypeLibVtbl* vtable;               // Points to s_type_lib_vtbl
    CHAOS_IL2CPP_UINT32 refcount;       // Reference count
    const ComTypeLibData* data;         // Static type data for the single interface
};

// ── Factory functions ──

/// Get or create the ITypeInfo* for a CCW that has typelib_data set.
/// Returns nullptr if typelib_data is not set or on allocation failure.
void* GetComTypeInfoForCcw(com_ccw::ComCcw* ccw) noexcept;

/// Get or create the ITypeLib* for a CCW that has typelib_data set.
/// Returns nullptr if typelib_data is not set or on allocation failure.
void* GetComTypeLibForCcw(com_ccw::ComCcw* ccw) noexcept;

}  // namespace chaos::il2cpp::runtime_core

#endif  // CHAOS_IL2CPP_COM_TYPELIB_H_
