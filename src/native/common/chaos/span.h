#ifndef CHAOS_IL2CPP_COMMON_SPAN_H_
#define CHAOS_IL2CPP_COMMON_SPAN_H_

#include "native_types.h"

#include <cstdint>
#include <cstdlib>
#include <cstring>

namespace chaos::il2cpp::common {

enum class SpanStorageKind : CHAOS_IL2CPP_UINT8
{
    kArray = 1,
    kRawInt32 = 2,
};

struct SpanRuntimeEntry
{
    SpanStorageKind storage_kind = SpanStorageKind::kArray;
    CHAOS_IL2CPP_INTPTR owner_handle = 0;
    CHAOS_IL2CPP_INTPTR data_handle = 0;
    CHAOS_IL2CPP_INT32 start = 0;
    CHAOS_IL2CPP_INT32 length = 0;
    bool read_only = false;
};

struct MemoryRuntimeEntry
{
    CHAOS_IL2CPP_INTPTR array_handle = 0;
    CHAOS_IL2CPP_INT32 start = 0;
    CHAOS_IL2CPP_INT32 length = 0;
};

// --- Basic helper functions (no static field data dependency) ---

SpanRuntimeEntry* require_span_runtime_entry(CHAOS_IL2CPP_INTPTR handle);

MemoryRuntimeEntry* require_memory_runtime_entry(CHAOS_IL2CPP_INTPTR handle);

CHAOS_IL2CPP_INTPTR create_array_span_int32(CHAOS_IL2CPP_INTPTR array_value, CHAOS_IL2CPP_INT32 start, CHAOS_IL2CPP_INT32 length);

CHAOS_IL2CPP_INTPTR create_raw_span_int32(void* data, CHAOS_IL2CPP_INT32 length, bool read_only);

CHAOS_IL2CPP_INTPTR create_memory_int32(CHAOS_IL2CPP_INTPTR array_value);

CHAOS_IL2CPP_INTPTR create_array_memory_int32(CHAOS_IL2CPP_INTPTR array_value, CHAOS_IL2CPP_INT32 start, CHAOS_IL2CPP_INT32 length);

CHAOS_IL2CPP_INTPTR memory_int32_get_span(CHAOS_IL2CPP_INTPTR memory_handle);

CHAOS_IL2CPP_INT32 span_int32_get_length(CHAOS_IL2CPP_INTPTR span_handle);

CHAOS_IL2CPP_INTPTR span_int32_get_item_address(CHAOS_IL2CPP_INTPTR span_handle, CHAOS_IL2CPP_INT32 index);

// --- Functions with static field data dependency (still generated by Scriban template) ---
// initialize_array_from_field_data_int32  — generated by Scriban (requires static field data tables)
// create_field_data_span_int32            — generated by Scriban (requires static field data tables)
// try_get_static_field_data               — generated by Scriban (requires static field data tables)

} // namespace chaos::il2cpp::common

#endif // CHAOS_IL2CPP_COMMON_SPAN_H_
