#ifndef CHAOS_IL2CPP_COMMON_SPAN_H_
#define CHAOS_IL2CPP_COMMON_SPAN_H_

#include <cstdint>
#include <cstdlib>
#include <cstring>

namespace ChaosIl2cpp::Common {

enum class SpanStorageKind : std::uint8_t
{
    kArray = 1,
    kRawInt32 = 2,
};

struct SpanRuntimeEntry
{
    SpanStorageKind storage_kind = SpanStorageKind::kArray;
    std::intptr_t owner_handle = 0;
    std::intptr_t data_handle = 0;
    std::int32_t start = 0;
    std::int32_t length = 0;
    bool read_only = false;
};

struct MemoryRuntimeEntry
{
    std::intptr_t array_handle = 0;
    std::int32_t start = 0;
    std::int32_t length = 0;
};

// --- Basic helper functions (no static field data dependency) ---

SpanRuntimeEntry* require_span_runtime_entry(std::intptr_t handle);

MemoryRuntimeEntry* require_memory_runtime_entry(std::intptr_t handle);

std::intptr_t create_array_span_int32(std::intptr_t array_value, std::int32_t start, std::int32_t length);

std::intptr_t create_raw_span_int32(void* data, std::int32_t length, bool read_only);

std::intptr_t create_memory_int32(std::intptr_t array_value);

std::intptr_t create_array_memory_int32(std::intptr_t array_value, std::int32_t start, std::int32_t length);

std::intptr_t memory_int32_get_span(std::intptr_t memory_handle);

std::int32_t span_int32_get_length(std::intptr_t span_handle);

std::intptr_t span_int32_get_item_address(std::intptr_t span_handle, std::int32_t index);

// --- Functions with static field data dependency (still generated by Scriban template) ---
// initialize_array_from_field_data_int32  — generated by Scriban (requires static field data tables)
// create_field_data_span_int32            — generated by Scriban (requires static field data tables)
// try_get_static_field_data               — generated by Scriban (requires static field data tables)

} // namespace ChaosIl2cpp::Common

#endif // CHAOS_IL2CPP_COMMON_SPAN_H_
