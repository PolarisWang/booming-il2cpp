using Chaos.IL2CPP.Contracts;

namespace Chaos.IL2CPP.HotUpdate;

public sealed class BridgeDispatcher
{
    private readonly Dictionary<string, AotToHotUpdateBridgeEntry> _aotToHotUpdateBridges = new(StringComparer.Ordinal);
    private readonly Dictionary<string, HotUpdateToAotBridgeEntry> _hotUpdateToAotBridges = new(StringComparer.Ordinal);
    private readonly Dictionary<string, HotUpdateToEngineBridgeEntry> _hotUpdateToEngineBridges = new(StringComparer.Ordinal);
    private readonly Dictionary<string, DelegateWrapperEntry> _delegateWrappers = new(StringComparer.Ordinal);
    private readonly Dictionary<string, AutoGeneratedBridgeEntry> _autoGeneratedBridges = new(StringComparer.Ordinal);
    private readonly Dictionary<string, BridgeTargetEntry> _targets = new(StringComparer.Ordinal);

    public void ApplyPlan(BridgePlan plan)
    {
        ArgumentNullException.ThrowIfNull(plan);

        _aotToHotUpdateBridges.Clear();
        _hotUpdateToAotBridges.Clear();
        _hotUpdateToEngineBridges.Clear();
        _delegateWrappers.Clear();
        _autoGeneratedBridges.Clear();
        _targets.Clear();

        foreach (var entry in plan.AotToHotUpdate)
        {
            _aotToHotUpdateBridges[entry.BridgeId] = entry;
        }

        foreach (var entry in plan.HotUpdateToAot)
        {
            _hotUpdateToAotBridges[entry.BridgeId] = entry;
        }

        foreach (var entry in plan.HotUpdateToEngine)
        {
            _hotUpdateToEngineBridges[entry.BridgeId] = entry;
        }

        foreach (var entry in plan.DelegateWrappers)
        {
            _delegateWrappers[entry.WrapperId] = entry;
        }

        RegisterAutoGenerated(plan);
    }

    public void RegisterAutoGenerated(BridgePlan plan)
    {
        ArgumentNullException.ThrowIfNull(plan);

        foreach (var entry in plan.AutoGenerated)
        {
            _autoGeneratedBridges[entry.BridgeId] = entry;
        }
    }

    public void RegisterManagedTarget(ManagedMethodIdentityArtifact identity, Func<IReadOnlyList<object?>, object?> target)
    {
        ArgumentNullException.ThrowIfNull(identity);
        RegisterTargetCore(ManagedMethodIdentityResolver.ResolveExecutionAuthorityKey(identity), target);
    }

    public object? Dispatch(string bridgeId, IReadOnlyList<object?> args)
    {
        ArgumentException.ThrowIfNullOrWhiteSpace(bridgeId);
        ArgumentNullException.ThrowIfNull(args);

        bridgeId = ManagedNaming.NormalizeSubjectIdAssembly(bridgeId);

        var bridge = RequireBridge(_autoGeneratedBridges, bridgeId, "auto-generated");
        var executionAuthorityKey = ResolveTargetAuthorityKey(bridge.TargetIdentity, bridge.TargetAuthorityKey);
        ValidateArgumentCount(bridge, args);

        return bridge.DispatchStyle switch
        {
            BridgeDispatchStyle.ManagedArgs => DispatchManaged(executionAuthorityKey, args),
            BridgeDispatchStyle.ByRefInt32 => DispatchByRefInt32(executionAuthorityKey, args),
            BridgeDispatchStyle.PointerInt32 => DispatchPointerInt32(executionAuthorityKey, args),
            BridgeDispatchStyle.ReadOnlySpanInt32 => DispatchReadOnlySpanInt32(executionAuthorityKey, args),
            _ => throw new InvalidOperationException($"unsupported bridge dispatch style '{bridge.DispatchStyle}'."),
        };
    }

    public void RegisterHotUpdateInt32UnaryTarget(ManagedMethodIdentityArtifact identity, Func<int, int> target)
    {
        ArgumentNullException.ThrowIfNull(identity);
        RegisterHotUpdateInt32UnaryTargetCore(ManagedMethodIdentityResolver.ResolveExecutionAuthorityKey(identity), target);
    }

    public void RegisterAotInt32BinaryTarget(ManagedMethodIdentityArtifact identity, Func<int, int, int> target)
    {
        ArgumentNullException.ThrowIfNull(identity);
        RegisterAotInt32BinaryTargetCore(ManagedMethodIdentityResolver.ResolveExecutionAuthorityKey(identity), target);
    }

    public void RegisterEngineInt32UnaryTarget(ManagedMethodIdentityArtifact identity, Func<int, int> target)
    {
        ArgumentNullException.ThrowIfNull(identity);
        RegisterEngineInt32UnaryTargetCore(ManagedMethodIdentityResolver.ResolveExecutionAuthorityKey(identity), target);
    }

    public void RegisterByRefInt32Target(ManagedMethodIdentityArtifact identity, ByRefInt32BridgeTarget target)
    {
        ArgumentNullException.ThrowIfNull(identity);
        RegisterByRefInt32TargetCore(ManagedMethodIdentityResolver.ResolveExecutionAuthorityKey(identity), target);
    }

    public void RegisterPointerInt32Target(ManagedMethodIdentityArtifact identity, PointerInt32BridgeTarget target)
    {
        ArgumentNullException.ThrowIfNull(identity);
        RegisterPointerInt32TargetCore(ManagedMethodIdentityResolver.ResolveExecutionAuthorityKey(identity), target);
    }

    public void RegisterReadOnlySpanInt32Target(ManagedMethodIdentityArtifact identity, ReadOnlySpanInt32BridgeTarget target)
    {
        ArgumentNullException.ThrowIfNull(identity);
        RegisterReadOnlySpanInt32TargetCore(ManagedMethodIdentityResolver.ResolveExecutionAuthorityKey(identity), target);
    }

    public int InvokeAotToHotUpdateInt32(string bridgeId, int value)
    {
        bridgeId = ManagedNaming.NormalizeSubjectIdAssembly(bridgeId);
        var bridge = RequireBridge(_aotToHotUpdateBridges, bridgeId, "AOT->HotUpdate");
        var target = RequireTargetInt32Unary(
            ResolveTargetAuthorityKey(bridge.HotUpdateIdentity, bridge.HotUpdateAuthorityKey),
            "hot-update unary");
        return target(value);
    }

    public int InvokeHotUpdateToAotInt32(string bridgeId, int left, int right)
    {
        bridgeId = ManagedNaming.NormalizeSubjectIdAssembly(bridgeId);
        var bridge = RequireBridge(_hotUpdateToAotBridges, bridgeId, "HotUpdate->AOT");
        var target = RequireTargetAotInt32Binary(
            ResolveTargetAuthorityKey(bridge.AotIdentity, bridge.AotAuthorityKey),
            "AOT binary");
        return target(left, right);
    }

    public int InvokeHotUpdateToEngineInt32(string bridgeId, int value)
    {
        bridgeId = ManagedNaming.NormalizeSubjectIdAssembly(bridgeId);
        var bridge = RequireBridge(_hotUpdateToEngineBridges, bridgeId, "HotUpdate->Engine");
        var target = RequireTargetInt32Unary(
            ResolveTargetAuthorityKey(bridge.EngineIdentity, bridge.EngineAuthorityKey),
            "engine unary");
        return target(value);
    }

    public Func<int, int> CreateAotDelegateWrapper(string wrapperId)
    {
        wrapperId = ManagedNaming.NormalizeSubjectIdAssembly(wrapperId);
        var wrapper = RequireBridge(_delegateWrappers, wrapperId, "delegate wrapper");
        var target = RequireTargetInt32Unary(
            ResolveTargetAuthorityKey(wrapper.HotUpdateIdentity, wrapper.HotUpdateAuthorityKey),
            "hot-update unary");
        return value => target(value);
    }

    private static string ResolveTargetAuthorityKey(
        ManagedMethodIdentityArtifact? identity,
        string? authorityKey)
    {
        return ResolveAuthorityKey(identity, authorityKey);
    }

    private static string ResolveAuthorityKey(
        ManagedMethodIdentityArtifact? identity,
        string? authorityKey)
    {
        if (!string.IsNullOrWhiteSpace(authorityKey))
        {
            return authorityKey;
        }

        if (identity is not null)
        {
            return ManagedMethodIdentityResolver.ResolveExecutionAuthorityKey(identity);
        }

        throw new InvalidOperationException("bridge dispatch requires an explicit execution authority key.");
    }

    private void RegisterTargetCore(string executionAuthorityKey, Func<IReadOnlyList<object?>, object?> target)
    {
        ArgumentException.ThrowIfNullOrWhiteSpace(executionAuthorityKey);
        ArgumentNullException.ThrowIfNull(target);
        _targets[executionAuthorityKey] = BridgeTargetEntry.Managed(target);
    }

    private void RegisterHotUpdateInt32UnaryTargetCore(string executionAuthorityKey, Func<int, int> target)
    {
        ArgumentException.ThrowIfNullOrWhiteSpace(executionAuthorityKey);
        ArgumentNullException.ThrowIfNull(target);
        _targets[executionAuthorityKey] = BridgeTargetEntry.Int32Unary(target, args =>
        {
            if (args.Count != 1)
            {
                throw new InvalidOperationException($"hot-update unary target '{executionAuthorityKey}' expects 1 argument.");
            }

            return target(Convert.ToInt32(args[0]));
        });
    }

    private void RegisterAotInt32BinaryTargetCore(string executionAuthorityKey, Func<int, int, int> target)
    {
        ArgumentException.ThrowIfNullOrWhiteSpace(executionAuthorityKey);
        ArgumentNullException.ThrowIfNull(target);
        _targets[executionAuthorityKey] = BridgeTargetEntry.AotInt32Binary(target, args =>
        {
            if (args.Count != 2)
            {
                throw new InvalidOperationException($"AOT binary target '{executionAuthorityKey}' expects 2 arguments.");
            }

            return target(Convert.ToInt32(args[0]), Convert.ToInt32(args[1]));
        });
    }

    private void RegisterEngineInt32UnaryTargetCore(string executionAuthorityKey, Func<int, int> target)
    {
        ArgumentException.ThrowIfNullOrWhiteSpace(executionAuthorityKey);
        ArgumentNullException.ThrowIfNull(target);
        _targets[executionAuthorityKey] = BridgeTargetEntry.Int32Unary(target, args =>
        {
            if (args.Count != 1)
            {
                throw new InvalidOperationException($"engine unary target '{executionAuthorityKey}' expects 1 argument.");
            }

            return target(Convert.ToInt32(args[0]));
        });
    }

    private void RegisterByRefInt32TargetCore(string executionAuthorityKey, ByRefInt32BridgeTarget target)
    {
        ArgumentException.ThrowIfNullOrWhiteSpace(executionAuthorityKey);
        ArgumentNullException.ThrowIfNull(target);
        _targets[executionAuthorityKey] = BridgeTargetEntry.ByRefInt32(target);
    }

    private void RegisterPointerInt32TargetCore(string executionAuthorityKey, PointerInt32BridgeTarget target)
    {
        ArgumentException.ThrowIfNullOrWhiteSpace(executionAuthorityKey);
        ArgumentNullException.ThrowIfNull(target);
        _targets[executionAuthorityKey] = BridgeTargetEntry.PointerInt32(target);
    }

    private void RegisterReadOnlySpanInt32TargetCore(string executionAuthorityKey, ReadOnlySpanInt32BridgeTarget target)
    {
        ArgumentException.ThrowIfNullOrWhiteSpace(executionAuthorityKey);
        ArgumentNullException.ThrowIfNull(target);
        _targets[executionAuthorityKey] = BridgeTargetEntry.ReadOnlySpanInt32(target);
    }

    private static void ValidateArgumentCount(AutoGeneratedBridgeEntry bridge, IReadOnlyList<object?> args)
    {
        var expectedCount = bridge.CarrierSchema.ParameterKinds.Count;
        if (args.Count != expectedCount)
        {
            throw new InvalidOperationException(
                $"bridge '{bridge.BridgeId}' expects {expectedCount} argument(s) for dispatch style '{bridge.DispatchStyle}'.");
        }
    }

    private object? DispatchManaged(string executionAuthorityKey, IReadOnlyList<object?> args)
    {
        var entry = RequireTargetEntry(executionAuthorityKey, "managed");
        return entry.ManagedTarget is not null
            ? entry.ManagedTarget(args)
            : throw new InvalidOperationException($"target '{executionAuthorityKey}' does not support managed dispatch.");
    }

    private object? DispatchByRefInt32(string executionAuthorityKey, IReadOnlyList<object?> args)
    {
        if (args[0] is not HotUpdateByRefInt32Carrier carrier)
        {
            throw new InvalidOperationException(
                $"bridge target '{executionAuthorityKey}' expects a {nameof(HotUpdateByRefInt32Carrier)} carrier.");
        }

        var entry = RequireTargetEntry(executionAuthorityKey, "byref-int32");
        var target = entry.ByRefInt32Target
            ?? throw new InvalidOperationException($"target '{executionAuthorityKey}' does not support byref dispatch.");
        var value = carrier.Value;
        target(ref value);
        carrier.Value = value;
        return value;
    }

    private object? DispatchPointerInt32(string executionAuthorityKey, IReadOnlyList<object?> args)
    {
        var pointer = args[0] switch
        {
            HotUpdatePinnedInt32Carrier carrier => carrier.Pointer,
            IntPtr address => address,
            _ => throw new InvalidOperationException(
                $"bridge target '{executionAuthorityKey}' expects a pinned or raw pointer carrier."),
        };

        var entry = RequireTargetEntry(executionAuthorityKey, "pointer-int32");
        var target = entry.PointerInt32Target
            ?? throw new InvalidOperationException($"target '{executionAuthorityKey}' does not support pointer dispatch.");
        return target(pointer);
    }

    private object? DispatchReadOnlySpanInt32(string executionAuthorityKey, IReadOnlyList<object?> args)
    {
        if (args[0] is not HotUpdateReadOnlySpanInt32Carrier carrier)
        {
            throw new InvalidOperationException(
                $"bridge target '{executionAuthorityKey}' expects a {nameof(HotUpdateReadOnlySpanInt32Carrier)} carrier.");
        }

        var entry = RequireTargetEntry(executionAuthorityKey, "readonly-span-int32");
        var target = entry.ReadOnlySpanInt32Target
            ?? throw new InvalidOperationException($"target '{executionAuthorityKey}' does not support readonly-span dispatch.");
        return target(carrier.AsSpan());
    }

    private Func<int, int> RequireTargetInt32Unary(string executionAuthorityKey, string surfaceName)
    {
        var entry = RequireTargetEntry(executionAuthorityKey, surfaceName);
        return entry.Int32UnaryTarget
            ?? throw new InvalidOperationException($"missing {surfaceName} target '{executionAuthorityKey}'.");
    }

    private Func<int, int, int> RequireTargetAotInt32Binary(string executionAuthorityKey, string surfaceName)
    {
        var entry = RequireTargetEntry(executionAuthorityKey, surfaceName);
        return entry.AotInt32BinaryTarget
            ?? throw new InvalidOperationException($"missing {surfaceName} target '{executionAuthorityKey}'.");
    }

    private BridgeTargetEntry RequireTargetEntry(string executionAuthorityKey, string surfaceName)
    {
        if (_targets.TryGetValue(executionAuthorityKey, out var entry))
        {
            return entry;
        }

        throw new InvalidOperationException($"missing {surfaceName} target '{executionAuthorityKey}'.");
    }

    private static TBridge RequireBridge<TBridge>(
        IReadOnlyDictionary<string, TBridge> entries,
        string bridgeId,
        string surfaceName)
    {
        ArgumentException.ThrowIfNullOrWhiteSpace(bridgeId);

        if (entries.TryGetValue(bridgeId, out var entry))
        {
            return entry;
        }

        throw new InvalidOperationException($"missing {surfaceName} bridge '{bridgeId}'.");
    }

    private static TTarget RequireTarget<TTarget>(
        IReadOnlyDictionary<string, TTarget> entries,
        string executionAuthorityKey,
        string surfaceName)
    {
        if (entries.TryGetValue(executionAuthorityKey, out var entry))
        {
            return entry;
        }

        throw new InvalidOperationException($"missing {surfaceName} target '{executionAuthorityKey}'.");
    }
}

internal sealed record BridgeTargetEntry
{
    public enum TargetKind { Managed, Int32Unary, AotInt32Binary, ByRefInt32, PointerInt32, ReadOnlySpanInt32 }

    public TargetKind Kind { get; }
    public Func<IReadOnlyList<object?>, object?>? ManagedTarget { get; }
    public Func<int, int>? Int32UnaryTarget { get; }
    public Func<int, int, int>? AotInt32BinaryTarget { get; }
    public ByRefInt32BridgeTarget? ByRefInt32Target { get; }
    public PointerInt32BridgeTarget? PointerInt32Target { get; }
    public ReadOnlySpanInt32BridgeTarget? ReadOnlySpanInt32Target { get; }

    private BridgeTargetEntry(
        TargetKind kind,
        Func<IReadOnlyList<object?>, object?>? managedTarget = null,
        Func<int, int>? int32UnaryTarget = null,
        Func<int, int, int>? aotInt32BinaryTarget = null,
        ByRefInt32BridgeTarget? byRefInt32Target = null,
        PointerInt32BridgeTarget? pointerInt32Target = null,
        ReadOnlySpanInt32BridgeTarget? readOnlySpanInt32Target = null)
    {
        Kind = kind;
        ManagedTarget = managedTarget;
        Int32UnaryTarget = int32UnaryTarget;
        AotInt32BinaryTarget = aotInt32BinaryTarget;
        ByRefInt32Target = byRefInt32Target;
        PointerInt32Target = pointerInt32Target;
        ReadOnlySpanInt32Target = readOnlySpanInt32Target;
    }

    public static BridgeTargetEntry Managed(Func<IReadOnlyList<object?>, object?> target) =>
        new(TargetKind.Managed, managedTarget: target);

    public static BridgeTargetEntry Int32Unary(Func<int, int> target, Func<IReadOnlyList<object?>, object?> managedWrapper) =>
        new(TargetKind.Int32Unary, managedTarget: managedWrapper, int32UnaryTarget: target);

    public static BridgeTargetEntry AotInt32Binary(Func<int, int, int> target, Func<IReadOnlyList<object?>, object?> managedWrapper) =>
        new(TargetKind.AotInt32Binary, managedTarget: managedWrapper, aotInt32BinaryTarget: target);

    public static BridgeTargetEntry ByRefInt32(ByRefInt32BridgeTarget target) =>
        new(TargetKind.ByRefInt32, byRefInt32Target: target);

    public static BridgeTargetEntry PointerInt32(PointerInt32BridgeTarget target) =>
        new(TargetKind.PointerInt32, pointerInt32Target: target);

    public static BridgeTargetEntry ReadOnlySpanInt32(ReadOnlySpanInt32BridgeTarget target) =>
        new(TargetKind.ReadOnlySpanInt32, readOnlySpanInt32Target: target);
}
