using Chaos.IL2CPP.Contracts;

namespace Chaos.IL2CPP.HotUpdate;

public sealed class AutoBridgeGenerator
{
    public BridgePlan Generate(
        IReadOnlyList<ManagedMethodModel> aotMethods,
        IReadOnlyList<ManagedMethodModel> hotUpdateMethods)
    {
        ArgumentNullException.ThrowIfNull(aotMethods);
        ArgumentNullException.ThrowIfNull(hotUpdateMethods);

        var aotSignatureIndex = aotMethods
            .GroupBy(CreateSignatureKey, StringComparer.Ordinal)
            .ToDictionary(group => group.Key, group => group.ToList(), StringComparer.Ordinal);

        var autoGenerated = new List<AutoGeneratedBridgeEntry>();
        foreach (var method in hotUpdateMethods)
        {
            var signatureKey = CreateSignatureKey(method);
            if (!TryCreateDispatchContract(method, out var dispatchStyle, out var carrierSchema))
            {
                throw new NotSupportedException($"unsupported signature: {CreateDisplaySignature(method)}");
            }

            if (!aotSignatureIndex.ContainsKey(signatureKey))
            {
                throw new NotSupportedException($"unsupported signature: {CreateDisplaySignature(method)}");
            }

            var targetAuthorityKey = ResolveTargetAuthorityKey(method);
            autoGenerated.Add(new AutoGeneratedBridgeEntry
            {
                BridgeId = ManagedNaming.NormalizeSubjectIdAssembly(method.SubjectId),
                TargetAuthorityKey = targetAuthorityKey,
                TargetIdentity = ManagedMethodIdentityResolver.Create(method, executionAuthorityKey: targetAuthorityKey),
                SignatureKey = signatureKey,
                DispatchStyle = dispatchStyle,
                CarrierSchema = carrierSchema,
            });
        }

        return new BridgePlan
        {
            AotToHotUpdate = [],
            HotUpdateToAot = [],
            HotUpdateToEngine = [],
            DelegateWrappers = [],
            AutoGenerated = autoGenerated,
        };
    }

    private static string ResolveTargetAuthorityKey(ManagedMethodModel method)
    {
        ArgumentNullException.ThrowIfNull(method);

        if (!string.IsNullOrWhiteSpace(method.RuntimeGenericContext?.InstantiationStubId.Value))
        {
            return method.RuntimeGenericContext.InstantiationStubId.Value;
        }

        if (!string.IsNullOrWhiteSpace(method.DefinitionSubjectId))
        {
            return method.DefinitionSubjectId;
        }

        return method.SubjectId;
    }

    private static string CreateSignatureKey(ManagedMethodModel method)
    {
        return $"{method.ReturnType}({string.Join(",", method.Parameters.Select(static parameter => parameter.Type))})";
    }

    private static string CreateDisplaySignature(ManagedMethodModel method)
    {
        return $"{method.ReturnType} {method.Name}({string.Join(",", method.Parameters.Select(static parameter => parameter.Type))})";
    }

    private static bool TryCreateDispatchContract(
        ManagedMethodModel method,
        out BridgeDispatchStyle dispatchStyle,
        out BridgeCarrierSchema carrierSchema)
    {
        var signatureKey = CreateSignatureKey(method);
        switch (signatureKey)
        {
            case "System.Void()":
                dispatchStyle = BridgeDispatchStyle.ManagedArgs;
                carrierSchema = CreateSchema(BridgeCarrierKind.Void, [], "none", "none", "call-bounded");
                return true;
            case "System.Int32(System.Int32)":
                dispatchStyle = BridgeDispatchStyle.ManagedArgs;
                carrierSchema = CreateSchema(BridgeCarrierKind.Int32, [BridgeCarrierKind.Int32], "none", "none", "call-bounded");
                return true;
            case "System.Int32(System.Int32,System.Int32)":
                dispatchStyle = BridgeDispatchStyle.ManagedArgs;
                carrierSchema = CreateSchema(
                    BridgeCarrierKind.Int32,
                    [BridgeCarrierKind.Int32, BridgeCarrierKind.Int32],
                    "none",
                    "none",
                    "call-bounded");
                return true;
            case "System.String(System.String)":
                dispatchStyle = BridgeDispatchStyle.ManagedArgs;
                carrierSchema = CreateSchema(BridgeCarrierKind.String, [BridgeCarrierKind.String], "none", "none", "call-bounded");
                return true;
            case "System.Object(System.Object)":
                dispatchStyle = BridgeDispatchStyle.ManagedArgs;
                carrierSchema = CreateSchema(BridgeCarrierKind.Object, [BridgeCarrierKind.Object], "none", "none", "call-bounded");
                return true;
            case "System.Void(System.Int32&)":
                dispatchStyle = BridgeDispatchStyle.ByRefInt32;
                carrierSchema = CreateSchema(
                    BridgeCarrierKind.Void,
                    [BridgeCarrierKind.ByRefInt32],
                    "caller-owned mutable cell",
                    "none",
                    "call-bounded");
                return true;
            case "System.Int32(System.Int32*)":
                dispatchStyle = BridgeDispatchStyle.PointerInt32;
                carrierSchema = CreateSchema(
                    BridgeCarrierKind.Int32,
                    [BridgeCarrierKind.PointerInt32],
                    "pointer-owned memory",
                    "caller pins memory for the call",
                    "call-bounded");
                return true;
            case "System.Int32(System.ReadOnlySpan<System.Int32>)":
                dispatchStyle = BridgeDispatchStyle.ReadOnlySpanInt32;
                carrierSchema = CreateSchema(
                    BridgeCarrierKind.Int32,
                    [BridgeCarrierKind.ReadOnlySpanInt32],
                    "none",
                    "none",
                    "call-bounded");
                return true;
            default:
                dispatchStyle = BridgeDispatchStyle.ManagedArgs;
                carrierSchema = null!;
                return false;
        }
    }

    private static BridgeCarrierSchema CreateSchema(
        BridgeCarrierKind returnKind,
        BridgeCarrierKind[] parameterKinds,
        string writeBackRule,
        string pinningRule,
        string lifetimeRule)
    {
        return new BridgeCarrierSchema
        {
            ReturnKind = returnKind,
            ParameterKinds = parameterKinds,
            WriteBackRule = writeBackRule,
            PinningRule = pinningRule,
            LifetimeRule = lifetimeRule,
        };
    }
}
