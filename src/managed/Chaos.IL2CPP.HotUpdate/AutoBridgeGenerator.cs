using Chaos.IL2CPP.Contracts;

namespace Chaos.IL2CPP.HotUpdate;

public sealed class AutoBridgeGenerator
{
    public BridgePlan Generate(
        IReadOnlyList<ManagedMethodModel> aotMethods,
        IReadOnlyList<ManagedMethodModel> hotUpdateMethods)
    {
        ArgumentNullException.ThrowIfNull(aotMethods);
        ArgumentNullException.ThrowIfNull(hotUpdateMethods);

        var supportedSignatures = new HashSet<string>(StringComparer.Ordinal)
        {
            "System.Void()",
            "System.Int32(System.Int32)",
            "System.Int32(System.Int32,System.Int32)",
            "System.String(System.String)",
            "System.Object(System.Object)",
        };

        var aotSignatureIndex = aotMethods
            .GroupBy(CreateSignatureKey, StringComparer.Ordinal)
            .ToDictionary(group => group.Key, group => group.ToList(), StringComparer.Ordinal);

        var autoGenerated = new List<AutoGeneratedBridgeEntry>();
        foreach (var method in hotUpdateMethods)
        {
            var signatureKey = CreateSignatureKey(method);
            if (!supportedSignatures.Contains(signatureKey))
            {
                throw new NotSupportedException($"unsupported signature: {CreateDisplaySignature(method)}");
            }

            if (!aotSignatureIndex.ContainsKey(signatureKey))
            {
                throw new NotSupportedException($"unsupported signature: {CreateDisplaySignature(method)}");
            }

            autoGenerated.Add(new AutoGeneratedBridgeEntry
            {
                BridgeId = method.SubjectId,
                TargetSubjectId = method.SubjectId,
                SignatureKey = signatureKey,
            });
        }

        return new BridgePlan
        {
            AotToHotUpdate = [],
            HotUpdateToAot = [],
            HotUpdateToEngine = [],
            DelegateWrappers = [],
            AutoGenerated = autoGenerated,
        };
    }

    private static string CreateSignatureKey(ManagedMethodModel method)
    {
        return $"{method.ReturnType}({string.Join(",", method.Parameters.Select(static parameter => parameter.Type))})";
    }

    private static string CreateDisplaySignature(ManagedMethodModel method)
    {
        return $"{method.ReturnType} {method.Name}({string.Join(",", method.Parameters.Select(static parameter => parameter.Type))})";
    }
}
