using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using Chaos.IL2CPP.Contracts;

namespace Chaos.IL2CPP.Generator;

public sealed partial class NativeAotLoweringPlanner
{
    /// <summary>
    /// Build the GC slot map section — a single anonymous struct containing
    /// one nested struct entry per managed method with GC-referencing slots.
    ///
    /// Each entry matches the runtime layout expected by
    /// GcRegisterSlotMapsFromSection():
    ///   [GcSlotMapSectionEntryHdrV0]  → uint32_t entry_total_size + const void* code_address
    ///   [GcSlotMapV0 body]            → uint32_t frame_size + uint32_t num_gc_slots
    ///   [slots data]                  → uint32_t slots[num_gc_slots]
    ///
    /// Because the entries are nested within a single anonymous struct, they
    /// form a single contiguous memory range — no padding between entries
    /// since all fields are naturally aligned (uint32_t + pointer + uint32_t
    /// + uint32_t + uint32_t[]).
    ///
    /// Methods with zero GC-referencing slots are skipped (scanned
    /// conservatively at runtime).  P/Invoke wrappers are also skipped.
    /// </summary>
    internal string BuildGcSlotMapSection(IReadOnlyList<AotCoreIrMethodArtifact> methods)
    {
        const int PtrSize = 8; // 64-bit only

        // ── Pass 1: compute per-method slot info ──
        var entries = new List<(string NativeSymbol, uint FrameSize, uint[] SlotOffsets)>();

        foreach (var method in methods)
        {
            if (method.IsPInvoke || method.Instructions.Count == 0)
                continue;

            var abiSlots = GetMethodAbiParameterSlots(method);
            int paramCount = abiSlots.Count;
            int localCount = method.LocalCount;

            int evalStackSize = 0;
            try
            {
                evalStackSize = Math.Max(ComputeMaxEvalStackDepth(method.Instructions), 0);
            }
            catch { evalStackSize = 0; }

            // Hypothetical contiguous layout: [args][locals][eval_stack]
            uint localsBase = (uint)paramCount * (uint)PtrSize;
            uint evalBase = localsBase + (uint)localCount * (uint)PtrSize;
            uint frameSize = evalBase + (uint)evalStackSize * (uint)PtrSize;

            if (frameSize == 0)
                continue;

            var slotSet = new HashSet<uint>();

            // Parameters: only ReferenceType and InterfaceType carry GC refs.
            for (int i = 0; i < paramCount; i++)
            {
                var shape = abiSlots[i].TypeShape;
                if (shape is AotCoreIrTypeShapeKind.ReferenceType or AotCoreIrTypeShapeKind.InterfaceType)
                    slotSet.Add((uint)i * (uint)PtrSize);
            }

            // Locals: conservatively all (no per-local type tracking yet).
            for (int i = 0; i < localCount; i++)
                slotSet.Add(localsBase + (uint)i * (uint)PtrSize);

            // Eval stack: conservatively all.
            for (int i = 0; i < evalStackSize; i++)
                slotSet.Add(evalBase + (uint)i * (uint)PtrSize);

            if (slotSet.Count == 0)
                continue;

            entries.Add((method.NativeSymbol, frameSize, slotSet.OrderBy(s => s).ToArray()));
        }

        if (entries.Count == 0)
        {
            return
                "// ── GC Slot Map Section (empty) ───────────────────────────────\n" +
                "static const CHAOS_IL2CPP_UINT8 kChaosGcSlotMapsSection[1] = { 0 };\n" +
                "static const CHAOS_IL2CPP_UINT32 kChaosGcSlotMapsSize = 0;\n";
        }

        // ── Pass 2: emit the outer anonymous struct ──
        var sb = new StringBuilder(8192);
        sb.AppendLine("// ── GC Slot Map Section ───────────────────────────────────────────");
        sb.AppendLine("// Auto-generated by chaos-il2cpp codegen for precise stack root scanning.");
        sb.AppendLine("// One nested struct entry per method with GC-referencing stack slots.");
        sb.AppendLine("// Iterated by GcRegisterSlotMapsFromSection() which advances by");
        sb.AppendLine("// entry_total_size bytes per entry.");
        sb.AppendLine("#if defined(_MSC_VER)");
        sb.AppendLine("#pragma pack(push, 1)");
        sb.AppendLine("#endif");
        sb.AppendLine("#if defined(__GNUC__) || defined(__clang__)");
        sb.AppendLine("static const struct __attribute__((packed)) {");
        sb.AppendLine("#else");
        sb.AppendLine("static const struct {");
        sb.AppendLine("#endif");

        // Emit a nested struct for each entry.
        int totalBytes = 0;
        for (int ei = 0; ei < entries.Count; ei++)
        {
            var (nativeSymbol, frameSize, slotOffsets) = entries[ei];
            int numSlots = slotOffsets.Length;
            int entryBytes = 4 + PtrSize + 4 + 4 + numSlots * 4;

            sb.AppendLine("");
            sb.AppendLine("    /* ── Entry " + ei + ": " + nativeSymbol + " ── */");
            sb.AppendLine("    struct {");
            sb.AppendLine("        CHAOS_IL2CPP_UINT32 entry_total_size;");
            sb.AppendLine("        const void*         code_address;");
            sb.AppendLine("        CHAOS_IL2CPP_UINT32 frame_size;");
            sb.AppendLine("        CHAOS_IL2CPP_UINT32 num_gc_slots;");
            sb.AppendLine("        CHAOS_IL2CPP_UINT32 slots[" + numSlots + "];");
            sb.Append("    } entry" + ei + ";");

            totalBytes += entryBytes;
        }

        sb.AppendLine();
        sb.AppendLine("} kChaosGcSlotMapsSection = {");

        // ── Initializer values ──
        for (int ei = 0; ei < entries.Count; ei++)
        {
            var (nativeSymbol, frameSize, slotOffsets) = entries[ei];
            int numSlots = slotOffsets.Length;
            int entryBytes = 4 + PtrSize + 4 + 4 + numSlots * 4;

            if (ei > 0)
                sb.AppendLine(",");

            sb.AppendLine("    /* entry" + ei + " = " + nativeSymbol + " */");
            sb.AppendLine("    .entry" + ei + " = {");

            // entry_total_size
            sb.Append("        /* entry_total_size = " + entryBytes + " */ ");
            sb.Append(entryBytes).Append("u,");
            sb.AppendLine();

            // code_address
            sb.Append("        /* code_address */ ");
            sb.Append("reinterpret_cast<const void*>(&").Append(nativeSymbol).Append("),");
            sb.AppendLine();

            // frame_size
            sb.Append("        /* frame_size = " + frameSize + " */ ");
            sb.Append(frameSize).Append("u,");
            sb.AppendLine();

            // num_gc_slots
            sb.Append("        /* num_gc_slots = " + numSlots + " */ ");
            sb.Append(numSlots).Append("u,");
            sb.AppendLine();

            // slots[]
            sb.Append("        /* slots */ { ");
            for (int si = 0; si < slotOffsets.Length; si++)
            {
                if (si > 0) sb.Append(", ");
                sb.Append(slotOffsets[si]).Append("u");
            }
            sb.Append(" }");

            sb.AppendLine();
            sb.Append("    }");
        }

        sb.AppendLine();
        sb.AppendLine("};");
        sb.AppendLine("#if defined(_MSC_VER)");
        sb.AppendLine("#pragma pack(pop)");
        sb.AppendLine("#endif");
        sb.AppendLine();

        // Total size constant for CodeRegistrationV0 slot_map_section_end.
        sb.Append("static const CHAOS_IL2CPP_UINT32 kChaosGcSlotMapsSize = ")
            .Append(totalBytes)
            .AppendLine("u;");

        return sb.ToString();
    }
}
