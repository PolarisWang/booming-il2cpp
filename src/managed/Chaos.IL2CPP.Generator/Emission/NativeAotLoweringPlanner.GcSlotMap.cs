using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using Chaos.IL2CPP.Contracts;

namespace Chaos.IL2CPP.Generator;

public sealed partial class NativeAotLoweringPlanner
{
    /// <summary>
    /// Build the GC slot map section — a single anonymous struct containing
    /// one nested struct entry per managed method with GC-referencing slots.
    ///
    /// Each entry matches the runtime layout expected by
    /// GcRegisterSlotMapsFromSection():
    ///   [GcSlotMapSectionEntryHdrV0]  → uint32_t entry_total_size + const void* code_address
    ///   [GcSlotMapV0 body]            → uint32_t frame_size + uint32_t num_gc_slots
    ///   [slots data]                  → uint32_t slots[num_gc_slots]
    ///
    /// Because the entries are nested within a single anonymous struct, they
    /// form a single contiguous memory range — no padding between entries
    /// since all fields are naturally aligned (uint32_t + pointer + uint32_t
    /// + uint32_t + uint32_t[]).
    ///
    /// Methods with zero GC-referencing slots are skipped (scanned
    /// conservatively at runtime).  P/Invoke wrappers are also skipped.
    /// </summary>
    internal string BuildGcSlotMapSection(IReadOnlyList<AotCoreIrMethodArtifact> methods)
    {
        const int PtrSize = 8; // 64-bit only

        // ── Pass 1: compute per-method slot info ──
        var entries = new List<(string NativeSymbol, uint FrameSize, uint[] SlotOffsets)>();

        foreach (var method in methods)
        {
            if (method.IsPInvoke || method.Instructions.Count == 0)
                continue;

            var abiSlots = GetMethodAbiParameterSlots(method);
            int paramCount = abiSlots.Count;
            int localCount = method.LocalCount;

            int evalStackSize = 0;
            try
            {
                evalStackSize = Math.Max(ComputeMaxEvalStackDepth(method.Instructions), 0);
            }
            catch { evalStackSize = 0; }

            // Hypothetical contiguous layout: [args][locals][eval_stack]
            uint localsBase = (uint)paramCount * (uint)PtrSize;
            uint evalBase = localsBase + (uint)localCount * (uint)PtrSize;
            uint frameSize = evalBase + (uint)evalStackSize * (uint)PtrSize;

            if (frameSize == 0)
                continue;

            var slotSet = new HashSet<uint>();

            // Parameters: only ReferenceType and InterfaceType carry GC refs.
            for (int i = 0; i < paramCount; i++)
            {
                var shape = abiSlots[i].TypeShape;
                if (shape is AotCoreIrTypeShapeKind.ReferenceType or AotCoreIrTypeShapeKind.InterfaceType)
                    slotSet.Add((uint)i * (uint)PtrSize);
            }

            // Locals: conservatively all (no per-local type tracking yet).
            for (int i = 0; i < localCount; i++)
                slotSet.Add(localsBase + (uint)i * (uint)PtrSize);

            // Eval stack: conservatively all.
            for (int i = 0; i < evalStackSize; i++)
                slotSet.Add(evalBase + (uint)i * (uint)PtrSize);

            if (slotSet.Count == 0)
                continue;

            entries.Add((method.NativeSymbol, frameSize, slotSet.OrderBy(s => s).ToArray()));
        }

        if (entries.Count == 0)
        {
            // `extern` for the same reason as the populated path below: the
            // CodeRegistration section takes these symbols' addresses from its own
            // translation unit once the payload is split, so internal linkage would
            // leave every reference undefined.
            RegisterCrossSectionSymbol(
                "kChaosGcSlotMapsSection",
                "extern const CHAOS_IL2CPP_UINT8 kChaosGcSlotMapsSection[];",
                needsExternalLinkage: true);
            RegisterCrossSectionSymbol(
                "kChaosGcSlotMapsSize",
                "extern const CHAOS_IL2CPP_UINT32 kChaosGcSlotMapsSize;",
                needsExternalLinkage: true);

            return
                "// ── GC Slot Map Section (empty) ───────────────────────────────\n" +
                "extern const CHAOS_IL2CPP_UINT8 kChaosGcSlotMapsSection[1] = { 0 };\n" +
                "extern const CHAOS_IL2CPP_UINT32 kChaosGcSlotMapsSize = 0;\n";
        }

        // ── Pass 2: emit the packed struct + its single instance ──
        var sb = new StringBuilder(8192);

        // Total packed size of every entry, computed up front: the struct is
        // declared as one uint32 array of exactly this many words, and the same
        // value is published as kChaosGcSlotMapsSize for
        // CodeRegistrationV0.slot_map_section_end.
        int totalBytes = 0;
        foreach (var (_, _, slotOffsets) in entries)
            totalBytes += 4 + PtrSize + 4 + 4 + slotOffsets.Length * 4;

        sb.AppendLine("// ── GC Slot Map Section ───────────────────────────────────────────");
        sb.AppendLine("// Auto-generated by chaos-il2cpp codegen for precise stack root scanning.");
        sb.AppendLine("// One entry per method with GC-referencing stack slots, stored as a flat");
        sb.AppendLine("// packed word array. Iterated by GcRegisterSlotMapsFromSection() which");
        sb.AppendLine("// advances by entry_total_size bytes per entry.");
        sb.AppendLine("//");
        sb.AppendLine("// Layout per entry (packed, little-endian):");
        sb.AppendLine("//   [+0]  entry_total_size : u32");
        sb.AppendLine("//   [+4]  code_address     : pointer, splatted as lo32/hi32");
        sb.AppendLine("//   [+12] frame_size       : u32");
        sb.AppendLine("//   [+16] num_gc_slots     : u32");
        sb.AppendLine("//   [+20] slots[N]         : u32");
        sb.AppendLine("// The runtime reinterprets +12 as GcSlotMapV0, so this order is the");
        sb.AppendLine("// contract; the member NAMES below are not (nothing reads them).");
        sb.AppendLine("static_assert(sizeof(void*) == 8, \"slot maps are emitted for 64-bit targets\");");
        sb.AppendLine("");
        sb.AppendLine("// Splat a code address into two 32-bit words so it can live in the");
        sb.AppendLine("// uint32 array below. Taking &sym keeps the native symbol referenced.");
        sb.AppendLine("static CHAOS_IL2CPP_UINT32 chaos_ptr_lo32(const void* p) noexcept");
        sb.AppendLine("{");
        sb.AppendLine("    return static_cast<CHAOS_IL2CPP_UINT32>(reinterpret_cast<CHAOS_IL2CPP_UINTPTR>(p) & 0xFFFFFFFFu);");
        sb.AppendLine("}");
        sb.AppendLine("static CHAOS_IL2CPP_UINT32 chaos_ptr_hi32(const void* p) noexcept");
        sb.AppendLine("{");
        sb.AppendLine("    return static_cast<CHAOS_IL2CPP_UINT32>(reinterpret_cast<CHAOS_IL2CPP_UINTPTR>(p) >> 32);");
        sb.AppendLine("}");
        sb.AppendLine("");
        sb.AppendLine("#if defined(_MSC_VER)");
        sb.AppendLine("#pragma pack(push, 1)");
        sb.AppendLine("#endif");
        // The struct is NAMED, and the instance is `extern`, so a declaration can
        // be published for consumers in other translation units. An anonymous
        // struct could not be declared at all — the only available stand-in
        // (`extern const char x[]`) collides with the real definition whenever
        // the definer and a consumer share a TU (C2373: redefinition, different
        // type modifiers), and which sections share a TU depends on partitioning.
        // Naming the type makes the declaration exact and independent of layout.
        sb.AppendLine("#if defined(__GNUC__) || defined(__clang__)");
        sb.AppendLine("struct __attribute__((packed)) ChaosGcSlotMapsSectionV0 {");
        sb.AppendLine("#else");
        sb.AppendLine("struct ChaosGcSlotMapsSectionV0 {");
        sb.AppendLine("#endif");

        // The entries are one flat byte blob, NOT one named nested struct each.
        //
        // The nested-struct form declared five members per entry (`entry0`,
        // `entry1`, … `entry1719`) and cost ~237 characters each — 408,451
        // characters on the system chunk, 52% of a 785,725-character translation
        // unit, against a 350,000 per-TU budget.
        //
        // None of that text was load-bearing. The only consumer is
        // GcRegisterSlotMapsFromSection (gc_root_scanner.cpp), which walks the
        // object as PACKED BYTES: it reads `entry_total_size` at ptr+0, advances
        // by it, and reinterprets ptr+12 as GcSlotMapV0. Grep confirms no reader
        // anywhere names `entryN` or any member of the outer struct. The field
        // ORDER is the contract, not the member names — so the layout below is
        // byte-identical to the nested form while costing one line for the whole
        // section.
        //
        // The outer struct stays NAMED and the instance stays `extern`: consumers
        // in other translation units take its address, and the contract header
        // publishes `struct ChaosGcSlotMapsSectionV0;` as an incomplete type. That
        // requirement is why the type cannot become anonymous — see the note above
        // — but it says nothing about the members.
        sb.Append("    CHAOS_IL2CPP_UINT32 entries[")
          .Append(totalBytes / 4)
          .AppendLine("];");

        // Close the struct definition and open the single instance. The `extern`
        // (no `static`) is what lets consumers in other payload translation units
        // take its address; the named struct above is what makes the declaration
        // in the contract header an exact match rather than a lookalike.
        sb.AppendLine();
        sb.AppendLine("};");
        sb.AppendLine();
        sb.AppendLine("extern const ChaosGcSlotMapsSectionV0 kChaosGcSlotMapsSection = {");

        // ── Initializer values ──
        //
        // One flat, brace-nested list of uint32 words with the entry's
        // `code_address` splatted as two 32-bit halves — the object is declared as
        // a uint32 array, so a `const void*` cannot appear in its initializer.
        // Little-endian halves reproduce the pointer bytes exactly on the
        // supported targets (x64/arm64, both LE); a static_assert in the emitted
        // TU pins that assumption.
        //
        // Address-of the native symbol is still taken (`&sym`), so the linker
        // keeps the function and the runtime's `code_address` is unchanged.
        for (int ei = 0; ei < entries.Count; ei++)
        {
            var (nativeSymbol, frameSize, slotOffsets) = entries[ei];
            int numSlots = slotOffsets.Length;
            int entryBytes = 4 + PtrSize + 4 + 4 + numSlots * 4;

            sb.Append("    /* entry").Append(ei).Append(" */ ");

            // FLAT word list, not a brace-nested entry list: `entries` is a
            // scalar array (CHAOS_IL2CPP_UINT32[]), so nesting an entry's words in
            // `{ … }` is C2078 "too many initializers" — a scalar array aggregates
            // positionally with no sub-aggregates. The entry boundary is still
            // recoverable by the reader via entry_total_size, and the `/* entryN */`
            // comment marks it in the source.
            sb.Append(entryBytes).Append("u, ");
            // code_address, splatted into two 32-bit words.
            sb.Append("chaos_ptr_lo32(&").Append(nativeSymbol).Append("), ");
            sb.Append("chaos_ptr_hi32(&").Append(nativeSymbol).Append("), ");
            sb.Append(frameSize).Append("u, ")
              .Append(numSlots).Append("u, ");
            for (int si = 0; si < slotOffsets.Length; si++)
            {
                sb.Append(slotOffsets[si]).Append("u, ");
            }
            sb.AppendLine();
        }

        sb.AppendLine();
        sb.AppendLine("};");
        sb.AppendLine("#if defined(_MSC_VER)");
        sb.AppendLine("#pragma pack(pop)");
        sb.AppendLine("#endif");
        sb.AppendLine();

        // Total size constant for CodeRegistrationV0 slot_map_section_end.
        // `extern` for the same cross-TU reason as the section symbol above.
        sb.Append("extern const CHAOS_IL2CPP_UINT32 kChaosGcSlotMapsSize = ")
            .Append(totalBytes)
            .AppendLine("u;");

        // Publish both symbols so every payload translation unit can see them.
        // The struct's full definition lives only in this section, but consumers
        // in other TUs only take the object's ADDRESS, for which an incomplete
        // type suffices — and a forward declaration is legal even alongside the
        // full definition in the defining TU. (Declaring the object through a
        // stand-in type instead, e.g. `char[]`, is not: that collides with the
        // real definition whenever both land in one TU, C2373.)
        RegisterCrossSectionSymbol(
            "ChaosGcSlotMapsSectionV0",
            "struct ChaosGcSlotMapsSectionV0;",
            needsExternalLinkage: false);
        RegisterCrossSectionSymbol(
            "kChaosGcSlotMapsSection",
            "extern const ChaosGcSlotMapsSectionV0 kChaosGcSlotMapsSection;",
            needsExternalLinkage: true);
        RegisterCrossSectionSymbol(
            "kChaosGcSlotMapsSize",
            "extern const CHAOS_IL2CPP_UINT32 kChaosGcSlotMapsSize;",
            needsExternalLinkage: true);

        return sb.ToString();
    }
}
