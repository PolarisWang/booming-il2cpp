using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;

namespace Chaos.IL2CPP.Generator;

/// <summary>
/// Extracts enum type metadata from the AOT IR at codegen time and generates
/// static C++ arrays for field names/values, enabling runtime stubs to bypass
/// the reflection API chain (resolve_type_arg → TryDecodeReflectionQueryTypeHandle).
///
/// Alignment: Unity IL2CPP codegen embedment model — enum metadata is frozen
/// at build time in static constexpr C arrays, zero runtime reflection overhead.
/// </summary>
internal static class EnumMetadataExtractor
{
    private const uint KFlagIsEnum = 1u << 1;

    /// <summary>
    /// Generate the C++ header content containing static enum metadata tables
    /// and a lookup function keyed by FNV-1a 32-bit hash of the type subject_id.
    /// </summary>
    public static string GenerateHeader(
        IReadOnlyList<uint> moduleTypeFlags,
        IReadOnlyList<string> moduleTypeSubjectIds,
        IReadOnlyList<NativeAotLoweringPlanner.ReflectionMemberFieldEntry> fieldEntries)
    {
        var sb = new StringBuilder(16384);
        sb.AppendLine("// Auto-generated enum metadata tables — do not edit.");
        sb.AppendLine("// Generated by EnumMetadataExtractor at codegen time.");
        sb.AppendLine("#pragma once");
        sb.AppendLine();
        sb.AppendLine("#include <cstdint>");
        sb.AppendLine("#include <cstring>");
        sb.AppendLine();
        sb.AppendLine("// Types EnumFieldEntry/EnumMetadataTable defined in generated_code_compat.h.");
        sb.AppendLine("// Forward-declare ReflectionQueryTypeDescriptor (defined in reflection_query_model.h");
        sb.AppendLine("// in runtime-core). We only need its first fields: metadata_token + subject_id_utf8.");
        sb.AppendLine("namespace chaos { namespace il2cpp { namespace runtime_core {");
        sb.AppendLine("struct ReflectionQueryTypeDescriptor;");
        sb.AppendLine("}}}");
        sb.AppendLine();
        sb.AppendLine("// Minimal type descriptor with same initial layout as ReflectionQueryTypeDescriptor.");
        sb.AppendLine("// Only metadata_token (offset 0) and subject_id_utf8 (offset 8) need to be valid");
        sb.AppendLine("// for enum_resolve_meta to extract the subject_id. Everything else is zero.");
        sb.AppendLine("struct EnumTypeDescriptor {");
        sb.AppendLine("    CHAOS_IL2CPP_UINT32 metadata_token;");
        sb.AppendLine("    CHAOS_IL2CPP_UINT32 _padding;");
        sb.AppendLine("    const char* subject_id_utf8;");
        sb.AppendLine("};");
        sb.AppendLine();
        sb.AppendLine("// Registration function defined in runtime-core/reflection/type_resolve.cpp.");
        sb.AppendLine("extern \"C\" void ChaosRegisterExternalType(");
        sb.AppendLine("    CHAOS_IL2CPP_UINT32 fnv24_hash,");
        sb.AppendLine("    const chaos::il2cpp::runtime_core::ReflectionQueryTypeDescriptor* type_desc) noexcept;");
        sb.AppendLine();
        sb.AppendLine("// ── Enum dispatch entry struct (file scope for extern \"C\" access) ──");
        sb.AppendLine("#ifndef CHAOS_IL2CPP_ENUM_DISPATCH_ENTRY_DEFINED");
        sb.AppendLine("#define CHAOS_IL2CPP_ENUM_DISPATCH_ENTRY_DEFINED");
        sb.AppendLine("struct EnumDispatchEntry {");
        sb.AppendLine("    CHAOS_IL2CPP_UINT32 fnv24;");
        sb.AppendLine("    const EnumMetadataTable* table;");
        sb.AppendLine("};");
        sb.AppendLine("#endif");
        sb.AppendLine();
        sb.AppendLine("// Dispatch table registration defined in enum_stubs.cpp.");
        sb.AppendLine("// Registers a sorted FNV-24 dispatch table for fast metadata lookup.");
        sb.AppendLine("extern \"C\" void ChaosEnumRegisterDispatchTable(");
        sb.AppendLine("    const EnumDispatchEntry* entries, CHAOS_IL2CPP_UINT32 count) noexcept;");
        sb.AppendLine();
        sb.AppendLine("namespace chaos { namespace il2cpp { namespace codegen {");
        sb.AppendLine();

        // ── Collect enum types with their field data ────────────────────────
        var enumTypes = new List<EnumTypeData>();
        for (int i = 0; i < moduleTypeFlags.Count && i < moduleTypeSubjectIds.Count; i++)
        {
            if ((moduleTypeFlags[i] & KFlagIsEnum) == 0)
                continue;

            var subjectId = moduleTypeSubjectIds[i];
            if (string.IsNullOrEmpty(subjectId))
                continue;

            var fields = fieldEntries
                .Where(f => string.Equals(f.DeclaringTypeSubjectId, subjectId, StringComparison.Ordinal)
                         && f.ConstantValue.HasValue)
                .Select(f => new EnumFieldData(f.FieldName, f.ConstantValue!.Value))
                .OrderBy(f => f.Value)
                .ToList();

            // Skip the implicit "value__" field (constant_value is typically
            // the first field in metadata but has no semantic meaning for name lookup).
            // The filter above already excludes fields without ConstantValue,
            // which naturally drops "value__" in well-formed metadata where
            // only the instance field lacks a constant.  As a safety net,
            // also explicitly filter out "value__" if it somehow has a value.
            fields = fields.Where(f => !string.Equals(f.Name, "value__", StringComparison.Ordinal)).ToList();

            if (fields.Count == 0)
                continue;

            enumTypes.Add(new EnumTypeData(subjectId, fields));
        }

        if (enumTypes.Count == 0)
        {
            sb.AppendLine("// No enum types found in this closure.");
            sb.AppendLine("}}}  // namespace chaos::il2cpp::codegen");
            sb.AppendLine();
            return sb.ToString();
        }

        // ── Emit per-enum field entry arrays ───────────────────────────────
        // Note: EnumFieldEntry/EnumMetadataTable types defined in generated_code_compat.h.

        // Build C++ identifier for each enum type
        var typeIds = new Dictionary<string, string>(StringComparer.Ordinal);
        var hashToIdentifier = new Dictionary<uint, string>();

        for (int i = 0; i < enumTypes.Count; i++)
        {
            var et = enumTypes[i];
            var safeId = SanitizeToCppIdentifier(et.SubjectId);
            // Ensure uniqueness
            var uniqueId = safeId;
            int counter = 1;
            while (typeIds.ContainsValue(uniqueId))
                uniqueId = $"{safeId}_{counter++}";
            typeIds[et.SubjectId] = uniqueId;

            // Emit field array
            sb.AppendLine($"// ── Enum: {et.SubjectId} ──────────────────────────────");
            sb.AppendLine($"static constexpr EnumFieldEntry kEnumFields_{uniqueId}[] = {{");

            foreach (var field in et.Fields)
            {
                sb.AppendLine($"    {{ \"{EscapeCppString(field.Name)}\", {field.Value} }},");
            }

            sb.AppendLine("};");
            sb.AppendLine();

            // Emit metadata table
            sb.AppendLine($"static constexpr EnumMetadataTable kEnumTable_{uniqueId} = {{");
            sb.AppendLine($"    kEnumFields_{uniqueId}, {et.Fields.Count}");
            sb.AppendLine("};");
            sb.AppendLine();

            // ── Pre-allocated global string pointer array ────────────────────
            // Zero-initialized at program start. Populated once at static init
            // time by ChaosRegisterEnumGeneratedMetadata via ChaosEnumPreInitStringCache.
            // After that, ensure_enum_str_cache reads from this array and skips
            // lazy POH allocation — zero GC allocation on the hot path.
            sb.AppendLine($"// Pre-allocated managed string pointers for {et.SubjectId}.");
            sb.AppendLine($"// Populated at static init time via ChaosEnumPreInitStringCache.");
            sb.AppendLine($"// Zero-initialized: not yet populated; non-zero => pre-allocated.");
            sb.AppendLine($"static CHAOS_IL2CPP_INTPTR kEnumStrings_{uniqueId}[{et.Fields.Count}] = {{}};");
            sb.AppendLine();

            // Emit minimal type descriptor (matching ReflectionQueryTypeDescriptor layout)
            sb.AppendLine($"static constexpr EnumTypeDescriptor kEnumTypeDesc_{uniqueId} = {{");
            sb.AppendLine($"    0u,");
            sb.AppendLine($"    0u,");
            sb.AppendLine($"    \"{EscapeCppString(et.SubjectId)}\"");
            sb.AppendLine("};");
            sb.AppendLine();

            // Emit per-enum ToString switch function (returns CHAOS_IL2CPP_STRING_ID on match, 0 on miss)
            sb.AppendLine($"/// Per-enum ToString dispatch for {et.SubjectId} ({et.Fields.Count} fields).");
            sb.AppendLine($"/// Returns compile-time string constant on match, 0 for unrecognized values");
            sb.AppendLine($"/// (caller falls through to decimal formatting).");
            sb.AppendLine($"static CHAOS_IL2CPP_INTPTR ChaosEnumToString_{uniqueId}(CHAOS_IL2CPP_INT64 value) noexcept {{");
            foreach (var field in et.Fields)
            {
                sb.AppendLine($"    if (value == {field.Value}) return CHAOS_IL2CPP_STRING_ID(\"{EscapeCppString(field.Name)}\");");
            }
            sb.AppendLine("    return 0;  // unrecognized value → caller falls through to decimal");
            sb.AppendLine("}");
            sb.AppendLine();

            // Compute FNV-1a 32-bit hash with collision detection
            uint hash = ComputeFnv1a32(et.SubjectId);
            if (hashToIdentifier.TryGetValue(hash, out var existing))
            {
                Console.Error.WriteLine($"[WARNING] FNV-1a 32-bit hash collision between " +
                    $"'{existing}' and '{uniqueId}'. The second type falls back to reflection API.");
            }
            else
            {
                hashToIdentifier[hash] = uniqueId;
            }
        }

        // ── Build 24-bit hash (fnv24) map with collision detection ──────────
        // 24-bit collisions cause duplicate entries in the dispatch table,
        // so they MUST be resolved (build-time #error below).
        var fnv24ToIdentifier = new Dictionary<uint, string>();
        int fnv24CollisionCount = 0;
        foreach (var kv in hashToIdentifier)
        {
            uint fnv24 = kv.Key & 0xFFFFFFu;
            if (fnv24ToIdentifier.TryGetValue(fnv24, out var existing24))
            {
                Console.Error.WriteLine($"[ERROR] FNV-1a 24-bit hash collision between " +
                    $"'{existing24}' (0x{fnv24:X6}) and '{kv.Value}'. " +
                    $"Generate a build-time #error.");
                fnv24CollisionCount++;
            }
            else
            {
                fnv24ToIdentifier[fnv24] = kv.Value;
            }
        }

        // ── Build sorted FNV-24 dispatch table ──────────────────────────────
        // Sorted array enables binary search lookup at runtime instead of a
        // large switch-case.  This reduces generated code size with zero
        // performance cost (binary search on 360 entries = ~9 comparisons).
        var sortedFnv24 = fnv24ToIdentifier.OrderBy(kv => kv.Key).ToList();

        // ── Emit shared FNV-1a 32-bit hash helper ─────────────────────────
        sb.AppendLine("/// Compute FNV-1a 32-bit hash for a null-terminated string.");
        sb.AppendLine("/// Shared by chaos_find_enum_metadata and compute_enum_hash24.");
        sb.AppendLine("inline static CHAOS_IL2CPP_UINT32 compute_enum_hash32(");
        sb.AppendLine("    const char* s) noexcept");
        sb.AppendLine("{");
        sb.AppendLine("    CHAOS_IL2CPP_UINT32 h = 2166136261u;");
        sb.AppendLine("    for (; *s; ++s) {");
        sb.AppendLine("        h ^= static_cast<CHAOS_IL2CPP_UINT8>(*s);");
        sb.AppendLine("        h *= 16777619u;");
        sb.AppendLine("    }");
        sb.AppendLine("    return h;");
        sb.AppendLine("}");
        sb.AppendLine();
        sb.AppendLine("/// Compute FNV-1a 24-bit hash (matching ChaosReflectionGetTypeFromHandle).");
        sb.AppendLine("inline static CHAOS_IL2CPP_UINT32 compute_enum_hash24(");
        sb.AppendLine("    const char* s) noexcept {");
        sb.AppendLine("    return s && s[0] ? compute_enum_hash32(s) & 0xFFFFFFu : 0u;");
        sb.AppendLine("}");
        sb.AppendLine();

        // Dispatch table and lookup must be emitted BEFORE chaos_find_enum_metadata
        // since both are inline static and the compiler needs the declaration first.
        sb.AppendLine("// ── Dispatch table: sorted by FNV-24 for binary search ──");
        sb.AppendLine($"static constexpr EnumDispatchEntry kEnumDispatchTable[] = {{");
        foreach (var kv in sortedFnv24)
        {
            uint fnv24 = kv.Key & 0xFFFFFF;
            sb.AppendLine($"    {{ 0x{fnv24:X6}u, &kEnumTable_{kv.Value} }},");
        }
        sb.AppendLine("};");
        sb.AppendLine($"static constexpr CHAOS_IL2CPP_UINT32 kEnumDispatchCount = {sortedFnv24.Count}u;");
        sb.AppendLine();

        // ── Build ToString dispatch table (sorted by FNV-24) ──────────────────
        sb.AppendLine("// ── ToString dispatch table: sorted by FNV-24 for binary search ──");
        sb.AppendLine("#ifndef CHAOS_IL2CPP_ENUM_TOSTRING_DISPATCH_ENTRY_DEFINED");
        sb.AppendLine("#define CHAOS_IL2CPP_ENUM_TOSTRING_DISPATCH_ENTRY_DEFINED");
        sb.AppendLine("struct EnumToStringDispatchEntry {");
        sb.AppendLine("    CHAOS_IL2CPP_UINT32 fnv24;");
        sb.AppendLine("    CHAOS_IL2CPP_INTPTR (*to_string_fn)(CHAOS_IL2CPP_INT64 value) noexcept;");
        sb.AppendLine("};");
        sb.AppendLine("#endif");
        sb.AppendLine($"static constexpr EnumToStringDispatchEntry kEnumToStringDispatchTable[] = {{");
        foreach (var kv in sortedFnv24)
        {
            uint fnv24 = kv.Key & 0xFFFFFF;
            sb.AppendLine($"    {{ 0x{fnv24:X6}u, &ChaosEnumToString_{kv.Value} }},");
        }
        sb.AppendLine("};");
        sb.AppendLine($"static constexpr CHAOS_IL2CPP_UINT32 kEnumToStringDispatchCount = {sortedFnv24.Count}u;");
        sb.AppendLine();
        sb.AppendLine("/// Binary search lookup on the sorted dispatch table.");
        sb.AppendLine("/// Returns nullptr if fnv24 not found (fallback to resolve_type_arg +");
        sb.AppendLine("/// chaos_find_enum_metadata).");
        sb.AppendLine("inline static const EnumMetadataTable* chaos_dispatch_lookup(");
        sb.AppendLine("    CHAOS_IL2CPP_UINT32 fnv24) noexcept");
        sb.AppendLine("{");
        sb.AppendLine("    CHAOS_IL2CPP_UINT32 lo = 0u, hi = kEnumDispatchCount;");
        sb.AppendLine("    while (lo < hi) {");
        sb.AppendLine("        CHAOS_IL2CPP_UINT32 mid = lo + (hi - lo) / 2u;");
        sb.AppendLine("        if (kEnumDispatchTable[mid].fnv24 < fnv24)");
        sb.AppendLine("            lo = mid + 1u;");
        sb.AppendLine("        else if (kEnumDispatchTable[mid].fnv24 > fnv24)");
        sb.AppendLine("            hi = mid;");
        sb.AppendLine("        else");
        sb.AppendLine("            return kEnumDispatchTable[mid].table;");
        sb.AppendLine("    }");
        sb.AppendLine("    return nullptr;");
        sb.AppendLine("}");
        sb.AppendLine();
        // ── Emit lookup function (by subject_id string) ────────────────────
        sb.AppendLine("/// Lookup enum metadata by subject_id FNV-1a 32-bit hash via dispatch table binary search.");
        sb.AppendLine("/// Returns nullptr if the type is unknown (fallback to reflection API).");
        sb.AppendLine("inline static const EnumMetadataTable* chaos_find_enum_metadata(");
        sb.AppendLine("    const char* subject_id) noexcept");
        sb.AppendLine("{");
        sb.AppendLine("    if (subject_id == nullptr || subject_id[0] == '\\0')");
        sb.AppendLine("        return nullptr;");
        sb.AppendLine("    return chaos_dispatch_lookup(compute_enum_hash32(subject_id) & 0xFFFFFFu);");
        sb.AppendLine("}");
        sb.AppendLine();

        // Emit #error if fnv24 collisions detected (prevents silent wrong-metadata at runtime).
        if (fnv24CollisionCount > 0)
        {
            sb.AppendLine();
            sb.AppendLine("#error FNV-1a 24-bit hash collision detected in enum metadata. "
                + "Regenerate or increase hash bits. "
                + "See codegen warnings above for conflicting subject IDs.");
        }

        sb.AppendLine();
        sb.AppendLine("}}}  // namespace chaos::il2cpp::codegen");
        sb.AppendLine();
        // ── Generated metadata registration function ─────────────────────────
        // Replaces the old static initializer pattern. This function is called
        // from an IIFE in the generated module registration code (not from a
        // static initializer), which means:
        //   (a) the registration runs at static init time anyway (IIFE),
        //   (b) it's defined only in the single TU that includes this header,
        //   (c) no anonymous-namespace struct = no ODR concerns.
        //
        // The C-linkage variables are defined in enum_stubs.cpp (default nullptr).
        sb.AppendLine("extern \"C\" const EnumMetadataTable* (*g_chaos_resolve_enum_metadata)(");
        sb.AppendLine("    const char* subject_id) noexcept;");
        sb.AppendLine("extern \"C\" const EnumMetadataTable* (*g_chaos_resolve_enum_metadata_by_fnv24)(");
        sb.AppendLine("    CHAOS_IL2CPP_UINT32 fnv24) noexcept;");
        sb.AppendLine("extern \"C\" CHAOS_IL2CPP_INTPTR (*g_chaos_enum_tostring_dispatch_lookup)(");
        sb.AppendLine("    CHAOS_IL2CPP_UINT32 fnv24, CHAOS_IL2CPP_INT64 value) noexcept;");
        sb.AppendLine("extern \"C\" void ChaosEnumRegisterToStringDispatchTable(");
        sb.AppendLine("    const EnumToStringDispatchEntry* entries, CHAOS_IL2CPP_UINT32 count) noexcept;");
        sb.AppendLine("// Pre-allocate managed strings (in POH) from a compiled-in field entry array.");
        sb.AppendLine("// Allocates count managed strings from entry names, stores them in out_strings.");
        sb.AppendLine("// Called at static init time to eliminate lazy allocation on the hot path.");
        sb.AppendLine("extern \"C\" void ChaosEnumPreInitStringCache(");
        sb.AppendLine("    const EnumFieldEntry* entries, CHAOS_IL2CPP_UINT32 count,");
        sb.AppendLine("    CHAOS_IL2CPP_INTPTR* out_strings) noexcept;");
        sb.AppendLine("// Lookup function pointer for pre-allocated string arrays (set by");
        sb.AppendLine("// ChaosEnumRegisterPreInitTable in enum_stubs.cpp).");
        sb.AppendLine("extern \"C\" CHAOS_IL2CPP_INTPTR* (*g_chaos_enum_preinit_lookup)(");
        sb.AppendLine("    CHAOS_IL2CPP_UINT32 fnv24) noexcept;");
        sb.AppendLine("extern \"C\" void ChaosEnumRegisterPreInitTable(");
        sb.AppendLine("    const EnumPreInitEntry* entries, CHAOS_IL2CPP_UINT32 count) noexcept;");

        // ── Pre-allocated string dispatch table ───────────────────────────
        // Maps fnv24 to pre-allocated POH string pointer arrays.
        // Registered via ChaosEnumRegisterPreInitTable at static init time.
        // Used by ensure_enum_str_cache to skip lazy GC allocation.
        var sortedFnv24List = hashToIdentifier.OrderBy(kv => kv.Key).ToList();
        sb.AppendLine();
        sb.AppendLine("// Enclosing struct definition for the pre-init dispatch table entry.");
        sb.AppendLine("// (Defined in enum_stubs.cpp; redeclared here so the generated TU can");
        sb.AppendLine("// create constexpr arrays of it.)");
        sb.AppendLine("#ifndef CHAOS_IL2CPP_ENUM_PREINIT_ENTRY_DEFINED");
        sb.AppendLine("#define CHAOS_IL2CPP_ENUM_PREINIT_ENTRY_DEFINED");
        sb.AppendLine("struct EnumPreInitEntry {");
        sb.AppendLine("    CHAOS_IL2CPP_UINT32 fnv24;");
        sb.AppendLine("    CHAOS_IL2CPP_INTPTR* strings;");
        sb.AppendLine("};");
        sb.AppendLine("#endif");
        sb.AppendLine();
        sb.AppendLine("// ── Pre-allocated string dispatch table (sorted by fnv24 for binary search) ──");
        sb.AppendLine($"static constexpr EnumPreInitEntry kEnumPreInitTable[] = {{");
        foreach (var kv in sortedFnv24List)
        {
            uint fnv24 = kv.Key & 0xFFFFFFu;
            sb.AppendLine($"    {{ 0x{fnv24:X6}u, kEnumStrings_{kv.Value} }},");
        }
        sb.AppendLine("};");
        sb.AppendLine($"static constexpr CHAOS_IL2CPP_UINT32 kEnumPreInitCount = {sortedFnv24List.Count}u;");
        sb.AppendLine();
        sb.AppendLine();
        sb.AppendLine("// Static (internal linkage) so multiple TUs including this header don't ODR-violate.");
        sb.AppendLine("// Only the first page's IIFE calls this; other TUs' copies are dead code.");
        sb.AppendLine("static void ChaosRegisterEnumGeneratedMetadata() noexcept {");

        // Emit type registration for each enum type
        foreach (var kv in hashToIdentifier.OrderBy(kv => kv.Key))
        {
            var et = enumTypes.First(e => typeIds[e.SubjectId] == kv.Value);
            sb.AppendLine($"    ChaosRegisterExternalType(");
            sb.AppendLine($"        compute_enum_hash24(\"{EscapeCppString(et.SubjectId)}\"),");
            sb.AppendLine($"        reinterpret_cast<const chaos::il2cpp::runtime_core::ReflectionQueryTypeDescriptor*>(");
            sb.AppendLine($"            &chaos::il2cpp::codegen::kEnumTypeDesc_{kv.Value}));");
        }

        sb.AppendLine();
        sb.AppendLine("    if (g_chaos_resolve_enum_metadata == nullptr) {");
        sb.AppendLine("        g_chaos_resolve_enum_metadata =");
        sb.AppendLine("            &chaos::il2cpp::codegen::chaos_find_enum_metadata;");
        sb.AppendLine("    }");
        sb.AppendLine("    // Register the sorted dispatch table for binary-search metadata lookup.");
        sb.AppendLine("    ChaosEnumRegisterDispatchTable(");
        sb.AppendLine("        chaos::il2cpp::codegen::kEnumDispatchTable,");
        sb.AppendLine("        chaos::il2cpp::codegen::kEnumDispatchCount);");
        sb.AppendLine("    // Register the per-enum ToString dispatch table.");
        sb.AppendLine("    ChaosEnumRegisterToStringDispatchTable(");
        sb.AppendLine("        chaos::il2cpp::codegen::kEnumToStringDispatchTable,");
        sb.AppendLine("        chaos::il2cpp::codegen::kEnumToStringDispatchCount);");
        sb.AppendLine("    // Register the pre-allocated string dispatch table.");
        sb.AppendLine("    ChaosEnumRegisterPreInitTable(");
        sb.AppendLine("        chaos::il2cpp::codegen::kEnumPreInitTable,");
        sb.AppendLine("        chaos::il2cpp::codegen::kEnumPreInitCount);");

        // Emit pre-allocated string cache initialization for each enum type.
        // This allocates managed string objects (in POH) at static init time,
        // so the hot path (ensure_enum_str_cache) finds pre-allocated strings
        // and skips lazy allocation. Zero GC allocation on enum.ToString/Format.
        foreach (var kv in hashToIdentifier.OrderBy(kv => kv.Key))
        {
            var et = enumTypes.First(e => typeIds[e.SubjectId] == kv.Value);
            sb.AppendLine($"    // Pre-allocate {et.Fields.Count} field name strings for {et.SubjectId}");
            sb.AppendLine($"    ChaosEnumPreInitStringCache(");
            sb.AppendLine($"        chaos::il2cpp::codegen::kEnumFields_{kv.Value},");
            sb.AppendLine($"        {et.Fields.Count},");
            sb.AppendLine($"        chaos::il2cpp::codegen::kEnumStrings_{kv.Value});");
        }

        sb.AppendLine("}");
        sb.AppendLine();

        return sb.ToString();
    }

    private static uint ComputeFnv1a32(string s)
    {
        uint hash = 2166136261u;
        foreach (char c in s)
        {
            hash ^= (uint)(byte)c;
            hash *= 16777619u;
        }
        return hash;
    }

    private static string SanitizeToCppIdentifier(string subjectId)
    {
        // Convert "AssemblyName/Namespace.TypeName+Nested" to
        // a valid C++ identifier like "ASSEMBLY_NAMESPACE_TYPENAME_NESTED"
        var sb = new StringBuilder(subjectId.Length);
        bool lastWasInvalid = true;
        foreach (char c in subjectId)
        {
            if (char.IsLetterOrDigit(c))
            {
                sb.Append(char.ToUpperInvariant(c));
                lastWasInvalid = false;
            }
            else if (c == '+' || c == '.' || c == '/' || c == '_')
            {
                sb.Append('_');
                lastWasInvalid = false;
            }
            else if (!lastWasInvalid)
            {
                sb.Append('_');
                lastWasInvalid = true;
            }
        }
        // Ensure doesn't start with a digit
        if (sb.Length > 0 && char.IsDigit(sb[0]))
            sb.Insert(0, '_');
        // Ensure at least something
        if (sb.Length == 0)
            sb.Append("ENUM");
        return sb.ToString();
    }

    private static string EscapeCppString(string s)
    {
        var sb = new StringBuilder(s.Length);
        foreach (char c in s)
        {
            switch (c)
            {
                case '\\': sb.Append("\\\\"); break;
                case '"': sb.Append("\\\""); break;
                case '\r': sb.Append("\\r"); break;
                case '\n': sb.Append("\\n"); break;
                case '\t': sb.Append("\\t"); break;
                default: sb.Append(c); break;
            }
        }
        return sb.ToString();
    }

    private sealed record EnumTypeData(string SubjectId, List<EnumFieldData> Fields);
    private sealed record EnumFieldData(string Name, long Value);
}
