    private static string BuildObjectModelSection(NativeAotTemplateModel templateModel)
    {
        var model = new ScriptObject
        {
            ["object_model_code"] = ScribanTemplateRenderer.NormalizeIndentation(templateModel.ObjectModelCode),
        };
        return ScribanTemplateRenderer.RenderTemplate(NativeAotTemplateCatalog.GetObjectModelTemplate(), model);
    }



    /// <summary>
    /// Builds the shared header content emitted as native-aot.generated.header.h.
    /// Contains extern TypeInfoV0 declarations so every translation unit page has
    /// access to all type symbols without ODR violations from duplicate inline defs.
    /// When there are no type declarations (non-paged families), returns a minimal
    /// valid header so chaos_generated_module.h can include it unconditionally.
    /// </summary>
    private static string BuildSharedHeader(NativeAotTemplateModel templateModel)
    {
        var code = templateModel.TypeDeclarationsCode;
        if (string.IsNullOrEmpty(code))
        {
            return "// Auto-generated by chaos-il2cpp convert-to-cpp\n#pragma once\n";
        }
        return code;
    }



    /// <summary>
    /// Builds the generated sources list. If the lowering plan has page information,
    /// splits the methods across multiple translation unit pages. Otherwise produces
    /// a single translation unit (traditional behavior).
    /// </summary>
    private static (IReadOnlyList<NativeAotGeneratedSource> Sources, IReadOnlyList<NativeAotGeneratedArtifactRef> Artifacts)
        BuildGeneratedSources(NativeAotTemplateModel templateModel, NativeAotLoweringPlanArtifact loweringPlan)
    {
        var sources = new List<NativeAotGeneratedSource>();
        var artifacts = new List<NativeAotGeneratedArtifactRef>();

        // Always include the shape dispatch header
        sources.Add(new NativeAotGeneratedSource
        {
            RelativePath = NativeAotArtifactNames.ShapeDispatchHeader,
            Contents = templateModel.ShapeDispatchHeaderContent,
        });
        artifacts.Add(new NativeAotGeneratedArtifactRef
        {
            Kind = "shapeDispatchHeader",
            Path = NativeAotArtifactNames.ShapeDispatchHeader,
        });

        // Always emit enum metadata header — the generated C++ unconditionally
        // includes it (#include "enum_metadata.generated.h"). Families with no
        // enum types produce an empty file, which is valid C++.
        sources.Add(new NativeAotGeneratedSource
        {
            RelativePath = NativeAotArtifactNames.EnumMetadataHeader,
            Contents = templateModel.EnumMetadataHeaderContent,
        });
        artifacts.Add(new NativeAotGeneratedArtifactRef
        {
            Kind = "enumMetadataHeader",
            Path = NativeAotArtifactNames.EnumMetadataHeader,
        });

        var pages = loweringPlan.TranslationUnitPages;
        int? pageSize = loweringPlan.TranslationUnitPageSize;

	        const int autoPageSize = 500;
        // Auto-paging: when the plan doesn't specify pages but the method count
        // exceeds the threshold, create synthetic pages to split the output into
        // multiple translation units. This prevents oversized generated files
        // for test subjects with many methods (e.g. coverage subjects).
        // Note: the planner may set NativeAotPageSize to an artificially high value
        // (999999) to effectively disable paging for non-subject codegen.  For
        // pipeline subjects (e.g. 49086 methods in a numerics chunk), this value
        // is never exceeded, so no paging is set up.  We force auto-paging here
        // regardless of the planner's pageSize setting when the method count
        // clearly exceeds the auto-page threshold, preventing OOM during Scriban
        // template rendering of a single 200+ MB translation unit.
        if (templateModel.Methods.Count > autoPageSize && pages is not { Count: > 0 })
        {
            int totalMethods = templateModel.Methods.Count;
            int pageCount = (totalMethods + autoPageSize - 1) / autoPageSize;
            var autoPages = new List<AuditTranslationUnitPageArtifact>(pageCount);
            for (int i = 0; i < pageCount; i++)
            {
                string pageSuffix = i == 0 ? "" : $".page{i + 1}";
                autoPages.Add(new AuditTranslationUnitPageArtifact
                {
                    PageNumber = i + 1,
                    MethodCount = Math.Min(autoPageSize, totalMethods - i * autoPageSize),
                    Path = $"native-aot.generated{pageSuffix}.cpp",
                });
            }
            pages = autoPages;
            pageSize = autoPageSize;
        }

        if (pages is { Count: > 0 } && pageSize is > 0)
        {
            // Paged output: split methods across multiple translation units.
            // Uses estimated output size (based on MethodSource.Length) rather than
            // method count to keep each generated .cpp file within reasonable limits.
            var allMethods = templateModel.Methods;
            int totalMethods = allMethods.Count;

            // Cross-page NativeSymbol dedup: generic instantiation stubs
            // (__generic suffix) and type-forwarded methods share the same
            // NativeSymbol but may be assigned to different pages by the
            // size-based partitioner, causing C2084 (function already has a
            // body) on subsequent pages.  Pre-filter to unique symbols.
            var dedupedMethods = new List<NativeAotMethodTemplateModel>(totalMethods);
            var seenNs = new HashSet<string>(StringComparer.Ordinal);
            foreach (var m in allMethods)
                if (!string.IsNullOrEmpty(m.NativeSymbol) && seenNs.Add(m.NativeSymbol))
                    dedupedMethods.Add(m);
            allMethods = dedupedMethods;
            totalMethods = allMethods.Count;

            // ── Estimate page 0 overhead ──────────────────────────────
            // Page 0 carries object model (TypeInfoV0 inline defs), method
            // declarations, module registration, and generic registration.
            // Each entry is optional — use empty string length when null.
            int objectModelLength = templateModel.ObjectModelCodeBuilder?.Length
                                 ?? templateModel.ObjectModelCode?.Length
                                 ?? 0;
            int page0Overhead = objectModelLength
                              + (templateModel.MethodDeclarations?.Sum(d => d.Length) ?? 0)
                              + (templateModel.ModuleRegistrationCode?.Length ?? 0)
                              + (templateModel.GenericRegistrationCode?.Length ?? 0)
                              + 500; // Scriban template structural overhead

            // Threshold: ~350 KB of C++ source per page (~50 pages for 3788 methods).
            // Keeps generated files under ~50K lines / ~2 MB to avoid MSVC C1060
            // (compiler out of heap space) which triggers at ~15 MB / 448K lines.
            const int sizeThresholdChars = 350_000;
            const int perMethodOverhead = 200;
            const int perPageOverhead = 500;

            // Emit shared header with extern TypeInfoV0 declarations + shape dispatch header.
            // Always emitted (even empty) so chaos_generated_module.h can include it
            // unconditionally for chaos_valuetype_* forward declaration visibility.
            string headerContent = BuildSharedHeader(templateModel);
            sources.Add(new NativeAotGeneratedSource
            {
                RelativePath = NativeAotArtifactNames.GeneratedHeader,
                Contents = headerContent,
            });
            artifacts.Add(new NativeAotGeneratedArtifactRef
            {
                Kind = "generatedHeader",
                Path = NativeAotArtifactNames.GeneratedHeader,
            });

            // ── Size-based partitioning ────────────────────────────
            // Accumulate estimated method sizes into pages. Each page gets at
            // least one method (no empty pages). Page 0 accounts for overhead
            // from object model / registration code.
            int methodIdx = 0;
            int actualPageIdx = 0;
            while (methodIdx < totalMethods)
            {
                bool isFirstPage = (actualPageIdx == 0);
                int accumulated = isFirstPage ? page0Overhead : perPageOverhead;
                int pageStart = methodIdx;

                while (methodIdx < totalMethods)
                {
                    int methodSize = (allMethods[methodIdx].MethodSource?.Length ?? 0) + perMethodOverhead;
                    if (accumulated + methodSize > sizeThresholdChars && methodIdx > pageStart)
                        break;
                    accumulated += methodSize;
                    methodIdx++;
                }

                // Ensure at least one method on this page
                if (methodIdx == pageStart)
                    methodIdx = pageStart + 1;

                var pageMethods = allMethods
                    .Skip(pageStart)
                    .Take(methodIdx - pageStart)
                    .ToArray();

                // Pick page artifact or create on-the-fly for overflow pages
                AuditTranslationUnitPageArtifact page;
                if (actualPageIdx < pages.Count)
                {
                    page = pages[actualPageIdx];
                }
                else
                {
                    // Overflow page beyond the originally planned page count.
                    // Use native-aot.page-NNNN.cpp naming to match cmake glob
                    // (native-aot.page-*.cpp) and keep the lowering plan convention.
                    page = new AuditTranslationUnitPageArtifact
                    {
                        PageNumber = actualPageIdx + 1,
                        MethodCount = methodIdx - pageStart,
                        Path = $"native-aot.page-{actualPageIdx + 1:D4}.cpp",
                    };
                }

                // Only page 0 includes inline TypeInfoV0 definitions (includeObjectModel=true).
                // Subsequent pages rely on the shared header (native-aot.generated.header.h)
                // for forward declarations and extern references to type symbols, avoiding
                // multi-GB bloat from duplicating TypeInfoV0 definitions across hundreds of pages.

                // Normalize page path to flat (no directory prefix) so cmake
                // glob patterns match regardless of what the lowering plan uses.
                var pageFileName = Path.GetFileName(page.Path.AsSpan());
                string pageRelativePath = pageFileName.Length > 0 ? pageFileName.ToString() : page.Path;

                // Per-page type declarations and includes (for paging optimization)
                int pageNumber = page.PageNumber;
                string? pageTypeDecl = templateModel.PerPageTypeDeclarations?.GetValueOrDefault(pageNumber);
                IReadOnlyList<string>? pageIncludes = templateModel.PerPageIncludes?.GetValueOrDefault(pageNumber);

                // For page 0 with an ObjectModelCodeBuilder (large content), build
                // directly into a StringBuilder and store as ContentsBuilder to avoid
                // a 3+ GB ToString() copy on the Large Object Heap.
                if (isFirstPage && templateModel.ObjectModelCodeBuilder is { } omBuilder)
                {
                    var methodSections = pageMethods
                        .Select(BuildMethodSection)
                        .ToArray();
                    var includes = new List<string>(pageIncludes ?? templateModel.Includes);
                    // Page 0 includes inline TypeInfoV0 → no shared header needed
                    var pageBuilder = BuildGeneratedPageToBuilder(
                        templateModel, methodSections, includes,
                        includeRegistration: true,
                        includeObjectModel: true,
                        perPageTypeDeclarations: pageTypeDecl,
                        perPageIncludes: pageIncludes);
                    // Dedup type_id/mt symbols across all pages (C2374).
                    // Page 0 uses the StringBuilder path, so we must post-process.
                    string pageText = pageBuilder.ToString();
                    pageBuilder.Clear();
                    DeduplicateTypeIdMtSymbols(pageText, pageBuilder);
                    sources.Add(new NativeAotGeneratedSource
                    {
                        RelativePath = pageRelativePath,
                        Contents = "",
                        ContentsBuilder = pageBuilder,
                    });
                }
                else
                {
                    string content = BuildGeneratedPage(
                        templateModel, pageMethods,
                        includeRegistration: isFirstPage,
                        includeObjectModel: isFirstPage);
                    sources.Add(new NativeAotGeneratedSource
                    {
                        RelativePath = pageRelativePath,
                        Contents = content,
                    });
                }
                artifacts.Add(new NativeAotGeneratedArtifactRef
                {
                    Kind = "generatedTranslationUnit",
                    Path = page.Path,
                });

                actualPageIdx++;
            }
        }
        else
        {
            // Single translation unit (traditional behavior)
            // Emit shared header with extern TypeInfoV0 declarations so that
            // chaos_generated_module.h can include it unconditionally.
            string headerContent = BuildSharedHeader(templateModel);
            sources.Add(new NativeAotGeneratedSource
            {
                RelativePath = NativeAotArtifactNames.GeneratedHeader,
                Contents = headerContent,
            });
            artifacts.Add(new NativeAotGeneratedArtifactRef
            {
                Kind = "generatedHeader",
                Path = NativeAotArtifactNames.GeneratedHeader,
            });

            string content = BuildGeneratedTranslationUnit(templateModel);

            // Deduplicate inline constexpr type_id/mt symbols and fix MoveNext
            // declaration signatures (C2374 / C2733 / C2382).
            var _sb = new System.Text.StringBuilder(content.Length);
            DeduplicateTypeIdMtSymbols(content, _sb);
            content = _sb.ToString().TrimEnd();

            // Add struct forward declarations for placeholder value types at the
            // top of the cpp file (before namespace). These help PCH-mode MSVC
            // resolve chaos_resolve_managed_value_pointer<T> template arguments
            // when T is a struct defined in the generated header outside the PCH.
            //
            // IMPORTANT: Scan the header for existing typedef CHAOS_IL2CPP_INT32
            // chaos_valuetype_* declarations — these types are opaque 32-bit
            // value types (not structs), and emitting a `struct chaos_valuetype_*;`
            // forward declaration for them would cause C2371 (redefinition;
            // different basic types). Skip any type that already has a typedef in
            // the shared header.
            var _headerTypedefValueTypes = new System.Collections.Generic.HashSet<string>(StringComparer.Ordinal);
            foreach (string _hdrLine in headerContent.Split('\n'))
            {
                string _ht = _hdrLine.TrimStart();
                if (_ht.StartsWith("typedef CHAOS_IL2CPP_INT32 chaos_valuetype_", StringComparison.Ordinal))
                {
                    var _parts = _ht.Split(' ');
                    if (_parts.Length > 2)
                        _headerTypedefValueTypes.Add(_parts[_parts.Length - 1].TrimEnd(';'));
                }
            }
            var _fwdSb = new System.Text.StringBuilder();
            var _seenFwd = new System.Collections.Generic.HashSet<string>(StringComparer.Ordinal);
            foreach (string _line in content.Split('\n'))
            {
                string _t = _line.Trim();
                if (_t.Contains("chaos_resolve_managed_value_pointer<chaos_valuetype_") &&
                    (_t.Contains("__0__")))
                {
                    var _start = _t.IndexOf("chaos_valuetype_");
                    var _end = _t.IndexOf('>', _start);
                    if (_start > 0 && _end > _start)
                    {
                        var _typeName = _t.Substring(_start, _end - _start);
                        // Skip if the header already has a typedef for this type
                        // (opaque 32-bit value type, not a struct definition)
                        if (_headerTypedefValueTypes.Contains(_typeName))
                            continue;
                        if (_seenFwd.Add(_typeName))
                            _fwdSb.AppendLine("struct " + _typeName + ";");
                    }
                }
            }
            if (_fwdSb.Length > 0)
            {
                var _insertPos = content.IndexOf("#pragma warning(disable: 2362)");
                if (_insertPos > 0)
                {
                    _fwdSb.Insert(0, "// PCH workaround: struct forward declarations for template resolution\n");
                    _fwdSb.AppendLine();
                    content = content.Substring(0, _insertPos) + _fwdSb.ToString() + content.Substring(_insertPos);
                }

                // Also add explicit template instantiation right after the generated
                // header include, BEFORE any implicit use in method bodies. MSVC fails
                // to implicitly instantiate chaos_resolve_managed_value_pointer<T>
                // with struct types defined in non-PCH headers (C2672).
                foreach (string _fwd in _fwdSb.ToString().Split('\n', StringSplitOptions.RemoveEmptyEntries))
                {
                    string _ft = _fwd.Trim();
                    if (_ft.StartsWith("struct ") && _ft.EndsWith(";"))
                    {
                        string _tname = _ft.Substring(7, _ft.Length - 8);
                        string _explInst = $"template {_tname}* chaos_resolve_managed_value_pointer<{_tname}>(CHAOS_IL2CPP_INTPTR);\n";
                        var _hdrPos = content.IndexOf("#include \"native-aot.generated.header.h\"");
                        if (_hdrPos > 0)
                        {
                            _hdrPos = content.IndexOf('\n', _hdrPos) + 1;
                            content = content.Substring(0, _hdrPos) + _explInst + content.Substring(_hdrPos);
                        }
                    }
                }

                // PCH workaround: replace PCH include with explicit headers.
                // PCH-mode MSVC cannot resolve struct template arguments defined
                // in non-PCH headers, causing C2672. Replace the PCH so that
                // all headers are included freshly in the TU context.
                var _replHeaders = new System.Text.StringBuilder();
                _replHeaders.AppendLine("#include <cstdint>");
                _replHeaders.AppendLine("#include <cstddef>");
                _replHeaders.AppendLine("#include <cstring>");
                _replHeaders.AppendLine("#include <chaos/common.h>");
                _replHeaders.AppendLine("#include <chaos/type_info.h>");
                _replHeaders.AppendLine("#include <chaos/eh.h>");
                _replHeaders.AppendLine("#include <ChaosGeneratedRuntimePrelude.h>");
                // <coroutine> is required by async coroutine emission
                // (AsyncPromise/AsyncHandle use std::coroutine_handle and
                // std::suspend_always).  Include it when the PCH is replaced
                // to avoid C3774/C2039/C2065.
                _replHeaders.AppendLine("#include <coroutine>");
                // Runtime-core headers (same as chaos_pch.h provides)
                _replHeaders.AppendLine("#include \"runtime_core.h\"");
                _replHeaders.AppendLine("#include \"codegen_bridge.h\"");
                _replHeaders.AppendLine("#include \"module_registry.h\"");
                _replHeaders.AppendLine("#include \"abi_manifest.h\"");
                _replHeaders.AppendLine("#include \"hotpatch_table.h\"");
                _replHeaders.AppendLine("#include \"runtime_vtable.h\"");
                _replHeaders.AppendLine("#include \"runtime_instantiation.h\"");
                _replHeaders.AppendLine("#include \"reflection_query_model.h\"");
                _replHeaders.AppendLine("#include \"load_store_chaos_bridge.h\"");
                _replHeaders.AppendLine("#include \"interpreter_entry.h\"");
                _replHeaders.AppendLine("#include <gc/gc_bgc_inline.h>");
                _replHeaders.AppendLine("#include <gc/gc_card_table.h>");
                _replHeaders.AppendLine("#include <gc/gc_root_change.h>");
                _replHeaders.AppendLine("#include <gc/gc_layout.h>");
                _replHeaders.AppendLine("#include \"runtime_stubs/misc_stubs.h\"");
                _replHeaders.AppendLine("#include \"runtime_stubs/crypto_stubs.h\"");
                _replHeaders.AppendLine("#include \"runtime_stubs/vector_stubs.h\"");
                _replHeaders.AppendLine("#include \"chaos_runtime_host.h\"");
                string _replStr = _replHeaders.ToString();
                content = content.Replace("#include \"chaos_pch.h\"\r\n", _replStr);
                content = content.Replace("#include \"chaos_pch.h\"\n", _replStr);
            }

            sources.Add(new NativeAotGeneratedSource
            {
                RelativePath = NativeAotArtifactNames.GeneratedTranslationUnit,
                Contents = content,
            });
            artifacts.Add(new NativeAotGeneratedArtifactRef
            {
                Kind = "generatedTranslationUnit",
                Path = NativeAotArtifactNames.GeneratedTranslationUnit,
            });
        }

        // A1 + A2: Emit typed dispatch table header and dispatch wiring source.
        // These are always emitted when the planner produced non-empty content.
        if (!string.IsNullOrEmpty(templateModel.GeneratedModuleHeaderContent))
        {
            sources.Add(new NativeAotGeneratedSource
            {
                RelativePath = NativeAotArtifactNames.GeneratedModuleHeader,
                Contents = templateModel.GeneratedModuleHeaderContent,
            });
            artifacts.Add(new NativeAotGeneratedArtifactRef
            {
                Kind = "generatedModuleHeader",
                Path = NativeAotArtifactNames.GeneratedModuleHeader,
            });
        }
        if (!string.IsNullOrEmpty(templateModel.GeneratedModuleSourceContent))
        {
            sources.Add(new NativeAotGeneratedSource
            {
                RelativePath = NativeAotArtifactNames.GeneratedModuleSource,
                Contents = templateModel.GeneratedModuleSourceContent,
            });
            artifacts.Add(new NativeAotGeneratedArtifactRef
            {
                Kind = "generatedModuleSource",
                Path = NativeAotArtifactNames.GeneratedModuleSource,
            });
        }
        if (!string.IsNullOrEmpty(templateModel.ManifestJson))
        {
            sources.Add(new NativeAotGeneratedSource
            {
                // Use MethodsManifest (not Manifest) to avoid being overwritten by
                // the artifact manifest (NativeAotManifestArtifact) written at
                // NativeAotArtifactNames.Manifest in ConvertToCppHandler.EmitNativeAot().
                RelativePath = NativeAotArtifactNames.MethodsManifest,
                Contents = templateModel.ManifestJson,
            });
            // No artifact ref — this is consumed internally by the verification orchestrator.
        }

        // ── Post-processing: safeHeaderValuetypeTypedefs ──
        // Scan all generated page sources for chaos_valuetype_* references that lack
        // a corresponding typedef in the shared header (native-aot.generated.header.h).
        // These come from extern "C" declarations in TPG Scriban templates for external
        // runtime functions, which reference chaos_valuetype_* types not discovered by
        // AOT IR lowering or ObjectModelEmission (e.g. System.Data.Common internal enums
        // like DataRowVersion, ConflictOption, CommandBehavior).
        AppendMissingVtTypedefsToHeaderPostScan(sources);

        return (sources, artifacts);
    }

    /// <summary>
    /// Scan all generated sources for chaos_valuetype_* references missing from the
    /// shared header and append the needed typedefs to the header content.
    /// This catches types referenced in TPG Scriban template extern "C" declarations
    /// that are not part of the AOT subject methods' type closure.
    /// </summary>
    private static void AppendMissingVtTypedefsToHeaderPostScan(IReadOnlyList<NativeAotGeneratedSource> sources)
    {
        var existingVT = new HashSet<string>(StringComparer.Ordinal);
        int headerIdx = -1;
        string headerPath = NativeAotArtifactNames.GeneratedHeader;
        for (int si = 0; si < sources.Count; si++)
        {
            if (string.Equals(sources[si].RelativePath, headerPath, StringComparison.Ordinal))
            {
                headerIdx = si;
                CollectExistingValueTypeTypedefs(sources[si].Contents, existingVT);
                break;
            }
        }
        if (headerIdx < 0) return;

        var missingVT = new HashSet<string>(StringComparer.Ordinal);
        for (int si = 0; si < sources.Count; si++)
        {
            if (si == headerIdx) continue;
            var text = sources[si].Contents;
            if (string.IsNullOrEmpty(text)) continue;
            int pos = 0;
            while ((pos = text.IndexOf("chaos_valuetype_", pos, StringComparison.Ordinal)) >= 0)
            {
                int start = pos;
                int end = pos + 16;
                while (end < text.Length && (char.IsLetterOrDigit(text[end]) || text[end] == '_'))
                    end++;
                // Skip matches where no identifier characters follow "chaos_valuetype_"
                // (e.g. matches inside "chaos_valuetype_*" comment text).
                if (end == pos + 16) { pos = end; continue; }
                var sym = text.Substring(start, end - start);
                // Skip symbols containing non-identifier characters (safety net).
                bool valid = true;
                for (int i = 16; i < sym.Length && valid; i++)
                    if (!char.IsLetterOrDigit(sym[i]) && sym[i] != '_')
                        valid = false;
                if (valid && !existingVT.Contains(sym))
                    missingVT.Add(sym);
                pos = end;
            }
        }
        if (missingVT.Count == 0) return;

        var headerSb = new System.Text.StringBuilder(sources[headerIdx].Contents);
        headerSb.AppendLine();
        headerSb.AppendLine("// chaos_valuetype_* typedefs (post-scan: TPG extern declarations)");
        foreach (var name in missingVT.OrderBy(n => n, StringComparer.Ordinal))
        {
            headerSb.Append("typedef CHAOS_IL2CPP_INT32 ");
            headerSb.Append(name);
            headerSb.AppendLine(";");
        }
        headerSb.AppendLine();
        var oldSrc = sources[headerIdx];
        if (sources is IList<NativeAotGeneratedSource> mutableList)
        {
            mutableList[headerIdx] = new NativeAotGeneratedSource
            {
                RelativePath = oldSrc.RelativePath,
                Contents = headerSb.ToString(),
            };
        }
    }

    /// <summary>
    /// Collect existing chaos_valuetype_* typedef names from header content.
    /// Matches "typedef CHAOS_IL2CPP_INT32 chaos_valuetype_XYZ;" patterns.
    /// Also matches "struct chaos_valuetype_XYZ" definitions.
    /// </summary>
    private static void CollectExistingValueTypeTypedefs(string headerContent, HashSet<string> result)
    {
        const string typedefPrefix = "typedef CHAOS_IL2CPP_INT32 ";
        const string valuetypePrefix = "chaos_valuetype_";
        int pos = 0;
        while ((pos = headerContent.IndexOf(typedefPrefix, pos, StringComparison.Ordinal)) >= 0)
        {
            int vtStart = pos + typedefPrefix.Length;
            int end = headerContent.IndexOf(';', vtStart);
            if (end < 0) break;
            var name = headerContent.Substring(vtStart, end - vtStart).Trim();
            if (name.StartsWith(valuetypePrefix, StringComparison.Ordinal))
                result.Add(name);
            pos = end + 1;
        }
        const string structPrefix = "struct chaos_valuetype_";
        pos = 0;
        while ((pos = headerContent.IndexOf(structPrefix, pos, StringComparison.Ordinal)) >= 0)
        {
            int end = headerContent.IndexOfAny(new[] { ' ', '{' }, pos);
            if (end < 0) break;
            // Store bare symbol name (strip "struct " prefix) for comparison
            // with typedef names and references.
            result.Add(headerContent.Substring(pos + 7, end - pos - 7));
            pos = end + 1;
        }
    }

    private static string BuildMethodSection(NativeAotMethodTemplateModel methodModel)
    {
        var model = new ScriptObject
        {
            ["subject_id"] = methodModel.SubjectId,
            ["method_source"] = ScribanTemplateRenderer.NormalizeIndentation(methodModel.MethodSource),
        };
        return ScribanTemplateRenderer.RenderTemplate(NativeAotTemplateCatalog.GetMethodTemplate(), model);
    }



    private static T LoadRequiredJson<T>(string path)
    {
        if (!File.Exists(path))
        {
            throw new FileNotFoundException($"required native-aot lowering plan is missing: {path}", path);
        }

        var value = JsonSerializer.Deserialize<T>(File.ReadAllText(path), JsonOptions);
        if (value is null)
        {
            throw new InvalidOperationException($"failed to deserialize native-aot lowering plan: {path}");
        }

        return value;
    }



    private static void RequireStringField(string? value, string fieldName)
    {
        if (string.IsNullOrWhiteSpace(value))
        {
            throw new InvalidOperationException(
                $"native-aot lowering plan requires non-empty field '{fieldName}'");
        }
    }



    private static string ToCppStringLiteral(string value)
    {
        var builder = new StringBuilder(Math.Max(value.Length * 2 + 2, 256));
        builder.Append('"');

        foreach (var current in value)
        {
            builder.Append(current switch
            {
                '\\' => "\\\\",
                '"' => "\\\"",
                '\r' => "\\r",
                '\n' => "\\n",
                '\t' => "\\t",
                _ => current.ToString(),
            });
        }

        builder.Append('"');
        return builder.ToString();
    }



    /// <summary>
    /// Scan generated page content for calls to chaoternal_runtime_* functions
	/// <summary>
	/// Scan generated page content for calls to chaoternal_runtime_* functions
	/// that lack declarations, and prepend static inline stub declarations.
	/// </summary>
	/// <summary>
	/// Replace ChaosExternalRuntimeFallback() zero-arg calls with ChaosExternalRuntimeFallbackDefault().
	/// Catch-all external runtime helpers for void-returning methods (constructors) may emit
	/// ChaosExternalRuntimeFallback() without the required subject_id argument.
	/// </summary>
	private static void FixFallbackZeroArgCalls(StringBuilder sb)
    {
        if (sb.ToString().IndexOf("ChaosExternalRuntimeFallback();") < 0)
            return;
        sb.Replace("ChaosExternalRuntimeFallback();", "ChaosExternalRuntimeFallbackDefault();");
        // Prepend extern declaration — use StringBuilder search on modified content
        string modified = sb.ToString();
        int anchor = modified.LastIndexOf("#include");
        anchor = anchor >= 0 ? modified.IndexOf('\n', anchor) + 1 : 0;
        sb.Insert(anchor,
            "extern \"C\" CHAOS_IL2CPP_INTPTR ChaosExternalRuntimeFallbackDefault() noexcept;\n");
    }



    private static void AddExternalRuntimeStubs(StringBuilder sb)
    {
        string text = sb.ToString();
        var callRx = new Regex(@"\b(chaos_external_runtime_\w+)\(");
        // Match declarations/definitions: extern "C" / static inline / void return-type
        var declRx = new Regex(@"(?:extern|static inline|\bvoid)\b.*\bchaos_external_runtime_\w+\s*\(", RegexOptions.Multiline);
        var calls = callRx.Matches(text);
        if (calls.Count == 0) return;
        var missing = new HashSet<string>();
        foreach (Match m in calls) missing.Add(m.Groups[1].Value);
        foreach (Match m in declRx.Matches(text))
        {
            string sv = m.Value;
            int nextIdx = m.Index + m.Length;
            // Check if this match is for a () declaration (0 args) — if so,
            // check if it's a DEFINITION (has "{") or a DECLARATION (ends with ";").
            // Only skip declarations (they have wrong arg count).
            if (nextIdx < text.Length && text[nextIdx] == ')')
            {
                // Find end of this construct — scan up to 200 chars for ";" or "{"
                int scanPos = nextIdx + 1;
                bool isDefinition = false;
                while (scanPos < text.Length && scanPos < m.Index + 200)
                {
                    char sc = text[scanPos];
                    if (sc == ';') break;
                    if (sc == '{') { isDefinition = true; break; }
                    scanPos++;
                }
                if (!isDefinition)
                    continue; // skip () declarations (wrong arg count)
            }
            foreach (var s in missing.ToList())
                if (sv.Contains(s)) missing.Remove(s);
        }
        if (missing.Count == 0) return;
        // Pre-check: for each missing symbol, verify there's no existing definition
        // with "()" in the file (from catch-all fallback helpers).  These definitions
        // are valid (the call site also uses "()") and adding a second extern "C"
        // declaration with a different arg count would cause C2733.
        var symbolsToDeclare = new List<(string symbol, int argCount)>();
        foreach (var sym in missing.OrderBy(s => s))
        {
            // Check if there's already a "()" definition for this symbol
            var defMatch = System.Text.RegularExpressions.Regex.Match(text,
                System.Text.RegularExpressions.Regex.Escape(sym) + "\\(\\) noexcept\\s*\\{");
            if (defMatch.Success)
                continue; // existing () definition, no need for declaration
            int argCount = 0;
            // Count arguments from first call site
            var callMatch = System.Text.RegularExpressions.Regex.Match(text,
                System.Text.RegularExpressions.Regex.Escape(sym) + "\\(");
            if (callMatch.Success)
            {
                int pos = callMatch.Index + callMatch.Length;
                int depth = 0;
                bool inString = false;
                for (int i = pos; i < text.Length; i++)
                {
                    char c = text[i];
                    if (c == '"') inString = !inString;
                    else if (!inString)
                    {
                        if (c == '(') depth++;
                        else if (c == ')')
                        {
                            if (depth == 0) { if (i == pos) argCount = 0; break; }
                            depth--;
                        }
                        else if (c == ',' && depth == 0) argCount++;
                    }
                }
                argCount++;
            }
            symbolsToDeclare.Add((sym, argCount));
        }
        if (symbolsToDeclare.Count == 0) return;
        var stub = new StringBuilder();
        stub.AppendLine("// ── External runtime stubs (post-emission) ──");
        foreach (var (sym, argCount) in symbolsToDeclare)
        stub.AppendLine();
        string genSrc = sb.ToString();
        int anchor = genSrc.LastIndexOf("#include");
        if (anchor < 0) anchor = 0;
        else
        {
            int nl = genSrc.IndexOf('\n', anchor);
            if (nl >= 0) anchor = nl + 1;
        }
        sb.Insert(anchor, stub.ToString());

        // Fix existing () declarations: replace with corrected arg counts
        string postText = sb.ToString();
        foreach (var sym in missing.OrderBy(s => s))
        {
            int argCount = 0;
            var callMatch = System.Text.RegularExpressions.Regex.Match(text,
                System.Text.RegularExpressions.Regex.Escape(sym) + "\\(");
            while (callMatch.Success)
            {
                int ls = text.LastIndexOf((char)10, callMatch.Index);
                if (ls < 0) ls = 0;
                string lp = text.Substring(ls, callMatch.Index - ls).TrimStart();
                if (!lp.StartsWith("extern") && !lp.StartsWith("static"))
                    break;
                callMatch = callMatch.NextMatch();
            }
            if (callMatch.Success)
            {
                int pos = callMatch.Index + callMatch.Length;
                int depth = 0;
                bool inString = false;
                for (int i = pos; i < text.Length; i++)
                {
                    char c = text[i];
                    if (c == '"') inString = !inString;
                    else if (!inString)
                    {
                        if (c == '(') depth++;
                        else if (c == ')')
                        {
                            if (depth == 0) { if (i == pos) argCount = 0; break; }
                            depth--;
                        }
                        else if (c == ',' && depth == 0) argCount++;
                    }
                }
                argCount++;
            }
            string wrongDecl = "extern CHAOS_IL2CPP_INTPTR " + sym + "() noexcept;";
            string wrongDeclC = "extern \"C\" CHAOS_IL2CPP_INTPTR " + sym + "() noexcept;";
            string correctDecl = "extern CHAOS_IL2CPP_INTPTR " + sym + "(";
            for (int i = 0; i < argCount; i++)
            {
                if (i > 0) correctDecl += ", ";
                correctDecl += "CHAOS_IL2CPP_INTPTR";
            }
            correctDecl += ") noexcept;";
            if (postText.Contains(wrongDecl))
                sb.Replace(wrongDecl, correctDecl);
            if (postText.Contains(wrongDeclC))
                sb.Replace(wrongDeclC, correctDecl);
        }

    }

    /// <summary>
    /// Deduplicate inline constexpr type_id/mt symbols and replace async MoveNext
    /// declarations.  Flat-merge can produce duplicate definitions of common
    /// System.Private.CoreLib types (e.g. IEnumerable) from each merged assembly,
    /// causing C2374 redefinition errors.  Also replaces extern "C"
    /// CHAOS_IL2CPP_INTPTR MoveNext declarations with the ABI dispatch signature
    /// (CHAOS_IL2CPP_INT64, 4 params, noexcept) WHEN a coroutine wrapper
    /// (Entry_<uid>) exists for the same symbol, avoiding C2733/C2382 conflicts.
    /// Non-coroutine MoveNext methods (regular iterators) are left unchanged.
    /// </summary>
    private static void DeduplicateTypeIdMtSymbols(string content, System.Text.StringBuilder sb)
    {
        var _dedup = new System.Collections.Generic.HashSet<string>(StringComparer.Ordinal);
        // First pass: collect NativeSymbols that have coroutine wrappers
        var coroutineSymbols = new System.Collections.Generic.HashSet<string>(StringComparer.Ordinal);
        foreach (string _line in content.Split('\n'))
        {
            string _t = _line.Trim();
            // Entry_<uid>() functions are emitted by coroutine codegen for async
            // state machine MoveNext methods.  Extract the NativeSymbol from the
            // wrapping extern "C" definition on the next line.
            if (_t.StartsWith("extern \"C\" CHAOS_IL2CPP_INT64 ", StringComparison.Ordinal) &&
                _t.Contains("(CHAOS_IL2CPP_INTPTR, CHAOS_IL2CPP_INTPTR, CHAOS_IL2CPP_INTPTR, CHAOS_IL2CPP_INTPTR) noexcept", StringComparison.Ordinal))
            {
                var _symEnd = _t.IndexOf('(', 0);
                if (_symEnd > 0)
                {
                    string _sym = _t.Substring(0, _symEnd).TrimEnd();
                    _symEnd = _sym.LastIndexOf(' ');
                    if (_symEnd > 0)
                        coroutineSymbols.Add(_sym.Substring(_symEnd + 1));
                }
            }
        }
        // Second pass: dedup type_id/mt and replace async MoveNext declarations.
        // Also dedup function definitions within this page: two different methods
        // may emit the same externally-visible function (e.g. generic instantiation
        // stubs that collapse to the same chaos_stub_definition_*), causing C2084.
        var seenDefinitions = new System.Collections.Generic.HashSet<string>(StringComparer.Ordinal);
        foreach (string _line in content.Split('\n'))
        {
            string _t = _line.Trim();
            if (_t.StartsWith("inline constexpr CHAOS_IL2CPP_UINT64 chaos_type_id_") ||
                _t.StartsWith("inline constexpr CHAOS_IL2CPP_UINT64 chaos_mt_") ||
                _t.StartsWith("inline constexpr CHAOS_IL2CPP_INTPTR chaos_type_id_") ||
                _t.StartsWith("inline constexpr CHAOS_IL2CPP_INTPTR chaos_mt_") ||
                _t.StartsWith("MethodTable chaos_mt_"))
            {
                int _eq = _t.IndexOf(" =");
                if (_eq > 0)
                {
                    string _sym = _t.Substring(0, _eq);
                    if (!_dedup.Add(_sym)) continue;
                }
            }
            // Replace extern "C" CHAOS_IL2CPP_INTPTR declarations for coroutine
            // MoveNext methods with the ABI dispatch signature.  Only replaces
            // declarations whose NativeSymbol also appears as a coroutine wrapper
            // (detected in the first pass above).
            if (_t.StartsWith("extern \"C\" CHAOS_IL2CPP_INTPTR ", StringComparison.Ordinal) &&
                _t.Contains("_MoveNext(", StringComparison.Ordinal) &&
                _t.EndsWith(";", StringComparison.Ordinal))
            {
                var _symEnd2 = _t.IndexOf('(', 0);
                if (_symEnd2 > 0)
                {
                    string _sym2 = _t.Substring(0, _symEnd2).TrimEnd();
                    _symEnd2 = _sym2.LastIndexOf(' ');
                    string _symName2 = _symEnd2 > 0 ? _sym2.Substring(_symEnd2 + 1) : _sym2;
                    if (coroutineSymbols.Contains(_symName2))
                    {
                        sb.AppendLine($"extern \"C\" CHAOS_IL2CPP_INT64 {_symName2}(CHAOS_IL2CPP_INTPTR, CHAOS_IL2CPP_INTPTR, CHAOS_IL2CPP_INTPTR, CHAOS_IL2CPP_INTPTR) noexcept;");
                        continue;
                    }
                }
            }
            // Dedup function definitions within this page (C2084).  Two
            // different methods may emit the same extern "C" function body
            // (e.g. collapse to the same chaos_stub_definition_*).  Skip
            // duplicate definitions — the first occurrence suffices.
            if (_t.StartsWith("extern \"C\" ", StringComparison.Ordinal) &&
                !_t.EndsWith(";", StringComparison.Ordinal))
            {
                // Use LAST '(' to handle function pointer syntax
                // (extern "C" void (*name)(params)).  Using first '(' would
                // incorrectly truncate at the pointer-dereference paren.
                var _parenPos = _t.LastIndexOf('(');
                if (_parenPos > 0)
                {
                    string _fnSig = _t.Substring(0, _parenPos).TrimEnd();
                    if (!seenDefinitions.Add(_fnSig))
                        continue;
                }
            }
            sb.AppendLine(_line);
        }
    }

