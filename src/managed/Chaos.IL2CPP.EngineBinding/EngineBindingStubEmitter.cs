using System.Reflection;
using System.Text;

namespace Chaos.IL2CPP.EngineBinding;

public static class EngineBindingStubEmitter
{
    public static string GenerateForInterface(Type interfaceType)
    {
        ArgumentNullException.ThrowIfNull(interfaceType);

        if (!interfaceType.IsInterface)
        {
            throw new ArgumentException("Engine binding stubs can only be generated from interface types.", nameof(interfaceType));
        }

        var exportMethods = interfaceType
            .GetMethods()
            .Select(
                method => new
                {
                    Method = method,
                    Attribute = method.GetCustomAttribute<EngineExportAttribute>(),
                })
            .Where(entry => entry.Attribute is not null)
            .ToList();
        var callbackMethods = interfaceType
            .GetMethods()
            .Select(
                method => new
                {
                    Method = method,
                    Attribute = method.GetCustomAttribute<EngineCallbackAttribute>(),
                })
            .Where(entry => entry.Attribute is not null)
            .ToList();

        var builder = new StringBuilder();
        var contractSymbol = ToSnakeCase(interfaceType.Name);

        builder.AppendLine("// Generated by Chaos.IL2CPP.EngineBinding v0.");
        builder.AppendLine("#include \"engine_bridge.h\"");
        builder.AppendLine();

        foreach (var exportMethod in exportMethods)
        {
            ValidateSupportedSignature(exportMethod.Method);

            builder.AppendLine(
                $"extern \"C\" engine_status_t {contractSymbol}_{ToSnakeCase(exportMethod.Attribute!.ExportName)}("
                + "engine_runtime_context_t* runtime) {");
            builder.AppendLine("    (void)runtime;");
            builder.AppendLine("    return ENGINE_STATUS_NOT_SUPPORTED;");
            builder.AppendLine("}");
            builder.AppendLine();
        }

        foreach (var callbackMethod in callbackMethods)
        {
            ValidateSupportedSignature(callbackMethod.Method);

            builder.AppendLine(
                $"extern \"C\" engine_status_t {contractSymbol}_register_{ToSnakeCase(callbackMethod.Attribute!.CallbackName)}(");
            builder.AppendLine("    engine_runtime_context_t* runtime,");
            builder.AppendLine("    engine_callback_fn_t callback,");
            builder.AppendLine("    void* user_data,");
            builder.AppendLine("    engine_callback_id_t* out_callback_id) {");
            builder.AppendLine("    return engine_register_callback(");
            builder.AppendLine("        runtime,");
            builder.AppendLine($"        \"{callbackMethod.Attribute.CallbackName}\",");
            builder.AppendLine("        callback,");
            builder.AppendLine("        user_data,");
            builder.AppendLine("        out_callback_id);");
            builder.AppendLine("}");
            builder.AppendLine();
        }

        return builder.ToString().TrimEnd() + Environment.NewLine;
    }

    private static void ValidateSupportedSignature(MethodInfo method)
    {
        if (method.ReturnType != typeof(void))
        {
            throw new NotSupportedException(
                $"Engine binding v0 only supports void-return interface methods. Unsupported method: {method.DeclaringType?.FullName}.{method.Name}");
        }

        if (method.GetParameters().Length != 0)
        {
            throw new NotSupportedException(
                $"Engine binding v0 only supports parameterless interface methods. Unsupported method: {method.DeclaringType?.FullName}.{method.Name}");
        }
    }

    private static string ToSnakeCase(string value)
    {
        if (string.IsNullOrWhiteSpace(value))
        {
            throw new ArgumentException("value must not be empty.", nameof(value));
        }

        var builder = new StringBuilder();
        for (var index = 0; index < value.Length; index++)
        {
            var current = value[index];
            if (char.IsLetterOrDigit(current))
            {
                if (char.IsUpper(current)
                    && builder.Length > 0
                    && builder[^1] != '_')
                {
                    builder.Append('_');
                }

                builder.Append(char.ToLowerInvariant(current));
                continue;
            }

            if (builder.Length > 0 && builder[^1] != '_')
            {
                builder.Append('_');
            }
        }

        return builder.ToString().Trim('_');
    }
}
