using Chaos.IL2CPP.HotUpdate;
using Chaos.TestFramework;

namespace HotUpdateHostPack;

internal static class HotUpdateRoundtripBenchmarkEntry
{
    private const string BridgeId = "BenchHotUpdateRoundtrip/HotPatch::Roundtrip(System.Int32)";
    private const string SubjectId = "BenchHotUpdateRoundtrip/HotPatch::Roundtrip(System.Int32)";
    private const int IterationCount = 1000;

    [ChaosBenchmark(
        ChaosBenchmarkCategory.HotUpdate,
        ChaosMetric.WallClockUs,
        Alias = "hot-update-roundtrip-bench",
        CapabilityFamily = ChaosCapabilityFamily.HotUpdateWorkflow,
        Capability = ChaosCapabilityItem.PatchCallbackFlow,
        Requires = ChaosRuntimeFeature.HotUpdate,
        Archetype = ChaosSolutionArchetype.FullProjectHotUpdateSolution,
        HotUpdateCapability = ChaosHotUpdateCapability.PatchCallbackFlow
            | ChaosHotUpdateCapability.SharedContractBinding,
        Modes = ChaosExecutionMode.Managed,
        WarmupCount = 1,
        IterationCount = 30,
        InvocationCount = 1)]
    public static int RunWorkload()
    {
        var dispatcher = new BridgeDispatcher();
        dispatcher.ApplyPlan(new BridgePlan
        {
            AotToHotUpdate = [],
            HotUpdateToAot = [],
            HotUpdateToEngine = [],
            DelegateWrappers = [],
            AutoGenerated =
            [
                new AutoGeneratedBridgeEntry
                {
                    BridgeId = BridgeId,
                    TargetSubjectId = SubjectId,
                    SignatureKey = "System.Int32(System.Int32)",
                },
            ],
        });
        dispatcher.RegisterManagedTarget(SubjectId, args => AotCallback(Convert.ToInt32(args[0])) + 1);

        var checksum = 0;
        for (var index = 0; index < IterationCount; index++)
        {
            checksum += Convert.ToInt32(dispatcher.Dispatch(BridgeId, [index]));
        }

        return checksum;
    }

    private static int AotCallback(int value)
    {
        return value + 1;
    }
}
