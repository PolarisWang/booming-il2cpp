using System;
using System.Reflection;
using Xunit;

public class ReflectionModuleTests
{
    [Fact]
    public void AllAutoGeneratedMethodsCanExecute()
    {
        var type = typeof(ReflectionModule);
        Assert.NotNull(type);
    }

    /// <summary>
    /// 验证 Module.Name 和 Module.FullyQualifiedName 返回非空值
    /// </summary>
    [Fact]
    public void Fact_ModuleNameProperties_NotEmpty()
    {
        Module m = typeof(int).Module;
        Assert.False(string.IsNullOrEmpty(m.Name));
        Assert.False(string.IsNullOrEmpty(m.FullyQualifiedName));
    }

    /// <summary>
    /// 验证 Module.Assembly 返回正确的程序集
    /// </summary>
    [Fact]
    public void Fact_ModuleAssembly_Matches()
    {
        Module m = typeof(string).Module;
        Assembly asm = m.Assembly;
        Assert.NotNull(asm);
        Assert.Equal(typeof(string).Assembly, asm);
    }

    /// <summary>
    /// 验证 Module.GetTypes 返回模块中定义的类型
    /// </summary>
    [Fact]
    public void Fact_ModuleGetTypes_ReturnsTypes()
    {
        Module m = typeof(int).Module;
        Type[] types = m.GetTypes();
        Assert.NotNull(types);
        Assert.True(types.Length > 0);
    }

    /// <summary>
    /// 验证 Module.GetType 能根据名称查找类型
    /// </summary>
    [Fact]
    public void Fact_ModuleGetType_ByName()
    {
        Module m = typeof(int).Module;
        Type t = m.GetType("System.Int32");
        Assert.NotNull(t);
        Assert.Equal(typeof(int), t);
    }

    /// <summary>
    /// 验证 Module.GetCustomAttributes 返回自定义特性
    /// </summary>
    [Fact]
    public void Fact_ModuleGetCustomAttributes()
    {
        Module m = typeof(int).Module;
        object[] attrs = m.GetCustomAttributes(typeof(System.Runtime.CompilerServices.CompilationRelaxationsAttribute), false);
        Assert.NotNull(attrs);
    }
}
