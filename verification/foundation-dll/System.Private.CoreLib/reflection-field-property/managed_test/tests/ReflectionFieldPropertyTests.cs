using System;
using System.Reflection;
using Xunit;

public class ReflectionFieldPropertyTests
{
    [Fact]
    public void AllAutoGeneratedMethodsCanExecute()
    {
        var type = typeof(ReflectionFieldProperty);
        Assert.NotNull(type);
    }

    // 辅助类型
    class TestHelper
    {
        public int PublicField = 100;
        private string _privateField = "secret";
        public static double StaticField = 3.14;
        public string ReadWriteProp { get; set; } = "prop-value";
        public int ReadOnlyProp { get; } = 42;
        public static bool StaticProp { get; set; } = true;
    }

    /// <summary>
    /// 验证 FieldInfo.GetValue/SetValue 能读写实例字段值
    /// </summary>
    [Fact]
    public void Fact_FieldInfo_GetSetValue_InstanceField()
    {
        var obj = new TestHelper();
        FieldInfo fi = typeof(TestHelper).GetField("PublicField");
        Assert.NotNull(fi);

        object val = fi.GetValue(obj);
        Assert.Equal(100, val);

        fi.SetValue(obj, 200);
        Assert.Equal(200, fi.GetValue(obj));
    }

    /// <summary>
    /// 验证 FieldInfo.FieldType 返回正确的字段类型
    /// </summary>
    [Fact]
    public void Fact_FieldInfo_FieldType_ReturnsCorrectType()
    {
        FieldInfo fi = typeof(TestHelper).GetField("PublicField");
        Assert.Equal(typeof(int), fi.FieldType);
    }

    /// <summary>
    /// 验证 FieldInfo.IsStatic / IsPublic 判断正确
    /// </summary>
    [Fact]
    public void Fact_FieldInfo_IsStatic_IsPublic()
    {
        FieldInfo publicFi = typeof(TestHelper).GetField("PublicField");
        Assert.True(publicFi.IsPublic);
        Assert.False(publicFi.IsStatic);
    }

    /// <summary>
    /// 验证 PropertyInfo.GetValue/SetValue 能读写属性
    /// </summary>
    [Fact]
    public void Fact_PropertyInfo_GetSetValue()
    {
        var obj = new TestHelper();
        PropertyInfo pi = typeof(TestHelper).GetProperty("ReadWriteProp");
        Assert.NotNull(pi);

        object val = pi.GetValue(obj);
        Assert.Equal("prop-value", val);

        pi.SetValue(obj, "new-value");
        Assert.Equal("new-value", pi.GetValue(obj));
    }

    /// <summary>
    /// 验证 PropertyInfo.PropertyType / CanRead / CanWrite 属性
    /// </summary>
    [Fact]
    public void Fact_PropertyInfo_MetadataProperties()
    {
        PropertyInfo rw = typeof(TestHelper).GetProperty("ReadWriteProp");
        Assert.Equal(typeof(string), rw.PropertyType);
        Assert.True(rw.CanRead);
        Assert.True(rw.CanWrite);

        PropertyInfo ro = typeof(TestHelper).GetProperty("ReadOnlyProp");
        Assert.Equal(typeof(int), ro.PropertyType);
        Assert.True(ro.CanRead);
        Assert.False(ro.CanWrite);

        PropertyInfo sp = typeof(TestHelper).GetProperty("StaticProp",
            BindingFlags.Public | BindingFlags.Static);
        Assert.Equal(typeof(bool), sp.PropertyType);
    }
}
