using System;
using System.Collections.Generic;
using System.IO;
using Xunit;

public class ReflectionTypeTests
{
    [Fact]
    public void AllAutoGeneratedMethodsCanExecute()
    {
        var type = typeof(ReflectionType);
        Assert.NotNull(type);
    }

    /// <summary>
    /// 验证 Type.GetType(string) 能正确加载程序集中的类型
    /// </summary>
    [Fact]
    public void Fact_GetType_ByString_ReturnsExpectedType()
    {
        Type t = Type.GetType("System.String");
        Assert.NotNull(t);
        Assert.Equal("System.String", t.FullName);
    }

    /// <summary>
    /// 验证 typeof() 运算符与 GetTypeFromHandle 返回一致
    /// </summary>
    [Fact]
    public void Fact_GetTypeFromHandle_MatchesTypeOf()
    {
        Type fromHandle = Type.GetTypeFromHandle(typeof(int).TypeHandle);
        Assert.Equal(typeof(int), fromHandle);
    }

    /// <summary>
    /// 验证 Type.Name / Type.FullName / Type.Namespace 属性
    /// </summary>
    [Fact]
    public void Fact_TypeNameProperties_ReturnCorrectValues()
    {
        Type t = typeof(Dictionary<string, object>);
        Assert.Equal("Dictionary`2", t.Name);
        Assert.Contains("System.Collections.Generic", t.Namespace);
        Assert.Contains("Dictionary", t.FullName);
    }

    /// <summary>
    /// 验证 IsAbstract / IsSealed / IsInterface / IsValueType 等布尔属性
    /// </summary>
    [Fact]
    public void Fact_TypeBooleanAttributes_CorrectlyIdentified()
    {
        Assert.True(typeof(Stream).IsAbstract);
        Assert.False(typeof(Stream).IsSealed);
        Assert.True(typeof(String).IsSealed);
        Assert.False(typeof(int).IsAbstract);
        Assert.True(typeof(IDisposable).IsInterface);
        Assert.True(typeof(int).IsValueType);
        Assert.False(typeof(string).IsValueType);
    }

    /// <summary>
    /// 验证 IsGenericType / IsArray / IsNested / IsPublic 属性
    /// </summary>
    [Fact]
    public void Fact_TypeStructuralAttributes_CorrectlyIdentified()
    {
        Assert.True(typeof(List<int>).IsGenericType);
        Assert.False(typeof(int).IsGenericType);
        Assert.True(typeof(int[]).IsArray);
        Assert.True(typeof(int).IsPublic);
        Assert.False(typeof(int).IsNested);
    }
}
