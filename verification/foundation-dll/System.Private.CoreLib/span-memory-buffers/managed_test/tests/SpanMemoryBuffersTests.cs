using System;
using System.Runtime.InteropServices;
using Xunit;

public class SpanMemoryBuffersTests
{
    [Fact]
    public void AllAutoGeneratedMethodsCanExecute()
    {
        var type = typeof(SpanMemoryBuffers);
        Assert.NotNull(type);
    }

    /// <summary>
    /// 测试 Span<T> 索引器、Slice、ToArray、Fill、Clear
    /// </summary>
    [Fact]
    public void Test_SpanOfT_BasicOperations()
    {
        int[] arr = { 10, 20, 30, 40, 50 };
        Span<int> span = new(arr);

        Assert.Equal(10, span[0]);
        Assert.Equal(50, span[4]);
        span[0] = 99;
        Assert.Equal(99, span[0]);
        Assert.Equal(99, arr[0]);

        Span<int> sliced = span.Slice(2);
        Assert.Equal(3, sliced.Length);
        Assert.Equal(30, sliced[0]);

        Span<int> sliced2 = span.Slice(1, 2);
        Assert.Equal(2, sliced2.Length);

        int[] copied = span.ToArray();
        Assert.Equal(arr.Length, copied.Length);

        Span<int> fillSpan = new int[4];
        fillSpan.Fill(42);
        Assert.Equal(42, fillSpan[0]);
        fillSpan.Clear();
        Assert.Equal(0, fillSpan[0]);

        Span<int> empty = Span<int>.Empty;
        Assert.True(empty.IsEmpty);

        // Span indexer throws IndexOutOfRangeException for invalid indices
        Assert.Throws<IndexOutOfRangeException>(() => { int[] tmp = new int[2]; var s = new Span<int>(tmp); _ = s[-1]; });
        Assert.Throws<IndexOutOfRangeException>(() => { int[] tmp = new int[2]; var s = new Span<int>(tmp); _ = s[10]; });
    }

    /// <summary>
    /// 测试 ReadOnlySpan<T> 基本操作
    /// </summary>
    [Fact]
    public void Test_ReadOnlySpan_BasicOperations()
    {
        ReadOnlySpan<int> ros = new int[] { 1, 2, 3, 4, 5 };
        Assert.Equal(1, ros[0]);
        Assert.Equal(5, ros[4]);
        Assert.Equal(3, ros.Slice(2)[0]);
        Assert.Equal(2, ros.Slice(1, 2).Length);

        int[] arr = ros.ToArray();
        Assert.Equal(5, arr.Length);
    }

    /// <summary>
    /// 测试 Memory<T> 基本操作
    /// </summary>
    [Fact]
    public void Test_MemoryOfT_BasicOperations()
    {
        int[] arr = { 100, 200, 300, 400, 500 };
        Memory<int> memory = new(arr);

        Memory<int> sliced = memory.Slice(2);
        Assert.Equal(3, sliced.Length);

        Memory<int> sliced2 = memory.Slice(1, 2);
        Assert.Equal(2, sliced2.Length);

        Span<int> span = memory.Span;
        Assert.Equal(100, span[0]);

        int[] copied = memory.ToArray();
        Assert.Equal(arr.Length, copied.Length);

        Memory<int> defaultMem = default;
        Assert.True(defaultMem.IsEmpty);

        Assert.Throws<ArgumentOutOfRangeException>(() => memory.Slice(-1));
    }

    /// <summary>
    /// 测试 MemoryMarshal 辅助方法
    /// </summary>
    [Fact]
    public void Test_MemoryMarshalHelpers()
    {
        int[] arr = { 10, 20, 30 };
        ReadOnlySpan<int> ros = new(arr);
        ref readonly int ref1 = ref MemoryMarshal.GetReference(ros);
        Assert.Equal(10, ref1);

        Span<int> span = new(arr);
        ref int ref2 = ref MemoryMarshal.GetReference(span);
        Assert.Equal(10, ref2);
        ref2 = 99;
        Assert.Equal(99, span[0]);
    }

    /// <summary>
    /// 测试 Span<T>.CopyTo 方法
    /// </summary>
    [Fact]
    public void Test_SpanCopyTo()
    {
        var srcArr = new int[] { 1, 2, 3, 4, 5 };
        Span<int> src = new(srcArr);
        var dstArr = new int[5];
        Span<int> dst = new(dstArr);
        src.CopyTo(dst);
        Assert.Equal(1, dst[0]);
        Assert.Equal(5, dst[4]);

        var smallArr = new int[3];
        Assert.Throws<ArgumentException>(() => { var s = new Span<int>(srcArr); var d = new Span<int>(smallArr); s.CopyTo(d); });
    }
}
