using System;
using System.Reflection;
using System.Text;
using Xunit;

public class ReflectionActivationTests
{
    [Fact]
    public void AllAutoGeneratedMethodsCanExecute()
    {
        var type = typeof(ReflectionActivation);
        Assert.NotNull(type);
    }

    /// <summary>
    /// 验证 Activator.CreateInstance<T>() 能创建泛型实例
    /// </summary>
    [Fact]
    public void Fact_CreateInstance_Generic_Works()
    {
        var sb = Activator.CreateInstance<StringBuilder>();
        Assert.NotNull(sb);
        Assert.IsType<StringBuilder>(sb);
    }

    /// <summary>
    /// 验证 Activator.CreateInstance(Type) 通过 Type 创建实例
    /// </summary>
    [Fact]
    public void Fact_CreateInstance_ByType_CreatesObject()
    {
        object obj = Activator.CreateInstance(typeof(Version));
        Assert.NotNull(obj);
        Assert.IsType<Version>(obj);
    }

    /// <summary>
    /// 验证 Activator.CreateInstance(Type, object[]) 带参数创建实例
    /// </summary>
    [Fact]
    public void Fact_CreateInstance_WithArgs_PassesParameters()
    {
        object obj = Activator.CreateInstance(typeof(Version), new object[] { 1, 0 });
        Assert.NotNull(obj);
        var v = (Version)obj;
        Assert.Equal(1, v.Major);
        Assert.Equal(0, v.Minor);
    }

    /// <summary>
    /// 验证 ConstructorInfo.Invoke 通过构造函数创建实例
    /// </summary>
    [Fact]
    public void Fact_ConstructorInfo_Invoke_CreatesInstance()
    {
        ConstructorInfo ci = typeof(StringBuilder).GetConstructor(Type.EmptyTypes);
        object obj = ci.Invoke(null);
        Assert.NotNull(obj);
        Assert.IsType<StringBuilder>(obj);
    }

    /// <summary>
    /// 验证 Activator.CreateInstance(Type, BindingFlags, Binder, object[], CultureInfo) 重载
    /// </summary>
    [Fact]
    public void Fact_CreateInstance_WithBindingFlags_Works()
    {
        object obj = Activator.CreateInstance(typeof(StringBuilder),
            BindingFlags.Public | BindingFlags.Instance,
            null, null, null);
        Assert.NotNull(obj);
        Assert.IsType<StringBuilder>(obj);
    }
}
