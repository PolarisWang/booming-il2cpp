using System;
using System.Reflection;
using Xunit;

public class AttributesCustomMetadataTests
{
    [Fact]
    public void AllAutoGeneratedMethodsCanExecute()
    {
        var type = typeof(AttributesCustomMetadata);
        Assert.NotNull(type);
    }

    /// <summary>
    /// 测试 Assembly 级别自定义属性获取
    /// </summary>
    [Fact]
    public void Assembly_GetCustomAttribute_Should_Return_AssemblyMetadata()
    {
        var assembly = typeof(int).Assembly;
        var attr = assembly.GetCustomAttribute(typeof(AssemblyDescriptionAttribute));
        Assert.NotNull(attr);
        Assert.IsType<AssemblyDescriptionAttribute>(attr);
    }

    /// <summary>
    /// 测试 Attribute.IsDefined 判断属性是否存在
    /// </summary>
    [Fact]
    public void Attribute_IsDefined_Should_Detect_Existing_Attribute()
    {
        var assembly = typeof(int).Assembly;
        bool defined = Attribute.IsDefined(assembly, typeof(AssemblyDescriptionAttribute));
        Assert.True(defined);

        bool notDefined = Attribute.IsDefined(assembly, typeof(ObsoleteAttribute));
        Assert.False(notDefined);
    }

    /// <summary>
    /// 测试 Attribute.GetCustomAttributes 返回多个属性
    /// </summary>
    [Fact]
    public void GetCustomAttributes_Should_Return_All_Matching_Attributes()
    {
        var assembly = typeof(int).Assembly;
        var attrs = assembly.GetCustomAttributes(typeof(AssemblyDescriptionAttribute), false);
        Assert.NotEmpty(attrs);
    }

    /// <summary>
    /// 测试 MemberInfo.GetCustomAttributes 泛型版本
    /// </summary>
    [Fact]
    public void Type_GetCustomAttributes_Should_Work()
    {
        var type = typeof(string);
        var attrs = type.GetCustomAttributes(typeof(SerializableAttribute), false);
        Assert.NotEmpty(attrs);
    }

    /// <summary>
    /// 测试自定义 Attribute 的 TypeId 属性
    /// </summary>
    [Fact]
    public void Attribute_TypeId_Should_Return_Type()
    {
        var attr = new ObsoleteAttribute("test");
        Assert.NotNull(attr.TypeId);
    }
}
