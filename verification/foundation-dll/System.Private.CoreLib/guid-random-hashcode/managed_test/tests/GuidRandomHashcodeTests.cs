using System;
using Xunit;

public class GuidRandomHashcodeTests
{
    [Fact]
    public void AllAutoGeneratedMethodsCanExecute()
    {
        var type = typeof(GuidRandomHashcode);
        Assert.NotNull(type);
    }

    /// <summary>
    /// 测试 Guid.NewGuid、Guid.Parse、Guid.TryParse、Guid.ToString、Guid.Equals
    /// </summary>
    [Fact]
    public void Test_GuidBasicOperations()
    {
        Guid g1 = Guid.NewGuid();
        Assert.NotEqual(Guid.Empty, g1);

        Guid g2 = Guid.NewGuid();
        Assert.NotEqual(g1, g2);

        string guidStr = "A1B2C3D4-E5F6-7890-ABCD-EF1234567890";
        Guid parsed = Guid.Parse(guidStr);
        Assert.Equal(guidStr, parsed.ToString().ToUpperInvariant());

        Assert.True(Guid.TryParse(guidStr, out Guid tryResult));
        Assert.Equal(parsed, tryResult);

        Assert.False(Guid.TryParse("not-a-guid", out _));
        Assert.False(Guid.TryParse("", out _));
        Assert.False(Guid.TryParse(null, out _));

        Guid gA = new("A1B2C3D4-E5F6-7890-ABCD-EF1234567890");
        Guid gB = new("A1B2C3D4-E5F6-7890-ABCD-EF1234567890");
        Assert.True(gA.Equals(gB));
        Assert.True(gA == gB);
        Assert.Equal(gA.GetHashCode(), gB.GetHashCode());
    }

    /// <summary>
    /// 测试 Random.Next、NextBytes 的多重行为
    /// </summary>
    [Fact]
    public void Test_RandomNextAndNextBytes()
    {
        var rng = new Random();
        int val = rng.Next();
        Assert.InRange(val, 0, int.MaxValue);

        int bounded = rng.Next(100);
        Assert.InRange(bounded, 0, 99);

        int ranged = rng.Next(50, 100);
        Assert.InRange(ranged, 50, 99);

        Assert.Throws<ArgumentOutOfRangeException>(() => rng.Next(-1));
        Assert.Throws<ArgumentOutOfRangeException>(() => rng.Next(10, 5));

        byte[] buffer = new byte[32];
        rng.NextBytes(buffer);
        rng.NextBytes(Array.Empty<byte>());
    }

    /// <summary>
    /// 测试 HashCode.Combine、HashCode.Add 和 HashCode.ToHashCode
    /// </summary>
    [Fact]
    public void Test_HashCodeCombineAndAdd()
    {
        int h1 = HashCode.Combine(42, 99);
        int h2 = HashCode.Combine(42, 100);
        Assert.NotEqual(h1, h2);

        int h3 = HashCode.Combine(42, 99);
        Assert.Equal(h1, h3);

        int h4 = HashCode.Combine("hello", 42, true);
        int h5 = HashCode.Combine("hello", 42, true);
        Assert.Equal(h4, h5);

        HashCode hc = default;
        hc.Add(10);
        hc.Add("test");
        hc.Add(3.14);
        int combined = hc.ToHashCode();

        HashCode hc2 = default;
        hc2.Add(10);
        hc2.Add("test");
        hc2.Add(3.14);
        Assert.Equal(combined, hc2.ToHashCode());
    }

    /// <summary>
    /// 测试 Guid 从字节数组构造和 Parse 异常路径
    /// </summary>
    [Fact]
    public void Test_GuidCtorAndExceptionPaths()
    {
        byte[] guidBytes = new byte[16];
        for (int i = 0; i < 16; i++) guidBytes[i] = (byte)(i + 1);
        Guid fromBytes = new(guidBytes);
        Assert.Equal(32, fromBytes.ToString("N").Length);

        Assert.Throws<FormatException>(() => Guid.Parse("invalid-guid"));
        Assert.Throws<FormatException>(() => Guid.Parse(""));
        Assert.Throws<ArgumentNullException>(() => Guid.Parse(null!));

        Assert.False(fromBytes.Equals("not-a-guid"));
    }

    /// <summary>
    /// 测试 Random 种子确定性
    /// </summary>
    [Fact]
    public void Test_RandomDeterministicAndNextDouble()
    {
        var rng1 = new Random(42);
        var rng2 = new Random(42);
        for (int i = 0; i < 10; i++)
        {
            Assert.Equal(rng1.Next(), rng2.Next());
        }

        var rng = new Random();
        for (int i = 0; i < 100; i++)
        {
            double d = rng.NextDouble();
            Assert.InRange(d, 0.0, 1.0);
        }
    }
}
