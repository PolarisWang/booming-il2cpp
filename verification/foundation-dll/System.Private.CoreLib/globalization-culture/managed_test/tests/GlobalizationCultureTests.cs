using System;
using System.Globalization;
using Xunit;

public class GlobalizationCultureTests
{
    [Fact]
    public void AllAutoGeneratedMethodsCanExecute()
    {
        var type = typeof(GlobalizationCulture);
        Assert.NotNull(type);
    }

    /// <summary>
    /// 测试 CultureInfo.CurrentCulture 与 InvariantCulture 基本获取
    /// </summary>
    [Fact]
    public void CultureInfo_Current_And_Invariant_Should_Be_Accessible()
    {
        var current = CultureInfo.CurrentCulture;
        Assert.NotNull(current);

        var invariant = CultureInfo.InvariantCulture;
        Assert.NotNull(invariant);
        Assert.Equal("", invariant.Name);
    }

    /// <summary>
    /// 测试 CultureInfo.GetCultureInfo 获取特定文化信息
    /// </summary>
    [Fact]
    public void CultureInfo_GetCultureInfo_Should_Return_Known_Culture()
    {
        var ci = CultureInfo.GetCultureInfo("en-US");
        Assert.NotNull(ci);
        Assert.Equal("en-US", ci.Name);
        Assert.NotNull(ci.DisplayName);
    }

    /// <summary>
    /// 测试 CultureInfo.Name / DisplayName / DateTimeFormat / NumberFormat 属性
    /// </summary>
    [Fact]
    public void CultureInfo_Properties_Should_Be_Accessible()
    {
        var ci = CultureInfo.InvariantCulture;
        Assert.Equal("", ci.Name);
        Assert.NotNull(ci.DisplayName);
        Assert.NotNull(ci.DateTimeFormat);
        Assert.NotNull(ci.NumberFormat);
    }

    /// <summary>
    /// 测试 CompareInfo.Compare / IndexOf 字符串比较
    /// </summary>
    [Fact]
    public void CompareInfo_Compare_And_IndexOf_Should_Work()
    {
        var compareInfo = CultureInfo.InvariantCulture.CompareInfo;
        int cmp = compareInfo.Compare("abc", "abc");
        Assert.Equal(0, cmp);

        cmp = compareInfo.Compare("abc", "abd");
        Assert.True(cmp < 0);

        int idx = compareInfo.IndexOf("hello world", "world");
        Assert.Equal(6, idx);
    }

    /// <summary>
    /// 测试 TextInfo.ToUpper / ToLower / CultureName
    /// </summary>
    [Fact]
    public void TextInfo_Transformations_Should_Work()
    {
        var textInfo = CultureInfo.InvariantCulture.TextInfo;
        Assert.Equal("HELLO", textInfo.ToUpper("hello"));
        Assert.Equal("hello", textInfo.ToLower("HELLO"));
        Assert.NotNull(textInfo.CultureName);
    }
}
