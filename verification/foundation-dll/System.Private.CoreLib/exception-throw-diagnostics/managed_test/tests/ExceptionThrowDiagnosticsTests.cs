using System;
using Xunit;

public class ExceptionThrowDiagnosticsTests
{
    [Fact]
    public void AllAutoGeneratedMethodsCanExecute()
    {
        var type = typeof(ExceptionThrowDiagnostics);
        Assert.NotNull(type);
    }

    /// <summary>
    /// 测试 Exception 基本构造与 Message 属性读取
    /// </summary>
    [Fact]
    public void Exception_Constructor_And_Message_Should_Work()
    {
        var ex = new Exception("test message");
        Assert.Equal("test message", ex.Message);
        Assert.Null(ex.InnerException);
    }

    /// <summary>
    /// 测试异常链与 GetBaseException
    /// </summary>
    [Fact]
    public void Exception_InnerException_Chain_Should_Resolve()
    {
        var inner = new Exception("inner");
        var outer = new Exception("outer", inner);
        Assert.Equal(inner, outer.InnerException);
        Assert.Equal(inner, outer.GetBaseException());
    }

    /// <summary>
    /// 测试派生异常类型 ArgumentException / ArgumentNullException / ArgumentOutOfRangeException
    /// </summary>
    [Fact]
    public void ArgumentException_Derived_Types_Should_Construct()
    {
        var argEx = new ArgumentException("invalid arg", "paramName");
        Assert.Contains("invalid arg", argEx.Message);

        var nullEx = new ArgumentNullException("paramName");
        Assert.Contains("paramName", nullEx.Message);

        var rangeEx = new ArgumentOutOfRangeException("paramName");
        Assert.Contains("paramName", rangeEx.Message);
    }

    /// <summary>
    /// 测试 InvalidOperationException / NotSupportedException / NotImplementedException
    /// </summary>
    [Fact]
    public void Common_Exception_Types_Should_Construct()
    {
        var ioe = new InvalidOperationException("invalid op");
        Assert.Contains("invalid op", ioe.Message);

        var nse = new NotSupportedException("not supported");
        Assert.Contains("not supported", nse.Message);

        var nie = new NotImplementedException("not impl");
        Assert.Contains("not impl", nie.Message);
    }

    /// <summary>
    /// 测试 Exception.ToString 与 HResult 属性
    /// </summary>
    [Fact]
    public void Exception_ToString_And_HResult_Should_Be_Accessible()
    {
        var ex = new Exception("test");
        var str = ex.ToString();
        Assert.Contains("test", str);
        Assert.IsType<int>(ex.HResult);
    }
}
