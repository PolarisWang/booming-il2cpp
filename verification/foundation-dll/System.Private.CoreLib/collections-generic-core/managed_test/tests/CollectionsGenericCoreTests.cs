using System;
using System.Collections.Generic;
using Xunit;

public class CollectionsGenericCoreTests
{
    [Fact]
    public void AllAutoGeneratedMethodsCanExecute()
    {
        var type = typeof(CollectionsGenericCore);
        Assert.NotNull(type);
    }

    /// <summary>
    /// 测试 List<T> 的 Add、Remove、Contains、IndexOf、Sort、Find
    /// </summary>
    [Fact]
    public void Test_ListOfT_BasicOperations()
    {
        var list = new List<int>();
        list.Add(10);
        list.Add(20);
        list.Add(30);
        list.Add(20);
        Assert.Equal(4, list.Count);
        Assert.Equal(10, list[0]);

        Assert.True(list.Contains(10));
        Assert.False(list.Contains(99));

        Assert.Equal(0, list.IndexOf(10));
        Assert.Equal(1, list.IndexOf(20));

        bool removed = list.Remove(20);
        Assert.True(removed);
        Assert.Equal(3, list.Count);

        list.Clear();
        list.Add(3);
        list.Add(1);
        list.Add(4);
        list.Add(1);
        list.Add(5);
        list.Sort();
        Assert.Equal(new[] { 1, 1, 3, 4, 5 }, list.ToArray());

        Assert.Equal(3, list.Find(x => x >= 3));
    }

    /// <summary>
    /// 测试 Dictionary<K,V> 的 Add、TryGetValue、ContainsKey、Remove
    /// </summary>
    [Fact]
    public void Test_Dictionary_BasicOperations()
    {
        var dict = new Dictionary<string, int>();
        dict.Add("one", 1);
        dict.Add("two", 2);
        dict.Add("three", 3);
        Assert.Equal(3, dict.Count);

        Assert.Throws<ArgumentException>(() => dict.Add("one", 10));

        Assert.True(dict.TryGetValue("one", out int val1));
        Assert.Equal(1, val1);

        Assert.False(dict.TryGetValue("nonexistent", out int val2));
        Assert.Equal(0, val2);

        Assert.True(dict.ContainsKey("two"));
        Assert.False(dict.ContainsKey("four"));

        Assert.True(dict.Remove("one"));
        Assert.False(dict.ContainsKey("one"));
    }

    /// <summary>
    /// 测试 HashSet<T> 的 Add、Contains、Remove
    /// </summary>
    [Fact]
    public void Test_HashSet_BasicOperations()
    {
        var set = new HashSet<int>();
        Assert.True(set.Add(10));
        Assert.True(set.Add(20));
        Assert.True(set.Add(30));
        Assert.False(set.Add(20));
        Assert.Equal(3, set.Count);

        Assert.True(set.Contains(10));
        Assert.False(set.Contains(99));

        Assert.True(set.Remove(20));
        Assert.False(set.Contains(20));
        Assert.Equal(2, set.Count);
    }

    /// <summary>
    /// 测试集合的异常路径和边界情况
    /// </summary>
    [Fact]
    public void Test_Collections_ExceptionPaths()
    {
        var list = new List<int> { 1, 2, 3 };
        Assert.Throws<ArgumentOutOfRangeException>(() => list[-1]);
        Assert.Throws<ArgumentOutOfRangeException>(() => list[10]);

        var dict = new Dictionary<string, int>();
        Assert.Throws<ArgumentNullException>(() => dict.Add(null!, 1));
        Assert.Throws<ArgumentNullException>(() => dict.ContainsKey(null!));
        Assert.Throws<ArgumentNullException>(() => dict.TryGetValue(null!, out _));
    }

    /// <summary>
    /// 测试集合在多种数据类型上的泛型行为
    /// </summary>
    [Fact]
    public void Test_Collections_WithDifferentTypes()
    {
        var intList = new List<int> { 1, 2, 3 };
        Assert.Equal(1, intList.IndexOf(2));

        var strList = new List<string> { "a", "b", "c" };
        Assert.True(strList.Contains("b"));

        var intDict = new Dictionary<int, int> { { 1, 10 }, { 2, 20 } };
        Assert.True(intDict.ContainsKey(1));

        var strSet = new HashSet<string> { "x", "y", "z" };
        Assert.True(strSet.Contains("y"));
    }
}
