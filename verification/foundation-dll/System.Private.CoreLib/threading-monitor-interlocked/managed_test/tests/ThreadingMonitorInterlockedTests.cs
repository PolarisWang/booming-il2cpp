using System;
using System.Threading;
using Xunit;

public class ThreadingMonitorInterlockedTests
{
    [Fact]
    public void AllAutoGeneratedMethodsCanExecute()
    {
        var type = typeof(ThreadingMonitorInterlocked);
        Assert.NotNull(type);
    }

    /// <summary>
    /// 测试 Interlocked.Increment / Decrement
    /// </summary>
    [Fact]
    public void Interlocked_Increment_Decrement_Should_Modify_Atomically()
    {
        int value = 0;
        int result = Interlocked.Increment(ref value);
        Assert.Equal(1, result);
        Assert.Equal(1, value);

        result = Interlocked.Decrement(ref value);
        Assert.Equal(0, result);
        Assert.Equal(0, value);
    }

    /// <summary>
    /// 测试 Interlocked.Exchange / CompareExchange
    /// </summary>
    [Fact]
    public void Interlocked_Exchange_And_CompareExchange_Should_Swap()
    {
        int value = 10;
        int old = Interlocked.Exchange(ref value, 20);
        Assert.Equal(10, old);
        Assert.Equal(20, value);

        int compared = Interlocked.CompareExchange(ref value, 30, 20);
        Assert.Equal(20, compared);
        Assert.Equal(30, value);

        compared = Interlocked.CompareExchange(ref value, 99, 0);
        Assert.Equal(30, compared);
        Assert.Equal(30, value);
    }

    /// <summary>
    /// 测试 Interlocked.Add
    /// </summary>
    [Fact]
    public void Interlocked_Add_Should_Sum_Atomically()
    {
        int value = 10;
        int result = Interlocked.Add(ref value, 5);
        Assert.Equal(15, result);
        Assert.Equal(15, value);
    }

    /// <summary>
    /// 测试 Monitor.Enter / Exit 同步原语
    /// </summary>
    [Fact]
    public void Monitor_Enter_Exit_Should_Synchronize()
    {
        var lockObj = new object();
        bool taken = false;
        try
        {
            Monitor.Enter(lockObj, ref taken);
            Assert.True(taken);
        }
        finally
        {
            if (taken)
                Monitor.Exit(lockObj);
        }
    }

    /// <summary>
    /// 测试 Interlocked.MemoryBarrier
    /// </summary>
    [Fact]
    public void Interlocked_MemoryBarrier_Should_Not_Throw()
    {
        Interlocked.MemoryBarrier();
        Assert.True(true);
    }
}
