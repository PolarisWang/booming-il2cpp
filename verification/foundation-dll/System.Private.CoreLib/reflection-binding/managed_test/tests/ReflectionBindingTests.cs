using System;
using System.Globalization;
using System.Reflection;
using Xunit;

public class ReflectionBindingTests
{
    [Fact]
    public void AllAutoGeneratedMethodsCanExecute()
    {
        var type = typeof(ReflectionBinding);
        Assert.NotNull(type);
    }

    // 辅助类型
    class TestHelper
    {
        private int _hiddenField = 123;
        public int PublicField = 456;
        public int PublicProperty { get; set; } = 789;
        private static string _staticField = "static";
        public static string StaticMethod() => "static-result";
        private string PrivateMethod() => "private-result";
    }

    /// <summary>
    /// 验证 Type.GetMethod with BindingFlags 能获取私有方法
    /// </summary>
    [Fact]
    public void Fact_GetMethod_WithBindingFlags_FindsPrivateMethod()
    {
        MethodInfo mi = typeof(TestHelper).GetMethod("PrivateMethod",
            BindingFlags.NonPublic | BindingFlags.Instance);
        Assert.NotNull(mi);
        var obj = new TestHelper();
        object result = mi.Invoke(obj, null);
        Assert.Equal("private-result", result);
    }

    /// <summary>
    /// 验证 Type.GetField with BindingFlags 能获取私有字段
    /// </summary>
    [Fact]
    public void Fact_GetField_WithBindingFlags_FindsPrivateField()
    {
        FieldInfo fi = typeof(TestHelper).GetField("_hiddenField",
            BindingFlags.NonPublic | BindingFlags.Instance);
        Assert.NotNull(fi);
        var obj = new TestHelper();
        object val = fi.GetValue(obj);
        Assert.Equal(123, val);
    }

    /// <summary>
    /// 验证 Type.GetProperty with BindingFlags 能获取属性
    /// </summary>
    [Fact]
    public void Fact_GetProperty_WithBindingFlags()
    {
        PropertyInfo pi = typeof(TestHelper).GetProperty("PublicProperty",
            BindingFlags.Public | BindingFlags.Instance);
        Assert.NotNull(pi);
        var obj = new TestHelper();
        object val = pi.GetValue(obj);
        Assert.Equal(789, val);
    }

    /// <summary>
    /// 验证 MethodBase.Invoke with BindingFlags 通过 Invoke 调用静态方法
    /// </summary>
    [Fact]
    public void Fact_Invoke_WithBindingFlags_CallsStaticMethod()
    {
        MethodInfo mi = typeof(TestHelper).GetMethod("StaticMethod",
            BindingFlags.Public | BindingFlags.Static);
        object result = mi.Invoke(null, BindingFlags.Default, null,
            new object[] { }, CultureInfo.InvariantCulture);
        Assert.Equal("static-result", result);
    }

    /// <summary>
    /// 验证 Type.GetField 无 BindingFlags 只能获取公开字段
    /// </summary>
    [Fact]
    public void Fact_GetField_Default_OnlyPublic()
    {
        FieldInfo publicFi = typeof(TestHelper).GetField("PublicField");
        Assert.NotNull(publicFi);
        FieldInfo privateFi = typeof(TestHelper).GetField("_hiddenField");
        Assert.Null(privateFi);
    }
}
