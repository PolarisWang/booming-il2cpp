using System;
using Xunit;

public class ObjectEqualityIdentityTests
{
    [Fact]
    public void AllAutoGeneratedMethodsCanExecute()
    {
        var type = typeof(ObjectEqualityIdentity);
        Assert.NotNull(type);
    }

    /// <summary>
    /// 测试 Object.Equals 实例方法与静态方法
    /// </summary>
    [Fact]
    public void Object_Equals_Should_Compare_By_Reference()
    {
        var a = new object();
        var b = new object();

        Assert.False(a.Equals(b));
        Assert.True(a.Equals(a));

        Assert.False(Object.Equals(a, b));
        Assert.True(Object.Equals(a, a));
        Assert.True(Object.Equals(null, null));
    }

    /// <summary>
    /// 测试 Object.ReferenceEquals 引用相等比较
    /// </summary>
    [Fact]
    public void Object_ReferenceEquals_Should_Compare_Identity()
    {
        var a = new object();
        var b = new object();

        Assert.False(Object.ReferenceEquals(a, b));
        Assert.True(Object.ReferenceEquals(a, a));
        Assert.True(Object.ReferenceEquals(null, null));

        int x = 42;
        Assert.False(Object.ReferenceEquals(x, x));
    }

    /// <summary>
    /// 测试 Object.GetHashCode 稳定性
    /// </summary>
    [Fact]
    public void Object_GetHashCode_Should_Be_Stable_Per_Instance()
    {
        var obj = new object();
        int hash1 = obj.GetHashCode();
        int hash2 = obj.GetHashCode();
        Assert.Equal(hash1, hash2);
    }

    /// <summary>
    /// 测试 Object.ToString 返回类型全名
    /// </summary>
    [Fact]
    public void Object_ToString_Should_Return_TypeName()
    {
        var obj = new object();
        Assert.Equal("System.Object", obj.ToString());
    }

    /// <summary>
    /// 测试 Object.GetType 返回正确运行时类型
    /// </summary>
    [Fact]
    public void Object_GetType_Should_Return_Runtime_Type()
    {
        object obj = new object();
        Assert.Equal(typeof(object), obj.GetType());

        object str = "hello";
        Assert.Equal(typeof(string), str.GetType());
    }
}
