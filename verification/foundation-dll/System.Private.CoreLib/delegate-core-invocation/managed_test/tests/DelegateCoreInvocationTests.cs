using System;
using Xunit;

public class DelegateCoreInvocationTests
{
    [Fact]
    public void AllAutoGeneratedMethodsCanExecute()
    {
        var type = typeof(DelegateCoreInvocation);
        Assert.NotNull(type);
    }

    /// <summary>
    /// 测试 Action 委托创建与调用
    /// </summary>
    [Fact]
    public void Action_Delegate_Create_And_Invoke_Should_Work()
    {
        int value = 0;
        Action action = () => value = 42;
        action();
        Assert.Equal(42, value);
    }

    /// <summary>
    /// 测试 Func<int, int> 委托创建与返回值
    /// </summary>
    [Fact]
    public void Func_Delegate_Create_And_Invoke_Should_Return_Value()
    {
        Func<int, int> func = x => x + 1;
        var result = func(41);
        Assert.Equal(42, result);
    }

    /// <summary>
    /// 测试 Delegate.Combine 与 Delegate.Remove
    /// </summary>
    [Fact]
    public void Delegate_Combine_And_Remove_Should_Manage_InvocationList()
    {
        Action a = () => { };
        Action b = () => { };
        var combined = (Action)Delegate.Combine(a, b);
        Assert.NotNull(combined);

        var removed = (Action)Delegate.Remove(combined, a);
        Assert.NotNull(removed);
    }

    /// <summary>
    /// 测试 MulticastDelegate.GetInvocationList
    /// </summary>
    [Fact]
    public void MulticastDelegate_GetInvocationList_Should_Return_All_Targets()
    {
        Action a = () => { };
        Action b = () => { };
        var combined = (Action)Delegate.Combine(a, b);
        var list = combined.GetInvocationList();
        Assert.Equal(2, list.Length);
    }

    /// <summary>
    /// 测试 Delegate.DynamicInvoke
    /// </summary>
    [Fact]
    public void Delegate_DynamicInvoke_Should_Invoke_With_Object_Args()
    {
        Func<int, int> func = x => x + 1;
        var result = (int)func.DynamicInvoke(41);
        Assert.Equal(42, result);
    }
}
