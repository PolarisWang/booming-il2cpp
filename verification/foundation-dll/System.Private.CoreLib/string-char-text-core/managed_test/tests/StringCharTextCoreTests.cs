using System;
using Xunit;

public class StringCharTextCoreTests
{
    [Fact]
    public void AllAutoGeneratedMethodsCanExecute()
    {
        var type = typeof(StringCharTextCore);
        Assert.NotNull(type);
    }

    /// <summary>
    /// 测试 String.Compare 的各种场景
    /// </summary>
    [Fact]
    public void Test_StringCompare_NormalAndEdge()
    {
        Assert.Equal(0, string.Compare("hello", "hello"));
        Assert.True(string.Compare("abc", "def") < 0);
        Assert.True(string.Compare("xyz", "abc") > 0);
        Assert.Equal(0, string.Compare("", ""));
        Assert.Equal(0, string.Compare(null, null));
        Assert.True(string.Compare(null, "a") < 0);
        Assert.Equal(0, string.Compare("hello", 0, "hello", 0, 5));
    }

    /// <summary>
    /// 测试 String.Concat 的各种重载
    /// </summary>
    [Fact]
    public void Test_StringConcat_VariousOverloads()
    {
        Assert.Equal("helloworld", string.Concat("hello", "world"));
        Assert.Equal("abc", string.Concat("a", "b", "c"));
        Assert.Equal("", string.Concat("", ""));
        Assert.Equal("hello", string.Concat("hello", null));
        Assert.Equal("abc", string.Concat(new[] { "a", "b", "c" }));
    }

    /// <summary>
    /// 测试 String.Contains / StartsWith / EndsWith
    /// </summary>
    [Fact]
    public void Test_StringContainsStartsWithEndsWith()
    {
        string text = "Hello, World!";
        Assert.True(text.Contains("World"));
        Assert.False(text.Contains("Universe"));
        Assert.True(text.StartsWith("Hello"));
        Assert.False(text.StartsWith("World"));
        Assert.True(text.EndsWith("World!"));
        Assert.False(text.EndsWith("Hello"));
    }

    /// <summary>
    /// 测试 String.IndexOf / Substring / Split / Join
    /// </summary>
    [Fact]
    public void Test_StringIndexOfSubstringSplitJoin()
    {
        string text = "a,b,c,d";
        Assert.Equal(0, text.IndexOf('a'));
        Assert.Equal(1, text.IndexOf(','));
        Assert.Equal(-1, text.IndexOf('z'));

        Assert.Equal("a", text.Substring(0, 1));
        Assert.Equal("b,c,d", text.Substring(2));
        Assert.Throws<ArgumentOutOfRangeException>(() => text.Substring(-1));

        var parts = text.Split(',');
        Assert.Equal(4, parts.Length);
        Assert.Equal("a", parts[0]);
        Assert.Equal("d", parts[3]);

        Assert.Equal("a-b-c-d", string.Join("-", parts));
    }

    /// <summary>
    /// 测试 String.Format / ToUpper / ToLower / Trim
    /// </summary>
    [Fact]
    public void Test_StringFormatToUpperToLowerTrim()
    {
        Assert.Equal("Value: 42", string.Format("Value: {0}", 42));
        Assert.Throws<FormatException>(() => string.Format("{0}", new object[] { }));

        Assert.Equal("HELLO", "hello".ToUpper());
        Assert.Equal("hello", "HELLO".ToLower());
        Assert.Equal("hello", "  hello  ".Trim());
        Assert.Equal("", "   ".Trim());
    }

    /// <summary>
    /// 测试 String.Replace 的各种场景
    /// </summary>
    [Fact]
    public void Test_StringReplace()
    {
        Assert.Equal("h*llo", "hello".Replace("e", "*"));
        Assert.Equal("hello", "hello".Replace("x", "y"));
        Assert.Equal("", "".Replace("a", "b"));
        Assert.Equal("hllo", "hello".Replace("e", ""));
        Assert.Equal("abab", "cbcb".Replace("c", "a"));
    }
}
