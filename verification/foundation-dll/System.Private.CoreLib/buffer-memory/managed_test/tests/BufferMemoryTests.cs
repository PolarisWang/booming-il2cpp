using System;
using Xunit;

public class BufferMemoryTests
{
    [Fact]
    public void AllAutoGeneratedMethodsCanExecute()
    {
        var type = typeof(BufferMemory);
        Assert.NotNull(type);
    }

    /// <summary>
    /// 测试目的：验证 Buffer.ByteLength 对字节数组返回正确长度
    /// </summary>
    [Fact]
    public void Test_ByteLength_ByteArray()
    {
        byte[] arr = new byte[100];
        int len = Buffer.ByteLength(arr);
        Assert.Equal(100, len);
    }

    /// <summary>
    /// 测试目的：验证 Buffer.ByteLength 对 int 数组返回元素个数乘以 sizeof(int)
    /// </summary>
    [Fact]
    public void Test_ByteLength_IntArray()
    {
        int[] arr = new int[25];
        int len = Buffer.ByteLength(arr);
        Assert.Equal(25 * sizeof(int), len);
    }

    /// <summary>
    /// 测试目的：验证 Buffer.ByteLength 对 null 数组抛出 ArgumentNullException
    /// </summary>
    [Fact]
    public void Test_ByteLength_NullArray()
    {
        Assert.Throws<ArgumentNullException>(() => Buffer.ByteLength(null!));
    }

    /// <summary>
    /// 测试目的：验证 Buffer.GetByte 正确获取指定索引的字节
    /// </summary>
    [Fact]
    public void Test_GetByte_Normal()
    {
        byte[] arr = { 10, 20, 30, 40, 50 };
        byte val = Buffer.GetByte(arr, 2);
        Assert.Equal(30, val);
    }

    /// <summary>
    /// 测试目的：验证 Buffer.GetByte 在越界时抛出 ArgumentException
    /// </summary>
    [Fact]
    public void Test_GetByte_OutOfRange()
    {
        byte[] arr = { 10, 20, 30 };
        Assert.Throws<ArgumentOutOfRangeException>(() => Buffer.GetByte(arr, 5));
    }

    /// <summary>
    /// 测试目的：验证 Buffer.SetByte 正确设置指定索引的字节
    /// </summary>
    [Fact]
    public void Test_SetByte_Normal()
    {
        byte[] arr = { 10, 20, 30, 40, 50 };
        Buffer.SetByte(arr, 1, 99);
        Assert.Equal(99, Buffer.GetByte(arr, 1));
    }

    /// <summary>
    /// 测试目的：验证 Buffer.SetByte 在越界时抛出 ArgumentException
    /// </summary>
    [Fact]
    public void Test_SetByte_OutOfRange()
    {
        byte[] arr = { 10, 20, 30 };
        Assert.Throws<ArgumentOutOfRangeException>(() => Buffer.SetByte(arr, 10, 0));
    }

    /// <summary>
    /// 测试目的：验证 Buffer.BlockCopy 正确复制数组内容
    /// </summary>
    [Fact]
    public void Test_BlockCopy_Normal()
    {
        byte[] src = { 1, 2, 3, 4, 5, 6, 7, 8 };
        byte[] dst = new byte[8];
        Buffer.BlockCopy(src, 2, dst, 0, 4);
        Assert.Equal(3, dst[0]);
        Assert.Equal(4, dst[1]);
        Assert.Equal(5, dst[2]);
        Assert.Equal(6, dst[3]);
    }

    /// <summary>
    /// 测试目的：验证 Buffer.BlockCopy 在参数无效时抛出异常
    /// </summary>
    [Fact]
    public void Test_BlockCopy_InvalidArguments()
    {
        byte[] src = { 1, 2, 3 };
        byte[] dst = new byte[3];
        Assert.Throws<ArgumentNullException>(() => Buffer.BlockCopy(null!, 0, dst, 0, 1));
        Assert.Throws<ArgumentNullException>(() => Buffer.BlockCopy(src, 0, null!, 0, 1));
    }

    /// <summary>
    /// 测试目的：验证 Buffer.BlockCopy 零长度复制
    /// </summary>
    [Fact]
    public void Test_BlockCopy_ZeroLength()
    {
        byte[] src = { 1, 2, 3 };
        byte[] dst = new byte[3];
        dst[0] = 99;
        Buffer.BlockCopy(src, 0, dst, 0, 0);
        Assert.Equal(99, dst[0]);
    }
}
