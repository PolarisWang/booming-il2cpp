using System;
using System.Collections.Generic;
using Xunit;

public class ReflectionGenericsTests
{
    [Fact]
    public void AllAutoGeneratedMethodsCanExecute()
    {
        var type = typeof(ReflectionGenerics);
        Assert.NotNull(type);
    }

    /// <summary>
    /// 验证 Type.MakeGenericType 能正确构造封闭泛型类型
    /// </summary>
    [Fact]
    public void Fact_MakeGenericType_ConstructsClosedType()
    {
        Type openType = typeof(List<>);
        Type closedType = openType.MakeGenericType(typeof(int));
        Assert.NotNull(closedType);
        Assert.Equal(typeof(List<int>), closedType);
        Assert.True(closedType.IsConstructedGenericType);
    }

    /// <summary>
    /// 验证 Type.GetGenericTypeDefinition 从封闭泛型还原开放定义
    /// </summary>
    [Fact]
    public void Fact_GetGenericTypeDefinition_ReturnsOpenType()
    {
        Type closedType = typeof(Dictionary<string, int>);
        Type openType = closedType.GetGenericTypeDefinition();
        Assert.NotNull(openType);
        Assert.True(openType.IsGenericTypeDefinition);
        Assert.Equal(typeof(Dictionary<,>), openType);
    }

    /// <summary>
    /// 验证 Type.GetGenericArguments 返回正确的泛型参数数组
    /// </summary>
    [Fact]
    public void Fact_GetGenericArguments_ReturnsTypeArgs()
    {
        Type closedType = typeof(Dictionary<string, Guid>);
        Type[] args = closedType.GetGenericArguments();
        Assert.Equal(2, args.Length);
        Assert.Equal(typeof(string), args[0]);
        Assert.Equal(typeof(Guid), args[1]);
    }

    /// <summary>
    /// 验证 IsGenericType / IsGenericTypeDefinition / IsConstructedGenericType 判断正确
    /// </summary>
    [Fact]
    public void Fact_GenericTypeBooleanFlags_Correct()
    {
        Assert.True(typeof(List<>).IsGenericType);
        Assert.True(typeof(List<>).IsGenericTypeDefinition);
        Assert.False(typeof(List<>).IsConstructedGenericType);

        Assert.True(typeof(List<int>).IsGenericType);
        Assert.False(typeof(List<int>).IsGenericTypeDefinition);
        Assert.True(typeof(List<int>).IsConstructedGenericType);

        Assert.False(typeof(int).IsGenericType);
    }

    /// <summary>
    /// 验证 ContainsGenericParameters 判断包含泛型参数的未绑定类型
    /// </summary>
    [Fact]
    public void Fact_ContainsGenericParameters_Detection()
    {
        Assert.True(typeof(List<>).ContainsGenericParameters);
        Assert.False(typeof(List<int>).ContainsGenericParameters);
    }
}
