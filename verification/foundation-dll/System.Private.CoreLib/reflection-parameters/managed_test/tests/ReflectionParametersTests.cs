using System;
using System.Reflection;
using System.Runtime.InteropServices;
using Xunit;

public class ReflectionParametersTests
{
    [Fact]
    public void AllAutoGeneratedMethodsCanExecute()
    {
        var type = typeof(ReflectionParameters);
        Assert.NotNull(type);
    }

    // 辅助类型 — 避免可选参数在必选参数之前
    class TestHelper
    {
        public void MethodWithParams(int id, string name, out bool flag, ref int refVal)
        {
            flag = true;
            refVal = 99;
        }
        public void MethodWithDefault(int optional = 42) { }
        public void MethodWithOutOnly(out int result) { result = 1; }
    }

    /// <summary>
    /// 验证 ParameterInfo.Name / ParameterType 返回正确的参数信息
    /// </summary>
    [Fact]
    public void Fact_ParameterInfo_NameAndType()
    {
        MethodInfo mi = typeof(TestHelper).GetMethod("MethodWithParams");
        ParameterInfo[] ps = mi.GetParameters();
        Assert.Equal("id", ps[0].Name);
        Assert.Equal(typeof(int), ps[0].ParameterType);
        Assert.Equal("name", ps[1].Name);
        Assert.Equal(typeof(string), ps[1].ParameterType);
    }

    /// <summary>
    /// 验证 HasDefaultValue / DefaultValue 返回正确的默认值
    /// </summary>
    [Fact]
    public void Fact_ParameterInfo_DefaultValue()
    {
        MethodInfo mi = typeof(TestHelper).GetMethod("MethodWithDefault");
        ParameterInfo p = mi.GetParameters()[0];
        Assert.True(p.HasDefaultValue);
        Assert.Equal(42, p.DefaultValue);
    }

    /// <summary>
    /// 验证 ParameterInfo.IsOptional 判断可选参数
    /// </summary>
    [Fact]
    public void Fact_ParameterInfo_IsOptional()
    {
        MethodInfo mi = typeof(TestHelper).GetMethod("MethodWithDefault");
        ParameterInfo p = mi.GetParameters()[0];
        Assert.True(p.IsOptional);
    }

    /// <summary>
    /// 验证 MethodBase.GetParameters 返回正确的参数数组
    /// </summary>
    [Fact]
    public void Fact_GetParameters_ReturnsCorrectCount()
    {
        MethodInfo mi = typeof(TestHelper).GetMethod("MethodWithParams");
        ParameterInfo[] ps = mi.GetParameters();
        Assert.Equal(4, ps.Length);
    }

    /// <summary>
    /// 验证 ParameterInfo.IsOut 判断输出参数
    /// </summary>
    [Fact]
    public void Fact_ParameterInfo_IsOutDetection()
    {
        MethodInfo mi = typeof(TestHelper).GetMethod("MethodWithOutOnly");
        ParameterInfo p = mi.GetParameters()[0];
        Assert.True(p.IsOut);
        Assert.True(p.ParameterType.IsByRef);
    }
}
