using System;
using System.Collections.Generic;
using System.Reflection;
using Xunit;

public class ReflectionAssemblyTests
{
    [Fact]
    public void AllAutoGeneratedMethodsCanExecute()
    {
        var type = typeof(ReflectionAssembly);
        Assert.NotNull(type);
    }

    /// <summary>
    /// 验证 Assembly.GetExecutingAssembly 返回非空程序集
    /// </summary>
    [Fact]
    public void Fact_GetExecutingAssembly_ReturnsNonNull()
    {
        Assembly asm = Assembly.GetExecutingAssembly();
        Assert.NotNull(asm);
        Assert.False(string.IsNullOrEmpty(asm.FullName));
    }

    /// <summary>
    /// 验证 Assembly.GetName 返回的 AssemblyName 包含名称和版本
    /// </summary>
    [Fact]
    public void Fact_GetName_ReturnsNameAndVersion()
    {
        Assembly asm = typeof(string).Assembly;
        AssemblyName name = asm.GetName();
        Assert.NotNull(name);
        Assert.False(string.IsNullOrEmpty(name.Name));
        Assert.NotNull(name.Version);
    }

    /// <summary>
    /// 验证 Assembly.FullName 属性返回完整名称
    /// </summary>
    [Fact]
    public void Fact_FullName_ReturnsNonEmpty()
    {
        Assembly asm = typeof(List<>).Assembly;
        Assert.False(string.IsNullOrEmpty(asm.FullName));
        Assert.Contains("System.Private.CoreLib", asm.FullName);
    }

    /// <summary>
    /// 验证 Assembly.GetTypes 返回程序集中定义的类型
    /// </summary>
    [Fact]
    public void Fact_GetTypes_ReturnsTypeArray()
    {
        Assembly asm = typeof(int).Assembly;
        Type[] types = asm.GetTypes();
        Assert.NotNull(types);
        Assert.True(types.Length > 0);
    }

    /// <summary>
    /// 验证 Type.Assembly 属性返回正确的程序集
    /// </summary>
    [Fact]
    public void Fact_TypeAssembly_MatchesTypeAssembly()
    {
        Assembly asm = typeof(Guid).Assembly;
        Assert.NotNull(asm);
        Assert.Contains("System.Private.CoreLib", asm.GetName().Name);
    }
}
