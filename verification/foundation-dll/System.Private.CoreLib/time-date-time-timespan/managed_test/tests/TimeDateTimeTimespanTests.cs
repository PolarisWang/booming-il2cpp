using System;
using System.Globalization;
using Xunit;

public class TimeDateTimeTimespanTests
{
    [Fact]
    public void AllAutoGeneratedMethodsCanExecute()
    {
        var type = typeof(TimeDateTimeTimespan);
        Assert.NotNull(type);
    }

    /// <summary>
    /// 测试 DateTime 构造函数（y/m/d 和 y/m/d/h/m/s）
    /// </summary>
    [Fact]
    public void DateTime_Constructor_Should_Create_Valid_Date()
    {
        var dt1 = new DateTime(2024, 1, 1);
        Assert.Equal(2024, dt1.Year);
        Assert.Equal(1, dt1.Month);
        Assert.Equal(1, dt1.Day);

        var dt2 = new DateTime(2024, 6, 15, 10, 30, 0);
        Assert.Equal(10, dt2.Hour);
        Assert.Equal(30, dt2.Minute);
        Assert.Equal(0, dt2.Second);
    }

    /// <summary>
    /// 测试 DateTime.AddDays / AddHours / AddMinutes
    /// </summary>
    [Fact]
    public void DateTime_AddMethods_Should_Adjust_Date_Correctly()
    {
        var dt = new DateTime(2024, 1, 1);
        Assert.Equal(new DateTime(2024, 1, 11), dt.AddDays(10));
        Assert.Equal(new DateTime(2024, 1, 1, 10, 0, 0), dt.AddHours(10));
        Assert.Equal(new DateTime(2024, 1, 1, 0, 30, 0), dt.AddMinutes(30));
    }

    /// <summary>
    /// 测试 DateTime.ToString 与 DateTime.Parse / TryParse
    /// </summary>
    [Fact]
    public void DateTime_Parse_And_ToString_Should_Roundtrip()
    {
        var dt = new DateTime(2024, 12, 25);
        string str = dt.ToString("yyyy-MM-dd", CultureInfo.InvariantCulture);
        Assert.Equal("2024-12-25", str);

        DateTime parsed = DateTime.Parse(str, CultureInfo.InvariantCulture);
        Assert.Equal(dt, parsed);

        bool success = DateTime.TryParse("2024-12-25", out DateTime tryParsed);
        Assert.True(success);
        Assert.Equal(dt, tryParsed);
    }

    /// <summary>
    /// 测试 TimeSpan 构造函数与 FromDays / FromHours
    /// </summary>
    [Fact]
    public void TimeSpan_Construction_And_From_Should_Work()
    {
        var ts = new TimeSpan(1, 2, 3);
        Assert.Equal(1, ts.Hours);
        Assert.Equal(2, ts.Minutes);
        Assert.Equal(3, ts.Seconds);

        var fromDays = TimeSpan.FromDays(1.5);
        Assert.Equal(36, fromDays.TotalHours, 0);

        var fromHours = TimeSpan.FromHours(2.5);
        Assert.Equal(150, fromHours.TotalMinutes, 0);
    }

    /// <summary>
    /// 测试 DateTime.Compare 与 DateTime.DaysInMonth
    /// </summary>
    [Fact]
    public void DateTime_Compare_And_DaysInMonth_Should_Be_Correct()
    {
        var dt1 = new DateTime(2024, 1, 1);
        var dt2 = new DateTime(2024, 6, 15);
        Assert.True(DateTime.Compare(dt1, dt2) < 0);
        Assert.True(DateTime.Compare(dt2, dt1) > 0);
        Assert.Equal(0, DateTime.Compare(dt1, dt1));

        Assert.Equal(29, DateTime.DaysInMonth(2024, 2));
        Assert.Equal(28, DateTime.DaysInMonth(2023, 2));
    }
}
