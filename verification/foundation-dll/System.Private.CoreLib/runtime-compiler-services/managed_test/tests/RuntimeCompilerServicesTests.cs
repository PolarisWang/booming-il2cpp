using System;
using System.Runtime.CompilerServices;
using Xunit;

public class RuntimeCompilerServicesTests
{
    [Fact]
    public void AllAutoGeneratedMethodsCanExecute()
    {
        var type = typeof(RuntimeCompilerServices);
        Assert.NotNull(type);
    }

    /// <summary>
    /// 测试 RuntimeHelpers.GetHashCode — 返回标识哈希而非内容哈希
    /// </summary>
    [Fact]
    public void RuntimeHelpers_GetHashCode_Should_Return_IdentityHash()
    {
        var obj = new object();
        int hash1 = RuntimeHelpers.GetHashCode(obj);
        int hash2 = RuntimeHelpers.GetHashCode(obj);
        Assert.Equal(hash1, hash2);

        var obj2 = new object();
        Assert.NotEqual(RuntimeHelpers.GetHashCode(obj), RuntimeHelpers.GetHashCode(obj2));
    }

    /// <summary>
    /// 测试 RuntimeHelpers.Equals — 引用相等比较
    /// </summary>
    [Fact]
    public void RuntimeHelpers_Equals_Should_Compare_By_Reference()
    {
        var a = new object();
        var b = new object();
        Assert.True(RuntimeHelpers.Equals(a, a));
        Assert.False(RuntimeHelpers.Equals(a, b));
    }

    /// <summary>
    /// 测试 RuntimeHelpers.GetObjectValue — 值类型装箱，引用类型原样返回
    /// </summary>
    [Fact]
    public void RuntimeHelpers_GetObjectValue_Should_Box_ValueTypes()
    {
        int value = 42;
        object boxed = RuntimeHelpers.GetObjectValue(value);
        Assert.IsType<int>(boxed);
        Assert.Equal(42, (int)boxed);

        string str = "hello";
        object same = RuntimeHelpers.GetObjectValue(str);
        Assert.Same(str, same);
    }

    /// <summary>
    /// 测试 FormattableStringFactory.Create
    /// </summary>
    [Fact]
    public void FormattableStringFactory_Create_Should_Produce_FormattableString()
    {
        var fs = FormattableStringFactory.Create("Hello {0}", 42);
        Assert.NotNull(fs);
        Assert.Equal("Hello 42", fs.ToString());
    }

    /// <summary>
    /// 测试 RuntimeWrappedException 构造与 WrappedException 属性
    /// </summary>
    [Fact]
    public void RuntimeWrappedException_Should_Wrap_Object()
    {
        var ex = new RuntimeWrappedException(42);
        Assert.Equal(42, ex.WrappedException);
    }
}
