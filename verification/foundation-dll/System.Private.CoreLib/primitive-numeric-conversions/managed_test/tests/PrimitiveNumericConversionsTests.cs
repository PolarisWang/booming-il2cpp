using System;
using Xunit;

public class PrimitiveNumericConversionsTests
{
    [Fact]
    public void AllAutoGeneratedMethodsCanExecute()
    {
        var type = typeof(PrimitiveNumericConversions);
        Assert.NotNull(type);
    }

    /// <summary>
    /// 验证 Convert.ToInt32(string) 在正常数字字符串下返回正确整数
    /// </summary>
    [Fact]
    public void Test_ToInt32_String_NormalInput()
    {
        int result = Convert.ToInt32("12345");
        Assert.Equal(12345, result);
    }

    /// <summary>
    /// 验证 Convert.ToInt32(string) 在 null、空字符串、非法格式时抛出异常
    /// </summary>
    [Fact]
    public void Test_ToInt32_String_InvalidInput()
    {
        Assert.Throws<FormatException>(() => Convert.ToInt32(""));
        Assert.Equal(0, Convert.ToInt32((string)null!));
        Assert.Throws<FormatException>(() => Convert.ToInt32("abc"));
    }

    /// <summary>
    /// 验证 Convert.ToInt32(string) 在超出 int 范围时抛出 OverflowException
    /// </summary>
    [Fact]
    public void Test_ToInt32_String_Overflow()
    {
        Assert.Throws<OverflowException>(() => Convert.ToInt32("2147483648"));
        Assert.Throws<OverflowException>(() => Convert.ToInt32("-2147483649"));
    }

    /// <summary>
    /// 验证 Convert.ToInt64(string) 返回正确长整数
    /// </summary>
    [Fact]
    public void Test_ToInt64_String_NormalInput()
    {
        long result = Convert.ToInt64("9876543210");
        Assert.Equal(9876543210L, result);
    }

    /// <summary>
    /// 验证 Convert.ToDouble(string) 返回正确双精度值
    /// </summary>
    [Fact]
    public void Test_ToDouble_String_NormalInput()
    {
        double result = Convert.ToDouble("3.14159");
        Assert.Equal(3.14159, result, precision: 5);
    }

    /// <summary>
    /// 验证 Convert.ToSingle(string) 返回正确单精度值
    /// </summary>
    [Fact]
    public void Test_ToSingle_String_NormalInput()
    {
        float result = Convert.ToSingle("2.71828");
        Assert.Equal(2.71828f, result, precision: 4);
    }

    /// <summary>
    /// 验证 Convert.ToInt32(Double) 在正常范围内正确转换
    /// </summary>
    [Fact]
    public void Test_ToInt32_Double_NormalInput()
    {
        int result = Convert.ToInt32(42.7);
        Assert.Equal(43, result);
    }

    /// <summary>
    /// 验证 Convert.ToBoolean(string) 在 "true"/"false" 下正确转换
    /// </summary>
    [Fact]
    public void Test_ToBoolean_String_NormalInput()
    {
        Assert.True(Convert.ToBoolean("true"));
        Assert.False(Convert.ToBoolean("false"));
    }

    /// <summary>
    /// 验证 Convert.ToBoolean(string) 在非法字符串下抛出异常
    /// </summary>
    [Fact]
    public void Test_ToBoolean_String_InvalidInput()
    {
        Assert.Throws<FormatException>(() => Convert.ToBoolean("yes"));
        Assert.False(Convert.ToBoolean((string)null!));
    }

    /// <summary>
    /// 验证 Convert.ToString(int) 正确转换整数为字符串
    /// </summary>
    [Fact]
    public void Test_ToString_Int32_NormalInput()
    {
        string result = Convert.ToString(42);
        Assert.Equal("42", result);
    }

    /// <summary>
    /// 验证 Int32.Parse 正常解析数字字符串
    /// </summary>
    [Fact]
    public void Test_Int32_Parse_NormalInput()
    {
        int result = int.Parse("1024");
        Assert.Equal(1024, result);
    }

    /// <summary>
    /// 验证 Convert.ToDecimal(string) 正常解析 decimal 字符串
    /// </summary>
    [Fact]
    public void Test_ToDecimal_String_NormalInput()
    {
        decimal result = Convert.ToDecimal("123.456");
        Assert.Equal(123.456m, result);
    }

    /// <summary>
    /// 验证 Convert.ToByte(string) 正常解析字节字符串
    /// </summary>
    [Fact]
    public void Test_ToByte_String_NormalInput()
    {
        byte result = Convert.ToByte("255");
        Assert.Equal(255, result);
    }
}
