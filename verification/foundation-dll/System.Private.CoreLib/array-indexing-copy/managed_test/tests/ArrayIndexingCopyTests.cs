using System;
using System.Collections.Generic;
using Xunit;

public class ArrayIndexingCopyTests
{
    [Fact]
    public void AllAutoGeneratedMethodsCanExecute()
    {
        var type = typeof(ArrayIndexingCopy);
        Assert.NotNull(type);
    }

    /// <summary>
    /// 测试 Array.Copy 和 Array.Clear 的各种重载和边界
    /// </summary>
    [Fact]
    public void Test_ArrayCopyAndClear()
    {
        int[] src = { 1, 2, 3, 4, 5 };
        int[] dst = new int[5];
        Array.Copy(src, dst, 5);
        Assert.Equal(src, dst);

        int[] partial = new int[3];
        Array.Copy(src, 1, partial, 0, 3);
        Assert.Equal(new[] { 2, 3, 4 }, partial);

        Assert.Throws<ArgumentNullException>(() => Array.Copy(null!, dst, 1));

        int[] arr = { 1, 2, 3, 4 };
        Array.Clear(arr, 0, 4);
        Assert.Equal(new[] { 0, 0, 0, 0 }, arr);

        int[] arr2 = { 1, 2, 3, 4, 5 };
        Array.Clear(arr2, 1, 2);
        Assert.Equal(new[] { 1, 0, 0, 4, 5 }, arr2);

        Assert.Throws<IndexOutOfRangeException>(() => Array.Clear(arr2, -1, 1));
    }

    /// <summary>
    /// 测试 Array.IndexOf 和 Array.LastIndexOf
    /// </summary>
    [Fact]
    public void Test_ArrayIndexOfAndLastIndexOf()
    {
        int[] arr = { 10, 20, 30, 20, 10 };
        Assert.Equal(0, Array.IndexOf(arr, 10));
        Assert.Equal(1, Array.IndexOf(arr, 20));
        Assert.Equal(4, Array.LastIndexOf(arr, 10));
        Assert.Equal(3, Array.LastIndexOf(arr, 20));
        Assert.Equal(-1, Array.IndexOf(arr, 99));
        Assert.Equal(-1, Array.LastIndexOf(arr, 99));
    }

    /// <summary>
    /// 测试 Array.Reverse 和 Array.Sort
    /// </summary>
    [Fact]
    public void Test_ArrayReverseAndSort()
    {
        int[] arr1 = { 1, 2, 3, 4, 5 };
        Array.Reverse(arr1);
        Assert.Equal(new[] { 5, 4, 3, 2, 1 }, arr1);

        int[] unsorted = { 9, 3, 7, 1, 5 };
        Array.Sort(unsorted);
        Assert.Equal(new[] { 1, 3, 5, 7, 9 }, unsorted);
    }

    /// <summary>
    /// 测试 Array.BinarySearch
    /// </summary>
    [Fact]
    public void Test_ArrayBinarySearch()
    {
        int[] sorted = { 1, 3, 5, 7, 9, 11, 13 };
        Assert.Equal(0, Array.BinarySearch(sorted, 1));
        Assert.Equal(3, Array.BinarySearch(sorted, 7));
        Assert.Equal(6, Array.BinarySearch(sorted, 13));

        int notFound = Array.BinarySearch(sorted, 2);
        Assert.True(notFound < 0);
    }

    /// <summary>
    /// 测试 Array.TrueForAll / Exists / Find / FindAll / ConvertAll
    /// </summary>
    [Fact]
    public void Test_ArrayFindAndConvertAndIndexer()
    {
        int[] arr = { 1, 2, 3, 4, 5, 6, 7, 8 };
        Assert.True(Array.TrueForAll(arr, x => x > 0));
        Assert.False(Array.TrueForAll(arr, x => x % 2 == 0));
        Assert.True(Array.Exists(arr, x => x == 5));
        Assert.Equal(2, Array.Find(arr, x => x % 2 == 0));

        int[] evens = Array.FindAll(arr, x => x % 2 == 0);
        Assert.Equal(new[] { 2, 4, 6, 8 }, evens);

        string[] strs = Array.ConvertAll(arr, x => x.ToString());
        Assert.Equal(new[] { "1", "2", "3", "4", "5", "6", "7", "8" }, strs);
    }

    /// <summary>
    /// 测试 Array.GetLength 和 GetValue
    /// </summary>
    [Fact]
    public void Test_ArrayGetLengthAndGetValue()
    {
        int[,] multi = new int[3, 4];
        Assert.Equal(3, multi.GetLength(0));
        Assert.Equal(4, multi.GetLength(1));

        int[] single = { 10, 20, 30 };
        Assert.Equal(10, (int)single.GetValue(0)!);
        Assert.Equal(30, (int)single.GetValue(2)!);
    }
}
