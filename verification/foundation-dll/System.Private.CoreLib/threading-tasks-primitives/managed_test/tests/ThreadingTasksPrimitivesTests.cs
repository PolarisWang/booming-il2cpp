using System;
using System.Threading;
using System.Threading.Tasks;
using Xunit;

public class ThreadingTasksPrimitivesTests
{
    [Fact]
    public void AllAutoGeneratedMethodsCanExecute()
    {
        var type = typeof(ThreadingTasksPrimitives);
        Assert.NotNull(type);
    }

    /// <summary>
    /// 测试 Task.CompletedTask 与 Task.FromResult
    /// </summary>
    [Fact]
    public void Task_CompletedTask_And_FromResult_Should_Be_Completed()
    {
        var completed = Task.CompletedTask;
        Assert.True(completed.IsCompleted);
        Assert.Equal(TaskStatus.RanToCompletion, completed.Status);

        var resultTask = Task.FromResult(42);
        Assert.True(resultTask.IsCompleted);
        Assert.Equal(42, resultTask.Result);
    }

    /// <summary>
    /// 测试 Task.Wait 不阻塞已完成的 Task
    /// </summary>
    [Fact]
    public void Task_Wait_On_CompletedTask_Should_Return_Immediately()
    {
        var task = Task.CompletedTask;
        task.Wait();
        Assert.True(task.IsCompleted);
    }

    /// <summary>
    /// 测试 Task.Status 和 Task.IsCompleted 属性
    /// </summary>
    [Fact]
    public void Task_Status_And_IsCompleted_Should_Reflect_State()
    {
        var completed = Task.CompletedTask;
        Assert.True(completed.IsCompleted);
        Assert.Equal(TaskStatus.RanToCompletion, completed.Status);

        var resultTask = Task.FromResult(42);
        Assert.Equal(TaskStatus.RanToCompletion, resultTask.Status);
    }

    /// <summary>
    /// 测试 Thread.CurrentThread 与 ManagedThreadId
    /// </summary>
    [Fact]
    public void Thread_CurrentThread_Properties_Should_Be_Accessible()
    {
        var thread = Thread.CurrentThread;
        Assert.NotNull(thread);
        Assert.True(thread.ManagedThreadId > 0);
    }

    /// <summary>
    /// 测试 Task.Delay 创建有效 Task
    /// </summary>
    [Fact]
    public void Task_Delay_Should_Create_Valid_Task()
    {
        var delayTask = Task.Delay(1);
        Assert.NotNull(delayTask);
        Assert.False(delayTask.IsCompleted);
        delayTask.Wait();
        Assert.True(delayTask.IsCompleted);
    }
}
