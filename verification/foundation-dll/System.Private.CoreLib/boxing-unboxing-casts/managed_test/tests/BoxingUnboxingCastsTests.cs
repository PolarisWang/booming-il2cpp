using System;
using System.Runtime.CompilerServices;
using Xunit;

public class BoxingUnboxingCastsTests
{
    [Fact]
    public void AllAutoGeneratedMethodsCanExecute()
    {
        var type = typeof(BoxingUnboxingCasts);
        Assert.NotNull(type);
    }

    /// <summary>
    /// 测试目的：验证值类型装箱后的拆箱转换正确性（int -> object -> int）
    /// </summary>
    [Fact]
    public void Test_Boxing_Int32_Unboxing()
    {
        object boxed = 42;
        int unboxed = (int)boxed;
        Assert.Equal(42, unboxed);
    }

    /// <summary>
    /// 测试目的：验证 is 运算符对不同值类型的正确判断
    /// </summary>
    [Fact]
    public void Test_IsOperator_TypeCheck()
    {
        object val = 42;
        Assert.True(val is int);
        Assert.False(val is byte);
        Assert.False(val is string);
    }

    /// <summary>
    /// 测试目的：验证 as 运算符在引用类型转换中的正确行为
    /// </summary>
    [Fact]
    public void Test_AsOperator_ReferenceType()
    {
        object obj = "hello";
        string? str = obj as string;
        Assert.Equal("hello", str);

        object num = 42;
        string? notStr = num as string;
        Assert.Null(notStr);
    }

    /// <summary>
    /// 测试目的：验证 Convert.ChangeType 在不同数值类型间的正确转换
    /// </summary>
    [Fact]
    public void Test_ChangeType_NumericConversions()
    {
        object result = Convert.ChangeType(42, typeof(byte));
        Assert.IsType<byte>(result);
        Assert.Equal((byte)42, result);

        object dblResult = Convert.ChangeType(42, typeof(double));
        Assert.IsType<double>(dblResult);
        Assert.Equal(42.0, dblResult);
    }

    /// <summary>
    /// 测试目的：验证 Type.IsAssignableFrom 对父子类型关系的正确判断
    /// </summary>
    [Fact]
    public void Test_IsAssignableFrom_TypeRelations()
    {
        Assert.True(typeof(object).IsAssignableFrom(typeof(string)));
        Assert.True(typeof(ValueType).IsAssignableFrom(typeof(int)));
        Assert.False(typeof(string).IsAssignableFrom(typeof(int)));
        Assert.True(typeof(IComparable).IsAssignableFrom(typeof(int)));
    }

    /// <summary>
    /// 测试目的：验证 Type.IsInstanceOfType 对对象实例的类型判断
    /// </summary>
    [Fact]
    public void Test_IsInstanceOfType_ObjectCheck()
    {
        Assert.True(typeof(int).IsInstanceOfType(42));
        Assert.False(typeof(string).IsInstanceOfType(42));
        Assert.True(typeof(object).IsInstanceOfType(42));
    }

    /// <summary>
    /// 测试目的：验证 Type.IsSubclassOf 的正确语义
    /// </summary>
    [Fact]
    public void Test_IsSubclassOf_Semantics()
    {
        Assert.False(typeof(ArgumentException).IsSubclassOf(typeof(ArgumentException)));
        Assert.True(typeof(ArgumentException).IsSubclassOf(typeof(Exception)));
        Assert.True(typeof(Exception).IsSubclassOf(typeof(object)));
        Assert.True(typeof(int).IsSubclassOf(typeof(ValueType)));
    }

    /// <summary>
    /// 测试目的：验证 Type.IsAssignableTo 的正确语义
    /// </summary>
    [Fact]
    public void Test_IsAssignableTo_Semantics()
    {
        Assert.True(typeof(string).IsAssignableTo(typeof(object)));
        Assert.True(typeof(int).IsAssignableTo(typeof(ValueType)));
        Assert.True(typeof(ArgumentException).IsAssignableTo(typeof(Exception)));
        Assert.False(typeof(Exception).IsAssignableTo(typeof(ArgumentException)));
    }

    /// <summary>
    /// 测试目的：验证 RuntimeHelpers.GetObjectValue 对值类型装箱的语义
    /// </summary>
    [Fact]
    public void Test_GetObjectValue_BoxingSemantics()
    {
        object val = RuntimeHelpers.GetObjectValue(42);
        Assert.IsType<int>(val);
        Assert.Equal(42, val);
    }

    /// <summary>
    /// 测试目的：验证 Array.CreateInstance(Type, int) 正确创建一维数组
    /// </summary>
    [Fact]
    public void Test_CreateInstance_OneDim()
    {
        Array arr = Array.CreateInstance(typeof(int), 10);
        Assert.NotNull(arr);
        Assert.Equal(10, arr.Length);
        Assert.IsType<int[]>(arr);
    }

    /// <summary>
    /// 测试目的：验证 Array.CreateInstance(Type, int, int) 正确创建二维数组
    /// </summary>
    [Fact]
    public void Test_CreateInstance_TwoDim()
    {
        Array arr = Array.CreateInstance(typeof(int), 3, 4);
        Assert.NotNull(arr);
        Assert.Equal(3, arr.GetLength(0));
        Assert.Equal(4, arr.GetLength(1));
    }

    /// <summary>
    /// 测试目的：验证 ValueType.Equals 对值类型相等性的正确判断
    /// </summary>
    [Fact]
    public void Test_ValueType_Equals_ValueEquality()
    {
        int a = 42;
        int b = 42;
        int c = 99;
        Assert.True(a.Equals(b));
        Assert.False(a.Equals(c));
    }
}
