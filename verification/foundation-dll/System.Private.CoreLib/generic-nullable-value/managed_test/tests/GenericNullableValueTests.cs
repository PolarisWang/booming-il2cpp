using System;
using Xunit;

public class GenericNullableValueTests
{
    [Fact]
    public void AllAutoGeneratedMethodsCanExecute()
    {
        var type = typeof(GenericNullableValue);
        Assert.NotNull(type);
    }

    /// <summary>
    /// 测试 Nullable<T>.HasValue 与 .Value 的基本语义
    /// </summary>
    [Fact]
    public void Nullable_HasValue_And_Value_Should_Reflect_State()
    {
        int? hasValue = 42;
        Assert.True(hasValue.HasValue);
        Assert.Equal(42, hasValue.Value);

        int? noValue = null;
        Assert.False(noValue.HasValue);
    }

    /// <summary>
    /// 测试 Nullable<T>.GetValueOrDefault
    /// </summary>
    [Fact]
    public void Nullable_GetValueOrDefault_Should_Return_Value_Or_Default()
    {
        int? hasValue = 42;
        Assert.Equal(42, hasValue.GetValueOrDefault());

        int? noValue = null;
        Assert.Equal(0, noValue.GetValueOrDefault());
        Assert.Equal(-1, noValue.GetValueOrDefault(-1));
    }

    /// <summary>
    /// 测试 Nullable<T>.Equals 与 GetHashCode
    /// </summary>
    [Fact]
    public void Nullable_Equals_And_GetHashCode_Should_Match_Underlying()
    {
        int? a = 42;
        int? b = 42;
        int? c = null;

        Assert.True(a.Equals(b));
        Assert.False(a.Equals(c));
        Assert.False(c.Equals(42));

        Assert.Equal(42.GetHashCode(), a.GetHashCode());
        Assert.Equal(0, c.GetHashCode());
    }

    /// <summary>
    /// 测试 Nullable<T>.ToString
    /// </summary>
    [Fact]
    public void Nullable_ToString_Should_Return_Value_Or_Empty()
    {
        int? hasValue = 42;
        Assert.Equal("42", hasValue.ToString());

        int? noValue = null;
        Assert.Equal("", noValue.ToString());
    }

    /// <summary>
    /// 测试 Nullable 装箱行为 — 有值时装箱为 underlying type，无值时返回 null
    /// </summary>
    [Fact]
    public void Nullable_Boxing_Should_Unbox_Correctly()
    {
        int? hasValue = 42;
        object boxed = hasValue;
        Assert.IsType<int>(boxed);
        Assert.Equal(42, (int)boxed);

        int? noValue = null;
        object nullBoxed = noValue;
        Assert.Null(nullBoxed);
    }
}
