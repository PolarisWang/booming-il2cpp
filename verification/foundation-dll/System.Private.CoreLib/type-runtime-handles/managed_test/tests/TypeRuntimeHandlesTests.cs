using System;
using Xunit;

public class TypeRuntimeHandlesTests
{
    [Fact]
    public void AllAutoGeneratedMethodsCanExecute()
    {
        var type = typeof(TypeRuntimeHandles);
        Assert.NotNull(type);
    }

    /// <summary>
    /// 测试 Type.GetTypeFromHandle 与 RuntimeTypeHandle 互转
    /// </summary>
    [Fact]
    public void RuntimeTypeHandle_Should_Roundtrip_Through_GetTypeFromHandle()
    {
        RuntimeTypeHandle handle = typeof(int).TypeHandle;
        Type restored = Type.GetTypeFromHandle(handle);
        Assert.Equal(typeof(int), restored);
    }

    /// <summary>
    /// 测试 Type.TypeHandle 对值类型与引用类型返回不同句柄
    /// </summary>
    [Fact]
    public void TypeHandle_Should_Differ_For_Different_Types()
    {
        RuntimeTypeHandle intHandle = typeof(int).TypeHandle;
        RuntimeTypeHandle stringHandle = typeof(string).TypeHandle;
        Assert.NotEqual(intHandle.Value, stringHandle.Value);
    }

    /// <summary>
    /// 测试 Type.IsValueType / IsEnum / IsArray 元数据属性
    /// </summary>
    [Fact]
    public void Type_Metadata_Properties_Should_Reflect_Type_Kind()
    {
        Assert.True(typeof(int).IsValueType);
        Assert.False(typeof(string).IsValueType);
        Assert.True(typeof(int[]).IsArray);
    }

    /// <summary>
    /// 测试 Type.GetFields 与 Type.GetMethods 反射元数据获取
    /// </summary>
    [Fact]
    public void Type_GetFields_And_GetMethods_Should_Return_Metadata()
    {
        var fields = typeof(int).GetFields();
        Assert.NotEmpty(fields);

        var methods = typeof(string).GetMethods();
        Assert.NotEmpty(methods);
    }

    /// <summary>
    /// 测试 Type.FullName / Name / BaseType
    /// </summary>
    [Fact]
    public void Type_Name_And_BaseType_Should_Be_Correct()
    {
        Assert.Equal("System.Int32", typeof(int).FullName);
        Assert.Equal("Int32", typeof(int).Name);
        Assert.Equal(typeof(ValueType), typeof(int).BaseType);
        Assert.Equal(typeof(object), typeof(string).BaseType);
    }
}
