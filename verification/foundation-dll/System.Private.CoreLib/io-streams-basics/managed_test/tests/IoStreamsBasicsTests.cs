using System;
using System.IO;
using Xunit;

public class IoStreamsBasicsTests
{
    [Fact]
    public void AllAutoGeneratedMethodsCanExecute()
    {
        var type = typeof(IoStreamsBasics);
        Assert.NotNull(type);
    }

    /// <summary>
    /// 测试 MemoryStream 写入、读取、定位、Flush、ToArray
    /// </summary>
    [Fact]
    public void MemoryStream_Write_Read_Seek_Should_Work()
    {
        using var ms = new MemoryStream();
        byte[] data = { 1, 2, 3, 4, 5 };
        ms.Write(data, 0, data.Length);
        Assert.Equal(5, ms.Length);
        Assert.Equal(5, ms.Position);

        ms.Seek(0, SeekOrigin.Begin);
        Assert.Equal(0, ms.Position);

        byte[] buffer = new byte[5];
        int bytesRead = ms.Read(buffer, 0, 5);
        Assert.Equal(5, bytesRead);
        Assert.Equal(data, buffer);
    }

    /// <summary>
    /// 测试 MemoryStream.ToArray
    /// </summary>
    [Fact]
    public void MemoryStream_ToArray_Should_Return_Copy()
    {
        using var ms = new MemoryStream();
        byte[] data = { 10, 20, 30 };
        ms.Write(data, 0, data.Length);
        byte[] arr = ms.ToArray();
        Assert.Equal(data, arr);
    }

    /// <summary>
    /// 测试 StringReader.ReadLine 与 ReadToEnd
    /// </summary>
    [Fact]
    public void StringReader_ReadLine_And_ReadToEnd_Should_Work()
    {
        using var reader = new StringReader("line1\nline2\nline3");
        Assert.Equal("line1", reader.ReadLine());
        Assert.Equal("line2", reader.ReadLine());
        Assert.Equal("line3", reader.ReadLine());
        Assert.Null(reader.ReadLine());

        using var reader2 = new StringReader("hello world");
        Assert.Equal("hello world", reader2.ReadToEnd());
    }

    /// <summary>
    /// 测试 StringWriter.Write 与 WriteLine
    /// </summary>
    [Fact]
    public void StringWriter_Write_And_WriteLine_Should_Produce_Text()
    {
        using var sw = new StringWriter();
        sw.Write("hello");
        sw.Write(" ");
        sw.WriteLine("world");
        sw.WriteLine();
        string result = sw.ToString();
        Assert.Contains("hello world", result);
    }

    /// <summary>
    /// 测试 BinaryWriter 写入后 BinaryReader 读取对应类型
    /// </summary>
    [Fact]
    public void BinaryWriter_Write_Then_BinaryReader_Read_Should_Match()
    {
        var ms = new MemoryStream();
        using (var bw = new BinaryWriter(ms, System.Text.Encoding.UTF8, leaveOpen: true))
        {
            bw.Write(42);
            bw.Write(3.14);
            bw.Write("hello");
        }

        ms.Seek(0, SeekOrigin.Begin);
        using var br = new BinaryReader(ms);
        Assert.Equal(42, br.ReadInt32());
        Assert.Equal(3.14, br.ReadDouble());
        Assert.Equal("hello", br.ReadString());
    }
}
