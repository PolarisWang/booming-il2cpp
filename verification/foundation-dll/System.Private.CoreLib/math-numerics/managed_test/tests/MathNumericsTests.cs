using System;
using Xunit;

public class MathNumericsTests
{
    [Fact]
    public void AllAutoGeneratedMethodsCanExecute()
    {
        var type = typeof(MathNumerics);
        Assert.NotNull(type);
    }

    /// <summary>
    /// 测试 Math.Abs 绝对值
    /// </summary>
    [Fact]
    public void Math_Abs_Should_Return_Positive_Value()
    {
        Assert.Equal(42, Math.Abs(-42));
        Assert.Equal(42, Math.Abs(42));
        Assert.Equal(3.14, Math.Abs(-3.14), 2);
    }

    /// <summary>
    /// 测试 Math.Floor / Ceiling / Round
    /// </summary>
    [Fact]
    public void Math_Floor_Ceiling_Round_Should_Work()
    {
        Assert.Equal(3.0, Math.Floor(3.7));
        Assert.Equal(4.0, Math.Ceiling(3.2));
        Assert.Equal(4.0, Math.Round(3.5));
        Assert.Equal(3.46, Math.Round(3.456, 2));
    }

    /// <summary>
    /// 测试 Math.Max / Min
    /// </summary>
    [Fact]
    public void Math_Max_Min_Should_Return_Correct_Extremum()
    {
        Assert.Equal(10, Math.Max(5, 10));
        Assert.Equal(5, Math.Min(5, 10));
        Assert.Equal(3.14, Math.Max(3.14, 2.71), 2);
    }

    /// <summary>
    /// 测试 Math.Pow / Sqrt / Sin / Cos
    /// </summary>
    [Fact]
    public void Math_Pow_Sqrt_Sin_Cos_Should_Return_Expected_Range()
    {
        Assert.Equal(8.0, Math.Pow(2.0, 3.0), 6);
        Assert.Equal(3.0, Math.Sqrt(9.0), 6);
        Assert.InRange(Math.Sin(0.0), -1, 1);
        Assert.InRange(Math.Cos(0.0), -1, 1);
        Assert.Equal(1.0, Math.Cos(0.0), 6);
    }

    /// <summary>
    /// 测试 Math.DivRem / Math.Clamp / BitConverter
    /// </summary>
    [Fact]
    public void Math_DivRem_Clamp_And_BitConverter_Should_Work()
    {
        int quotient = Math.DivRem(10, 3, out int remainder);
        Assert.Equal(3, quotient);
        Assert.Equal(1, remainder);

        Assert.Equal(5, Math.Clamp(5, 1, 10));
        Assert.Equal(1, Math.Clamp(0, 1, 10));
        Assert.Equal(10, Math.Clamp(20, 1, 10));

        byte[] bytes = BitConverter.GetBytes(42);
        Assert.Equal(4, bytes.Length);
        Assert.Equal(42, BitConverter.ToInt32(bytes, 0));
    }
}
