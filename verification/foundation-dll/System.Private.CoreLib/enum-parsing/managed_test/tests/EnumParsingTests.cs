using System;
using Xunit;

public class EnumParsingTests
{
    [Fact]
    public void AllAutoGeneratedMethodsCanExecute()
    {
        var type = typeof(EnumParsing);
        Assert.NotNull(type);
    }

    /// <summary>
    /// 测试目的：验证 Enum.Parse(Type, string) 正确解析枚举名称
    /// </summary>
    [Fact]
    public void Test_Parse_Name()
    {
        object result = Enum.Parse(typeof(DayOfWeek), "Monday");
        Assert.Equal(DayOfWeek.Monday, result);
    }

    /// <summary>
    /// 测试目的：验证 Enum.Parse(Type, string, bool) 解析时忽略大小写
    /// </summary>
    [Fact]
    public void Test_Parse_IgnoreCase()
    {
        object result = Enum.Parse(typeof(DayOfWeek), "monday", ignoreCase: true);
        Assert.Equal(DayOfWeek.Monday, result);
    }

    /// <summary>
    /// 测试目的：验证 Enum.Parse 大小写敏感时对大小写不匹配抛出 ArgumentException
    /// </summary>
    [Fact]
    public void Test_Parse_CaseSensitive_Fails()
    {
        Assert.Throws<ArgumentException>(() => Enum.Parse(typeof(DayOfWeek), "monday"));
    }

    /// <summary>
    /// 测试目的：验证 Enum.Parse 在非法名称时抛出异常
    /// </summary>
    [Fact]
    public void Test_Parse_InvalidName()
    {
        Assert.Throws<ArgumentException>(() => Enum.Parse(typeof(DayOfWeek), "InvalidDay"));
        Assert.Throws<ArgumentNullException>(() => Enum.Parse(typeof(DayOfWeek), null!));
    }

    /// <summary>
    /// 测试目的：验证 Enum.ToString() 返回正确的枚举名称
    /// </summary>
    [Fact]
    public void Test_ToString_ReturnsName()
    {
        string result = DayOfWeek.Monday.ToString();
        Assert.Equal("Monday", result);
    }

    /// <summary>
    /// 测试目的：验证 Enum.ToString(string) 使用格式说明符
    /// </summary>
    [Fact]
    public void Test_ToString_FormatSpecifier()
    {
        string result = DayOfWeek.Monday.ToString("G");
        Assert.Equal("Monday", result);

        string dResult = DayOfWeek.Monday.ToString("D");
        Assert.Equal("1", dResult);
    }

    /// <summary>
    /// 测试目的：验证 Enum.TryParse(Type, string, out object)
    /// </summary>
    [Fact]
    public void Test_TryParse_SuccessAndFailure()
    {
        object result;
        bool success = Enum.TryParse(typeof(DayOfWeek), "Tuesday", out result);
        Assert.True(success);
        Assert.Equal(DayOfWeek.Tuesday, result);

        bool fail = Enum.TryParse(typeof(DayOfWeek), "NotADay", out result);
        Assert.False(fail);
    }

    /// <summary>
    /// 测试目的：验证 Enum.IsDefined 对有效和无效枚举值的判断
    /// </summary>
    [Fact]
    public void Test_IsDefined_ValidAndInvalid()
    {
        Assert.True(Enum.IsDefined(typeof(DayOfWeek), "Monday"));
        Assert.True(Enum.IsDefined(typeof(DayOfWeek), DayOfWeek.Friday));
        Assert.False(Enum.IsDefined(typeof(DayOfWeek), "InvalidDay"));
    }

    /// <summary>
    /// 测试目的：验证 Enum.GetValues 返回所有枚举值
    /// </summary>
    [Fact]
    public void Test_GetValues_ReturnsAllValues()
    {
        Array values = Enum.GetValues(typeof(DayOfWeek));
        Assert.Equal(7, values.Length);
        Assert.Contains(DayOfWeek.Sunday, values.Cast<DayOfWeek>());
        Assert.Contains(DayOfWeek.Saturday, values.Cast<DayOfWeek>());
    }

    /// <summary>
    /// 测试目的：验证 Enum.GetNames 返回所有枚举名称
    /// </summary>
    [Fact]
    public void Test_GetNames_ReturnsAllNames()
    {
        string[] names = Enum.GetNames(typeof(DayOfWeek));
        Assert.Equal(7, names.Length);
        Assert.Contains("Sunday", names);
        Assert.Contains("Saturday", names);
    }

    /// <summary>
    /// 测试目的：验证 Enum.GetName(Type, object) 返回指定值的名称
    /// </summary>
    [Fact]
    public void Test_GetName_ReturnsNameForValue()
    {
        string? name = Enum.GetName(typeof(DayOfWeek), DayOfWeek.Wednesday);
        Assert.Equal("Wednesday", name);
    }

    /// <summary>
    /// 测试目的：验证 Enum.Format 使用不同格式说明符
    /// </summary>
    [Fact]
    public void Test_Format_WithFormatSpecifiers()
    {
        string fResult = Enum.Format(typeof(DayOfWeek), DayOfWeek.Monday, "F");
        Assert.Equal("Monday", fResult);

        string dResult = Enum.Format(typeof(DayOfWeek), DayOfWeek.Monday, "D");
        Assert.Equal("1", dResult);
    }
}
