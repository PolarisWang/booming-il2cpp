using System;
using System.Reflection;
using Xunit;

public class ReflectionMemberCompleteTests
{
    [Fact]
    public void AllAutoGeneratedMethodsCanExecute()
    {
        var type = typeof(ReflectionMemberComplete);
        Assert.NotNull(type);
    }

    // 辅助测试类型
    class TestHelper
    {
        public int ValueField = 42;
        public string NameProperty { get; set; } = "hello";
        public int Add(int a, int b) => a + b;
        public TestHelper() { }
        public TestHelper(int seed) { ValueField = seed; }
    }

    /// <summary>
    /// 验证 MethodInfo.Invoke 能正确调用实例方法
    /// </summary>
    [Fact]
    public void Fact_MethodInfo_InvokeInstanceMethod()
    {
        var obj = new TestHelper();
        MethodInfo mi = typeof(TestHelper).GetMethod("Add");
        object result = mi.Invoke(obj, new object[] { 3, 4 });
        Assert.Equal(7, result);
    }

    /// <summary>
    /// 验证 ConstructorInfo.Invoke 能正确创建实例
    /// </summary>
    [Fact]
    public void Fact_ConstructorInfo_InvokeCreatesInstance()
    {
        ConstructorInfo ci = typeof(TestHelper).GetConstructor(Type.EmptyTypes);
        object obj = ci.Invoke(null);
        Assert.NotNull(obj);
        Assert.IsType<TestHelper>(obj);
    }

    /// <summary>
    /// 验证 PropertyInfo.GetValue/SetValue 能读写属性
    /// </summary>
    [Fact]
    public void Fact_PropertyInfo_GetSetValue()
    {
        var obj = new TestHelper();
        PropertyInfo pi = typeof(TestHelper).GetProperty("NameProperty");
        pi.SetValue(obj, "world");
        object val = pi.GetValue(obj);
        Assert.Equal("world", val);
    }

    /// <summary>
    /// 验证 FieldInfo.GetValue/SetValue 能读写字段
    /// </summary>
    [Fact]
    public void Fact_FieldInfo_GetSetValue()
    {
        var obj = new TestHelper();
        FieldInfo fi = typeof(TestHelper).GetField("ValueField");
        fi.SetValue(obj, 99);
        object val = fi.GetValue(obj);
        Assert.Equal(99, val);
    }

    /// <summary>
    /// 验证 MemberInfo.Name/MemberType/DeclaringType 属性正确
    /// </summary>
    [Fact]
    public void Fact_MemberInfo_MetadataProperties()
    {
        MemberInfo mi = typeof(TestHelper).GetMethod("Add");
        Assert.Equal("Add", mi.Name);
        Assert.Equal(MemberTypes.Method, mi.MemberType);
        Assert.Equal(typeof(TestHelper), mi.DeclaringType);
    }
}
