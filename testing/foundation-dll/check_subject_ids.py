import json

meta = json.loads(open('D:/agent/booming-il2cpp/testing/foundation-dll/System.Private.CoreLib/chunks/text/managed/subjects/subjects.metadata.json', encoding='utf-8').read())
sample = meta['methods'][0]
print('Sample method:', sample['methodSubjectId'])
print('Sample genId:', sample.get('generatedMethodId', '?'))
print('Sample kind:', sample.get('kind', '?'))

def sanitize(name):
    return name.replace('.', '_').replace('+', '_').replace('/', '_').replace('`', '_')

msid = sample['methodSubjectId']
parts = msid.split('::')
type_and_method = parts[0]
if '/' in type_and_method:
    asm_name, type_name = type_and_method.split('/', 1)
else:
    asm_name, type_name = '', type_and_method

sanitized_asm = sanitize(asm_name)
sanitized_type = sanitize(type_name)
gen_id = sample.get('generatedMethodId', '?')

fact_id = f'CombinedSubjects/AutoGenerated.{sanitized_asm}.{sanitized_type}Tests::{gen_id}:System.Int64()'
bench_id = f'CombinedSubjects/AutoGenerated.{sanitized_asm}.{sanitized_type}Tests::Benchmark_{gen_id}:System.Void()'
print()
print('Computed AOT subject ID (fact): ', fact_id)
print('Computed AOT subject ID (bench):', bench_id)

# Check against actual generated code
with open('D:/agent/booming-il2cpp/testing/foundation-dll/System.Private.CoreLib/chunks/text/native/subjects/native-aot.generated.cpp', encoding='utf-8') as f:
    content = f.read()

if fact_id in content:
    print(f'FACT ID FOUND in generated code')
else:
    print(f'FACT ID NOT FOUND in generated code')
    # Try to find similar
    idx = content.find(f'AutoGenerated.{sanitized_asm}.{sanitized_type}Tests')
    if idx > 0:
        snippet = content[idx:idx+200]
        print(f'  Found similar at offset {idx}:')
        print(f'  {snippet[:150]}...')

if bench_id in content:
    print(f'BENCH ID FOUND in generated code')
else:
    print(f'BENCH ID NOT FOUND in generated code')
