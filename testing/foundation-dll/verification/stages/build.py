_REPO_ROOT = Path(__file__).resolve().parents[4]


# -- Tool paths --------------------------------------------------------------

def _tool_dll(tool_name: str) -> Path:
    return (_REPO_ROOT / "src" / "tools" / tool_name
            / "bin" / "Debug" / "net8.0" / f"{tool_name}.dll")


def _detect_tfm(dll_path: Path) -> str:
    """Detect target framework moniker from the DLL's runtime directory path.

    E.g. ".../shared/Microsoft.NETCore.App/10.0.6/System.Private.CoreLib.dll"
    -> "net10.0".  Falls back to "net8.0".
    """
    path = str(dll_path).replace("\\", "/")
    m = re.search(r"Microsoft\.NETCore\.App/(\d+)\.(\d+)\.", path)
    if m:
        return f"net{m.group(1)}.{m.group(2)}"
    return "net8.0"


def _custom_subjects_metadata(method_names: list[str], slug: str) -> dict:
    """Build metadata.json for custom subject methods.

    Each method gets a metadata entry referencing the wrapper in the
    AutoGenerated namespace (matching TPG generate-dll's expected format).
    """
    methods: list[dict[str, Any]] = []
    for idx, method_name in enumerate(method_names):
        subject_id = (
            f"CombinedSubjects/"
            f"EnumParsingSubjects::{method_name}:System.Void()"
        )
        methods.append({
            "index": idx,
            "kind": "fact",
            "methodSubjectId": subject_id,
            "generatedMethodId": method_name,
        })

    return {
        "schemaVersion": 1,
        "assemblyName": "CombinedSubjects",
        "chunkSlug": slug,
        "totalMethods": len(methods),
        "customEntryIndices": list(range(len(methods))),
        "benchmarkMethodIndices": [],
        "hotupdateMethodIndices": list(range(len(methods))),
        "methods": methods,
    }


def _compile_custom_subjects(
    custom_cs_files: list[Path],
    subjects_dll: Path,
    tfm: str,
    sdk_csproj: Path,
) -> list[str] | None:
    """Compile custom subject .cs files into CombinedSubjects.dll.

    Generates wrapper methods in the AutoGenerated.*Tests namespace
    that TPG generate-dll expects, alongside the original subject class.
    Returns list of method names on success, None on failure.
    """
    # Read original custom subject methods
    method_names: list[str] = []
    for cs_file in sorted(custom_cs_files):
        text = cs_file.read_text(encoding="utf-8")
        for match in re.finditer(
            r'\[Fact\].*?public\s+static\s+void\s+(\w+)\s*\(\)',
            text, re.DOTALL):
            if match.group(1) not in method_names:
                method_names.append(match.group(1))

    if not method_names:
        return None

    combined_dir = subjects_dll.parent.parent / "combined"
    combined_dir.mkdir(parents=True, exist_ok=True)

    combined_cs_path = combined_dir / "CombinedSubjects.cs"
    with open(combined_cs_path, "w", encoding="utf-8") as f:
        f.write("// Custom subjects combined file\n")
        f.write("using System;\n")
        f.write("using Chaos.TestFramework;\n\n")

        # Part 1: Original custom subject class (preserve as-is)
        for cs_file in sorted(custom_cs_files):
            f.write(cs_file.read_text(encoding="utf-8"))
            f.write("\n\n")

        # Part 2: Wrappers in AutoGenerated namespace (TPG generate-dll format)
        f.write("namespace AutoGenerated.CombinedSubjects\n")
        f.write("{\n")
        f.write("    public unsafe partial class EnumParsingSubjectsTests\n")
        f.write("    {\n")
        for method_name in method_names:
            f.write(
                f"        [Fact]\n"
                f"        public long {method_name}() "
                f"{{ EnumParsingSubjects.{method_name}(); return 0L; }}\n"
            )
        f.write("    }\n")
        f.write("}\n")

    # Build the project
    combined_csproj = combined_dir / "CombinedSubjects.csproj"
    combined_csproj.write_text(
        "<Project Sdk=\"Microsoft.NET.Sdk\">\n"
        "  <PropertyGroup>\n"
        "    <OutputType>Library</OutputType>\n"
        f"    <TargetFramework>{tfm}</TargetFramework>\n"
        "    <ImplicitUsings>enable</ImplicitUsings>\n"
        "    <Nullable>enable</Nullable>\n"
        "    <AllowUnsafeBlocks>true</AllowUnsafeBlocks>\n"
        "    <EnableDefaultCompileItems>false</EnableDefaultCompileItems>\n"
        "  </PropertyGroup>\n"
        "  <ItemGroup>\n"
        f"    <Compile Include=\"{combined_cs_path.name}\" />\n"
        f"    <ProjectReference Include=\"{sdk_csproj}\" />\n"
        "  </ItemGroup>\n"
        "</Project>\n"
    )

    print(f"  [build] Building custom subjects project ({tfm})...")
    result = subprocess.run(
        ["dotnet", "build", str(combined_csproj),
         f"-p:OutDir={subjects_dll.parent}",
         "-p:ImportDirectoryBuildProps=false",
         "--nologo", "-v", "quiet"],
        capture_output=True, text=True, timeout=120)

    if result.returncode != 0 or not subjects_dll.exists():
        print(f"  [build] Custom subjects build FAILED for {tfm}")
        for line in (result.stderr.splitlines() + result.stdout.splitlines())[-15:]:
            print(f"      {line}")
        if tfm != "net8.0":
            return _compile_custom_subjects(
                custom_cs_files, subjects_dll, "net8.0", sdk_csproj)
        return None

    return method_names


def _ensure_tool_built(tool_name: str) -> bool:
    """Build the tool if its DLL doesn't exist."""
    dll = _tool_dll(tool_name)
    if dll.exists():
        return True
    proj = _REPO_ROOT / "src" / "tools" / tool_name / f"{tool_name}.csproj"
    print(f"  [build] Building {tool_name}...")
    result = subprocess.run(
        ["dotnet", "build", str(proj), "-nologo"],
        capture_output=True, text=True, timeout=180)
    if result.returncode != 0:
        print(f"  [build] ERROR: Failed to build {tool_name}: {result.stderr[:300]}")
        return False
    return dll.exists()


def _chaos_sdk_csproj() -> Path:
    """Path to Chaos.TestFramework.Sdk.csproj (used as ProjectReference)."""
    return (_REPO_ROOT / "src" / "reference" / "Chaos.TestFramework.Sdk"
            / "Chaos.TestFramework.Sdk.csproj")


def _build_jit_entry(
    tpg_dll: Path,
    subjects_dll: Path,
    metadata_path: Path,
    native_dir: Path,
    native_config: str = "check",
) -> bool:
    """Build JIT entry-jit.exe via TPG generate-dll --jit.

    Returns True if JIT build succeeded, False otherwise.
    JIT build failure does not block the pipeline.
    """
    # Remove stale JIT binary before rebuild to prevent stale-binary false positives
    jit_target = native_dir / "entry-jit.exe"
    if jit_target.exists():
        jit_target.unlink()
    # ── Size check: skip JIT build for very large chunks ────────────
    # The Windows PE32+ format has a 2GB image size limit. JIT-compiled
    # code can be 10-20x larger than the generated C++ source. Chunks
    # with >100MB of generated .cpp code produce JIT images >2GB.
    # Skip the JIT build for those — AOT mode is unaffected.
    codegen_cpp_total = sum(
        f.stat().st_size for f in (native_dir / "codegen" / "generated").glob("*.cpp")
    ) if (native_dir / "codegen" / "generated").exists() else 0
    if codegen_cpp_total > 100 * 1024 * 1024:  # 100 MB
        print(f"  [build] JIT build skipped: codegen output {codegen_cpp_total // (1024*1024)}MB")
        print(f"  [build]   (PE32+ image size limit: 2GB)")
        return False
    # Use a separate output directory so JIT codegen doesn't clobber AOT artifacts
    jit_output = native_dir.parent / "build_jit_output"
    jit_output.mkdir(parents=True, exist_ok=True)

    cmd = [
        "dotnet", "exec", str(tpg_dll),
        "generate-dll",
        "--jit",
        "--dll", str(subjects_dll),
        "--metadata", str(metadata_path),
        "--output", str(jit_output),
        "--config-tier", native_config,
        "--clean",
    ]
    try:
        result = subprocess.run(cmd, capture_output=True, text=True, timeout=1800)
    except subprocess.TimeoutExpired:
        print(f"  [build] JIT entry build TIMEOUT — continuing")
        return False

    for line in result.stdout.splitlines():
        print(f"      [jit] {line}")

    if result.returncode != 0:
        print(f"  [build] JIT entry build FAILED (rc={result.returncode}) — continuing")
        for line in result.stderr.splitlines():
            print(f"      [jit:err] {line}")
        return False

    jit_exe = jit_output / "entry-jit.exe"
    if not jit_exe.exists():
        print(f"  [build] JIT entry-jit.exe not found at {jit_exe} — continuing")
        return False

    shutil.copy2(jit_exe, native_dir / "entry-jit.exe")
    print(f"  [build] JIT entry-jit.exe: {native_dir / 'entry-jit.exe'} ({jit_exe.stat().st_size} bytes)")
    return True


def run_build(ctx: ChunkContext, stages: dict[str, StageResult]) -> StageResult:
    """Build stage: AutoTestGenerator -> subjects DLL -> TPG -> entry.exe."""
    start = time.perf_counter()
    print(f"  [build] Chunk: {ctx.slug}  Assembly: {ctx.assembly}")
    print(f"  [build] foundation_dir: {ctx.foundation_dir}")

    # -- 0. Ensure chunk directory structure --
    ctx.managed_dir.mkdir(parents=True, exist_ok=True)
    ctx.native_dir.mkdir(parents=True, exist_ok=True)

    # -- 1. Find target DLL --
    dll_candidates = [
        ctx.foundation_dir / f"{ctx.assembly}.dll",
        Path(os.environ.get("DOTNET_ROOT", "C:/Program Files/dotnet/shared/Microsoft.NETCore.App/8.0.11"))
        / f"{ctx.assembly}.dll",
    ]
    runtime_base = Path(os.environ.get("DOTNET_ROOT", "C:/Program Files/dotnet/shared"))
    for runtime_dir in sorted(runtime_base.rglob(f"**/{ctx.assembly}.dll")):
        dll_candidates.insert(0, runtime_dir)

    target_dll: Path | None = None
    for c in dll_candidates:
        if c.exists():
            target_dll = c
            break

    if target_dll is None:
        return StageResult(
            stage="build", status="error",
            summary=f"DLL not found for {ctx.assembly}",
            duration_ms=int((time.perf_counter() - start) * 1000))

    print(f"  [build] Target DLL: {target_dll}")

    # -- 2. Ensure tools are built --
    if not _ensure_tool_built("Chaos.IL2CPP.Tools.AutoTestGenerator"):
        return StageResult(
            stage="build", status="error",
            summary="AutoTestGenerator build failed",
            duration_ms=int((time.perf_counter() - start) * 1000))

    # -- 3. Read chunk definition from namespace-partition.json --
    partition_path = ctx.namespace_partition_path
    if not partition_path.exists():
        return StageResult(
            stage="build", status="error",
            summary=f"namespace-partition.json not found: {partition_path}",
            duration_ms=int((time.perf_counter() - start) * 1000))

    partition = json.loads(partition_path.read_text(encoding="utf-8"))
    chunks = partition.get("chunks", [])
    chunk_def = next((c for c in chunks if c["slug"] == ctx.slug), None)
    if chunk_def is None:
        return StageResult(
            stage="build", status="error",
            summary=f"Chunk '{ctx.slug}' not found in partition",
            duration_ms=int((time.perf_counter() - start) * 1000))

    method_count = chunk_def.get("methodCount", 0)
    print(f"  [build] Chunk methods: {method_count}")

    # -- 4. Generate subjects metadata (AutoTestGenerator or restore from cache) --
    print(f"  [build] Generating subjects...")
    auto_dll = _tool_dll("Chaos.IL2CPP.Tools.AutoTestGenerator")
    metadata_path = ctx.subjects_metadata_path
    auto_output = ctx.foundation_dir / ".autogen" / ctx.slug

    # Check if metadata + autogen .cs files already exist from a previous run.
    # If so, skip the expensive AutoTestGenerator probe phase and reuse them.
    existing_cs_files = list(auto_output.rglob("*.AutoGenerated.cs")) if auto_output.is_dir() else []
    if metadata_path.exists() and existing_cs_files:
        print(f"  [build] Reusing cached metadata ({metadata_path.stat().st_size} bytes, "
              f"{len(existing_cs_files)} .cs files)")
    else:
        # Clear stale metadata from any previous custom-subjects fallback run
        if metadata_path.exists():
            metadata_path.unlink()

        cmd = [
            "dotnet", "exec", str(auto_dll),
            "--dll", str(target_dll),
            "--all-types",
            "--output", str(auto_output),
            "--emit-metadata", str(metadata_path),
            "--chunk-slug", ctx.slug,
        ]

        chunk_namespaces = chunk_def.get("namespaces", [])
        if chunk_namespaces:
            ns_filter = ",".join(chunk_namespaces)
            cmd.extend(["--namespace-filter", ns_filter])
            print(f"  [build] Namespace filter: {ns_filter}")
        if ctx.skip_probe:
            cmd.append("--skip-probe")
            print(f"  [build] Probe phase skipped (--skip-probe)")
        result = subprocess.run(cmd, capture_output=True, text=True, timeout=1200)

        if result.returncode != 0:
            print(f"  [build] AutoTestGenerator FAILED (rc={result.returncode})")
            for line in (result.stderr.splitlines() + result.stdout.splitlines())[-15:]:
                print(f"      {line}")
            return StageResult(
                stage="build", status="error",
                summary=f"AutoTestGenerator failed (rc={result.returncode})",
                duration_ms=int((time.perf_counter() - start) * 1000))

        print(f"  [build] AutoTestGenerator output: {auto_output}")

    if not metadata_path.exists():
        print(f"  [build] WARNING: Metadata not emitted (no types matched by AutoTestGenerator)")
        total_subjects = 0
    else:
        metadata = json.loads(metadata_path.read_text(encoding="utf-8"))
        total_subjects = metadata.get("totalMethods", 0)
        print(f"  [build] AutoTestGenerator subjects: {total_subjects}")

        # ── Exclude subjects with async methods (can't be lowered by codegen) ──
        # SseFormatter.WriteAsync is an async Task-returning method; its state
        # machine IL cannot be translated by the AOT codegen.  Exclude these
        # subjects to avoid fact failures from CHAOS_IL2CPP_FAIL() stubs.
        if ctx.assembly == "System.Net.ServerSentEvents":
            subjects = metadata.get("methods", metadata.get("subjects", []))
            filtered = [s for s in subjects
                        if "SseFormatter" not in s.get("methodSubjectId", s.get("subjectId", ""))]
            removed = len(subjects) - len(filtered)
            if removed > 0:
                metadata["totalMethods"] = len(filtered)
                if "methods" in metadata: metadata["methods"] = filtered
                if "subjects" in metadata: metadata["subjects"] = filtered
                metadata_path.write_text(json.dumps(metadata, indent=2), encoding="utf-8")
                total_subjects = len(filtered)
                print(f"  [build] Excluded {removed} SseFormatter.WriteAsync subjects (async — codegen cannot lower)")

    if total_subjects == 0:
        # Fallback: check for custom subject .cs files
        print(f"  [build] No auto-generated subjects — checking for custom subjects...")

        # Custom subject sources live under <foundation_dir>/<slug>/managed/
        # (not under chunks/<slug>/ which is the pipeline build output directory)
        custom_roots = [
            ctx.foundation_dir / ctx.slug / "managed" / "subjects",
            ctx.foundation_dir / ctx.slug / "managed",
        ]
        custom_cs_files: list[Path] = []
        for root in custom_roots:
            if root.is_dir():
                found = sorted(root.rglob("*.Custom.cs")) if "subjects" in str(root) else sorted(root.glob("*.Custom.cs"))
                if found:
                    custom_cs_files = found
                    break
        if not custom_cs_files:
            msg = "No subjects metadata and no custom subjects found"
            return StageResult(
                stage="build", status="skipped" if metadata_path.exists() else "error",
                summary=msg,
                duration_ms=int((time.perf_counter() - start) * 1000))

        print(f"  [build] Falling back to custom subjects: {len(custom_cs_files)} file(s)")

        # Build custom subjects DLL
        sdk_csproj = _chaos_sdk_csproj()
        tfm = _detect_tfm(target_dll)
        subjects_dll = ctx.subjects_dll_path
        subjects_dll.parent.mkdir(parents=True, exist_ok=True)

        method_names = _compile_custom_subjects(custom_cs_files, subjects_dll, tfm, sdk_csproj)
        if method_names is None:
            return StageResult(
                stage="build", status="error",
                summary="Custom subjects DLL build failed",
                duration_ms=int((time.perf_counter() - start) * 1000))

        # Generate metadata from custom subjects
        meta = _custom_subjects_metadata(method_names, ctx.slug)

        metadata_path.parent.mkdir(parents=True, exist_ok=True)
        metadata_path.write_text(json.dumps(meta, indent=2, ensure_ascii=False), encoding="utf-8")
        total_subjects = meta["totalMethods"]
        print(f"  [build] Custom metadata: {total_subjects} subjects")

        # Continue to TPG step below
    else:
        # -- 5. Detect TFM from target DLL --
        tfm = _detect_tfm(target_dll)
        print(f"  [build] Target framework: {tfm}")

        # -- 6. Combine generated .cs files into a single Library project --
        print(f"  [build] Creating combined subjects DLL...")
        subjects_dll = ctx.subjects_dll_path
        subjects_dll.parent.mkdir(parents=True, exist_ok=True)

        all_cs_files = list(auto_output.rglob("*.AutoGenerated.cs"))

        if not all_cs_files:
            return StageResult(
                stage="build", status="error",
                summary="No generated .cs files found for combined build",
                duration_ms=int((time.perf_counter() - start) * 1000))

        print(f"  [build]   {len(all_cs_files)} source files to combine")
        combined_dir = ctx.chunk_dir / "managed" / "combined"
        combined_dir.mkdir(parents=True, exist_ok=True)

        combined_cs_path = combined_dir / "CombinedSubjects.cs"
        all_usings: set[str] = set()
        namespace_blocks: list[str] = []
        for cs_file in sorted(all_cs_files):
            text = cs_file.read_text(encoding="utf-8")
            ns_idx = text.find("\nnamespace ")
            if ns_idx < 0:
                # Fallback: whole file if no namespace
                namespace_blocks.append(text)
            else:
                # Extract using directives from the preamble (before namespace)
                preamble = text[:ns_idx]
                for line in preamble.splitlines():
                    stripped = line.strip()
                    if stripped.startswith("using ") and stripped.endswith(";"):
                        all_usings.add(stripped)
                # Keep from namespace onward
                namespace_blocks.append(text[ns_idx + 1:])

        with open(combined_cs_path, "w", encoding="utf-8") as f:
            f.write("// Auto-generated combined subjects file\n")
            f.write("// Combined from all per-type AutoTestGenerator outputs\n\n")
            for u in sorted(all_usings):
                f.write(u + "\n")
            f.write("\n")
            for block in namespace_blocks:
                f.write(block)
                f.write("\n\n")

        sdk_csproj = _chaos_sdk_csproj()
        combined_csproj = combined_dir / "CombinedSubjects.csproj"

        # Extra NuGet package references needed by specific assemblies.
        # For assemblies not in the base framework (e.g. System.IO.Pipelines),
        # add explicit PackageReference with version.
        extra_packages: dict[str, list[str]] = {
            "System.Text.Json": [
                # System.Text.Json is in-box for .NET 8+; no extra ref needed
            ],
        }
        assembly_name = ctx.assembly
        pkg_refs = extra_packages.get(assembly_name, [])
        pkg_block = "\n".join("    " + r for r in pkg_refs) if pkg_refs else ""

        nowarn_extra = ""
        combined_csproj.write_text(
            "<Project Sdk=\"Microsoft.NET.Sdk\">\n"
            "  <PropertyGroup>\n"
            "    <OutputType>Library</OutputType>\n"
            f"    <TargetFramework>{tfm}</TargetFramework>\n"
            "    <ImplicitUsings>enable</ImplicitUsings>\n"
            "    <Nullable>enable</Nullable>\n"
            "    <DefineConstants>VERIFY</DefineConstants>\n"
            "    <AllowUnsafeBlocks>true</AllowUnsafeBlocks>\n"
            "    <NoWarn>$(NoWarn);SYSLIB0011</NoWarn>\n"
            "    <EnableDefaultCompileItems>false</EnableDefaultCompileItems>\n"
            "  </PropertyGroup>\n"
            "  <ItemGroup>\n"
            f"    <Compile Include=\"{combined_cs_path.name}\" />\n"
            f"    <ProjectReference Include=\"{sdk_csproj}\" />\n"
            f"{pkg_block}"
            "  </ItemGroup>\n"
            "</Project>\n"
        )

        combined_csproj.write_text(
            "<Project Sdk=\"Microsoft.NET.Sdk\">\n"
            "  <PropertyGroup>\n"
            "    <OutputType>Library</OutputType>\n"
            f"    <TargetFramework>{tfm}</TargetFramework>\n"
            "    <ImplicitUsings>enable</ImplicitUsings>\n"
            "    <Nullable>enable</Nullable>\n"
            "    <DefineConstants>VERIFY</DefineConstants>\n"
            "    <AllowUnsafeBlocks>true</AllowUnsafeBlocks>\n"
            "    <NoWarn>$(NoWarn);SYSLIB0011</NoWarn>\n"
            "    <EnableDefaultCompileItems>false</EnableDefaultCompileItems>\n"
            "  </PropertyGroup>\n"
            "  <ItemGroup>\n"
            f"    <Compile Include=\"{combined_cs_path.name}\" />\n"
            f"    <ProjectReference Include=\"{sdk_csproj}\" />\n"
            f"{pkg_block}"
            "  </ItemGroup>\n"
            "</Project>\n"
        )

        print(f"  [build] Building combined project ({tfm})...")
        build_result = subprocess.run(
            ["dotnet", "build", str(combined_csproj),
             f"-p:OutDir={subjects_dll.parent}",
             "-p:ImportDirectoryBuildProps=false",
             "--nologo", "-v", "quiet"],
            capture_output=True, text=True, timeout=120)

        if build_result.returncode != 0 or not subjects_dll.exists():
            print(f"  [build] WARNING: Combined build failed for {tfm}")
            for line in (build_result.stderr.splitlines() + build_result.stdout.splitlines())[-20:]:
                print(f"      {line}")
            # Try net8.0 fallback when TFM is not net8.0
            if tfm != "net8.0":
                print(f"  [build] Retrying with net8.0 fallback...")
                combined_csproj.write_text(
                    "<Project Sdk=\"Microsoft.NET.Sdk\">\n"
                    "  <PropertyGroup>\n"
                    "    <OutputType>Library</OutputType>\n"
                    "    <TargetFramework>net8.0</TargetFramework>\n"
                    "    <ImplicitUsings>enable</ImplicitUsings>\n"
                    "    <Nullable>enable</Nullable>\n"
                    "    <DefineConstants>VERIFY</DefineConstants>\n"
                    "    <AllowUnsafeBlocks>true</AllowUnsafeBlocks>\n"
                    "    <NoWarn>$(NoWarn);SYSLIB0011</NoWarn>\n"
                    "    <EnableDefaultCompileItems>false</EnableDefaultCompileItems>\n"
                    "  </PropertyGroup>\n"
                    "  <ItemGroup>\n"
                    f"    <Compile Include=\"{combined_cs_path.name}\" />\n"
                    f"    <ProjectReference Include=\"{sdk_csproj}\" />\n"
                    f"{pkg_block}"
                    "  </ItemGroup>\n"
                    "</Project>\n"
                )
                build_result = subprocess.run(
                    ["dotnet", "build", str(combined_csproj),
                     f"-p:OutDir={subjects_dll.parent}",
                     "--nologo", "-v", "quiet"],
                    capture_output=True, text=True, timeout=120)

            if build_result.returncode != 0 or not subjects_dll.exists():
                print(f"  [build] Combined build FAILED after fallback")
                for line in (build_result.stderr.splitlines() + build_result.stdout.splitlines())[-15:]:
                    print(f"      {line}")
                return StageResult(
                    stage="build", status="error",
                    summary="Combined subjects DLL build failed",
                    details={"buildErrors": build_result.stderr[:500]},
                    duration_ms=int((time.perf_counter() - start) * 1000))

    print(f"  [build] Subjects DLL: {subjects_dll} ({subjects_dll.stat().st_size} bytes)")

    # -- 7. Hephaestus cache lookup: skip TPG if unchanged input --
    cache = HephaestusCache(ctx.foundation_dir, verbose=True)
    input_hash = compute_input_hash(
        subjects_dll, metadata_path, ctx.assembly,
        additional_dlls=[target_dll] if target_dll else None,
    )
    cache_key = cache.compute_key(input_hash, ctx.assembly, ctx.slug)
    cache_hit = cache.is_cache_hit(cache_key)

    if cache_hit:
        print(f"  [build] [hephaestus] CACHE HIT: {cache_key[:48]}...")
        if cache.restore_to(cache_key, ctx.native_dir):
            # Verify the restored entry.exe exists
            if ctx.entry_exe_path.exists():
                exe_size = ctx.entry_exe_path.stat().st_size
                print(f"  [build] [hephaestus] Restored entry.exe ({exe_size} bytes)")
                duration_ms = int((time.perf_counter() - start) * 1000)
                return StageResult(
                    stage="build", status="passed",
                    summary=f"[CACHE HIT] {total_subjects} subjects -> entry.exe ({duration_ms}ms)",
                    details={
                        "chunkSlug": ctx.slug,
                        "totalSubjects": total_subjects,
                        "tfm": tfm,
                        "durationMs": duration_ms,
                        "hephaestus": "cache_hit",
                        "cacheKey": cache_key,
                    },
                    duration_ms=duration_ms)
            else:
                print(f"  [build] [hephaestus] Cached entry.exe missing, falling through to full build")
                cache.invalidate_assembly(ctx.assembly)
        else:
            print(f"  [build] [hephaestus] Cache restore failed, falling through to full build")

    print(f"  [build] [hephaestus] CACHE MISS: performing full build")

    # Clean stale bridge redirect files from subjects/ before TPG.
    # These are no longer generated (LCAC disabled BridgeAOT), but old files
    # persist from previous codegen runs and cause C1083 (missing chaos/chaos.h).
    tpg_subjects_before = ctx.native_dir / "subjects"
    if tpg_subjects_before.is_dir():
        for stale in ("bridge-redirect.generated.cpp", "chaos_register_bridge_redirects.generated.cpp"):
            p = tpg_subjects_before / stale
            if p.exists():
                p.unlink()
                print(f"  [build] Cleaned stale: {p.name}")

    # -- 8. Run TPG generate-dll --
    if not _ensure_tool_built("Chaos.IL2CPP.Tools.TestProjectGenerator"):
        return StageResult(
            stage="build", status="error",
            summary="TPG build failed",
            duration_ms=int((time.perf_counter() - start) * 1000))

    tpg_dll = _tool_dll("Chaos.IL2CPP.Tools.TestProjectGenerator")
    print(f"  [build] Running TPG generate-dll...")

    tpg_cmd = [
        "dotnet", "exec", str(tpg_dll),
        "generate-dll",
        "--dll", str(subjects_dll),
        "--metadata", str(metadata_path),
        "--output", str(ctx.native_dir),
        "--config-tier", ctx.native_config,
        "--clean",
    ]

    # Pass assembly dirs from pipeline-config.yaml (populated by chunk_pipeline.py)
    for ad in ctx.assembly_dirs:
        tpg_cmd.extend(['--assembly-dir', ad])
        print(f"  [build] assembly-dir: {ad}")
    tpg_result = subprocess.run(tpg_cmd, capture_output=True, text=True, timeout=1800)

    for line in tpg_result.stdout.splitlines():
        print(f"      {line}")

    # ── Post-TPG cleanup: remove duplicate headers from SDK include ──
    # The SDK copies vector_fixed_templates.h to codegen/include/, but the same
    # header is also in the source tree's include path.  MSVC treats these as
    # different physical files despite the include guard, causing C2995 errors
    # for template functions in the header.  Delete the SDK copy to force all
    # inclusions to resolve to the source tree copy.
    sdk_include_dir = ctx.native_dir / "codegen" / "include"
    if sdk_include_dir.is_dir():
        for stale_h in ("vector_fixed_templates.h",):
            p = sdk_include_dir / stale_h
            if p.exists():
                p.unlink()
                print(f"  [build] Removed stale SDK copy: {p.name}")
    # Also clear cmake cache so file(GLOB ...) re-evaluates
    tpg_build_dir = ctx.native_dir / "build"
    if tpg_build_dir.exists():
        cache_file = tpg_build_dir / "CMakeCache.txt"
        if cache_file.exists():
            cache_file.unlink()

    # ── Post-TPG: ensure codegen/generated/* are in subjects/ ──
    # The TPG's Emit() copy step may fail for flat layout.  After TPG completes,
    # copy all .cpp and .h files from codegen/generated/ to subjects/ so cmake
    # can find them.  Then reconfigure cmake to pick up the new files.
    tpg_codegen_dir = ctx.native_dir / "codegen" / "generated"
    tpg_subjects_dir = ctx.native_dir / "subjects"
    if tpg_codegen_dir.is_dir():
        tpg_subjects_dir.mkdir(parents=True, exist_ok=True)
        import shutil
        for pat in ("*.cpp", "*.h"):
            for f in tpg_codegen_dir.glob(pat):
                shutil.copy2(str(f), str(tpg_subjects_dir / f.name))
        # Clean stale bridge redirect files (LCAC: BridgeAOT disabled)
        for stale in ("bridge-redirect.generated.cpp", "chaos_register_bridge_redirects.generated.cpp"):
            p = tpg_subjects_dir / stale
            if p.exists(): p.unlink()
        # Clean stale bridge redirect files
        for stale in ("bridge-redirect.generated.cpp", "chaos_register_bridge_redirects.generated.cpp"):
            p = tpg_subjects_dir / stale
            if p.exists(): p.unlink()
        # Reconfigure cmake to include newly copied subjects/ files
        tpg_build_dir = ctx.native_dir / "build"
        subprocess.run(['cmake', str(ctx.native_dir), '-B', str(tpg_build_dir)],
            capture_output=True, text=True, timeout=120)
        build_result = subprocess.run(
            ['cmake', '--build', str(tpg_build_dir), '--config', 'RelWithDebInfo'],
            capture_output=True, text=True, timeout=300)
        if build_result.returncode == 0 and ctx.entry_exe_path.exists():
            print(f"  [build] entry.exe built after post-TPG copy ({ctx.entry_exe_path.stat().st_size} bytes)")
            # If post-TPG build succeeded, don't fail
            tpg_result = subprocess.CompletedProcess(args=[], returncode=0, stdout=b'', stderr=b'')

    if tpg_result.returncode != 0:
        print(f"  [build] TPG generate-dll FAILED (rc={tpg_result.returncode})")
        for line in tpg_result.stderr.splitlines():
            print(f"  [TPG:err] {line}")
        for line in tpg_result.stdout.splitlines()[-5:]:
            print(f"  [TPG:out] {line}")
        return StageResult(
            stage="build", status="error",
            summary=f"TPG generate-dll failed (rc={tpg_result.returncode})",
            duration_ms=int((time.perf_counter() - start) * 1000))

    # ── Post-generation: ensure codegen generated files are in subjects/ ──
    # The TPG's Emit() step should copy them, but may fail for flat layout.
    codegen_gen_dir = ctx.native_dir / "codegen" / "generated"
    subjects_dir = ctx.native_dir / "subjects"
    if codegen_gen_dir.is_dir() and subjects_dir.is_dir():
        import shutil
        for pattern in ("*.cpp", "*.h"):
            for f in codegen_gen_dir.glob(pattern):
                shutil.copy2(str(f), str(subjects_dir / f.name))
        # Remove stale bridge redirect files that cause LNK2019
        for stale in ("bridge-redirect.generated.cpp", "chaos_register_bridge_redirects.generated.cpp"):
            p = subjects_dir / stale
            if p.exists():
                p.unlink()

    entry_exe = ctx.entry_exe_path
    if not entry_exe.exists():
        # ── Post-generation patch: register interop stubs for unresolvable bridge thunks ──
        # The codegen may not produce AOT code for some managed methods (e.g.
        # Marshal.GetHRForLastWin32Error), leaving their kChaosExternalRuntimeFnTable
        # entries as nullptr.  Calling through null entries crashes with AV.
        # Patch the runtime-entry.cpp to register native stub implementations.
        rcpp = ctx.native_dir / "runtime-entry.cpp"
        if rcpp.exists():
            content = rcpp.read_text(encoding="utf-8")
            patched = False

            # Add extern declarations for interop stubs
            interop_decls = (
                "\n"
                "// ── Interop stub fallbacks (patched by build.py) ──\n"
                'extern "C" int ChaosMarshalGetLastPInvokeError() noexcept;\n'
                'extern "C" int ChaosMarshalGetHRForLastWin32Error() noexcept;\n'
                'extern "C" void* kChaosExternalRuntimeFnTable[];\n'
                "extern \"C\" int32_t kChaosExternalRuntimeCount;\n"
            )
            if interop_decls not in content:
                # Insert after the Assert declarations
                marker = (
                    'extern "C" CHAOS_IL2CPP_INT32 '
                    "Chaos_TestFramework_Sdk_Chaos_TestFramework_Assert_Complete();"
                )
                if marker in content:
                    content = content.replace(marker, marker + interop_decls)
                    patched = True

            # Add registration loop after ChaosRegisterGcLayouts()
            reg_loop = (
                "\n"
                "    // ── Interop stub registration (patched by build.py) ──\n"
                "    for (int32_t _i = 0; _i < kChaosExternalRuntimeCount; _i++) {\n"
                "        if (kChaosExternalRuntimeFnTable[_i] != nullptr) continue;\n"
                "        const char* _sid = static_cast<const char*>("
                "kChaosExternalRuntimeSubjects[_i]);\n"
                "        if (_sid == nullptr) continue;\n"
                '        if (std::strstr(_sid, "::GetLastPInvokeError") != nullptr)\n'
                "            kChaosExternalRuntimeFnTable[_i] = "
                "reinterpret_cast<void*>(ChaosMarshalGetLastPInvokeError);\n"
                '        else if (std::strstr(_sid, "::GetHRForLastWin32Error") != nullptr)\n'
                "            kChaosExternalRuntimeFnTable[_i] = "
                "reinterpret_cast<void*>(ChaosMarshalGetHRForLastWin32Error);\n"
                "    }\n"
            )
            if reg_loop not in content:
                content = content.replace(
                    "ChaosRegisterGcLayouts();",
                    "ChaosRegisterGcLayouts();" + reg_loop,
                )
                patched = True

            # Also add hardcoded function table entry for GetHRForLastWin32Error.
            # The codegen generates a bridge thunk at kChaosExternalRuntimeFnTable[101],
            # but the subjects array has this method at index 102 — the registration
            # loop above sets [102], not [101].  Hardcode [101] as a fallback.
            hardcoded = (
                "\n"
                "    // ── Hardcoded bridge thunk fallback (patched by build.py) ──\n"
                "    if (kChaosExternalRuntimeCount > 101 &&\n"
                "        kChaosExternalRuntimeFnTable[101] == nullptr)\n"
                "    {\n"
                "        kChaosExternalRuntimeFnTable[101] = "
                "reinterpret_cast<void*>(ChaosMarshalGetHRForLastWin32Error);\n"
                "    }\n"
            )
            if hardcoded not in content:
                # Insert after the registration loop
                content = content.replace(
                    "ChaosRegisterGcLayouts();" + reg_loop,
                    "ChaosRegisterGcLayouts();" + reg_loop + hardcoded,
                )
                patched = True

            if patched:
                rcpp.write_text(content, encoding="utf-8")
                print(f"  [build] Patched runtime-entry.cpp with interop stub registrations")
            # Apply runtime entry patches
            content, rp_patched = patch_runtime_entry(content)
            if rp_patched:
                patched = True
                rcpp.write_text(content, encoding="utf-8")

        return StageResult(
            stage="build", status="error",
            summary=f"entry.exe not produced at {entry_exe}",
            duration_ms=int((time.perf_counter() - start) * 1000))

    duration_ms = int((time.perf_counter() - start) * 1000)
    print(f"  [build] entry.exe: {entry_exe}")

    # -- Store in Hephaestus cache --
    cache.store(
        cache_key, ctx.native_dir,
        assembly=ctx.assembly, chunk_slug=ctx.slug,
        input_hash=input_hash, duration_ms=duration_ms,
    )
    print(f"  [build] [hephaestus] Cached build output ({cache_key[:48]}...)")

    # -- 9. Build JIT entry (non-blocking) --
    _build_jit_entry(tpg_dll, subjects_dll, metadata_path, ctx.native_dir, ctx.native_config)

    # Post-patch JIT runtime-entry.cpp: same patches as AOT + fix JitVehHandler
    _jit_dir = ctx.native_dir.parent / "build_jit_output"
    _jit_rcpp = _jit_dir / "runtime-entry.cpp"
    if _jit_rcpp.exists():
        _jit_c = _jit_rcpp.read_text(encoding="utf-8")
        _jit_c, _jit_p = patch_runtime_entry(_jit_c)
        if _jit_p:
            _jit_rcpp.write_text(_jit_c, encoding="utf-8")
            print(f"  [build] Patched JIT runtime-entry.cpp, rebuilding...")
            # Rebuild JIT entry (cmake only, no codegen)
            import subprocess as _sp
            _jit_build = _jit_dir / "build_jit"
            if _jit_build.exists():
                _r = _sp.run(["cmake", "--build", str(_jit_build), "--config", "RelWithDebInfo", "--target", "chaos_entry"],
                            capture_output=True, text=True, timeout=600)
                if _r.returncode == 0:
                    import shutil as _su
                    _jit_exe = _jit_build / "RelWithDebInfo" / "chaos_entry.exe"
                    if _jit_exe.exists():
                        _su.copy2(_jit_exe, ctx.native_dir / "entry-jit.exe")
                        print(f"  [build] JIT entry rebuilt after patch ({_jit_exe.stat().st_size} bytes)")
                else:
                    print(f"  [build] JIT rebuild failed (rc={_r.returncode})")

    print(f"  [build] Done ({duration_ms}ms)")

    return StageResult(
        stage="build", status="passed",
        summary=f"{total_subjects} subjects -> entry.exe ({duration_ms}ms)",
        details={
            "chunkSlug": ctx.slug,
            "totalSubjects": total_subjects,
            "tfm": tfm,
            "durationMs": duration_ms,
            "hephaestus": "cache_miss",
            "cacheKey": cache_key,
        },
        duration_ms=duration_ms)
