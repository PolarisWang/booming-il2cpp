"""Hotupdate stage — ATG patch pass + entry.exe --hotupdate --patch-data.

Flow:
  1. Run ATG --patch-mode to generate patch C# code with transformed return values
  2. Build patch DLL via dotnet build
  3. Run PatchDataExtractor (subject-only mode) to produce patch.patchdata
  4. Run entry.exe --hotupdate --patch-data patch.patchdata
  5. Parse per-method baseline/patched/revert JSON, verify semantic change
"""

from __future__ import annotations

import json
import os
import subprocess
import time
from pathlib import Path
from typing import Any

from verification.orchestration.context import ChunkContext, StageResult

_REPO_ROOT = Path(__file__).resolve().parents[4]


# -- C++ identifier sanitization (matches SanitizeCppIdentifier in ProjectModel.cs) --

def _sanitize_cpp_identifier(name: str) -> str:
    """Convert .NET type name to C++ identifier: '.'→'_', strip non-alphanum."""
    result: list[str] = []
    for c in name:
        if c.isalnum() or c == '_':
            result.append(c)
        elif c == '.':
            result.append('_')
    if result and result[0].isdigit():
        result.insert(0, '_')
    return ''.join(result)


def _parse_type_name_from_subject_id(method_subject_id: str) -> str:
    """Extract full type name from 'Assembly/Type::Method:Ret(Params)'."""
    if '::' not in method_subject_id:
        return ''
    type_method = method_subject_id.split('::')[0]
    if '/' in type_method:
        return type_method.split('/', 1)[1]
    return type_method


def _generate_patch_host_arrays(native_dir: Path, metadata: dict) -> bool:
    """Generate patch-host-arrays.cpp with per-method host arrays for ApplyPatchFromMemoryEx.

    Reads subjects.metadata.json to compute AOT registry (namespace, type, method) names
    for each hotupdate subject, then writes a C++ file defining kPatchDataHostNamespace,
    kPatchDataHostTypeNames[], kPatchDataHostMethodNames[], and kPatchDataCount.
    """
    assembly_name = metadata.get('assemblyName', '')
    if not assembly_name:
        print('  [hotupdate] ERROR: metadata missing assemblyName')
        return False

    host_ns = 'AutoGenerated.' + _sanitize_cpp_identifier(assembly_name)
    hotupdate_indices: list[int] = metadata.get('hotupdateMethodIndices', [])
    methods: list[dict] = metadata.get('methods', [])
    method_by_index = {m['index']: m for m in methods}

    host_type_names: list[str] = []
    host_method_names: list[str] = []
    for idx in hotupdate_indices:
        m = method_by_index.get(idx, {})
        msid = m.get('methodSubjectId', '')
        full_type = _parse_type_name_from_subject_id(msid)
        # Strip "AutoGenerated.{assembly}." prefix to get the raw type name
        # as the AOT codegen registered it (e.g. "System_Collections_Generic_XTests"
        # NOT "AutoGenerated.System_Private_CoreLib.System_Collections_Generic_XTests").
        prefix = 'AutoGenerated.' + _sanitize_cpp_identifier(assembly_name) + '.'
        if full_type.startswith(prefix):
            type_name = full_type[len(prefix):]
        else:
            type_name = full_type
        host_type_names.append(type_name)

        gmid = m.get('generatedMethodId')
        if gmid:
            host_method_names.append(gmid)
        elif '::' in msid:
            host_method_names.append(msid.split('::')[1].split(':')[0])
        else:
            host_method_names.append('unknown_method')

    lines = [
        '// patch-host-arrays.cpp — Auto-generated by hotupdate pipeline',
        '// Per-method host arrays for ApplyPatchFromMemoryEx.',
        '#include <cstdint>',
        '',
        f'extern const char* const kPatchDataHostNamespace = "{host_ns}";',
        'extern const char* const kPatchDataHostTypeNames[] = {',
    ]
    for n in host_type_names:
        lines.append(f'    "{n}",')
    lines.append('};')
    lines.append('extern const char* const kPatchDataHostMethodNames[] = {')
    for n in host_method_names:
        lines.append(f'    "{n}",')
    lines.append('};')
    lines.append(f'extern const int kPatchDataCount = {len(host_type_names)};')
    lines.append('')

    (native_dir / 'patch-host-arrays.cpp').write_text('\n'.join(lines), encoding='utf-8')
    print(f'  [hotupdate] Generated patch-host-arrays.cpp ({len(host_type_names)} entries)')
    return True


def _run_cmake_rebuild(native_dir: Path) -> bool:
    """Incremental cmake rebuild: recompiles patch-host-arrays.cpp and relinks entry.exe."""
    build_dir = native_dir / 'build'
    if not build_dir.exists():
        print(f'  [hotupdate] Build directory not found: {build_dir}')
        return False

    # Reconfigure cmake to pick up any page file count changes (stale page files
    # from previous codegen runs are cleaned by the TPG, but the cmake cache may
    # still reference them).  The reconfigure re-evaluates file(GLOB ...) rules.
    subprocess.run(['cmake', str(native_dir), '-B', str(build_dir)],
        capture_output=True, text=True, timeout=120)

    result = subprocess.run(
        ['cmake', '--build', str(build_dir), '--config', 'RelWithDebInfo'],
        capture_output=True, text=True, timeout=300)

    if result.returncode != 0:
        for line in (result.stderr.splitlines() + result.stdout.splitlines())[-10:]:
            print(f'      {line}')
        return False

    print(f'  [hotupdate] cmake rebuild OK')
    return True


# -- Tool helpers (mirrors build.py) -----------------------------------------

def _tool_dll(tool_name: str) -> Path:
    return (_REPO_ROOT / "src" / "tools" / tool_name
            / "bin" / "Debug" / "net8.0" / f"{tool_name}.dll")


def _ensure_tool_built(tool_name: str) -> bool:
    """Rebuild the tool DLL if the source has changed since last build."""
    proj = (_REPO_ROOT / "src" / "tools" / tool_name / f"{tool_name}.csproj")
    dll = _tool_dll(tool_name)
    if dll.exists() and proj.exists():
        src_time = max(
            p.stat().st_mtime
            for p in proj.parent.rglob("*.cs")
            if p.is_file()
        ) if any(True for _ in proj.parent.rglob("*.cs")) else proj.stat().st_mtime
        if src_time <= dll.stat().st_mtime:
            return True
    result = subprocess.run(
        ["dotnet", "build", str(proj), "-nologo"],
        capture_output=True, text=True, timeout=120)
    if result.returncode != 0:
        for line in (result.stderr.splitlines() + result.stdout.splitlines())[-5:]:
            print(f"      {line}")
        return False
    return True


def _build_patch_dll(patch_output: Path, patch_dll: Path, target_dll: Path | None = None) -> bool:
    """Combine ATG --patch-mode generated .cs files and build into a DLL."""
    # Exclude obj/ build artifacts, CombinedPatchSubjects.cs (self-reference),
    # and AssemblyAttributes files generated by the build system.
    all_patch_files = sorted(
        p for p in patch_output.rglob("*.cs")
        if "obj" not in p.parts
        and p.name != "CombinedPatchSubjects.cs"
        and "AssemblyAttributes" not in p.name
        and "AssemblyInfo" not in p.name
        and "GlobalUsings" not in p.name
    )
    if not all_patch_files:
        print(f"  [hotupdate] No patch .cs files found in {patch_output}")
        return False

    combined_cs = patch_dll.parent / "CombinedPatchSubjects.cs"
    # Concatenate ATG output files as-is — all usings and code bodies are
    # generated correctly by ATG --patch-mode.
    parts = [pf.read_text(encoding="utf-8") for pf in all_patch_files]
    content = "\n\n".join(parts)
    combined_cs.write_text(content, encoding="utf-8")

    # Detect TFM from target DLL path (e.g. ".../9.0.0/...System.Private.CoreLib.dll" → net9.0)
    import re as _re
    _version_match = _re.search(r'Microsoft\.NETCore\.App[\\/](\d+)\.', str(target_dll))
    tfm = f"net{_version_match.group(1)}" if _version_match else "net9.0"
    sdk_csproj = (_REPO_ROOT / "src" / "reference" / "Chaos.TestFramework.Sdk"
                  / "Chaos.TestFramework.Sdk.csproj")
    csproj = patch_dll.parent / "PatchSubjects.csproj"
    csproj.write_text(
        "<Project Sdk=\"Microsoft.NET.Sdk\">\n"
        "  <PropertyGroup>\n"
        "    <OutputType>Library</OutputType>\n"
        f"    <TargetFramework>{tfm}</TargetFramework>\n"
        "    <ImplicitUsings>enable</ImplicitUsings>\n"
        "    <Nullable>enable</Nullable>\n"
        "    <AllowUnsafeBlocks>true</AllowUnsafeBlocks>\n"
        "    <EnableDefaultCompileItems>false</EnableDefaultCompileItems>\n"
        "  </PropertyGroup>\n"
        "  <ItemGroup>\n"
        f"    <Compile Include=\"{combined_cs.name}\" />\n"
        f"    <ProjectReference Include=\"{sdk_csproj}\" />\n"
        "  </ItemGroup>\n"
        "</Project>\n"
    )

    result = subprocess.run(
        ["dotnet", "build", str(csproj),
         f"-p:OutDir={patch_dll.parent}",
         "--nologo"],
        capture_output=True, text=True, timeout=120,
    )
    if result.returncode != 0:
        for line in (result.stderr.splitlines() + result.stdout.splitlines())[-10:]:
            print(f"      {line}")
        return False

    return patch_dll.exists()


def run_hotupdate_chunk(ctx: ChunkContext, stages: dict[str, StageResult]) -> StageResult:
    """HotUpdate stage: generate patch data, run entry.exe, verify semantic change."""
    start = time.perf_counter()

    exe_path = ctx.entry_exe_path
    if not exe_path.exists():
        return StageResult(
            stage="hotupdate", status="skipped",
            summary=f"entry.exe not found, skipping hotupdate",
            duration_ms=int((time.perf_counter() - start) * 1000),
        )

    metadata_path = ctx.subjects_metadata_path
    if not metadata_path.exists():
        return StageResult(
            stage="hotupdate", status="skipped",
            summary="subjects.metadata.json not found, skipping hotupdate",
            duration_ms=int((time.perf_counter() - start) * 1000),
        )

    metadata = json.loads(metadata_path.read_text(encoding="utf-8"))
    hotupdate_indices = metadata.get("hotupdateMethodIndices", [])
    if not hotupdate_indices:
        print(f"  [hotupdate] No hotupdate subjects in metadata, skipping")
        return StageResult(
            stage="hotupdate", status="skipped_no_subjects",
            summary="no hotupdate subjects",
            duration_ms=int((time.perf_counter() - start) * 1000),
        )

    # ── Step 1: Try to generate patch data (ATG --patch-mode + build) ──
    _patch_generation_attempted = False
    # Full patch data generation pipeline: ATG --patch-mode → csc → PatchDataExtractor.
    # PatchDataExtractor reads the patch DLL's PE metadata and produces a self-contained
    # .patchdata binary (format "PADT" magic) that the runtime PatchLoader can apply.
    # The flow: ATG generates CombinedPatchSubjects.cs → dotnet build → PatchSubjects.dll
    # → TPG extract-patch-data → patch.patchdata → ApplyPatchFromMemoryEx at runtime.
    patch_data_path = None
    print(f"  [hotupdate] Attempting ATG --patch-mode to generate patch DLL...")

    # Find target DLL (same logic as build.py)
    target_dll: Path | None = None
    dll_candidates = [
        ctx.foundation_dir / f"{ctx.assembly}.dll",
    ]
    runtime_base = Path(os.environ.get("DOTNET_ROOT", "C:/Program Files/dotnet/shared"))
    for runtime_dir in sorted(runtime_base.rglob(f"**/{ctx.assembly}.dll")):
        dll_candidates.insert(0, runtime_dir)
    for c in dll_candidates:
        if c.exists():
            target_dll = c
            break

    if target_dll is None:
        print(f"  [hotupdate] Target DLL not found, skipping ATG --patch-mode")
    elif _ensure_tool_built("Chaos.IL2CPP.Tools.AutoTestGenerator"):
        _patch_generation_attempted = True
        auto_dll = _tool_dll("Chaos.IL2CPP.Tools.AutoTestGenerator")
        patch_output = ctx.foundation_dir / ".autogen" / f"{ctx.slug}.patch"

        cmd = [
            "dotnet", "exec", str(auto_dll),
            "--dll", str(target_dll),
            "--all-types",
            "--output", str(patch_output),
            "--chunk-slug", ctx.slug,
            "--patch-mode",
        ]

        chunk_partition = json.loads(ctx.namespace_partition_path.read_text(encoding="utf-8"))
        chunk_def = next((c for c in chunk_partition.get("chunks", []) if c["slug"] == ctx.slug), None)
        if chunk_def and chunk_def.get("namespaces"):
            cmd.extend(["--namespace-filter", ",".join(chunk_def["namespaces"])])

        atg_result = subprocess.run(cmd, capture_output=True, text=True, timeout=1200)
        if atg_result.returncode == 0:
            # Try to build the generated patch DLL
            patch_dll = ctx.chunk_dir / "managed" / "subjects" / "patch" / "PatchSubjects.dll"
            patch_dll.parent.mkdir(parents=True, exist_ok=True)
            if _build_patch_dll(patch_output, patch_dll, target_dll):
                print(f"  [hotupdate] Patch DLL built: {patch_dll}")
                # Extract patch data via TPG (IL2CPP codegen layer)
                if _ensure_tool_built("Chaos.IL2CPP.Tools.TestProjectGenerator"):
                    tpg_dll = _tool_dll("Chaos.IL2CPP.Tools.TestProjectGenerator")
                    patch_data_path = ctx.chunk_dir / "native" / "patch.patchdata"
                    patch_data_path.parent.mkdir(parents=True, exist_ok=True)
                    extract_cmd = [
                        "dotnet", "exec", str(tpg_dll),
                        "extract-patch-data",
                        "--dll", str(patch_dll),
                        "--output", str(patch_data_path),
                    ]
                    extract_result = subprocess.run(
                        extract_cmd, capture_output=True, text=True, timeout=120)
                    if extract_result.returncode == 0:
                        patch_data_size = patch_data_path.stat().st_size
                        print(f"  [hotupdate] Patch data: {patch_data_path} ({patch_data_size} bytes)")
                        if patch_data_size == 0:
                            print(f"  [hotupdate] WARN: patch data is empty, disabling --patch-data")
                            patch_data_path = None
                    else:
                        print(f"  [hotupdate] TPG extract-patch-data failed, falling back to no-patch mode")
                        for line in (extract_result.stderr.splitlines() + extract_result.stdout.splitlines())[-5:]:
                            print(f"      {line}")
                        patch_data_path = None
                else:
                    print(f"  [hotupdate] TPG build failed, falling back to no-patch mode")
                    patch_data_path = None
            else:
                print(f"  [hotupdate] Patch DLL build failed, falling back to no-patch mode")
        else:
            print(f"  [hotupdate] ATG --patch-mode failed, falling back to no-patch mode")
            for line in (atg_result.stderr.splitlines() + atg_result.stdout.splitlines())[-10:]:
                print(f"      {line}")
    else:
        print(f"  [hotupdate] ATG build failed, falling back to no-patch mode")

    # ── Step 2: Generate per-method host arrays and rebuild entry.exe ──
    # When patch data was successfully extracted, generate patch-host-arrays.cpp
    # with real per-method AOT registry mappings and do an incremental cmake
    # rebuild.  This enables ApplyPatchFromMemoryEx in entry.exe to map
    # Subject_N methods to their correct HotpatchNameRegistry entries.
    if patch_data_path is not None:
        if _generate_patch_host_arrays(ctx.native_dir, metadata):
            if _run_cmake_rebuild(ctx.native_dir):
                print(f"  [hotupdate] entry.exe rebuilt with per-method host arrays")
            else:
                print(f"  [hotupdate] WARN: cmake rebuild failed, falling back to no-patch mode")
                patch_data_path = None
        else:
            print(f"  [hotupdate] WARN: host array generation failed, falling back to no-patch mode")
            patch_data_path = None

    # ── Step 3: Run entry.exe --hotupdate [--patch-data ...] [--benchmark-iterations N] ──
    hotupdate_args = [str(exe_path), "--hotupdate"]
    if patch_data_path:
        hotupdate_args.extend(["--patch-data", str(patch_data_path)])
        print(f"  [hotupdate] Running with --patch-data {patch_data_path.name}...")
    else:
        print(f"  [hotupdate] Running without --patch-data (no semantic change expected)...")

    # When patch data is available, run benchmark before/after for performance comparison
    # Use 50 iterations — enough for rough perf comparison without making hotupdate stage too slow
    benchmark_iterations = 50 if patch_data_path else 0
    if benchmark_iterations > 0:
        hotupdate_args.extend(["--benchmark-iterations", str(benchmark_iterations)])
        print(f"  [hotupdate] With before/after benchmark ({benchmark_iterations} iter)...")

    try:
        r = subprocess.run(
            hotupdate_args,
            capture_output=True, text=True, timeout=120,
        )
    except subprocess.TimeoutExpired:
        return StageResult(
            stage="hotupdate", status="error",
            summary="hotupdate timed out after 120s",
            duration_ms=int((time.perf_counter() - start) * 1000),
        )

    stdout = r.stdout or ""
    stderr = r.stderr or ""

    # ── Step 4b: Parse JSON output with structural integrity check ──
    hotupdate_data: dict[str, Any] = {}
    json_truncated = False
    try:
        json_start = stdout.find("{")
        json_end = stdout.rfind("}") + 1
        if json_start >= 0 and json_end > json_start:
            payload = stdout[json_start:json_end]
            hotupdate_data = json.loads(payload)
    except (json.JSONDecodeError, KeyError):
        # If parsing fails, try appending missing closing brackets.
        # entry.exe may crash before flushing the final }}, but all
        # section data is already written.
        try:
            if json_start >= 0:
                payload = stdout[json_start:]
                for suffix in ("}", "}}", ""):
                    try:
                        hotupdate_data = json.loads(payload + suffix)
                        if hotupdate_data.get("passedMethods", 0) > 0:
                            break
                    except json.JSONDecodeError:
                        continue
        except Exception:
            pass

    # B1: Structural integrity check — verify baselineFact count matches totalMethods.
    # If they don't match, the JSON was truncated and partial data is unreliable.
    if hotupdate_data:
        total = hotupdate_data.get("totalMethods", 0)
        baseline_fact = hotupdate_data.get("baselineFact", [])
        if total > 0 and len(baseline_fact) != total:
            json_truncated = True
            print(f"  [hotupdate] WARNING: JSON truncated — expected {total} baseline entries, got {len(baseline_fact)}")

    passed = hotupdate_data.get("passedMethods", 0)
    failed = hotupdate_data.get("failedMethods", 0)
    assert_failed = hotupdate_data.get("patchedAssertFailed", 0)
    all_semantic = hotupdate_data.get("allSemantic", False)
    all_revert = hotupdate_data.get("allRevert", False)
    semantic_changed = hotupdate_data.get("semanticChangedCount", 0)
    reverted_fact = hotupdate_data.get("revertedFact", [])
    baseline_benchmark = hotupdate_data.get("baselineBenchmark", [])
    patched_benchmark = hotupdate_data.get("patchedBenchmark", [])

    # Compute per-method revert pass count
    revert_passed = sum(1 for r in reverted_fact if r.get("passed"))

    ctx.results_dir.mkdir(parents=True, exist_ok=True)
    result_path = ctx.results_dir / "hotupdate.json"
    result_data = {
        "exitCode": r.returncode,
        "passed": passed,
        "failed": failed,
        "assertFailed": assert_failed,
        "allSemantic": all_semantic,
        "allRevert": all_revert,
        "revertPassed": revert_passed,
        "semanticChangedCount": semantic_changed,
        "patchDataUsed": patch_data_path is not None,
        "patchFailed": patch_data_path is None and _patch_generation_attempted,
        "truncated": json_truncated,
        "crash": hotupdate_data.get("_crash", False),
        "hasBaselineBenchmark": len(baseline_benchmark) > 0,
        "hasPatchedBenchmark": len(patched_benchmark) > 0,
        "details": hotupdate_data,
        "stderr": stderr[:500] if stderr else "",
    }
    result_path.write_text(json.dumps(result_data, indent=2), encoding="utf-8")

    # Determine status:
    # - Unified pass criterion (applies to both with and without patch data):
    #   methods must execute without crashing (failed==0 && passed>0) and
    #   revert must work cleanly (allRevert=true).
    # - With IL rewriting, allSemantic will naturally be true (sentinel vs real value),
    #   but we no longer require it as a hard gate — the combination of "methods run
    #   correctly + revert cleanly" is sufficient to prove the mechanism works.
    # - assert_failed > 0 means the patch introduced a crash in a previously-passing
    #   method — this is a genuine regression and should fail.
    # FP-9: Check patchFailed BEFORE the patch_data_path branch (the result_data
    # field is always written for the no-patch-data path at line 498, so checking
    # it inside the if patch_data_path: branch is dead code).
    # FP-10: If JSON is truncated, NEVER report passed — partial data is unreliable.
    if json_truncated:
        status = "failed_truncated"
    elif result_data.get("patchFailed") or hotupdate_data.get("patched_method_count", 1) == 0:
        status = "skipped_patch_not_applied"
    elif patch_data_path:
        status = "passed" if (assert_failed == 0 and all_revert and passed > 0) else "failed"
        if passed == 0:
            status = "failed"
    else:
        # FP-10: Without patch data, hotupdate ran baseline+patched+revert on the
        # SAME unpatched code. This tests nothing — report as skipped, not passed.
        if _patch_generation_attempted:
            status = "skipped_patch_failed"
        elif passed > 0:
            status = "skipped_no_patch"
        elif passed == 0 and r.returncode == 0:
            status = "skipped_no_subjects"
        else:
            status = "passed" if failed == 0 and passed > 0 else "failed"

    # A6: Warn when patch data generation was attempted but failed
    if patch_data_path is None and _patch_generation_attempted:
        print(f"  [hotupdate] WARNING: Patch data generation failed earlier — "
              f"running without semantic verification (status={status})")
        result_data["patchFailed"] = True

    # Mark truncated JSON
    if json_truncated:
        result_data["_truncated"] = True

    duration_ms = int((time.perf_counter() - start) * 1000)
    benchmark_note = f", bench={len(baseline_benchmark)}" if baseline_benchmark else ""
    print(f"  [hotupdate] {status}: {passed} passed, "
          f"assert_failed={assert_failed}, semantic_changed={semantic_changed}, revert={revert_passed}/{len(reverted_fact) or '?'}"
          f"{benchmark_note} ({duration_ms}ms)")

    return StageResult(
        stage="hotupdate", status=status,
        summary=f"{status}: {passed} passed, assert_failed={assert_failed}, semantic_changed={semantic_changed}",
        details=result_data,
        duration_ms=duration_ms,
    )
