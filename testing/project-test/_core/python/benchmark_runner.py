"""Benchmark stage runner — whole-application performance measurement.

Runs entry.exe --benchmark <entry_index> <iterations> and parses the
JSON timing output produced by runtime-entry.cpp.
"""

from __future__ import annotations

import json
import subprocess
import time
from pathlib import Path
from typing import Any

from _pipeline.stage_result import StageResult


def _find_entry_method_index(ctx) -> int:
    """Parse native-aot.methods.json for the Program::Main entry index.

    Uses the same logic as project_pipeline_adapter._find_entry_method_index:
    matches the qualified nativeSymbol to avoid hitting AutoGeneratedProgram::Main
    (index 7) before the real Program::Main (index 14).
    """
    codegen_dir = ctx.codegen_dir
    for d in sorted(codegen_dir.iterdir()):
        if d.is_dir():
            manifest = d / "native-aot.methods.json"
            if manifest.exists():
                try:
                    data = json.loads(manifest.read_text(encoding="utf-8"))
                    methods: list[dict[str, Any]] = data.get("methods", [])
                    for m in methods:
                        ns = m.get("nativeSymbol", "")
                        # Match qualified symbol to avoid AutoGeneratedProgram_Main
                        if "Program_Main" in ns and "AutoGenerated" not in ns:
                            return m.get("index", 0)
                    # Fallback: first method
                    if methods:
                        return methods[0].get("index", 0)
                except (json.JSONDecodeError, OSError):
                    pass
    return 0


def run_project_benchmark(ctx, stages) -> StageResult:
    """Stage 5: Benchmark — run entry.exe --benchmark for app-level metrics.

    Runs the entry point method repeatedly and reports elapsed time and
    throughput.  Fact stage must pass first (entry-aot.exe must exist).
    """
    start = time.perf_counter()

    exe = ctx.entry_exe_path
    if not exe.exists():
        return StageResult(
            stage="benchmark", status="skipped",
            summary="entry-aot.exe not found — run codegen stage first",
            duration_ms=int((time.perf_counter() - start) * 1000),
        )

    entry_index = _find_entry_method_index(ctx)
    iterations = 100000

    # Build command
    cmd = [str(exe), "--benchmark", str(entry_index), str(iterations)]

    try:
        r = subprocess.run(cmd, capture_output=True, text=True, timeout=120)
    except subprocess.TimeoutExpired:
        return StageResult(
            stage="benchmark", status="failed",
            summary="benchmark timed out after 120s",
            duration_ms=int((time.perf_counter() - start) * 1000),
        )

    if r.returncode != 0:
        return StageResult(
            stage="benchmark", status="failed",
            summary=f"benchmark exited with code {r.returncode}",
            details={"stderr": r.stderr.strip()[-500:]},
            duration_ms=int((time.perf_counter() - start) * 1000),
        )

    # Parse JSON output (last JSON line in stdout, after any log output)
    timing: dict[str, Any] = {}
    for line in r.stdout.splitlines():
        line = line.strip()
        if line.startswith("{"):
            try:
                timing = json.loads(line)
            except json.JSONDecodeError:
                continue

    if not timing:
        return StageResult(
            stage="benchmark", status="failed",
            summary="no JSON timing output found",
            details={"stdout": r.stdout[-500:]},
            duration_ms=int((time.perf_counter() - start) * 1000),
        )

    elapsed_ms = timing.get("elapsedMilliseconds", 0.0)
    ops_per_sec = timing.get("opsPerSecond", 0.0)

    return StageResult(
        stage="benchmark", status="passed",
        summary=(f"entry[{entry_index}] x{iterations} "
                 f"in {elapsed_ms:.1f}ms ({ops_per_sec:.0f} ops/s)"),
        details={
            "entryIndex": entry_index,
            "iterations": iterations,
            "elapsedMilliseconds": elapsed_ms,
            "opsPerSecond": ops_per_sec,
        },
        duration_ms=int((time.perf_counter() - start) * 1000),
    )
