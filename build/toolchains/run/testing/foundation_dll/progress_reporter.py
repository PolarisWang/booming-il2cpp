"""Phase 3 — Progress reporter for foundation-dll translation.

Scans all 14 DLLs / 116 families and reports per-DLL and per-family
stage status.  Stages:

    0 — ledger entry exists
    1 — methodSubjectIds populated
    2 — auto-generated skeletons present (Phase 1)
    3 — AI assertions filled in handwritten file (Phase 2)
    4 — verified (tests pass)
"""

from __future__ import annotations

import json
import re
import sys
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any


REPO_ROOT = Path(__file__).resolve().parents[5]
LEDGER_PATH = (
    REPO_ROOT
    / "verification"
    / "projections"
    / "foundation-dll-audit"
    / "capability-family-ledger.json"
)
TESTS_ROOT = REPO_ROOT / "testing" / "foundation-dll"
VERIFICATION_ROOT = REPO_ROOT / "testing" / "foundation-dll"


# ---------------------------------------------------------------------------
# Stage helpers
# ---------------------------------------------------------------------------

STAGE_LABELS = ["ledger-exists", "method-ids", "auto-generated", "ai-filled", "verified"]


@dataclass
class FamilyProgress:
    assembly_name: str
    family_id: str
    display_name: str
    method_count: int
    has_test_dir: bool = False
    has_auto_generated_cs: bool = False
    has_handwritten_cs: bool = False
    has_benchmark: bool = False
    has_hotupdate: bool = False
    has_verification_claims: bool = False
    has_review_bundle: bool = False
    has_execution_project: bool = False
    auto_body_count: int = 0
    auto_skip_count: int = 0
    hw_method_count: int = 0  # methods in handwritten file
    stage: int = 0

    @property
    def stage_label(self) -> str:
        return STAGE_LABELS[self.stage] if self.stage < len(STAGE_LABELS) else "unknown"


@dataclass
class DllProgress:
    assembly_name: str
    families: list[FamilyProgress] = field(default_factory=list)

    @property
    def total(self) -> int:
        return len(self.families)

    @property
    def with_method_ids(self) -> int:
        return sum(1 for f in self.families if f.method_count > 0)

    @property
    def with_auto_generated(self) -> int:
        return sum(1 for f in self.families if f.has_auto_generated_cs)

    @property
    def with_ai_filled(self) -> int:
        return sum(1 for f in self.families if f.hw_method_count > 0)

    @property
    def at_stage(self) -> dict[int, int]:
        counts: dict[int, int] = {}
        for f in self.families:
            counts[f.stage] = counts.get(f.stage, 0) + 1
        return counts


