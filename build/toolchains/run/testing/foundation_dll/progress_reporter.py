# Scanning
# ---------------------------------------------------------------------------


def _family_slug(family_id: str) -> str:
    parts = [part for part in str(family_id).split("/") if part]
    if len(parts) < 4:
        return str(family_id).replace("/", "-")
    return "-".join(parts[2:])


def _count_real_test_methods(path: Path) -> int:
    """Count test methods that are NOT the TODO_ImplementGeneratedCoverage placeholder."""
    if not path.is_file():
        return 0
    text = path.read_text(encoding="utf-8")
    placeholder_count = text.count("TODO_ImplementGeneratedCoverage")
    # Count all [Fact or [Theory or [Benchmark( annotations
    fact_count = len(re.findall(r"\[Fact[^]]*\]", text))
    theory_count = len(re.findall(r"\[Theory\]", text))
    return max(0, fact_count + theory_count - placeholder_count)


def _count_auto_body_and_skip(path: Path) -> tuple[int, int]:
    """Count auto-generated test methods and how many have Skip."""
    if not path.is_file():
        return 0, 0
    text = path.read_text(encoding="utf-8")
    total = len(re.findall(r"\[Fact\]", text))
    skipped = len(re.findall(r"\[Fact\(Skip\s*=", text))
    return total, skipped


def scan_family(
    assembly_name: str, family: dict[str, Any]
) -> FamilyProgress:
    family_id = str(family.get("familyId") or "")
    display_name = str(family.get("displayName") or family_id)
    method_count = int(family.get("methodCount") or 0)
    slug = _family_slug(family_id)

    fp = FamilyProgress(
        assembly_name=assembly_name,
        family_id=family_id,
        display_name=display_name,
        method_count=method_count,
    )

    # Test directory (within verification path: .../test/)
    test_dir = VERIFICATION_ROOT / assembly_name / slug / "test"
    if test_dir.is_dir():
        fp.has_test_dir = True

        auto_path = test_dir / f"{''.join(p.capitalize() for p in slug.split('-'))}Tests.AutoGenerated.cs"
        handwritten_path = test_dir / f"{''.join(p.capitalize() for p in slug.split('-'))}Tests.cs"

        # Check handwritten
        if handwritten_path.is_file():
            fp.has_handwritten_cs = True
            fp.hw_method_count = _count_real_test_methods(handwritten_path)

        # Check auto-generated
        if auto_path.is_file():
            fp.has_auto_generated_cs = True
            fp.auto_body_count, fp.auto_skip_count = _count_auto_body_and_skip(auto_path)

    # Verification directory (family root)
    verif_dir = VERIFICATION_ROOT / assembly_name / slug
    if verif_dir.is_dir():
        fp.has_benchmark = (verif_dir / "benchmark").is_dir()
        fp.has_hotupdate = (verif_dir / "host").is_dir()
        fp.has_verification_claims = (verif_dir / "method-capability-contracts.json").is_file()
        fp.has_review_bundle = (verif_dir / "review" / "bundle.json").is_file()
        fp.has_execution_project = (verif_dir / "test").is_dir()

    # Derive stage
    if not method_count:
        fp.stage = 0
    elif not fp.has_auto_generated_cs:
        fp.stage = 1
    elif fp.has_handwritten_cs and fp.hw_method_count == 0 and not fp.has_auto_generated_cs:
        # Handwritten file exists (all needs-manual) but no auto-generated — unusual, still stage 2
        fp.stage = 2
    elif fp.has_handwritten_cs:
        # Handwritten file exists → AI-filled (Stage 3), even if all methods are skipped as needs-manual
        fp.stage = 3
    elif fp.has_auto_generated_cs:
        fp.stage = 2
    else:
        fp.stage = 1

    return fp


def scan_all() -> list[DllProgress]:
    ledger = json.loads(LEDGER_PATH.read_text(encoding="utf-8"))
    dlls: list[DllProgress] = []

    for dll in ledger.get("dlls", []):
        assembly_name = str(dll.get("assemblyName") or "")
        families = dll.get("families", [])
        dll_progress = DllProgress(assembly_name=assembly_name)
        for fam in families:
            dll_progress.families.append(scan_family(assembly_name, fam))
        dlls.append(dll_progress)

    return dlls


