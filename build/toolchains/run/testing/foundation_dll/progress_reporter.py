def _status_badge(stage: int) -> str:
    badges = {
        0: "[STAGE-0] no-entry",
        1: "[STAGE-1] method-ids",
        2: "[STAGE-2] auto-gen",
        3: "[STAGE-3] ai-filled",
        4: "[STAGE-4] verified",
    }
    return badges.get(stage, "[?] unknown")


def report_summary(dlls: list[DllProgress]) -> str:
    lines: list[str] = []
    lines.append("# Foundation-DLL Translation Progress Report")
    lines.append("")
    lines.append(f"_Generated: {__import__('datetime').datetime.now().strftime('%Y-%m-%d %H:%M:%S')}_")
    lines.append("")
    lines.append("## Summary")
    lines.append("")
    lines.append("| Metric | Value |")
    lines.append("|--------|-------|")

    total_families = sum(d.total for d in dlls)
    total_with_ids = sum(d.with_method_ids for d in dlls)
    total_auto_gen = sum(d.with_auto_generated for d in dlls)
    total_ai_filled = sum(d.with_ai_filled for d in dlls)

    lines.append(f"| DLLs | {len(dlls)} |")
    lines.append(f"| Families | {total_families} |")
    lines.append(f"| Families with methodSubjectIds | {total_with_ids} |")
    lines.append(f"| Families with auto-generated skeletons | {total_auto_gen} |")
    lines.append(f"| Families with AI-filled assertions | {total_ai_filled} |")
    lines.append("")

    # Stage distribution
    stage_counts: dict[int, int] = {}
    for d in dlls:
        for f in d.families:
            stage_counts[f.stage] = stage_counts.get(f.stage, 0) + 1

    lines.append("| Stage | Count |")
    lines.append("|-------|-------|")
    for s in sorted(stage_counts):
        lines.append(f"| {_status_badge(s)} | {stage_counts[s]} |")
    lines.append("")

    # Per-DLL table
    lines.append("## Per-DLL Breakdown")
    lines.append("")
    lines.append("| DLL | Families | w/ methodIds | w/ AutoGen | w/ AI-Filled | Stage Distribution |")
    lines.append("|-----|----------|-------------|------------|--------------|--------------------|")
    for d in dlls:
        stages = d.at_stage
        stage_parts = [f"S{s}={stages.get(s, 0)}" for s in sorted(stages)]
        lines.append(
            f"| {d.assembly_name} | {d.total} | {d.with_method_ids} | "
            f"{d.with_auto_generated} | {d.with_ai_filled} | "
            f"{', '.join(stage_parts)} |"
        )
    lines.append("")

    # Per-family detail
    lines.append("## Per-Family Detail")
    lines.append("")

    for d in dlls:
        lines.append(f"### {d.assembly_name}")
        lines.append("")
        hdr = (
            "| Family | Display Name | Stage | Methods | "
            "AutoBody | Skipped | HW Methods | "
            "Benchmark | HotUpdate | Claims |"
        )
        sep = "|--------|--------------|-------|---------|----------|---------|------------|-----------|-----------|--------|"
        lines.append(hdr)
        lines.append(sep)
        for f in d.families:
            lines.append(
                f"| {_family_slug(f.family_id)} | {f.display_name} | "
                f"{_status_badge(f.stage)} | {f.method_count} | "
                f"{f.auto_body_count} | {f.auto_skip_count} | {f.hw_method_count} | "
                f"{'Y' if f.has_benchmark else '-'} | "
                f"{'Y' if f.has_hotupdate else '-'} | "
                f"{'Y' if f.has_verification_claims else '-'} |"
            )
        lines.append("")

    # Legend
    lines.append("## Legend")
    lines.append("")
    lines.append("| Stage | Meaning |")
    lines.append("|-------|---------|")
    lines.append("| STAGE-0 no-entry | Family exists in ledger but has no methodSubjectIds |")
    lines.append("| STAGE-1 method-ids | methodSubjectIds populated, no test project generated yet |")
    lines.append("| STAGE-2 auto-gen | Test project + auto-generated skeletons present (Phase 1) |")
    lines.append("| STAGE-3 ai-filled | Handwritten file has real assertion logic (Phase 2) |")
    lines.append("| STAGE-4 verified | Tests pass on native runtime |")
    lines.append("")

    return "\n".join(lines)


def report_json(dlls: list[DllProgress]) -> dict[str, Any]:
    return {
        "reportType": "foundation-dll-progress",
        "dllCount": len(dlls),
        "familyCount": sum(d.total for d in dlls),
        "stageCounts": {
            str(s): sum(1 for d in dlls for f in d.families if f.stage == s)
            for s in sorted({f.stage for d in dlls for f in d.families})
        },
        "dlls": [
            {
                "assemblyName": d.assembly_name,
                "totalFamilies": d.total,
                "withMethodIds": d.with_method_ids,
                "withAutoGenerated": d.with_auto_generated,
                "withAiFilled": d.with_ai_filled,
                "families": [
                    {
                        "familyId": f.family_id,
                        "displayName": f.display_name,
                        "methodCount": f.method_count,
                        "stage": f.stage,
                        "stageLabel": f.stage_label,
                        "hasTestDir": f.has_test_dir,
                        "hasAutoGenerated": f.has_auto_generated_cs,
                        "hasBenchmark": f.has_benchmark,
                        "hasHotUpdate": f.has_hotupdate,
                        "autoBodyCount": f.auto_body_count,
                        "autoSkipCount": f.auto_skip_count,
                        "hwMethodCount": f.hw_method_count,
                    }
                    for f in d.families
                ],
            }
            for d in dlls
        ],
    }


def main() -> None:
    # Handle Windows console encoding
    if sys.stdout.encoding and sys.stdout.encoding.lower() in ("gbk", "gb2312"):
        sys.stdout.reconfigure(encoding="utf-8")

    dlls = scan_all()
    fmt = sys.argv[1] if len(sys.argv) > 1 else "markdown"

    if fmt == "json":
        output = json.dumps(report_json(dlls), indent=2, ensure_ascii=False)
    else:
        output = report_summary(dlls)

    print(output)


if __name__ == "__main__":
    main()
