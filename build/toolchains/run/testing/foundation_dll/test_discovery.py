from __future__ import annotations

import re
from pathlib import Path
from typing import Any


CAPABILITY_ATTR_RE = re.compile(r'\[CapabilityTest\("(?P<family>[^"]+)"(?P<args>[^\]]*)\)\]')


def _relative(repo_root: Path, path: Path) -> str:
    return path.resolve().relative_to(repo_root.resolve()).as_posix()


def _discover_from_family_root(repo_root: Path, family_root: Path) -> dict[str, Any] | None:
    csproj_paths = sorted(family_root.glob("*.csproj"))
    source_paths = sorted(path for path in family_root.glob("*.cs") if not path.name.endswith(".AutoGenerated.cs"))
    if not csproj_paths or not source_paths:
        return None

    for source_path in source_paths:
        text = source_path.read_text(encoding="utf-8")
        match = CAPABILITY_ATTR_RE.search(text)
        if match is None:
            continue
        family_id = match.group("family")
        attr_args = match.group("args") or ""
        include_benchmark = "IncludeBenchmark = true" in attr_args
        include_hotupdate = "IncludeHotUpdate = true" in attr_args

        return {
            "familyId": family_id,
            "assemblyName": family_root.parent.name,
            "testProjectPath": _relative(repo_root, csproj_paths[0]),
            "testSourcePath": _relative(repo_root, source_path),
            "gates": {
                "native-proof": {"enabled": True},
                "benchmark": {"enabled": include_benchmark or "[Benchmark(" in text},
                "hotupdate-proof": {
                    "enabled": include_hotupdate or "ChaosUnitCategory.HotUpdateContract" in text,
                },
            },
        }
    return None


def discover_family_tests(repo_root: Path) -> dict[str, Any]:
    root = repo_root / "tests" / "families"
    results: list[dict[str, Any]] = []
    if not root.is_dir():
        return {"familyCount": 0, "families": results}

    for assembly_root in sorted(path for path in root.iterdir() if path.is_dir()):
        for family_root in sorted(path for path in assembly_root.iterdir() if path.is_dir()):
            payload = _discover_from_family_root(repo_root, family_root)
            if payload is not None:
                results.append(payload)

    return {
        "familyCount": len(results),
        "families": results,
    }
