"""Clean old family verification structure, preserving important files.

Removes auto-generated directories (il2cpp_dist/, managed_test/, native_test/)
and regenerates a minimal il2cpp_dist/CMakeLists.txt forwarding stub.

Usage:
    python clean_family_structure.py
    python clean_family_structure.py --families convert-char boxing-unboxing-casts
    python clean_family_structure.py --dry-run
"""

from __future__ import annotations

import argparse
import shutil
import sys
from pathlib import Path

_HERE = Path(__file__).resolve().parent
_REPO_ROOT = _HERE.parents[4]
_VERIFICATION_BASE = _REPO_ROOT / "testing" / "foundation-dll"
_DEFAULT_ASSEMBLY = "System.Private.CoreLib"

# Files/directories to remove (relative to family root)
_CLEANUP_REMOVE_DIRS: list[str] = [
    "il2cpp_dist",         # entrypoint, genuine, patch, hotupdate (all superseded)
    "managed_test",         # tests, benchmarks (superseded by managed/subjects/)
    "native_test",          # hotupdate skeleton, benchmark entries
]

# Files under codegen/ to remove (auto-generated by convert-to-cpp pipeline,
# will be regenerated)
_CODEGEN_REMOVE: list[str] = [
    "CMakeLists.txt",
    "runtime-entry.cpp",
]

# Reports to remove from family root (auto-generated, will be regenerated)
_REPORTS_REMOVE: list[str] = [
    "benchmark-comparison-report.json",
    "hotupdate-verification-report.json",
    "mechanism-audit-report.json",
    "post-hotupdate-benchmark-report.json",
    "principle-alignment-report.json",
]

# Reports to preserve
_REPORTS_PRESERVE: list[str] = [
    "unified-verification-report.json",
]


def _slug_to_stub_name(slug: str) -> str:
    """Convert family slug to C++ stub library name.
    e.g. convert-char -> convert_char, boxing-unboxing-casts -> boxing_unboxing_casts
    """
    return slug.replace("-", "_")


def _clean_family(family_dir: Path, *, dry_run: bool = False) -> list[str]:
    """Clean one family directory. Returns list of actions taken."""
    actions: list[str] = []
    slug = family_dir.name

    if not family_dir.is_dir():
        return actions

    # Remove top-level auto-generated dirs
    for d in _CLEANUP_REMOVE_DIRS:
        target = family_dir / d
        if target.is_dir():
            if dry_run:
                actions.append(f"  [DIR] would remove: {d}/")
            else:
                shutil.rmtree(target)
                actions.append(f"  [DIR] removed: {d}/")

    # Remove codegen/ artifacts that should be regenerated
    # (keep codegen/<AssemblyName>/generated/ files — those come from convert-to-cpp)
    codegen_dir = family_dir / "codegen"
    if codegen_dir.is_dir():
        for f in _CODEGEN_REMOVE:
            target = codegen_dir / f
            if target.exists():
                if dry_run:
                    actions.append(f"  [FIL] would remove: codegen/{f}")
                else:
                    if target.is_dir():
                        shutil.rmtree(target)
                    else:
                        target.unlink()
                    actions.append(f"  [FIL] removed: codegen/{f}")

        # Remove top-level codegen/generated/ if empty (it's a leftover from
        # old flat layout; new layout has codegen/<Assembly>/generated/)
        old_generated = codegen_dir / "generated"
        if old_generated.is_dir():
            try:
                if not any(old_generated.iterdir()):
                    if dry_run:
                        actions.append(f"  [DIR] would remove: codegen/generated/ (empty)")
                    else:
                        old_generated.rmdir()
                        actions.append(f"  [DIR] removed: codegen/generated/ (empty)")
            except StopIteration:
                pass  # empty dir

    # Remove auto-generated reports (preserve unified report)
    for f in _REPORTS_REMOVE:
        target = family_dir / f
        if target.exists():
            if dry_run:
                actions.append(f"  [FIL] would remove: {f}")
            else:
                target.unlink()
                actions.append(f"  [FIL] removed: {f}")

    # Remove native/build/ (will be regenerated by pipeline)
    native_build = family_dir / "native" / "build"
    if native_build.is_dir():
        if dry_run:
            actions.append(f"  [DIR] would remove: native/build/")
        else:
            shutil.rmtree(native_build)
            actions.append(f"  [DIR] removed: native/build/")

    # Remove native/entry.exe (will be regenerated)
    native_exe = family_dir / "native" / "entry.exe"
    if native_exe.exists():
        if dry_run:
            actions.append(f"  [FIL] would remove: native/entry.exe")
        else:
            native_exe.unlink()
            actions.append(f"  [FIL] removed: native/entry.exe")

    # Remove build-output/ and obj/ under managed/ (dotnet build artifacts)
    for sub in ["subjects", "patch"]:
        build_out = family_dir / "managed" / sub / "build-output"
        if build_out.is_dir():
            if dry_run:
                actions.append(f"  [DIR] would remove: managed/{sub}/build-output/")
            else:
                shutil.rmtree(build_out)
                actions.append(f"  [DIR] removed: managed/{sub}/build-output/")
        obj_dir = family_dir / "managed" / sub / "obj"
        if obj_dir.is_dir():
            if dry_run:
                actions.append(f"  [DIR] would remove: managed/{sub}/obj/")
            else:
                shutil.rmtree(obj_dir)
                actions.append(f"  [DIR] removed: managed/{sub}/obj/")

    # Remove managed/patch/patchdata/ (will be regenerated by pipeline)
    patchdata_dir = family_dir / "managed" / "patch" / "patchdata"
    if patchdata_dir.is_dir():
        if dry_run:
            actions.append(f"  [DIR] would remove: managed/patch/patchdata/")
        else:
            shutil.rmtree(patchdata_dir)
            actions.append(f"  [DIR] removed: managed/patch/patchdata/")

    # Remove reports_generated/ (will be regenerated by pipeline)
    reports_gen = family_dir / "reports_generated"
    if reports_gen.is_dir():
        if dry_run:
            actions.append(f"  [DIR] would remove: reports_generated/")
        else:
            shutil.rmtree(reports_gen)
            actions.append(f"  [DIR] removed: reports_generated/")

    return actions


def _regenerate_il2cpp_stub(family_dir: Path, *, dry_run: bool = False) -> list[str]:
    """Ensure a minimal il2cpp_dist/CMakeLists.txt forwarding stub exists.

    The top-level System.Private.CoreLib/CMakeLists.txt uses
    add_subdirectory(<slug>/il2cpp_dist) for each family, so each family
    must have this directory with a minimal CMakeLists.txt.
    """
    actions: list[str] = []
    slug = family_dir.name
    stub_name = _slug_to_stub_name(slug)

    il2cpp_dir = family_dir / "il2cpp_dist"
    cmake_file = il2cpp_dir / "CMakeLists.txt"

    if not dry_run:
        il2cpp_dir.mkdir(parents=True, exist_ok=True)

    cmake_content = (
        f"cmake_minimum_required(VERSION 3.20)\n"
        f"project(chaos_family_native_{stub_name})\n"
        f"add_library(chaos_family_native_{stub_name} INTERFACE)\n"
        f"target_include_directories(chaos_family_native_{stub_name} INTERFACE "
        f"\"${{CMAKE_CURRENT_SOURCE_DIR}}/../native\")\n"
    )

    if dry_run:
        actions.append(f"  [STUB] would write: il2cpp_dist/CMakeLists.txt")
    else:
        if not cmake_file.exists() or cmake_file.read_text(encoding="utf-8") != cmake_content:
            cmake_file.write_text(cmake_content, encoding="utf-8")
            actions.append(f"  [STUB] wrote: il2cpp_dist/CMakeLists.txt")
        else:
            actions.append(f"  [STUB] up-to-date: il2cpp_dist/CMakeLists.txt")

    return actions


def _discover_families(assembly: str) -> list[str]:
    """Discover family slugs from capability-family-contract.json files."""
    base = _VERIFICATION_BASE / assembly
    if not base.is_dir():
        return []
    families = []
    for entry in sorted(base.iterdir()):
        if entry.is_dir() and (entry / "capability-family-contract.json").exists():
            families.append(entry.name)
    return families


def main() -> None:
    parser = argparse.ArgumentParser(description="Clean old family verification structure")
    parser.add_argument("--assembly", default=_DEFAULT_ASSEMBLY, help="Assembly name")
    parser.add_argument("--families", nargs="*", default=None,
                        help="Families to clean (default: all discovered)")
    parser.add_argument("--dry-run", action="store_true",
                        help="Print what would be done without making changes")
    args = parser.parse_args()

    families = args.families or _discover_families(args.assembly)
    if not families:
        print(f"No families found for {args.assembly}")
        sys.exit(1)

    print(f"Cleaning {len(families)} families (assembly={args.assembly})")
    if args.dry_run:
        print("  *** DRY RUN — no changes will be made ***")
    print()

    total_actions = 0
    for slug in families:
        family_dir = _VERIFICATION_BASE / args.assembly / slug
        actions = _clean_family(family_dir, dry_run=args.dry_run)
        stub_actions = _regenerate_il2cpp_stub(family_dir, dry_run=args.dry_run)
        all_actions = actions + stub_actions

        if all_actions:
            print(f"[{slug}]")
            for a in all_actions:
                print(f"  {a}")
            total_actions += len(all_actions)
        else:
            print(f"[{slug}] — clean, nothing to do")

    print(f"\n{'='*50}")
    print(f"Total actions: {total_actions} across {len(families)} families")
    if args.dry_run:
        print("  (dry run — no changes made)")
    else:
        print("  Done.")


if __name__ == "__main__":
    main()