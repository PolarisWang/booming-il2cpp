"""debug_fact_static_crash.py — Resolve Fact Static native verify crash offsets to source symbols.

Usage:
  # Full auto: run Fact Static exe under cdb, capture crash, resolve symbols
  python build/toolchains/run/testing/foundation_dll/debug_fact_static_crash.py <family>

  # Manual: skip cdb run, resolve a known offset against existing .map
  python build/toolchains/run/testing/foundation_dll/debug_fact_static_crash.py <family> --offset 0x1bef

What it does:
  1. Locates the Fact Static build directory and .map file for the family
  2. (auto mode) Runs the Fact Static exe under cdb to capture crash offset + stack trace
  3. Looks up each stack frame RVA in the .map file to resolve symbol names
  4. Prints a source-level crash report

Requirements:
  - The .map file must exist (generated by fact_verifier.py since /MAP was added)
  - cdb.exe must be accessible (auto mode) — install via Windows SDK
"""

from __future__ import annotations

import re
import subprocess
import sys
from dataclasses import dataclass, field
from pathlib import Path


# ── Config ────────────────────────────────────────────────────────────────

REPO_ROOT = Path(__file__).resolve().parents[5]  # .../build/toolchains/run/testing/foundation_dll/ -> repo
VERIFICATION_BASE = REPO_ROOT / "verification" / "foundation-dll"
DEFAULT_CDB = Path(r"C:\Program Files (x86)\Windows Kits\10\Debuggers\x64\cdb.exe")


# ── Data types ────────────────────────────────────────────────────────────

@dataclass
class MapEntry:
    """A single code symbol from a .map file."""
    offset: int     # section-relative offset (== RVA for section 0001)
    symbol: str     # decorated symbol name (mangled C++)

    __slots__ = ("offset", "symbol")


@dataclass
class StackFrame:
    """A single stack frame from a crash dump."""
    rva: int

    def resolve(self, entries: list[MapEntry]) -> str:
        """Find the symbol whose offset range contains this RVA."""
        best: MapEntry | None = None
        for e in entries:
            if e.offset <= self.rva:
                if best is None or e.offset > best.offset:
                    best = e
        if best:
            return f"{best.symbol} + 0x{self.rva - best.offset:x}"
        return f"?? + 0x{self.rva:x}"


@dataclass
class CrashReport:
    exception_code: str = ""
    fault_address: str = ""
    access_type: str = ""
    frames: list[StackFrame] = field(default_factory=list)


# ── Map file parsing ─────────────────────────────────────────────────────

def parse_map_file(map_path: Path) -> list[MapEntry]:
    """Parse a .map file's code symbols (section 0001 = .text).

    The MSVC map file format after 'Publics by Value' is:

      0001:00000860  main  0000000140001860 f   fact_static_fact_static_combined.obj

    Column: section:offset  symbol  VA  attributes  obj
    """
    entries: list[MapEntry] = []
    in_publics = False
    pat = re.compile(r'^\s*(\w+):([0-9a-fA-F]+)\s+(\S+)')

    with open(map_path, encoding="utf-8", errors="replace") as f:
        for line in f:
            if "Publics by Value" in line:
                in_publics = True
                continue
            if not in_publics:
                continue
            if not line.strip():
                continue

            m = pat.match(line)
            if not m:
                continue
            section = m.group(1)
            if section != "0001":       # only code section
                continue
            offset = int(m.group(2), 16)
            symbol = m.group(3).strip()

            # Skip linker-absolute entries and thunks
            if symbol.startswith("__") and symbol[2:].isidentifier():
                continue

            entries.append(MapEntry(offset=offset, symbol=symbol))

    return entries


# ── cdb interaction ───────────────────────────────────────────────────────

def run_cdb(exe_path: Path, cdb_path: Path = DEFAULT_CDB) -> CrashReport:
    """Run the exe under cdb, capture exception details."""
    if not cdb_path.exists():
        print(f"  [ERROR] cdb not found at {cdb_path}")
        sys.exit(1)

    cmd = [str(cdb_path), "-c", "g; .exr -1; kb 10; q", "-o", str(exe_path)]
    r = subprocess.run(cmd, capture_output=True, text=True, timeout=60)
    output = r.stdout + r.stderr
    report = CrashReport()

    m = re.search(r'ExceptionCode:\s*([0-9a-fA-Fx]+)', output)
    if m:
        report.exception_code = m.group(1)

    m = re.search(r'Attempt to (\w+) from address ([0-9a-fA-Fx`]+)', output)
    if m:
        report.access_type = m.group(1)
        report.fault_address = m.group(2)

    # Parse stack frames: lines containing "verify_<family>+0xOFFSET"
    for line in output.splitlines():
        m2 = re.search(r'(?:verify_[\w-]+|fact_runtime_[\w-]+)\+0x([0-9a-fA-F]+)', line)
        if m2:
            report.frames.append(StackFrame(rva=int(m2.group(1), 16)))

    return report


# ── Main ──────────────────────────────────────────────────────────────────

def main() -> None:
    import argparse
    parser = argparse.ArgumentParser(description="Fact Static crash offset resolver")
    parser.add_argument("family", help="Family slug (e.g., convert-char)")
    parser.add_argument("--assembly", default="System.Private.CoreLib")
    parser.add_argument("--cdb", default=str(DEFAULT_CDB))
    parser.add_argument("--map", help="Path to .map file (auto-detected if omitted)")
    parser.add_argument("--offset", help="Crash RVA (hex) to resolve without running cdb")
    args = parser.parse_args()

    build_dir = VERIFICATION_BASE / args.assembly / args.family / "native_test" / "fact-verify" / "build"
    exe_path = build_dir / f"fact_static_{args.family}.exe"
    map_path = Path(args.map) if args.map else build_dir / f"fact_static_{args.family}.map"

    if not build_dir.exists():
        print(f"  [ERROR] Build directory not found: {build_dir}")
        print(f"  Run Fact Static first: python build/toolchains/run/testing/foundation_dll/fact_verifier.py {args.family}")
        sys.exit(1)
    if not map_path.exists():
        print(f"  [ERROR] Map file not found: {map_path}")
        print(f"  Rebuild Fact Static (pipeline now generates .map files automatically).")
        sys.exit(1)

    # Parse .map
    entries = parse_map_file(map_path)
    print(f"  Map: {map_path}  ({len(entries)} code symbols)")

    # Capture crash
    report: CrashReport
    if args.offset:
        report = CrashReport()
        report.frames.append(StackFrame(rva=int(args.offset, 16)))
    else:
        if not exe_path.exists():
            print(f"  [ERROR] Exe not found: {exe_path}")
            sys.exit(1)
        print(f"  Running cdb on: {exe_path}")
        report = run_cdb(exe_path, Path(args.cdb))

    # Report
    print("=" * 60)
    print("CRASH ANALYSIS")
    print("=" * 60)
    if report.exception_code:
        print(f"  Exception:  {report.exception_code}")
    if report.fault_address:
        print(f"  Fault addr: {report.fault_address} ({report.access_type})")
    print()

    if not report.frames:
        print("  (no frames captured — exe may have completed normally)")
        sys.exit(1)

    print(f"  Stack ({len(report.frames)} frames):")
    for i, frame in enumerate(report.frames):
        resolved = frame.resolve(entries)
        print(f"    #{i}:  {resolved}")

    first = report.frames[0]
    print(f"\n  CRASH SITE: {first.resolve(entries)}")
    print()
    print("  Next steps:")
    print("    grep the resolved symbol in the generated .cpp")
    print("    Check for: null deref, odd-checksum tag collision, static init ordering")


if __name__ == "__main__":
    main()
