"""Benchmark POC orchestrator — runs the full managed-vs-native benchmark pipeline
for a single family.

Pipeline:
    1. Fill managed benchmark bodies (C# AutoGenerated.cs with real calls)
    2. Run managed baseline (dotnet run ManagedBenchmarkHarness)
    3. Generate native benchmark entry (C++ BenchmarkNativeEntry.cpp)
    4. Build native benchmark executable (cmake + ninja/msbuild)
    5. Run native benchmark
    6. Compare managed vs native → emit benchmark-comparison-report.json

Usage:
    python benchmark_poc_runner.py ^
        --assembly-name System.Private.CoreLib ^
        --family-id family/System.Private.CoreLib/convert/char
"""

from __future__ import annotations

import argparse
import json
import os
