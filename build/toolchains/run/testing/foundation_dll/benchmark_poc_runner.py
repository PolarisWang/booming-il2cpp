def _info(msg: str) -> None:
    print(f"[benchmark-poc] {msg}")


def _capture(args: list[str], cwd: Path) -> str:
    _info(f"Running: {' '.join(args)}")
    result = subprocess.run(args, cwd=cwd, capture_output=True, text=True)
    if result.returncode != 0:
        if result.stdout:
            print(result.stdout, file=sys.stdout)
        if result.stderr:
            print(result.stderr, file=sys.stderr)
        print(f"FATAL: command failed with exit code {result.returncode}", file=sys.stderr)
        sys.exit(result.returncode)
    return result.stdout


def _find_native_exe(repo_root: Path, target_name: str) -> Path:
    """Search for the native benchmark executable in known build output locations."""
    candidates = [
        repo_root / "artifacts" / "presets" / "windows-x64-reference" / "verification"
        / "foundation-dll" / "System.Private.CoreLib" / "convert-char" / "native" / "Release"
        / f"{target_name}.exe",
        repo_root / "artifacts" / "presets" / "windows-x64-reference" / "tests"
        / "contracts" / "native" / "hot-update" / "Release" / f"{target_name}.exe",
        repo_root / "artifacts" / "presets" / "windows-x64-reference" / f"{target_name}.exe",
        repo_root / "artifacts" / "presets" / "windows-x64-reference" / "Release" / f"{target_name}.exe",
    ]
    for candidate in candidates:
        if candidate.exists():
            return candidate

    # Broader recursive search
    build_dirs = [
        repo_root / "artifacts" / "presets",
    ]
    for bd in build_dirs:
        if bd.exists():
            matches = sorted(bd.rglob(f"{target_name}.exe"))
            if matches:
                return matches[0]

    print(f"FATAL: cannot find native benchmark executable '{target_name}.exe'", file=sys.stderr)
    print("Searched locations:", file=sys.stderr)
    for c in candidates:
        print(f"  {c}", file=sys.stderr)
    sys.exit(1)


def run_benchmark_poc(
    repo_root: Path,
    *,
    assembly_name: str,
    family_id: str,
    managed_harness_project: str = "ManagedBenchmarkHarness",
) -> dict[str, Any]:
    _info(f"Starting benchmark POC for {family_id}")
    family_slug = _slug_from_family_id(family_id)
    family_dir = repo_root / "verification" / "foundation-dll" / assembly_name / family_slug
    native_dir = family_dir / "native"
    benchmark_dir = family_dir / "benchmark"

    # Step 0: Load family data to get method subject IDs
    contract_path = family_dir / "capability-family-contract.json"
    if not contract_path.exists():
        print(f"FATAL: {contract_path} not found", file=sys.stderr)
        sys.exit(1)
    with open(contract_path, encoding="utf-8") as f:
        contract = json.load(f)
    method_subject_ids = [m["methodSubjectId"] for m in contract.get("methodContracts", []) if "methodSubjectId" in m]

    if not method_subject_ids:
        # Fall back to top-level methodSubjectIds array
        method_subject_ids = [str(s) for s in contract.get("methodSubjectIds", []) if str(s)]

    if not method_subject_ids:
        # Fall back to methodSubjectIds from family data (inline)
        method_subject_ids = [str(s) for s in family.get("methodSubjectIds", []) if str(s)]

    if not method_subject_ids:
        print(f"FATAL: no methodSubjectIds found for {family_id}", file=sys.stderr)
        sys.exit(1)

    _info(f"Found {len(method_subject_ids)} methods")
    family = {"familyId": family_id}

    # Step 1: Generate managed benchmark bodies
    _info("Step 1: Generating managed benchmark bodies")
    generate_benchmark_managed_bodies(
        repo_root,
        assembly_name=assembly_name,
        family=family,
        method_subject_ids=method_subject_ids,
    )

    # Step 2: Run managed baseline
    _info("Step 2: Running managed benchmark baseline")
    managed_output_path = benchmark_dir / "managed-baseline.json"
    csproj_path = benchmark_dir / f"{managed_harness_project}.csproj"
    if not csproj_path.exists():
        print(f"WARNING: {csproj_path} not found, skipping managed baseline", file=sys.stderr)
        managed_elapsed = None
    else:
        managed_stdout = _capture(
            ["dotnet", "run", "--project", str(csproj_path), "--configuration", "Release"],
            cwd=benchmark_dir,
        )
        managed_output_path.write_text(managed_stdout, encoding="utf-8")
        _info(f"Managed baseline written to {managed_output_path}")
        # Validate JSON
        try:
            json.loads(managed_stdout)
        except json.JSONDecodeError as e:
            print(f"WARNING: managed baseline JSON invalid: {e}", file=sys.stderr)
            managed_output_path = None

    # Steps 3-4: Build native benchmark from real IL2CPP AOT code
    _info("Steps 3-4: Building native benchmark from real IL2CPP AOT code")
    build_result = build_native_benchmark_real(family_slug)
    if not build_result["success"]:
        error_msg = build_result.get("error", "unknown build error")
        _info(f"Native benchmark build FAILED: {error_msg}")
        # Write comparison report showing build failure
        comparison_output = family_dir / "benchmark-comparison-report.json"
        report = {
            "schemaVersion": 1,
            "assemblyName": assembly_name,
            "familyId": family_id,
            "status": "build_failed",
            "error": error_msg,
            "summary": {
                "totalMethods": len(method_subject_ids),
                "matchedCount": 0,
                "unmatchedCount": 0,
                "invalidCount": len(method_subject_ids),
                "nativeFasterCount": 0,
                "managedFasterCount": 0,
                "equalCount": 0,
                "averageSpeedupPercent": 0.0,
            },
            "methodResults": [
                {"methodSubjectId": m, "status": "build_failed"}
                for m in method_subject_ids
            ],
        }
        with open(comparison_output, "w", encoding="utf-8") as f:
            json.dump(report, f, indent=2, ensure_ascii=False)
        _info(f"Comparison report (build failed) written to {comparison_output}")
        return report

    # Step 5: Run native benchmark for each method
    _info("Step 5: Running native benchmark for each method")
    native_raw_results = run_benchmark_real(
        build_result["exe_path"],
        len(method_subject_ids),
        iterations=10000,
    )

    native_results: list[dict[str, Any]] = []
    for r in native_raw_results:
        idx = r.get("methodIndex", 0)
        mid = method_subject_ids[idx] if idx < len(method_subject_ids) else f"unknown-{idx}"
        if "elapsedMilliseconds" in r:
            native_results.append({
                "methodIndex": idx,
                "methodSubjectId": mid,
                "elapsedMilliseconds": r["elapsedMilliseconds"],
                "opsPerSecond": r.get("opsPerSecond", 0.0),
                "iterations": r.get("iterations", 10000),
            })
        else:
            native_results.append({
                "methodIndex": idx,
                "methodSubjectId": mid,
                "elapsedMilliseconds": -1.0,
                "error": r.get("error", "unknown"),
            })

    native_output_path = native_dir / "native-benchmark.json"
    native_output_path.parent.mkdir(parents=True, exist_ok=True)
    with open(native_output_path, "w", encoding="utf-8") as f:
        json.dump({
            "schemaVersion": 1,
            "assemblyName": assembly_name,
            "familyId": family_id,
            "warmupIterations": 100,
            "measureIterations": 10000,
            "results": native_results,
        }, f, indent=2, ensure_ascii=False)
    _info(f"Native benchmark results written to {native_output_path}")

    # Step 6: Compare and generate report
    if managed_output_path and managed_output_path.exists():
        _info("Step 6: Comparing managed vs native benchmarks")
        comparison_output = family_dir / "benchmark-comparison-report.json"
        report = compare_benchmarks(
            managed_path=managed_output_path,
            native_path=native_output_path,
            output_path=comparison_output,
        )
        _info("Benchmark POC complete!")
        _info(f"  Average speedup: {report['summary']['averageSpeedupPercent']}%")
        _info(f"  Native faster: {report['summary']['nativeFasterCount']}/{report['summary']['totalMethods']}")
        return report
    else:
        _info("Benchmark POC complete (managed baseline skipped)")
        return {"summary": {"totalMethods": len(native_results), "averageSpeedupPercent": 0.0}}


def main() -> None:
    parser = argparse.ArgumentParser(description="Run benchmark POC pipeline")
    parser.add_argument("--assembly-name", default="System.Private.CoreLib", help="Assembly name")
    parser.add_argument("--family-id", default="family/System.Private.CoreLib/convert/char", help="Family ID")
    parser.add_argument("--repo-root", type=Path, default=Path.cwd(), help="Repository root")
    parser.add_argument("--managed-project", default="ManagedBenchmarkHarness", help="Managed harness project name")
    args = parser.parse_args()

    repo_root = args.repo_root.resolve()
    run_benchmark_poc(
        repo_root,
        assembly_name=args.assembly_name,
        family_id=args.family_id,
        managed_harness_project=args.managed_project,
    )


if __name__ == "__main__":
    main()
