namespace RuntimeSelfTest;

/// <summary>
/// Arithmetic operations proof — exercises basic integer arithmetic
/// through the il2cpp codegen pipeline.
/// </summary>
public static class ArithmeticProof
{
    public static int Add(int a, int b)
    {
        return a + b;
    }

    public static int Subtract(int a, int b)
    {
        return a - b;
    }

    public static int Multiply(int a, int b)
    {
        return a * b;
    }
}
