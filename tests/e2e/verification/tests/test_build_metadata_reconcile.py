"""Regression test for _reconcile_metadata_to_combined (A' fix).

Verifies that a stale subjects.metadata.json whose generatedMethodId values use
a different value-set suffix than the actual CombinedSubjects wrapper methods is
rewritten to match the real wrapper names, so TPG's aotSubjectIds exactly match
the wrappers codegen sees (closing the corelib numerics dispatch-slot collapse).
"""
from __future__ import annotations

import json
from pathlib import Path

from stages.build import _reconcile_metadata_to_combined


def _write(tmp_path: Path, name: str, content: str) -> Path:
    p = tmp_path / name
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(content, encoding="utf-8")
    return p


def _manifest(methods: list[dict]) -> str:
    return json.dumps({
        "schemaVersion": 1,
        "assemblyName": "System.Private.CoreLib",
        "chunkSlug": "numerics",
        "totalMethods": len(methods),
        "customEntryIndices": [],
        "benchmarkMethodIndices": list(range(len(methods))),
        "hotupdateMethodIndices": list(range(len(methods))),
        "methods": methods,
    })


def test_reconcile_fixes_drifted_value_set_suffix(tmp_path: Path) -> None:
    """Stale manifest genId Length_1__0 -> real wrapper Length_1__1."""
    combined = _write(
        tmp_path,
        "combined/CombinedSubjects.cs",
        "namespace AutoGenerated.System_Private_CoreLib\n"
        "{ public unsafe partial class System_Numerics_Vector2Tests\n"
        "  { public long CopyTo_0_System_Single_0() { return 0; }\n"
        "    public long Length_1__1() { return 0; }\n"
        "    public long LengthSquared_2__2() { return 0; }\n"
        "  }\n}\n",
    )
    metadata = _write(
        tmp_path,
        "subjects/subjects.metadata.json",
        _manifest([
            {"index": 0, "kind": "fact", "generatedMethodId": "CopyTo_0_System_Single_0"},
            {"index": 1, "kind": "fact", "generatedMethodId": "Length_1__0"},
            {"index": 2, "kind": "fact", "generatedMethodId": "LengthSquared_2__0"},
        ]),
    )

    n = _reconcile_metadata_to_combined(metadata, combined)

    assert n == 2  # Length + LengthSquared drifted; CopyTo already matched
    after = json.loads(metadata.read_text(encoding="utf-8"))
    by_id = {m["generatedMethodId"] for m in after["methods"]}
    assert "Length_1__1" in by_id
    assert "LengthSquared_2__2" in by_id
    assert "Length_1__0" not in by_id
    assert "LengthSquared_2__0" not in by_id
    assert "CopyTo_0_System_Single_0" in by_id  # untouched


def test_reconcile_noop_when_names_consistent(tmp_path: Path) -> None:
    """When manifest genIds already match wrappers, nothing is rewritten."""
    combined = _write(
        tmp_path,
        "combined/CombinedSubjects.cs",
        "namespace AutoGenerated.System_Private_CoreLib\n"
        "{ public unsafe partial class System_Numerics_Vector2Tests\n"
        "  { public long CopyTo_0_System_Single_0() { return 0; }\n"
        "  }\n}\n",
    )
    metadata = _write(
        tmp_path,
        "subjects/subjects.metadata.json",
        _manifest([
            {"index": 0, "kind": "fact", "generatedMethodId": "CopyTo_0_System_Single_0"},
        ]),
    )

    n = _reconcile_metadata_to_combined(metadata, combined)

    assert n == 0
    after = json.loads(metadata.read_text(encoding="utf-8"))
    assert after["methods"][0]["generatedMethodId"] == "CopyTo_0_System_Single_0"


def test_reconcile_skips_benchmark_and_ctor_wrappers(tmp_path: Path) -> None:
    """Benchmark_ and .ctor wrappers must not be treated as Fact dispatch targets."""
    combined = _write(
        tmp_path,
        "combined/CombinedSubjects.cs",
        "namespace AutoGenerated.System_Private_CoreLib\n"
        "{ public unsafe partial class System_Numerics_Vector2Tests\n"
        "  { public unsafe partial class System_Numerics_Vector2Tests() {}\n"
        "    public static void Benchmark_Length_1__1() {}\n"
        "    public long Length_1__1() { return 0; }\n"
        "  }\n}\n",
    )
    metadata = _write(
        tmp_path,
        "subjects/subjects.metadata.json",
        _manifest([
            {"index": 0, "kind": "fact", "generatedMethodId": "Length_1__0"},
        ]),
    )

    n = _reconcile_metadata_to_combined(metadata, combined)

    assert n == 1
    after = json.loads(metadata.read_text(encoding="utf-8"))
    assert after["methods"][0]["generatedMethodId"] == "Length_1__1"
