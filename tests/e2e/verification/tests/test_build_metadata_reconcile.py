def test_enrich_stamps_native_generated_when_wrapper_in_ir(tmp_path: Path) -> None:
    """A fact wrapper whose generatedMethodId is in aot-core-ir → NativeGenerated."""
    from stages.build import _enrich_metadata_body_availability

    meta = {
        "methods": [
            # kind=fact → translatable; matched below via "Length_1__1:" prefix.
            {"index": 0, "kind": "fact", "generatedMethodId": "Length_1__1"},
            # aot-coverage → never annotated (no wrapper body to lower).
            {"index": 1, "kind": "aot-coverage", "generatedMethodId": None},
        ]
    }
    ir_methods = [
        {"subjectId": "CombinedSubjects/AutoGenerated.Sys.CoreLib.Sys_Tests::Length_1__1:System.Int64()",
         "bodyAvailability": "has-canonical-body"},
        {"subjectId": "Chaos.TestFramework.Sdk/C:Assert::Complete:System.Int32()"},  # not CombinedSubjects
    ]
    annotated = _enrich_metadata_body_availability(meta, ir_methods)
    assert annotated == 1
    assert meta["methods"][0]["bodyAvailability"] == "NativeGenerated"
    assert "bodyAvailability" not in meta["methods"][1]  # aot-coverage left untouched


