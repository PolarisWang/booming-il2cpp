# ── classify_fact_record ───────────────────────────────────────────────


def _failing_rec() -> dict:
    """A pre-assertion raise: the shape a null-arg subject produces."""
    return {"passed": False, "value": 0, "caught": True, "assertFailed": False}


def test_caught_before_assert_with_null_arg_is_nullArg():
    """Shaped failure + null-arg subject → nullArg, not realDefect."""
    rec = _failing_rec()
    # The null-arg matching uses rec["methodSubjectId"] (runner-form).
    rec["methodSubjectId"] = (
        "CombinedSubjects/AutoGenerated.System_Private_CoreLib.System_ArrayTests"
        "::CreateInstance_3_System_Type_int_0:System.Int64()"
    )
    kind = classify_fact_record(
        rec,
        return_type="System.Int64",
        manifest_prefixes=frozenset({("System.Array::CreateInstance", "System.Type,System.Int32")}),
        subject_id="System.Private.CoreLib/System.Array::CreateInstance:System.Array(System.Type,System.Int32)",
        null_arg_ids=frozenset({"CreateInstance_3_System_Type_int_0"}),
    )
    assert kind == "nullArg"


def test_assertion_failed_is_never_nullArg():
    """assertFailed=true means the assertion ran and disagreed — a real signal.

    Null-arg subjects raise *before* any assertion, so this combination must
    still be reported as a defect.
    """
    rec = {"passed": False, "value": 0, "caught": True, "assertFailed": True}
    kind = classify_fact_record(
        rec,
        return_type="System.Int64",
        manifest_prefixes=frozenset({("System.Math::Cos", "System.Double")}),
        subject_id="System.Private.CoreLib/System.Math::Cos:System.Double(System.Double)",
        null_arg_ids=frozenset({"Cos_8_double_0"}),
    )
    assert kind == "realDefect"


def test_shaped_failure_without_null_arg_stays_realDefect():
    """No null-arg signal → unchanged classification."""
    kind = classify_fact_record(
        _failing_rec(),
        return_type="System.Int64",
        manifest_prefixes=frozenset({("System.Math::Cos", "System.Double")}),
        subject_id="System.Private.CoreLib/System.Math::Cos:System.Double(System.Double)",
        null_arg_ids=frozenset(),
    )
    assert kind == "realDefect"


# ── envSensitive (GC snapshot / PRNG stream) ─────────────────────────


def _env_rec(sid: str, assert_failed: bool = True) -> dict:
    return {
        "passed": False, "value": 0,
        "caught": True, "assertFailed": assert_failed,
        "methodSubjectId": (
            "CombinedSubjects/AutoGenerated.System_Private_CoreLib.System_GCTests"
            f"::{sid}:System.Int64()"),
    }


def test_env_sensitive_gc_counter_is_envSensitive():
    """GC counters describe the probe's own process; entry.exe cannot match."""
    kind = classify_fact_record(
        _env_rec("CollectionCount_10_int_0"),
        return_type="System.Int64",
        manifest_prefixes=frozenset({("System.GC::CollectionCount", "System.Int32")}),
        subject_id="System.Private.CoreLib/System.GC::CollectionCount:System.Int32(System.Int32)",
        env_sensitive_ids=frozenset({"CollectionCount_10_int_0"}),
    )
    assert kind == "envSensitive"


def test_env_sensitive_also_covers_assertFailed_true():
    """envSensitive applies even when the assertion ran and disagreed."""
    kind = classify_fact_record(
        _env_rec("NextDouble_7__0", assert_failed=True),
        return_type="System.Int64",
        manifest_prefixes=frozenset({("System.Random::NextDouble", "")}),
        subject_id="System.Private.CoreLib/System.Random::NextDouble:System.Double()",
        env_sensitive_ids=frozenset({"NextDouble_7__0"}),
    )
    assert kind == "envSensitive"


def test_non_env_sensitive_shaped_failure_stays_realDefect():
    """A real codegen defect must not be swept into envSensitive."""
    kind = classify_fact_record(
        {"passed": False, "value": 0, "caught": True, "assertFailed": True,
         "methodSubjectId": "CombinedSubjects/AutoGenerated.X::Cos_8_double_0:System.Int64()"},
        return_type="System.Int64",
        manifest_prefixes=frozenset({("System.Math::Cos", "System.Double")}),
        subject_id="System.Private.CoreLib/System.Math::Cos:System.Double(System.Double)",
        env_sensitive_ids=frozenset({"CollectionCount_10_int_0"}),
    )
    assert kind == "realDefect"


# ── _get_env_sensitive_subject_ids: host-property accessors ────────────


def test_detects_get_current_processor_id(tmp_path):
    """Thread.GetCurrentProcessorId is a host property, not a function of input.

    Measured defect: a subject asserted ``AreEqual(6, …)`` because the probe ran
    on a 6-logical-CPU host.  Any other host (e.g. the 24-core dev machine, or a
    CI runner) cannot reproduce the literal, so the failure is an unportable
    expectation rather than an implementation defect.
    """
    _write_combined(tmp_path, """
        public long GetCurrentProcessorId_60__0()
        {
            var result_60_0 = global::System.Threading.Thread.GetCurrentProcessorId();
            Assert.AreEqual(6, result_60_0);
            return (long)(result_60_0);
        }

        public static void Benchmark_GetCurrentProcessorId_60__0()
        {
            _ = global::System.Threading.Thread.GetCurrentProcessorId();
        }
    """)
    ids = _get_env_sensitive_subject_ids(_make_ctx(tmp_path))
    assert "GetCurrentProcessorId_60__0" in ids
    # The Benchmark twin has no Assert and must not be bucketed.
    assert "Benchmark_GetCurrentProcessorId_60__0" not in ids


