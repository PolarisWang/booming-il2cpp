"""Regression tests for nullArg classification.

ATG's first value set for a reference-typed parameter is ``default(T)`` —
i.e. ``null``.  A subject such as::

    var result = global::System.Array.CreateInstance(default(System.Type)!, 0);

therefore calls the BCL with a null argument, which throws
``ArgumentNullException`` in real .NET.  The AOT body faithfully raises, so
the fact record is ``caught=true, assertFailed=false`` — indistinguishable at
the record level from a genuine runtime defect.

Bucketing those as ``realDefect`` is a false positive: it sends every such
subject to the bug backlog.  ``_get_null_arg_subject_ids`` detects them so
``classify_fact_record`` can return ``nullArg`` instead.

The critical constraint is precision: ``default(double)`` / ``default(int)``
are *legal* values that genuinely exercise the method (``Math.Cos(0.0)`` must
return 1.0).  Treating those as null-arg would suppress real defects — the
exact failure this classifier must avoid.
"""
from __future__ import annotations

from pathlib import Path

from stages.fact_chunk import (
    _get_null_arg_subject_ids,
    classify_fact_record,
)


def _make_ctx(chunk_dir: Path):
    """Minimal ChunkContext stand-in (mirrors test_fact_chunk_codegen_gate)."""
    from verification.orchestration.context import ChunkContext

    ctx = ChunkContext.__new__(ChunkContext)
    ctx.chunk_dir = chunk_dir
    return ctx


def _write_combined(chunk_dir: Path, body: str) -> None:
    combined = chunk_dir / "managed" / "combined"
    combined.mkdir(parents=True, exist_ok=True)
    (combined / "CombinedSubjects.cs").write_text(body, encoding="utf-8")


# ── _get_null_arg_subject_ids ──────────────────────────────────────────


def test_detects_reference_type_null_default(tmp_path):
    """default(System.Type)! marks a null reference argument."""
    _write_combined(tmp_path, """
        public long CreateInstance_3_System_Type_int_0()
        {
            var result_3_0 = global::System.Array.CreateInstance(default(System.Type)!, default(int));
            return (object)(result_3_0) != null ? 1L : 0L;
        }

        public static void Benchmark_CreateInstance_3_System_Type_int_0()
        {
        }
    """)
    ids = _get_null_arg_subject_ids(_make_ctx(tmp_path))
    assert "CreateInstance_3_System_Type_int_0" in ids


def test_ignores_value_type_default(tmp_path):
    """default(double) is a legal value that exercises the method.

    Math.Cos(0.0) must return 1.0 — suppressing it as a null-arg would hide a
    real float64 lowering defect.
    """
    _write_combined(tmp_path, """
        public long Cos_8_double_0()
        {
            var result_8_0 = global::System.Math.Cos(default(double));
            Assert.AreEqual(1d, result_8_0);
            return BitConverter.DoubleToInt64Bits(result_8_0);
        }

        public static void Benchmark_Cos_8_double_0()
        {
        }
    """)
    ids = _get_null_arg_subject_ids(_make_ctx(tmp_path))
    assert "Cos_8_double_0" not in ids


def test_ignores_body_with_real_string_argument(tmp_path):
    """A real (non-null) argument may be what exercises the defect."""
    _write_combined(tmp_path, """
        public long CreateInstance_8_string_string_3()
        {
            var result_8_3 = global::System.Activator.CreateInstance("", "");
            return (object)(result_8_3) != null ? 1L : 0L;
        }

        public static void Benchmark_CreateInstance_8_string_string_3()
        {
        }
    """)
    ids = _get_null_arg_subject_ids(_make_ctx(tmp_path))
    assert "CreateInstance_8_string_string_3" not in ids


def test_missing_combined_subjects_is_not_fatal(tmp_path):
    """Absent CombinedSubjects.cs → empty set, no exception."""
    assert _get_null_arg_subject_ids(_make_ctx(tmp_path)) == frozenset()


# ── classify_fact_record ───────────────────────────────────────────────


def _failing_rec() -> dict:
    """A pre-assertion raise: the shape a null-arg subject produces."""
    return {"passed": False, "value": 0, "caught": True, "assertFailed": False}


def test_caught_before_assert_with_null_arg_is_nullArg():
    """Shaped failure + null-arg subject → nullArg, not realDefect."""
    rec = _failing_rec()
    # The null-arg matching uses rec["methodSubjectId"] (runner-form).
    rec["methodSubjectId"] = (
        "CombinedSubjects/AutoGenerated.System_Private_CoreLib.System_ArrayTests"
        "::CreateInstance_3_System_Type_int_0:System.Int64()"
    )
    kind = classify_fact_record(
        rec,
        return_type="System.Int64",
        manifest_prefixes=frozenset({("System.Array::CreateInstance", "System.Type,System.Int32")}),
        subject_id="System.Private.CoreLib/System.Array::CreateInstance:System.Array(System.Type,System.Int32)",
        null_arg_ids=frozenset({"CreateInstance_3_System_Type_int_0"}),
    )
    assert kind == "nullArg"


def test_assertion_failed_is_never_nullArg():
    """assertFailed=true means the assertion ran and disagreed — a real signal.

    Null-arg subjects raise *before* any assertion, so this combination must
    still be reported as a defect.
    """
    rec = {"passed": False, "value": 0, "caught": True, "assertFailed": True}
    kind = classify_fact_record(
        rec,
        return_type="System.Int64",
        manifest_prefixes=frozenset({("System.Math::Cos", "System.Double")}),
        subject_id="System.Private.CoreLib/System.Math::Cos:System.Double(System.Double)",
        null_arg_ids=frozenset({"Cos_8_double_0"}),
    )
    assert kind == "realDefect"


def test_shaped_failure_without_null_arg_stays_realDefect():
    """No null-arg signal → unchanged classification."""
    kind = classify_fact_record(
        _failing_rec(),
        return_type="System.Int64",
        manifest_prefixes=frozenset({("System.Math::Cos", "System.Double")}),
        subject_id="System.Private.CoreLib/System.Math::Cos:System.Double(System.Double)",
        null_arg_ids=frozenset(),
    )
    assert kind == "realDefect"
