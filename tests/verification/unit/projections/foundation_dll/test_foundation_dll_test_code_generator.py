from __future__ import annotations

import shutil
from pathlib import Path

from tests._support.fs import make_temp_repo_root
from tests._support.module_loading import load_module


REPO_ROOT = Path(__file__).resolve().parents[5]
GENERATOR_MODULE_PATH = REPO_ROOT / "build" / "toolchains" / "run" / "testing" / "foundation_dll" / "test_code_generator.py"


def test_generate_family_skeleton_creates_minimal_file_set() -> None:
    generator_module = load_module(GENERATOR_MODULE_PATH, "chaos_foundation_dll_test_code_generator")
    repo_root = make_temp_repo_root("verification", "foundation-dll-test-code-generator")

    try:
        result = generator_module.generate_family_skeleton(
            repo_root,
            assembly_name="System.Private.CoreLib",
            family={
                "familyId": "family/System.Private.CoreLib/convert/char",
                "displayName": "Convert.Char Conversions",
                "testCode": {
                    "requestedMethodCount": 18,
                },
            },
        )

        output_root = repo_root / "tests" / "families" / "System.Private.CoreLib" / "convert-char"
        assert output_root.is_dir()
        assert (output_root / "ConvertCharTests.cs").is_file()
        assert (output_root / "ConvertCharTests.AutoGenerated.cs").is_file()
        assert (output_root / "ConvertCharTests.csproj").is_file()
        assert (output_root / "README.md").is_file()
        assert result["familyId"] == "family/System.Private.CoreLib/convert/char"
        assert "tests/families/System.Private.CoreLib/convert-char/ConvertCharTests.AutoGenerated.cs" in result["artifacts"]
    finally:
        shutil.rmtree(repo_root, ignore_errors=True)


def test_generate_family_skeleton_does_not_overwrite_handwritten_file() -> None:
    generator_module = load_module(GENERATOR_MODULE_PATH, "chaos_foundation_dll_test_code_generator_existing")
    repo_root = make_temp_repo_root("verification", "foundation-dll-test-code-generator-existing")

    try:
        output_root = repo_root / "tests" / "families" / "System.Private.CoreLib" / "convert-char"
        output_root.mkdir(parents=True, exist_ok=True)
        handwritten = output_root / "ConvertCharTests.cs"
        handwritten.write_text("// handwritten\n", encoding="utf-8")

        generator_module.generate_family_skeleton(
            repo_root,
            assembly_name="System.Private.CoreLib",
            family={
                "familyId": "family/System.Private.CoreLib/convert/char",
                "displayName": "Convert.Char Conversions",
                "testCode": {
                    "requestedMethodCount": 18,
                },
            },
        )

        assert handwritten.read_text(encoding="utf-8") == "// handwritten\n"
        assert (output_root / "ConvertCharTests.AutoGenerated.cs").is_file()
    finally:
        shutil.rmtree(repo_root, ignore_errors=True)
