from __future__ import annotations

import json
import shutil
from pathlib import Path

from tests._support.fs import make_temp_repo_root
from tests._support.module_loading import load_module


REPO_ROOT = Path(__file__).resolve().parents[5]
SCANNER_MODULE_PATH = (
    REPO_ROOT / "build" / "toolchains" / "run" / "testing" / "foundation_dll" / "case_index_scanner.py"
)


def test_scan_case_indexes_from_generated_source() -> None:
    scanner_module = load_module(SCANNER_MODULE_PATH, "chaos_foundation_dll_case_index_scanner")
    repo_root = make_temp_repo_root("verification", "foundation-dll-case-index-scanner")

    try:
        family_root = repo_root / "verification" / "foundation-dll" / "System.Private.CoreLib" / "convert-char"
        test_root = family_root / "test"
        benchmark_root = family_root / "benchmark"
        host_root = family_root / "host"
        test_root.mkdir(parents=True, exist_ok=True)
        benchmark_root.mkdir(parents=True, exist_ok=True)
        host_root.mkdir(parents=True, exist_ok=True)

        (test_root / "ConvertCharTests.AutoGenerated.cs").write_text(
            "using Chaos.TestFramework;\n"
            "public static class ConvertCharGeneratedTests\n"
            "{\n"
            "    [MethodSubjectId(\"System.Private.CoreLib/System.Convert::ToChar:System.Char(System.Boolean)\")]\n"
            "    [CapabilityFamilyId(CapabilityFamilyId.SystemPrivateCoreLib_ConvertChar)]\n"
            "    [VerificationRoute(VerificationRoute.Native)]\n"
            "    public static void Method_System_Convert_ToChar_System_Boolean() { }\n"
            "}\n",
            encoding="utf-8",
        )
        (benchmark_root / "ConvertCharBenchmarks.AutoGenerated.cs").write_text(
            "using Chaos.TestFramework;\n"
            "public static class ConvertCharGeneratedBenchmarks\n"
            "{\n"
            "    [BenchmarkSubjectId(\"System.Private.CoreLib/System.Convert::ToChar:System.Char(System.Boolean)\")]\n"
            "    [CapabilityFamilyId(CapabilityFamilyId.SystemPrivateCoreLib_ConvertChar)]\n"
            "    [BenchmarkRoute(BenchmarkRoute.Native)]\n"
            "    [BenchmarkProfile(BenchmarkProfile.Default)]\n"
            "    public static void Benchmark_System_Convert_ToChar_System_Boolean() { }\n"
            "}\n",
            encoding="utf-8",
        )
        (host_root / "ConvertCharHotUpdate.AutoGenerated.cs").write_text(
            "using Chaos.TestFramework;\n"
            "public static class ConvertCharGeneratedHotUpdate\n"
            "{\n"
            "    [HotUpdateSubjectId(\"System.Private.CoreLib/System.Convert::ToChar:System.Char(System.Boolean)\")]\n"
            "    [CapabilityFamilyId(CapabilityFamilyId.SystemPrivateCoreLib_ConvertChar)]\n"
            "    [HotUpdateDirection(HotUpdateDirection.HostToPatch)]\n"
            "    public static void HotUpdate_System_Convert_ToChar_System_Boolean() { }\n"
            "}\n",
            encoding="utf-8",
        )

        result = scanner_module.scan_case_indexes(
            repo_root,
            assembly_name="System.Private.CoreLib",
            family_id="family/System.Private.CoreLib/convert/char",
        )

        test_index = json.loads((family_root / "method-test-case-index.json").read_text(encoding="utf-8"))
        benchmark_index = json.loads((family_root / "method-benchmark-case-index.json").read_text(encoding="utf-8"))
        hotupdate_index = json.loads((family_root / "method-hotupdate-case-index.json").read_text(encoding="utf-8"))

        assert len(test_index["cases"]) == 1
        assert len(benchmark_index["cases"]) == 1
        assert len(hotupdate_index["cases"]) == 1
        assert test_index["cases"][0]["methodSubjectId"].startswith("System.Private.CoreLib/System.Convert::ToChar:")
        assert test_index["cases"][0]["memberName"] == "Method_System_Convert_ToChar_System_Boolean"
        assert benchmark_index["cases"][0]["profileCode"] == "Default"
        assert hotupdate_index["cases"][0]["direction"] == "HostToPatch"
        assert "verification/foundation-dll/System.Private.CoreLib/convert-char/method-test-case-index.json" in result["artifacts"]
    finally:
        shutil.rmtree(repo_root, ignore_errors=True)
