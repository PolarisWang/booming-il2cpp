from __future__ import annotations

import shutil
from pathlib import Path

from tests._support.fs import make_temp_repo_root
from tests._support.module_loading import load_module


REPO_ROOT = Path(__file__).resolve().parents[5]
DISCOVERY_MODULE_PATH = REPO_ROOT / "build" / "toolchains" / "run" / "testing" / "foundation_dll" / "test_discovery.py"


def test_discover_family_tests_reads_capability_test_metadata_from_project_files() -> None:
    discovery_module = load_module(DISCOVERY_MODULE_PATH, "chaos_foundation_dll_test_discovery")
    repo_root = make_temp_repo_root("verification", "foundation-dll-test-discovery")

    try:
        family_root = repo_root / "tests" / "families" / "System.Private.CoreLib" / "convert-char"
        family_root.mkdir(parents=True, exist_ok=True)
        (family_root / "ConvertCharTests.csproj").write_text("<Project Sdk=\"Microsoft.NET.Sdk\" />\n", encoding="utf-8")
        (family_root / "ConvertCharTests.cs").write_text(
            "using Chaos.TestFramework;\n"
            "[CapabilityTest(\"family/System.Private.CoreLib/convert/char\", IncludeBenchmark = true, IncludeHotUpdate = true)]\n"
            "public partial class ConvertCharTests\n"
            "{\n"
            "    [Benchmark(ChaosBenchmarkCategory.RuntimeDispatch, ChaosMetric.WallClockUs, P99Ms = 100)]\n"
            "    public void Bench() {}\n"
            "    [ChaosUnitTest(ChaosUnitCategory.HotUpdateContract)]\n"
            "    public void HotUpdate() {}\n"
            "}\n",
            encoding="utf-8",
        )
        (family_root / "ConvertCharTests.AutoGenerated.cs").write_text("public partial class ConvertCharTests {}\n", encoding="utf-8")

        result = discovery_module.discover_family_tests(repo_root)

        assert len(result["families"]) == 1
        family = result["families"][0]
        assert family["familyId"] == "family/System.Private.CoreLib/convert/char"
        assert family["assemblyName"] == "System.Private.CoreLib"
        assert family["testProjectPath"] == "tests/families/System.Private.CoreLib/convert-char/ConvertCharTests.csproj"
        assert family["gates"]["benchmark"]["enabled"] is True
        assert family["gates"]["hotupdate-proof"]["enabled"] is True
        assert family["gates"]["native-proof"]["enabled"] is True
    finally:
        shutil.rmtree(repo_root, ignore_errors=True)
