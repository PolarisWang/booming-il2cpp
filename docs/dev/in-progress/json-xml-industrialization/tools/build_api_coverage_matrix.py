#!/usr/bin/env python3
"""build_api_coverage_matrix.py — JSON/XML API 覆盖矩阵生成器。

分母：ref-pack 8.0.11 的 public API（System.Text.Json / System.Xml.ReaderWriter）
      + shared 8.0.11 的 System.Private.Xml（ref-pack 无此程序集）
分子：各 chunk 的 fact-results.json，经「测试方法 → API 方法」映射后 join。

⚠️ 已知局限（必须写进产物）：
  1. 映射为 **(declaringType, methodName) 级，不含参数** ——
     「该类型的该方法有任一变体被覆盖」即算命中，故覆盖率是**下限估计**。
  2. 部分测试对象无法映射到分母（分母缺该类型），归入 `unmapped`。
"""
import json
import io
import re
import sys
from pathlib import Path
from collections import defaultdict

# 本文件位于 <repo>/docs/dev/in-progress/json-xml-industrialization/tools/
#   parents[0]=tools  [1]=json-xml-industrialization  [2]=in-progress  [3]=dev
#   [4]=docs  [5]=<repo>
REPO = Path(__file__).resolve().parents[5]
TASK_DIR = Path(__file__).resolve().parents[1]
DENOM_DIR = TASK_DIR / "proof/denominators"
FACT_ROOT = REPO / "artifacts/foundation-dll"

# 测试方法名 → (declaringType, methodName)
#   CombinedSubjects/AutoGenerated.System_Text_Json.System_Text_Json_JsonDocumentTests::Parse_7_string_X_0
#   → ("System.Text.Json.JsonDocument", "Parse")
PATTERN = re.compile(r'AutoGenerated\.(.*?)Tests::([A-Za-z_][A-Za-z0-9]*?)_(\d+)')


def normalize_type(raw: str) -> str:
    """把测试类型名还原为真实的托管类型全名。

    实测格式：`{Assembly_With_Underscores}.{Namespace_With_Underscores}`
      System_Private_Xml.System_Xml_NameTable      -> System.Xml.NameTable
      System_Text_Json.System_Text_Json_JsonDocument -> System.Text.Json.JsonDocument
      System_Private_Xml.System_Xml_XPath_XPathDocument -> System.Xml.XPath.XPathDocument

    即**第一段是 assembly 名**（下划线形式），其后是真实的命名空间+类型
    （同样以下划线编码）。故：按首个 '.' 切分，丢弃 assembly 段，
    其余下划线转点。

    ⚠️ 早期实现用「去重复段」启发式，会产出 `System.Private.Xml.System.Xml.NameTable`
       这类多一层前缀的错误结果 —— 已废弃。
    """
    if '.' in raw:
        _, rest = raw.split('.', 1)
    else:
        rest = raw
    return rest.replace('_', '.')


def load_denominator() -> dict:
    """返回 {(declaringType, methodName): [methodSubjectId, ...]}"""
    index = defaultdict(list)
    for p in sorted(DENOM_DIR.glob('*/dll-method-manifest.json')):
        d = json.load(io.open(p, encoding='utf-8'))
        for m in d['methods']:
            key = (m['declaringType'], m['methodName'])
            index[key].append({
                'assembly': d['assemblyName'],
                'methodSubjectId': m['methodSubjectId'],
            })
    return index


# resultKind → 矩阵档位
VERDICT_MAP = {
    'real': 'real',
    'stubGap': 'stub',
    'unassertable': 'unassertable',
    'smoke': 'smoke',
    'failed': 'failed',
    'realDefect': 'fake-green',      # 执行了但与期望不符 —— 声称 real 实为缺陷
    'factoryGap': 'factory-gap',
    'nullArg': 'null-arg',
    'envSensitive': 'env-sensitive',
}


def load_facts():
    """遍历所有 JSON/XML chunk 的 fact-results.json，产出 (key, resultKind) 列表"""
    rows = []
    for p in FACT_ROOT.glob('*/chunks/*/results/fact-results.json'):
        norm = str(p).replace('\\', '/')
        if 'System.Text.Json' not in norm and 'System.Private.Xml' not in norm \
           and 'System.Xml.ReaderWriter' not in norm:
            continue
        chunk = norm.split('foundation-dll/')[-1].replace('/results/fact-results.json', '')
        try:
            d = json.load(io.open(p, encoding='utf-8'))
        except Exception:
            continue
        for rec in d.get('aot', []):
            sid = rec.get('methodSubjectId', '')
            m = PATTERN.search(sid)
            if not m:
                rows.append((None, rec.get('resultKind', '?'), chunk, sid))
                continue
            key = (normalize_type(m.group(1)), m.group(2))
            rows.append((key, rec.get('resultKind', '?'), chunk, sid))
    return rows


def main():
    denom = load_denominator()
    facts = load_facts()

    total_api = sum(len(v) for v in denom.values())
    print(f"分母: {len(denom)} 个 (type, method) 键 / {total_api} 个方法重载", file=sys.stderr)

    # 每个 API 方法收集覆盖它的 fact 记录
    covered = defaultdict(list)          # key -> [resultKind, ...]
    unmapped = defaultdict(int)          # (chunk) -> count
    unmapped_samples = []
    for key, kind, chunk, sid in facts:
        if key is None:
            unmapped[chunk] += 1
            if len(unmapped_samples) < 20:
                unmapped_samples.append((chunk, sid))
            continue
        covered[key].append(kind)

    # 分类：一个方法只要有任一变体是 real，就算 real-covered
    # 优先级：real > fake-green > failed > stub > unassertable > smoke
    PRIORITY = ['real', 'fake-green', 'failed', 'stub', 'unassertable', 'smoke',
                'factory-gap', 'null-arg', 'env-sensitive']

    counters = defaultdict(int)          # 按方法重载数
    fact_counters = defaultdict(int)     # 按 fact 记录数（与 realVerified 口径可比）
    matrix = []
    for key, entries in sorted(denom.items()):
        kinds = covered.get(key, [])
        verdicts = {VERDICT_MAP.get(k, k) for k in kinds}
        if not verdicts:
            v = 'not-covered'
        else:
            v = next((p for p in PRIORITY if p in verdicts), 'other')
        counters[v] += len(entries)
        # fact 记录口径：该键下每条 fact 记录按其自身 resultKind 归档
        for k in kinds:
            fact_counters[VERDICT_MAP.get(k, k)] += 1
        matrix.append({
            'declaringType': key[0],
            'methodName': key[1],
            'verdict': v,
            'overloads': [e['methodSubjectId'] for e in entries],
            'observedResultKinds': sorted(set(kinds)),
        })

    mapped_facts = sum(1 for k, *_ in facts if k is not None)
    print(f"映射命中: {mapped_facts}/{len(facts)} fact 记录", file=sys.stderr)

    out = {
        'schemaVersion': 2,
        'denominatorSource': {
            'System.Text.Json': 'ref-pack 8.0.11 (pure public)',
            'System.Xml.ReaderWriter': 'ref-pack 8.0.11 (pure public)',
            'System.Private.Xml': 'shared 8.0.11 (ref-pack has no such assembly)',
        },
        'granularity': '(declaringType, methodName) — 不含参数，覆盖率为下限估计',
        'totalMethods': total_api,
        'totalMethodNameKeys': len(denom),
        'verdictCounts': dict(counters),
        'verdictCountsByFactRecord': dict(fact_counters),
        'factRecords': len(facts),
        'factMapped': mapped_facts,
        'factUnmapped': len(facts) - mapped_facts,
        'matrix': matrix,
    }
    outpath = TASK_DIR / "api-coverage-matrix-v2.json"
    outpath.write_text(json.dumps(out, ensure_ascii=False, indent=1), encoding='utf-8')
    print(f"[written] {outpath}", file=sys.stderr)

    print("\n=== 档位分布 A：按方法重载数（分母口径）===")
    for k, v in sorted(counters.items(), key=lambda x: -x[1]):
        pct = v / total_api * 100
        print(f"  {k:16s} {v:>5}  ({pct:5.1f}%)")
    print(f"\n  {'合计':16s} {total_api:>5}")

    print("\n=== 档位分布 B：按 fact 记录数（与 realVerified 口径可比）===")
    for k, v in sorted(fact_counters.items(), key=lambda x: -x[1]):
        pct = v / max(1, len(facts)) * 100
        print(f"  {k:16s} {v:>5}  ({pct:5.1f}%)")
    print(f"\n  {'合计':16s} {len(facts):>5}")
    if unmapped:
        print(f"\n=== 未映射的 fact 记录 {sum(unmapped.values())} 条（分母缺对应类型）===")
        for c, n in sorted(unmapped.items(), key=lambda x: -x[1])[:8]:
            print(f"  {n:>4}  {c}")
        print("  样例:")
        for c, s in unmapped_samples[:6]:
            print(f"    {s.split('::')[-1][:70]}")


if __name__ == '__main__':
    main()
