#!/usr/bin/env python3
"""
Split fast_dispatch.cpp into sub-files using the unity-build pattern.

Each sub-file is a .inc file #included from the main fast_dispatch.cpp.
No CMake changes, no static keyword removal, no ODR issues.
All code remains in a single translation unit.

Usage:
  cd src/native/interpreter/
  python3 ../../../scripts/codegen/split_fast_dispatch.py
"""

import os

SRC = "/home/debian/agent/booming-il2cpp/src/native/interpreter"
ORIG = os.path.join(SRC, "fast_dispatch.cpp")
BACKUP = os.path.join(SRC, "fast_dispatch_full.cpp.bak")

# ── Read original ────────────────────────────────────────────────────────
with open(ORIG, "r") as f:
    text = f.read()
    lines = text.splitlines(keepends=True)

N = len(lines)

# ── Define sections (0-indexed line ranges) ──────────────────────────────
# Verified against current file structure via grep.

SECTIONS = {
    # (output_name, [(start, end), ...], section_comment)
    "fast_dispatch_core": (
        [(0, 54), (55, 112), (113, 163), (165, 428)],
        "Core: includes, defines, TLS pool, conversion helpers, SEH helpers, basic op handlers (LdcI4..Dup)"
    ),
    "fast_dispatch_branch": (
        [(429, 618)],
        "Branch handlers: PGO recording + Br/BrTrue/BrFalse/Beq/Blt/Bgt/Ble/Bge + unsigned variants"
    ),
    "fast_dispatch_arithmetic": (
        [(619, 1042)],
        "Arithmetic: tag validation + Add/Sub/Mul/Div/Rem + comparison + conversion + overflow"
    ),
    "fast_dispatch_call": (
        [(1043, 1594), (2534, 2726)],
        "Call handling: Call/CallVirt/CallBridge/CallVirtConstrained + MIC + overflow helpers + Calli + Switch"
    ),
    "fast_dispatch_seh": (
        [(1595, 1782)],
        "SEH: Throw/Rethrow/Leave/EndFinally/EndFilter"
    ),
    "fast_dispatch_object": (
        [(1783, 2187)],
        "Object: array element access + field load/store + StFldBarrier + helpers"
    ),
    "fast_dispatch_type": (
        [(2188, 2533)],
        "Type: CastClass/IsInst + Conv_*/ConvOvf_* conversion handlers"
    ),
    "fast_dispatch_execute": (
        [(2727, N - 2)],
        "Execute: FastExecute main loop + OSR + histogram + ExecutionResult conversion"
    ),
}

# ── Verify ranges ────────────────────────────────────────────────────────
def verify_ranges():
    """Check that ranges don't overlap and cover the expected area."""
    covered = set()
    for name, (ranges, _desc) in SECTIONS.items():
        for s, e in ranges:
            for i in range(s, e + 1):
                assert i not in covered, f"Line {i} covered twice ({name})"
                covered.add(i)
    # Verify each covered line looks reasonable
    for i in sorted(covered):
        if not lines[i].strip():
            continue
    missing = set(range(N)) - covered
    if missing:
        print(f"  [warn] Lines not covered: {sorted(missing)}")
    print(f"  [ok] {len(covered)}/{N} lines covered")

# ── Write sub-files ──────────────────────────────────────────────────────
def write_sub_files():
    for name, (ranges, desc) in SECTIONS.items():
        path = os.path.join(SRC, f"{name}.inc")
        with open(path, "w") as f:
            f.write(f'// ── {name}.inc — {desc} ──\n')
            f.write(f'// Auto-extracted from fast_dispatch.cpp. DO NOT EDIT this file directly.\n')
            f.write(f'// Edit fast_dispatch.cpp and re-run split_fast_dispatch.py to regenerate.\n\n')
            for s, e in ranges:
                for i in range(s, e + 1):
                    f.write(lines[i])
                f.write('\n')
        print(f"  [ok] {name}.inc ({sum(e-s+1 for s,e in ranges)} lines)")

# ── Write new fast_dispatch.cpp ──────────────────────────────────────────
def write_main():
    path = ORIG
    with open(path, "w") as f:
        f.write('// fast_dispatch.cpp — Unity-build aggregator\n')
        f.write('//\n')
        f.write('// This file aggregates all sub-files into a single translation unit.\n')
        f.write('// Edit individual .inc files or regenerate from fast_dispatch_full.cpp.bak\n')
        f.write('// using the split_fast_dispatch.py script.\n')
        f.write('//\n')
        f.write('// The preamble (includes + namespace opens) lives in fast_dispatch_core.inc.\n')
        f.write('// All other .inc files are included within namespace chaos::il2cpp::runtime_core.\n\n')

        # Include each sub-file — preamble is in fast_dispatch_core.inc
        sub_order = [
            "fast_dispatch_core",
            "fast_dispatch_branch",
            "fast_dispatch_arithmetic",
            "fast_dispatch_call",
            "fast_dispatch_seh",
            "fast_dispatch_object",
            "fast_dispatch_type",
            "fast_dispatch_execute",
        ]
        for name in sub_order:
            f.write(f'#include "{name}.inc"\n')

        # Close namespace opened by fast_dispatch_core.inc
        f.write('}  // namespace chaos::il2cpp::runtime_core\n')

    print("  [ok] fast_dispatch.cpp (aggregator)")

# ── Main ─────────────────────────────────────────────────────────────────
def main():
    print(f"Reading {ORIG} ({N} lines)")
    print()

    # Backup original
    if not os.path.exists(BACKUP):
        import shutil
        shutil.copy2(ORIG, BACKUP)
        print(f"  [ok] Backed up to {BACKUP}")
    else:
        print(f"  [ok] Backup already exists at {BACKUP}")

    print()
    print("Verifying ranges ...")
    verify_ranges()

    print()
    print("Writing sub-files ...")
    write_sub_files()

    print()
    print("Writing fast_dispatch.cpp (aggregator) ...")
    write_main()

    print()
    print("All done! Next steps:")
    print("  cmake --build build/x64-check --target chaos_interpreter")
    print("  ctest -L interpreter --test-dir build/x64-check")

if __name__ == "__main__":
    main()
